// Участок для карточки — у самого рискованного датчика из зоны роли, а не выбранный
// заранее номер: у техника комплекса свой участок, чужой сервер не отдаст.
let участок: Promise<number | null> | null = null
function адрес(path: string): Promise<string | null> {
  if (path !== 'card') return Promise.resolve(path)
  участок ??= apiFetch(sensorRiskUrl({ synthetic: true, limit: 20 }))
    .then((r) => (r.ok ? (r.json() as Promise<SensorRiskPage>) : null))
    .then((d) => d?.items.find((s) => s.section_id != null)?.section_id ?? null)
    .catch(() => null)
  return участок.then((id) => (id == null ? null : `/objects/${id}`))
}

function ждать(selector: string, закрыт: () => boolean): Promise<Element | null> {
  const до = Date.now() + ЖДАТЬ_МС
  return new Promise((готово) => {
    // Элемент должен не только появиться, но и встать на место: дашборд догружает
    // плитки над таблицей, и подсветка, поставленная сразу, оставалась выше таблицы
    // (Слава, 28.09.2026). Ждём, пока верх элемента не сдвинется два тика подряд.
    let прошлый: number | null = null
    let стоит = 0
    const тик = () => {
      const el = document.querySelector(selector)
      const r = el?.getBoundingClientRect()
      if (el && r && r.height > 0) {
        const верх = r.top + window.scrollY
        стоит = прошлый === верх ? стоит + 1 : 0
        прошлый = верх
        if (стоит >= 2) return готово(el)
      }
      if (закрыт() || Date.now() > до) return готово(null)
      setTimeout(тик, 150)
    }
    тик()
  })
}

export function запуститьТур() {
  участок = null
  let занят = false
  let закрыт = false

  // Ищем ближайший шаг в сторону dir, чей экран открылся и элемент появился.
  const go = async (d: Driver, from: number, dir: 1 | -1) => {
    if (занят) return
    занят = true
    try {
      for (let i = from + dir; i >= 0 && i < ШАГИ.length; i += dir) {
        const путь = await адрес(ШАГИ[i].path)
        if (закрыт) return
        if (путь == null) continue
        // preact-router прокрутку не сбрасывает: с конца длинной карточки участка
        // /orders открывался на 10 727 px вниз, и блок поиска оставался за краем окна.
        if (window.location.pathname !== путь) {
          route(путь)
          window.scrollTo(0, 0)
        }
        if (await ждать(ШАГИ[i].element, () => закрыт)) {
          if (d.isActive()) d.moveTo(i)
          else d.drive(i)
          return
        }
      }
      // Впереди шагов не осталось — тур закончен; позади — остаёмся на месте.
      if (dir === 1) d.destroy()
    } finally {
      занят = false
    }
  }

  const steps: DriveStep[] = ШАГИ.map((s) => ({
    element: s.element,
    popover: { title: s.title, description: s.text },
  }))
  const d = driver({
    steps,
    showProgress: true,
    progressText: '{{current}} из {{total}}',
    nextBtnText: 'Далее',
    prevBtnText: 'Назад',
    doneBtnText: 'Готово',
    popoverClass: 'tour-popover',
    // Без анимации: driver.js запоминает прошлый элемент только в конце 400-мс
    // перехода, и «Далее», нажатое раньше, оставляло подсветку на двух элементах.
    animate: false,
    stagePadding: 6,
    smoothScroll: true,
    onNextClick: () => void go(d, d.getActiveIndex() ?? -1, 1),
    onPrevClick: () => void go(d, d.getActiveIndex() ?? 0, -1),
    onDestroyed: () => {
      закрыт = true
      следить.disconnect()
    },
    onPopoverRender: (p) => p.closeButton.setAttribute('aria-label', 'Закрыть тур'),
  })
  // Экран догрузился уже при открытом шаге (ответ API, опрос раз в минуту) — страница
  // меняет высоту, элемент сдвигается; переставляем подсветку следом за ним.
  const следить = new ResizeObserver(() => d.isActive() && d.refresh())
  следить.observe(document.body)
  void go(d, -1, 1)
}
