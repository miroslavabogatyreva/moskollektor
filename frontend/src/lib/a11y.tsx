// Строка таблицы ведёт на карточку кликом по <tr onClick> — добавляет клавиатурную
// навигацию без переписывания разметки под <a href>: используется в четырёх
// таблицах (дашборд, журнал, заявки, карточка объекта — MOS-128), обёртка
// в <a> потребовала бы стилизовать первую ячейку отдельно в каждой из четырёх.
//
// role: 'link' здесь был раньше и ломал саму задачу (нашёл второй проверяющий,
// 5f, деревом доступности, 22.09.2026): роль на <tr> вытесняет строке из
// таблицы её реальную роль row, ячейки перестают быть cell, и программа чтения
// объявляет всю строку одной ссылкой без разбивки по колонкам — клавиатурный
// пользователь терял табличную навигацию, которая была ДО правки. Без роли
// строка снова row, Enter по-прежнему работает через onKeyDown.
//
// class row-link (styles/index.css) — курсор, подсветка и шеврон «›» справа: строку,
// которая открывает карточку, видно без наведения (визуальный проход 28.09.2026).
export function rowLink(onActivate: () => void) {
  return {
    class: 'row-link',
    tabindex: 0,
    onClick: onActivate,
    onKeyDown: (e: KeyboardEvent) => {
      if (e.key === 'Enter') onActivate()
    },
  }
}

// Обходная ссылка перед длинной таблицей: без неё клавиатурный пользователь
// идёт Tab-ом через все строки, чтобы попасть дальше (нашёл moskollektor-15
// на дашборде — 3 173 строки, вход по Enter работал, выхода не было). Видна
// только в фокусе — sr-only/focus:not-sr-only, стандартные утилиты Tailwind,
// своего CSS не заводим. Позиция и цвет — тоже классами (не style=): inline
// style сильнее любого класса по специфичности и перебивает sr-only, из-за
// этого первая версия была видна всегда, а не только в фокусе (нашёл fe).
// targetId — id элемента сразу после таблицы.
export function SkipTable({ targetId }: { targetId: string }) {
  return (
    <a
      href={`#${targetId}`}
      class="sr-only focus:not-sr-only focus:fixed focus:top-2 focus:left-2 focus:z-10 focus:rounded focus:px-3 focus:py-2 focus:[background:var(--brand)] focus:[color:var(--text-on-brand)]"
    >
      Пропустить таблицу
    </a>
  )
}
