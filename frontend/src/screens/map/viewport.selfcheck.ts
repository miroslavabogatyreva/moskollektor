// Самопроверка арифметики окна просмотра (viewport.ts) — MOS-126, задача 5.15,
// строка приёмки М-05. Отдельный файл, а не блок внутри viewport.ts: он
// пользуется process, которого нет в браузере, а viewport.ts идёт в бандл
// карты — этот файл экран не импортирует, в бандл он не попадает.
//
// Запуск: node frontend/src/screens/map/viewport.selfcheck.ts
// (Node 22+ выполняет .ts напрямую благодаря встроенному вырезанию типов.)

declare const process: { exitCode?: number }

import { fullView, isFullView, panView, zoomView } from './viewport.ts'

let failed = false
const assertEqual = (got: number, want: number, label: string) => {
  if (Math.abs(got - want) > 1e-9) {
    console.error(`FAIL: ${label} — получено ${got}, ожидалось ${want}`)
    failed = true
  }
}

// приближение из центра сужает окно ровно вдвое и держит центр на месте
let v = zoomView(fullView(1000), 0.2, 500, 1000, 10)
assertEqual(v[1] - v[0], 200, 'ширина после зума x0.2')
assertEqual(v[0], 400, 'левая граница после зума из центра')
assertEqual(v[1], 600, 'правая граница после зума из центра')

// зум у левого края коллектора не уходит в отрицательные пикеты
v = zoomView(fullView(1000), 0.1, 0, 1000, 10)
assertEqual(v[0], 0, 'левый край не уходит в минус')
assertEqual(v[1], 100, 'ширина сохраняется у левого края')

// зум у правого края не вылезает за maxPicket
v = zoomView(fullView(1000), 0.1, 1000, 1000, 10)
assertEqual(v[1], 1000, 'правый край не вылезает за maxPicket')
assertEqual(v[0], 900, 'ширина сохраняется у правого края')

// окно не может стать уже заданного минимума (иначе метки схлопнутся обратно)
v = zoomView([490, 510], 0.001, 500, 1000, 10)
assertEqual(v[1] - v[0], 10, 'ширина не падает ниже minWidth')

// отдаление до размера всей оси даёт ровно полный вид
v = zoomView([400, 600], 5, 500, 1000, 10)
if (!isFullView(v, 1000)) {
  console.error(`FAIL: отдаление не вернуло полный вид, получено ${v}`)
  failed = true
}

// пан вправо у правого края не вылезает за maxPicket
v = panView([900, 1000], 0.5, 1000)
assertEqual(v[0], 900, 'пан вправо у края: левая граница держится')
assertEqual(v[1], 1000, 'пан вправо у края: правая граница не вылезает')

// пан влево у левого края не уходит в минус
v = panView([0, 100], -0.5, 1000)
assertEqual(v[0], 0, 'пан влево у края: левая граница держится на нуле')
assertEqual(v[1], 100, 'пан влево у края: правая граница держится')

// пан в пределах оси действительно сдвигает окно на заданную долю
v = panView([400, 600], 0.5, 1000)
assertEqual(v[0], 500, 'пан внутри оси сдвигает левую границу')
assertEqual(v[1], 700, 'пан внутри оси сдвигает правую границу')

// вырожденная ось (maxPicket = 0) не должна давать NaN — раньше ratio = 0/0
// расползался по всему окну (нашла 28)
v = zoomView(fullView(0), 0.5, 0, 0, 1)
if (v.some((n) => Number.isNaN(n))) {
  console.error(`FAIL: зум на вырожденной оси даёт NaN, получено ${v}`)
  failed = true
}
assertEqual(v[0], 0, 'вырожденная ось: левая граница')
assertEqual(v[1], 0, 'вырожденная ось: правая граница')

// самый короткий коллектор в парке — 8 пикетов (888, 889), не 1000: тот же
// сценарий приближения из центра, но на реальном, а не круглом масштабе
v = zoomView(fullView(8), 0.25, 4, 8, 1)
assertEqual(v[0], 3, 'короткий коллектор (8 пикетов): левая граница после зума')
assertEqual(v[1], 5, 'короткий коллектор (8 пикетов): правая граница после зума')

if (failed) {
  console.error('viewport: самопроверка провалена')
  process.exitCode = 1
} else {
  console.log('viewport: самопроверка ок, 11 случаев')
}
