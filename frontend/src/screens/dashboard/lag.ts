// Отставание среза расчёта от края данных словами — MOS-129, задача 5.18,
// приёмка М-04. Отдельный файл, как risk.ts/risk.selfcheck.ts: чистая логика
// без DOM, проверяется node-скриптом, не браузером.
//
// ЗАЧЕМ ВООБЩЕ. На экране живут три разных момента, и их легко принять за один:
//   1. край данных — докуда доехала выгрузка заказчика (30.06.2026);
//   2. срез расчёта — на какой момент считали признаки (`as_of`);
//   3. время расчёта — когда прогон отработал (`computed_at`, сегодня).
// Плановый прогон берёт срез равным краю, и тогда 1 и 2 совпадают. Прогон,
// запущенный руками с флагом `--as-of`, их разводит — и до MOS-148 экран
// показывал срез, а подписывал его концом выгрузки. Здесь мы называем разрыв
// вслух, когда он есть, и молчим, когда его нет: строка «отставание 0 суток»,
// висящая всегда, читается как украшение и перестаёт замечаться.
//
// Считает разрыв сервер (`GET /api/data-status`, поле `lag_days`), а не браузер:
// вычитание двух дат здесь пошло бы в часовом поясе того, кто смотрит.
//
// ЧЕТВЁРТОЕ ВРЕМЯ ПРИДЁТ ОТДЕЛЬНО. MOS-123 поставит в шапку страницы «обновлено»
// — момент, когда браузер последний раз сходил за данными. Оно не равно ни
// одному из трёх выше, и подписи не должны совпасть: здесь их три — «Данные
// по состоянию на», «расчёт от» и «срез расчёта», слова «обновлено» среди них
// нет нарочно. Кто возьмётся за MOS-123, пусть сверится с этим списком, иначе
// MOS-129 починит одно время и создаст другое (замечание сессии moskollektor-29
// в тикете MOS-129).
//
// Единицы «ч» и «сут» — те же, которыми печатает журнал прогона
// (`backend/app/worker/run.py`), чтобы экран и журнал читались одинаково.
//
// Подлежащее в текст не входит: его называет тот, кто печатает строку. Иначе
// на экране выходит «срез расчёта — 01.07.2026: срез расчёта ушёл вперёд» —
// так и было, поймано глазами на живом прогоне 521.

// Меньше минуты — считаем, что срез и край сошлись. Порог в сутках.
//
// Сначала здесь стоял час, и это была ошибка, которую поймал живой прогон.
// Рассуждение было такое: плановый прогон ставит срезом конец суток края,
// деление на 86 400 даёт не круглый ноль, дадим запас побольше. На стенде
// оказалось иначе: `lag_days` планового прогона равен ровно 0,0 — срез и край
// считаются одним и тем же запросом (`app.db.КРАЙ_ДАННЫХ`), и расходиться им
// не на чем. А вот единственный ручной прогон, который вообще можно поставить
// вперёд, отстоит ровно на час: расчёт по модели v3 отказывается считать, если
// срез ушёл от файла ml-score дальше чем на 1,5 часа (`ФайлНеГодится`,
// backend/app/worker/score_v3.py), и прогон со срезом на сутки вперёд падает,
// не дойдя до записи. Час в сутках — это 0,0416667, а замеренный разрыв —
// 0,04168: порог в час прошёл бы в двух стотысячных от того самого случая,
// ради которого он написан. Минута от любого настоящего случая далеко.
const СОШЛИСЬ = 1 / 1440

export interface Отставание {
  разошлись: boolean
  текст: string
}

export function отставание(lagDays: number | null | undefined): Отставание {
  if (lagDays == null) {
    return { разошлись: false, текст: 'срез расчёта сервер не назвал' }
  }
  if (Math.abs(lagDays) < СОШЛИСЬ) {
    return { разошлись: false, текст: 'по тем же данным' }
  }
  const модуль = Math.abs(lagDays)
  const величина = модуль < 1 ? `${Math.round(модуль * 24)} ч` : `${Math.round(модуль)} сут`
  return lagDays > 0
    ? { разошлись: true, текст: `ушёл вперёд данных на ${величина} — таких данных нет` }
    : { разошлись: true, текст: `отстал от данных на ${величина} — свежих расчёт не видел` }
}
