// Самопроверка lag.ts — MOS-129, задача 5.18, приёмка М-04.
// Запуск: node frontend/src/screens/dashboard/lag.selfcheck.ts

declare const process: { exitCode?: number }

import { отставание } from './lag.ts'

let failed = false
const assertEqual = (got: unknown, want: unknown, label: string) => {
  if (got !== want) {
    console.error(
      `FAIL: ${label} — получено ${JSON.stringify(got)}, ожидалось ${JSON.stringify(want)}`,
    )
    failed = true
  }
}

// Плановый прогон: срез равен краю. Ровно это отдаёт стенд сегодня —
// GET /api/data-status вернул lag_days 0.0 при data_edge = as_of = 30.06.2026.
assertEqual(отставание(0).разошлись, false, 'ноль — срез и край сошлись')
assertEqual(отставание(0).текст, 'по тем же данным', 'ноль — текст')

// Секунды — это дрожание представления даты, а не разрыв: порог в минуту
// написан ради них, чтобы сравнение с точным нулём не зажигало тревогу.
assertEqual(отставание(0.0005).разошлись, false, '43 секунды — сошлись')

// А час — уже разрыв, и это не абстрактный случай: ровно на час вперёд ставится
// единственный ручной прогон, который проходит защиту модели v3 (дальше 1,5 ч
// от файла ml-score расчёт отказывается считать). Замеренное на стенде значение
// 0,04168 обязано попасть в «разошлись» с запасом, а не впритык.
assertEqual(отставание(0.04168).разошлись, true, 'час вперёд — разошлись')
assertEqual(отставание(0.04168).текст.includes('1 ч'), true, 'час вперёд — назван часом')
assertEqual(отставание(-0.03).разошлись, true, '43 минуты назад — тоже разрыв')

// Ручной прогон со срезом впереди данных: экран обязан сказать, что таких
// данных нет. Это и был дефект MOS-148 — прогон 501 на стенде со срезом
// 01.07.2026 при крае 30.06.2026.
const вперёд = отставание(1)
assertEqual(вперёд.разошлись, true, 'сутки вперёд — разошлись')
assertEqual(
  вперёд.текст,
  'ушёл вперёд данных на 1 сут — таких данных нет',
  'сутки вперёд — текст',
)

// Ручной прогон по старым данным: свежие есть, а расчёт их не видел.
const назад = отставание(-83)
assertEqual(назад.разошлись, true, '83 суток назад — разошлись')
assertEqual(
  назад.текст,
  'отстал от данных на 83 сут — свежих расчёт не видел',
  '83 суток назад — текст',
)

// Меньше суток, но больше часа — считаем часами, а не «0 сут»: округление
// до суток превратило бы шестичасовой разрыв в ноль и спрятало его.
assertEqual(отставание(0.25).текст.includes('6 ч'), true, 'четверть суток — шесть часов')
assertEqual(отставание(-0.5).текст.includes('12 ч'), true, 'полсуток — двенадцать часов')

// Метод ответил, но среза не знает: прогонов ещё не было. Это не ноль —
// пустое место здесь читается как «всё в порядке», поэтому говорим словами.
assertEqual(отставание(null).текст, 'срез расчёта сервер не назвал', 'null — сказано словами')
assertEqual(отставание(undefined).разошлись, false, 'undefined — не тревога')

if (failed) {
  console.error('lag.selfcheck: есть расхождения')
  process.exitCode = 1
} else {
  console.log('lag.selfcheck ok')
}
