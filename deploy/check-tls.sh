#!/bin/sh
# Замер для строки приёмки НФ-75: TLS не ниже 1.2, шифров RC4 и 3DES нет.
#
# Строка требует двух вещей: отклонить 1.0 и 1.1, принять 1.2 и 1.3, и записать
# версии с наборами в протокол. Вывод этого скрипта и есть такая запись:
#     sh check-tls.sh localhost > ../docs/protocol-tls.md
#
# Главное доказательство здесь — nmap, а не openssl, и вот почему.
# openssl отказывается собирать ClientHello со старыми версиями: свежие сборки
# вырезают TLS 1.0 и 1.1 на уровне политики. Тогда команда падает с текстом
# "no protocols available" ДО строки CONNECTED — это отказ нашего клиента,
# рукопожатия не было вовсе, и предъявлять такой вывод комиссии нельзя.
# Проверено 15.09.2026 на example.com: без понижения уровня падает клиент,
# с `-cipher DEFAULT@SECLEVEL=0` рукопожатие по TLS 1.0 проходит.
# nmap строит записи TLS сам и версию 0x0301 отправит независимо от того,
# что умеет линкованная библиотека, — поэтому его ответ говорит о сервере.
set -eu

HOST="${1:-127.0.0.1}"
PORT="${2:-443}"

# Адрес нового вида (IPv6) оба инструмента берут иначе: nmap требует флага -6,
# а openssl — адреса в квадратных скобках, иначе он примет двоеточие внутри
# адреса за отделитель порта. Узнаём такой адрес по двоеточию в нём.
case "$HOST" in
    *:*) NMAP6="-6"; TARGET="[$HOST]"; KIND="IPv6" ;;
    *)   NMAP6="";   TARGET="$HOST";   KIND="IPv4" ;;
esac

# На маке два openssl: /usr/bin/openssl — это LibreSSL, он ведёт себя с флагами
# иначе. Берём тот, что из homebrew, если он есть.
OPENSSL=/opt/homebrew/bin/openssl
[ -x "$OPENSSL" ] || OPENSSL=$(command -v openssl)

echo "# Протокол НФ-75: версии TLS и наборы шифров"
echo
echo "Замер $(date '+%d.%m.%Y %H:%M %Z'), узел \`$TARGET:$PORT\`, адрес вида $KIND."
echo "Инструменты: \`$(nmap --version 2>/dev/null | head -1)\`, \`$($OPENSSL version)\`."
echo
echo '## Главное доказательство: nmap'
echo
echo 'Ожидание: секции TLSv1.2 и TLSv1.3 со списком наборов есть,'
echo 'секций TLSv1.0 и TLSv1.1 нет вообще.'
echo
echo '```'
# -n выключает обратный DNS: без него nmap печатает в протокол предупреждение
# mass_dns про ненайденные серверы имён, а заказчику это читать незачем.
# shellcheck disable=SC2086
nmap -n $NMAP6 --script ssl-enum-ciphers -p "$PORT" "$HOST" 2>&1 || true
echo '```'
echo
echo '## Контроль: четыре форсированных подключения openssl'
echo
echo 'Как читать: смотреть на строку «Итог», а не на строку `Protocol`.'
echo 'openssl печатает в `Protocol` запрошенную версию, а не согласованную, поэтому'
echo 'при отказе сервера там всё равно стоит `TLSv1` — и без строки «Итог» протокол'
echo 'читается как «TLS 1.0 прошёл». Настоящий признак отказа сервера — текст'
echo '`alert protocol version` и `Cipher is (NONE)`; признак отказа нашего клиента —'
echo '`no protocols available`, при нём рукопожатия не было и замер не засчитывается.'
echo 'Порядок строк внутри блока ни о чём не говорит: ошибки идут в поток ошибок'
echo 'и смешиваются с обычным выводом не в том порядке, в каком происходили.'
echo

for V in tls1 tls1_1 tls1_2 tls1_3; do
    case "$V" in
        # Понижаем уровень безопасности клиента, иначе он откажет сам за сервер.
        tls1|tls1_1) EXTRA="-cipher DEFAULT@SECLEVEL=0" ;;
        *)           EXTRA="" ;;
    esac
    # shellcheck disable=SC2086
    OUT=$(echo | $OPENSSL s_client -connect "$TARGET:$PORT" -"$V" $EXTRA 2>&1 || true)

    # Вывод openssl читается неверно без этой строки. При отказе сервера он всё
    # равно печатает `Protocol: TLSv1`, потому что показывает запрошенную версию,
    # а не согласованную, — и человек, листающий протокол, видит «TLS 1.0 прошёл».
    # Отличаем три случая по тексту, а не по строке Protocol.
    case "$OUT" in
        *"no protocols available"*)
            VERDICT="ОТКАЗАЛ НАШ КЛИЕНТ — рукопожатия не было, замер не засчитан" ;;
        *"alert protocol version"*|*"alert handshake failure"*|*"Cipher is (NONE)"*)
            VERDICT="СЕРВЕР ОТКЛОНИЛ — это и есть доказательство для НФ-75" ;;
        # Успех опознаём по положительному признаку, а не по отсутствию возражений.
        # Строку `New, TLSv1.2, Cipher is ...` openssl печатает только после
        # состоявшегося рукопожатия. Пока этой ветки не было, «всё остальное»
        # объявлялось успехом — и скрипт, наведённый на порт, где никто не слушает,
        # писал четыре «СЕРВЕР ПРИНЯЛ» подряд при полном отсутствии сервера.
        *"New, TLS"*)
            VERDICT="СЕРВЕР ПРИНЯЛ — $(echo "$OUT" | grep -m1 '^New,' | sed 's/^New, //')" ;;
        *)
            VERDICT="СОЕДИНЕНИЯ НЕ БЫЛО — сервер не ответил, замер не засчитан" ;;
    esac

    echo "### -$V"
    echo
    echo "**Итог: $VERDICT**"
    echo
    echo '```'
    echo "$OUT" \
        | grep -E 'CONNECTED|Protocol|Cipher|alert|no protocols available|handshake failure|connect:' \
        | head -6 || true
    echo '```'
    echo
done
