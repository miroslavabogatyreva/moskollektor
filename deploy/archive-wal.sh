#!/bin/sh
# archive_command базы стенда (задача 1.18): кладёт сегмент журнала в архив сжатым.
# Зовёт его сама база: archive_command='sh /archive-wal.sh %p %f'
# (deploy/docker-compose.yml). Аргументы — путь к сегменту и его имя.
#
# Три правила из документации PostgreSQL («Continuous Archiving», archive_command):
# 1. Код 0 — только когда сегмент надёжно лежит в архиве: пишем во временный файл,
#    сбрасываем его на диск (sync) и лишь потом переименовываем. Оборванная запись
#    не оставит битый файл с правильным именем.
# 2. Сегмент с таким именем уже в архиве и совпадает по содержимому — это тоже
#    успех. Так бывает после сбоя между mv и отметкой архиватора: база повторит
#    тот же сегмент. Прежняя команда `test ! -f` отвечала на повтор кодом 1 вечно,
#    база держала сегмент в pg_wal и копила следующие, пока не кончится диск.
# 3. Имя то же, а содержимое другое — ошибка, файл в архиве не трогаем: чужой
#    сегмент молча затёр бы восстановление.
set -eu
# Копии выключены (BACKUP_ENABLED=0 в deploy/.env): сегмент не нужен, без копии
# кластера накатывать его не на что. Код 0, а не отказ: на отказ база копила бы
# сегменты в pg_wal, пока не кончится диск.
[ "${BACKUP_ENABLED:-1}" = 1 ] || exit 0
src=$1
dir=${ARCHIVE_DIR:-/backups/wal}
f=$dir/$2.zst

if [ -f "$f" ]; then
  zstd -q -d -c "$f" | cmp -s - "$src" && exit 0
  echo "archive-wal: в архиве уже лежит $2 с другим содержимым" >&2
  exit 1
fi
zstd -q -f -o "$f.tmp" "$src"
sync "$f.tmp"
mv "$f.tmp" "$f"
