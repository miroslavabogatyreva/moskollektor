-- 027_forecast_legacy_reason.sql — старые строки журнала не выдают себя за изменения.
--
-- ЗАЧЕМ. Миграция 026 добавила `pred.forecast.write_reason` со значением по умолчанию
-- `change`, и это значение легло на ВСЕ строки, написанные до политики, — на стенде
-- 21.09.2026 это 431 529 строк из 434 702. Но те строки писались безусловно, каждый
-- объект в каждом прогоне: никакого «изменения» за ними не стоит. Колонка, которая
-- объясняет, почему строка попала в журнал, объясняла неправду про 99 % строк.
--
-- Молчащая неправда дороже отсутствующей колонки: на приёмке мы говорим «вот причина
-- каждой сохранённой строки», и первый же вопрос «а почему 21 сентября менялось
-- вообще всё?» остался бы без честного ответа.
--
-- ЧТО ДЕЛАЕМ. Пятое значение `legacy` — «написано до политики, безусловно». Не `full`:
-- `full` означает прогон с поднятым `pred.run.full_log`, а у старых прогонов он false,
-- и одно поле противоречило бы другому. `legacy` не врёт ни о чём.
--
-- ГРАНИЦА БЕРЁТСЯ ИЗ ЖУРНАЛА МИГРАЦИЙ, А НЕ ИЗ НОМЕРА ПРОГОНА. Номер прогона свой
-- в каждой среде: на стенде политика началась с прогона 150, на чистой базе начнётся
-- с первого. `public.schema_migration.applied_at` для 026 отвечает на этот вопрос
-- в любой среде: всё, что посчитано раньше этого момента, написано старым порядком.

ALTER TABLE pred.forecast DROP CONSTRAINT forecast_write_reason_chk;
ALTER TABLE pred.forecast ADD CONSTRAINT forecast_write_reason_chk
    CHECK (write_reason IN ('first', 'change', 'heartbeat', 'full', 'legacy'));

UPDATE pred.forecast f
   SET write_reason = 'legacy'
  FROM pred.run r
 WHERE r.run_id = f.run_id
   AND r.started_at < (SELECT applied_at FROM public.schema_migration
                        WHERE filename = '026_forecast_write_policy.sql');

COMMENT ON COLUMN pred.forecast.write_reason IS
    'Почему строка записана: first — первый прогноз объекта, change — вероятность или класс риска изменились, heartbeat — безусловная запись по времени, full — прогон с полным журналом (обучение, замер метрик), legacy — написано до политики MOS-147, безусловно';
