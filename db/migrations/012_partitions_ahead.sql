-- 012_partitions_ahead.sql — партиции smvu.reading на будущее и автодосоздание
-- Задача MOS-83 (Q2.10). Накатывается после 004_events.sql (создаёт smvu.reading)
-- и после 001…006 по возрастанию номера. Номер 012 закреплён явно: разрыв
-- 007-011 в каталоге намеренный, эти номера розданы в docs/plan.md задачам,
-- которые ещё не сделаны, 013 занят соседней задачей (013_setpoints.sql).
--
-- Зачем. 004_events.sql:224-243 нарезал партиции smvu.reading помесячно на весь
-- присланный архив — январь 2019 … июнь 2026, 90 штук. Сегодня 15.09.2026,
-- последняя партиция reading_2026_06 кончилась два с половиной месяца назад:
-- живой поток показаний из задачи Q3.7 придёт с сегодняшней меткой времени
-- и ни в одну месячную партицию не попадёт.
--
-- Почему это не мелочь. Правило 004_events.sql:245-247 — smvu.reading_default
-- обязан быть ПУСТЫМ. Пока в нём есть хоть одна строка, присоединение следующей
-- месячной партиции заставляет Postgres прочитать default целиком под блокировкой
-- ACCESS EXCLUSIVE (тот же механизм, что описан в шапке 004_events.sql:224-227) —
-- база встаёт на минуты. И это не разовая неприятность: без запаса партиций
-- вперёд дыра открывается заново каждый месяц.
--
-- Два куска:
--   1. Статический список месячных партиций июль 2026 — декабрь 2027 (18 штук),
--      тем же способом, что и 004_events.sql:232-243 — закрывает дыру сейчас.
--   2. smvu.ensure_partitions(months integer) — планировщик из задачи Q3.4 будет
--      звать её по расписанию, чтобы запас партиций никогда не кончался и дыра
--      вроде сегодняшней не открылась снова в июле 2028. pg_partman не ставим:
--      решение уже принято и обосновано в 004_events.sql:685-704 (раздел 10) —
--      тридцать строк на plpgsql делают то же самое без лишней зависимости в образе.
--
-- Идемпотентность: весь файл на CREATE ... IF NOT EXISTS / CREATE OR REPLACE.
-- Повторный накат (планировщик MOS-85, модуль наката) не упадёт и ничего заново
-- не пересоздаст — партиции и функция, которые уже есть, молча пропускаются.

CREATE SCHEMA IF NOT EXISTS smvu;   -- уже есть после 004_events.sql, но файл обязан быть самодостаточным

-- ---------------------------------------------------------------------------
-- 1. Партиции июль 2026 — декабрь 2027 (18 штук)
-- ---------------------------------------------------------------------------
DO $$
DECLARE
    m date := date '2026-07-01';
BEGIN
    WHILE m < date '2028-01-01' LOOP
        EXECUTE format(
            'CREATE TABLE IF NOT EXISTS smvu.reading_%s PARTITION OF smvu.reading '
            'FOR VALUES FROM (%L) TO (%L)',
            to_char(m, 'YYYY_MM'), m, m + interval '1 month');
        m := m + interval '1 month';
    END LOOP;
END $$;

-- ---------------------------------------------------------------------------
-- 2. smvu.ensure_partitions(months) — автодосоздание на будущее
-- ---------------------------------------------------------------------------
-- Досоздаёт месячные партиции smvu.reading от текущего месяца включительно
-- на `months` месяцев вперёд. Идемпотентность целиком на IF NOT EXISTS в
-- CREATE TABLE ... PARTITION OF: партиция, которая уже есть, пропускается без
-- ошибки, повторный вызов с тем же months не создаёт ничего нового. Планировщик
-- Q3.4 держит запас с большим отрывом от периода своей проверки (например,
-- ensure_partitions(24) раз в сутки) — тогда дыра вроде сегодняшней физически
-- не возникает.
CREATE OR REPLACE FUNCTION smvu.ensure_partitions(months integer)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    m    date := date_trunc('month', now())::date;
    stop date := (date_trunc('month', now()) + make_interval(months => months))::date;
BEGIN
    WHILE m < stop LOOP
        EXECUTE format(
            'CREATE TABLE IF NOT EXISTS smvu.reading_%s PARTITION OF smvu.reading '
            'FOR VALUES FROM (%L) TO (%L)',
            to_char(m, 'YYYY_MM'), m, m + interval '1 month');
        m := m + interval '1 month';
    END LOOP;
END;
$$;

COMMENT ON FUNCTION smvu.ensure_partitions(integer) IS
    'Досоздаёт недостающие месячные партиции smvu.reading на N месяцев вперёд от текущей даты (от начала текущего месяца). Вызывает планировщик из задачи Q3.4';
