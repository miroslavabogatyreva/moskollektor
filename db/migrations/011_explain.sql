-- 011. Готовый текст объяснения лежит в той же строке, что и прогноз. Q7.5 (MOS-68).
--
-- Зачем колонка, а не сборка текста на лету. Текст собирается из трёх признаков,
-- сильнее всего отклонившихся от нормы НА МОМЕНТ РАСЧЁТА (задача Q7.7). Через час
-- признаки уже другие, и фраза, собранная при показе карточки, будет объяснять
-- не тот прогноз, который в этой строке лежит. Прогноз и его объяснение обязаны
-- стареть вместе.
--
-- Почему text, а не jsonb с частями фразы. Шаблоны лежат в ref.explain_template
-- (миграция 006, десять пар «признак → фраза»), подстановку делает бэкенд,
-- а наружу едет готовая строка: фронт объяснение не собирает (задача Q7.8).
-- Разбирать текст обратно на части никому не нужно.
--
-- NULL допустим и означает ровно одно: объяснение к этому прогнозу ещё не собрано.
-- Пустая строка означала бы, что собрали и вышло пусто — это разные вещи,
-- поэтому запрещаем её проверкой, а не соглашением.
ALTER TABLE pred.forecast ADD COLUMN explanation_ru text
    CONSTRAINT forecast_explanation_not_blank CHECK (explanation_ru <> '');

COMMENT ON COLUMN pred.forecast.explanation_ru IS
    'Готовая фраза для диспетчера: три строки по трём сильнее всего отклонившимся признакам. Собирает backend/app/domain/explain.py по шаблонам ref.explain_template. NULL — ещё не собрано';

