-- 016. Убрать слово после {value} из восьми фраз. Часть задачи Q7.7 (MOS-70).
--
-- ЧТО СЛОМАНО. Слово, относящееся к числу, стояло в двух местах сразу: и в шаблоне,
-- и в подстановке. На настоящих шаблонах 16.09.2026 это дало:
--     «За неделю датчик писал в 333 раза раза реже…»
--     «За неделю датчик писал в 20 раз раза реже…»
--     «Датчики этого участка молчат 110 суток суток подряд…»
-- и, отдельной бедой, неверное склонение там, где слово осталось в шаблоне:
--     «271 записей» вместо «271 запись», «84 записей» вместо «84 записи».
--
-- ПОЧЕМУ СЛОВО ДОЛЖНО ЖИТЬ В КОДЕ, А НЕ В ШАБЛОНЕ. Русское склонение зависит
-- от числа: 1 запись, 2 записи, 5 записей, 21 запись, 271 запись. Посчитать это
-- в SQL нельзя, а в шаблоне можно записать только одну форму — и она будет верна
-- примерно для половины чисел. Поэтому правило одно: шаблон несёт {value}
-- и больше ничего, число вместе со своим словом собирает
-- backend/app/domain/explain.py, функция _число.
--
-- Расхождение кода со справочником теперь ловит проверка формы
-- explain.форма_шаблонов_верна: она смотрит, не стоит ли сразу после {value}
-- слово из списка тех, что подставляет код. Зовётся и самопроверкой, и расчётом,
-- одним и тем же кодом, поэтому разойтись им негде.

-- Записи «Неисправен»: слово убираем, код подставит «271 запись» / «84 записи».
UPDATE ref.explain_template SET phrase_ru =
    'По всему коллектору за 7 суток — {value} со значением «Неисправен», это больше обычного.'
 WHERE feature_code = 'bad7.up';

UPDATE ref.explain_template SET phrase_ru =
    'По всему коллектору за 7 суток — {value} со значением «Неисправен», это меньше обычного.'
 WHERE feature_code = 'bad7.down';

UPDATE ref.explain_template SET phrase_ru =
    'У этого датчика за 7 суток {value} со значением «Неисправен» — показания дребезжат, значение прыгает туда и обратно.'
 WHERE feature_code = 'chatter_7d.up';

-- Отношение темпа: код подставит «в 333 раза» или «в 20 раз».
UPDATE ref.explain_template SET phrase_ru =
    'За неделю датчик писал в {value} чаще, чем обычно за последние два месяца.'
 WHERE feature_code = 'rate_ratio_7d.up';

UPDATE ref.explain_template SET phrase_ru =
    'За неделю датчик писал в {value} реже, чем обычно за последние два месяца, и это тревожнее: замолчавший датчик не сообщит об аварии.'
 WHERE feature_code = 'rate_ratio_7d.down';

UPDATE ref.explain_template SET phrase_ru =
    'За неделю датчик писал в {value} чаще, чем обычно за год.'
 WHERE feature_code = 'rate_ratio_year.up';

UPDATE ref.explain_template SET phrase_ru =
    'За неделю датчик писал в {value} реже, чем обычно за год, и это тревожнее: замолчавший датчик не сообщит об аварии.'
 WHERE feature_code = 'rate_ratio_year.down';

-- Сутки молчания: код подставит «110 суток», «21 сутки», «1 сутки».
UPDATE ref.explain_template SET phrase_ru =
    'Датчики этого участка молчат {value} подряд. Пока они молчат, судить о состоянии участка не по чему — это и есть причина риска.'
 WHERE feature_code = 'section_silent';

-- Проверка прямо в миграции: после неё ни в одной фразе за {value} не должно
-- стоять слово, которое подставит код. Накат упадёт, если останется хоть одна —
-- лучше не накатиться, чем накатиться и выдать диспетчеру «110 суток суток».
DO $$
DECLARE
    плохие text;
BEGIN
    SELECT string_agg(feature_code, ', ') INTO плохие
      FROM ref.explain_template
     WHERE phrase_ru LIKE '%{value}%'
       AND lower(split_part(trim(leading ' ' from split_part(phrase_ru, '{value}', 2)), ' ', 1))
           IN ('раз', 'раза', 'запись', 'записи', 'записей', 'сутки', 'суток');
    IF плохие IS NOT NULL THEN
        RAISE EXCEPTION 'после {value} осталось слово, которое подставит и код: %', плохие;
    END IF;
END $$;
