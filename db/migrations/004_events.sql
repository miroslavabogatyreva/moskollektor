-- Осторожно с названием «Тепловой датчик»: это НЕ термометр. Это пороговый пожарный
-- извещатель, он сообщает о факте превышения, а не о температуре, и числовых значений
-- не пишет вовсе. Замер по каналу 93953 «ТД ПК206 ур.1» за весь 2025 год: «Норма»
-- 3194 раза, «Неопределен» 3155, «Не замкнут» 39 — ни одного числа.
-- Числовой ряд даёт другой тип, «Датчик температуры»: канал 2943 «Темп. ПК366»
-- за тот же год писал 24 (551 раз), 22 (535), 20 (438), 26 (434), 18 (347).
--
-- Отсюда следствие для признаков. Сезонные season_sin и season_cos осмысленны только
-- там, где есть числовой ряд достаточной глубины. Строгий счёт (год покрыт, если записи
-- есть хотя бы в десяти месяцах из двенадцати; нужно два таких года): «Датчик
-- температуры» проходит 585 каналов из 600, «Тепловой датчик» — 105 из 472, причём
-- у 298 тепловых нет ни одного покрытого года. То есть сезонность строится примерно
-- на 585 каналах — 5 % парка, а не на 1072, как выходит по сумме двух «температурных»
-- типов. Это надо сказать Николаю до обучения, а не после.

-- Канал данных — то, чем оперирует выгрузка заказчика. Физических датчиков в ней нет:
-- справочник_каналов_датчиков.csv отдаёт 11 485 каналов, и у каждого свой тег. Один прибор
-- может давать несколько каналов (температура и фаза), но связь «прибор -> каналы»
-- заказчик не прислал, поэтому канал у нас и есть единица учёта.
--
-- section_id собирается разборщиком code/tag_to_section.py из двух колонок справочника:
-- коллектор берётся из тега до дефиса ("847-11.1.131.2." -> 847), пикет — из названия
-- датчика ("КД АВ ПК106 ур.3" -> 106). На выгрузке от 09.09.2026 так привязывается
-- 10 720 каналов из 11 485, это 93,3 %, и получается 3173 участка на 30 коллекторах.
-- Оставшиеся 765 каналов стоят в диспетчерских пунктах ("КД окно пультовая ДП"),
-- участка у них нет и быть не должно — section_id остаётся NULL.
--
--
-- Три процента — это среднее по всему архиву, и оно обманывает. Доля растёт вглубь
-- истории: замер по первым 5 млн строк файла за 2019 год даёт 936 неизвестных каналов
-- из 5248 встретившихся (17,8 % каналов) и 625 187 строк (12,5 %). Оно и понятно —
-- справочник отражает сегодняшний парк, а журнал помнит всё, что снимали за восемь лет.
-- Для нас это значит, что заглушки важнее именно там, где лежит длинная история
-- для оценки наработки: без них мы потеряли бы восьмую часть 2019 года.
--
-- Доля по годам (строк по снятым каналам от всех строк года):
--   2019  11,82 %     2022  0,76 %
--   2020  11,64 %     2023  0,07 %
--   2021   6,19 %     2024  0,01 %
--                     2025  0,00 %     2026  0,00 %
--
-- ГРАНИЦА ПАРКА, и это важнее самой доли. Падение не плавное: между 2021 и 2022 годом
-- доля падает в восемь раз, и ещё в восемь к 2023-му. С другой стороны видно то же
-- событие: из 1 142 снятых каналов 721 замолчал между июнём 2021 и декабрём 2022,
-- пики — июль 2021 (189 каналов) и февраль 2022 (133). В 2021–2022 годах прошла
-- массовая замена или перенумерация оборудования.
-- Для обучения это не факт, а граница: модель, обученная на данных до 2022 года,
-- училась на другом парке. Обучающее окно выбирать с оглядкой на эту дату, а не
-- «берём всю историю, её много».
--
-- Справочник покрывает не весь журнал. В журнале встречается 12 627 каналов, и 1 143
-- из них справочник не знает — это 9,4 млн строк, снятое с эксплуатации оборудование.
-- Терять 3 % истории из-за отсутствующей строки справочника нельзя, поэтому загрузчик
-- заводит такому каналу заглушку с is_stub = true: тип и тег неизвестны, участка нет,
-- показания грузятся и в отчёте о качестве стоят отдельной группой. В расчёт признаков
-- заглушки не идут — у них section_id остаётся NULL, а свёртка берёт только участки.
--
-- equipment_id — склейка с реестром ТОиР. Не состоялась — остаётся NULL, канал всё равно
-- идёт в модель по участку. Списали оборудование — ссылка обнуляется, канал с историей
-- показаний остаётся.
CREATE TABLE smvu.channel (
    channel_id   integer PRIMARY KEY,          -- ид_канала_данных
    system_kind  text REFERENCES smvu.system_kind,  -- тип_инж_системы; NULL у заглушки
    sensor_kind  text REFERENCES smvu.sensor_kind,  -- тип_датчика; NULL у заглушки
    tag          text UNIQUE,                  -- тег_инженерной_системы, "847-11.1.131.2."
    name         text,                         -- название_датчика, "КД АВ ПК106 ур.3"
    collector    text,                         -- префикс тега: коллектор
    picket       integer,                      -- номер ПК из названия
    -- Участок. Внешний ключ на ref.object_xref добавляет 005_xref.sql.
    -- NULL — канал не в коллекторе либо канал-заглушка, см. комментарий выше.
    section_id   integer,
    equipment_id bigint REFERENCES asset.equipment(id) ON DELETE SET NULL,
    -- Канал есть в журнале, но его нет в справочнике заказчика. Таких 1 143 штуки
    -- и 9,4 млн строк — это снятое с эксплуатации оборудование, чью историю нам
    -- всё равно прислали. Строку заводит загрузчик перед заливкой показаний, иначе
    -- внешний ключ reading.channel_id отверг бы 3 % истории.
    is_stub      boolean NOT NULL DEFAULT false,
    is_active    boolean NOT NULL DEFAULT true
);

CREATE INDEX channel_section_idx ON smvu.channel (section_id) WHERE is_active;
CREATE INDEX channel_kind_idx    ON smvu.channel (system_kind, sensor_kind);

COMMENT ON TABLE smvu.channel IS
    'Каналы данных СМВУ: справочник_каналов_датчиков.csv плюс разобранный участок';


-- Дерево объектов диспетчера: справочник_объектов_диспетчер.csv, 95 строк.
-- Три уровня: район (1 строка) -> объект (16) -> подобъект (78: ДУ, ДП, шкафы ОПС, ОС, ПС).
-- ВНИМАНИЕ. Связи этого дерева с каналами заказчик не прислал: общей колонки нет ни одной,
-- из 32 префиксов тега с ид_объект совпал один. Пока связь не названа (ОВ-46), таблица
-- стоит отдельно и в расчёте не участвует — она нужна для интерфейса диспетчера,
-- который эти имена знает наизусть.
CREATE TABLE smvu.object_tree (
    object_id integer PRIMARY KEY,             -- ид_объект
    level     smallint NOT NULL,               -- иерархия_уровень: 1 район, 2 объект, 3 подобъект
    -- Родитель. В выгрузке корень (район, ид_объект 5773) ссылается на 3831, которого
    -- в файле нет. Загрузчик обнуляет такую ссылку: иначе ключ отверг бы корень,
    -- а с ним и всё дерево. NULL здесь означает «вершина присланного куска дерева».
    parent_id integer REFERENCES smvu.object_tree(object_id),
    kind      text NOT NULL,                   -- вид_объекта: district, controlHouse, guardObject
    name      text NOT NULL                    -- диспетчерское_название_объекта
);

CREATE INDEX object_tree_parent_idx ON smvu.object_tree (parent_id);

-- ---------------------------------------------------------------------------
-- 2. Показания СМВУ — главная и единственная загружаемая таблица
-- ---------------------------------------------------------------------------
-- Раньше здесь было две таблицы: smvu.event под тревоги и smvu.reading под телеметрию.
-- Выгрузка от 09.09.2026 показала, что заказчик отдаёт ОДИН поток: каждая строка журнала
-- это показание канала, а тревога отличается от нормы булевым флагом в той же строке.
-- Держать два хранилища под один файл незачем, поэтому event удалена, а reading приняла
-- все шесть колонок выгрузки.
--
-- Типизированное событие («метан выше уставки», «затопление») здесь не хранится и пока
-- не вычисляется: сначала нужен справочник уставок из Регламента и понимание, что для
-- модели считать событием. Появится признак, которому оно нужно, — заведём отдельно.
--
-- Почему value_text, а не только value_num. Значение приходит текстом и смешивает три
-- вещи: числа («28», «0.01»), состояния («Норма», «Обнаружено движение», «Не замкнут»)
-- и нулевую эпоху «01.01.1970 03:00:00», которая означает «значения нет». Замер
-- на первых 2 млн строк файла за 2019 год: числами разбираются 47,1 %, остальные 52,9 %
-- числами не являются. Колонка real в одиночку потеряла бы всю охранную и почти всю
-- пожарную подсистему — то есть ровно те два сценария, которых требует ТЗ разд. 6.
--
-- Почему помесячные партиции, а не недельные: 8 лет × 12 = 96 партиций. Планировщик
-- отбрасывает лишние за единицы миллисекунд. При недельных их было бы 417, и планирование
-- начало бы стоить дороже запроса.

CREATE TABLE smvu.reading (
    journal_id   bigint      NOT NULL,          -- ид_события: сквозной номер записи журнала
    read_time    timestamptz NOT NULL,          -- дата + время, склеенные загрузчиком
    channel_id   integer     NOT NULL REFERENCES smvu.channel,
    -- Денормализация: копия smvu.channel.section_id. Без неё любой запрос «показания
    -- по участку» тянет join на 11 485 строк справочника. NULL — канал не в коллекторе.
    section_id   integer,
    is_alarm     boolean     NOT NULL,          -- тревожное. В файлах 2019 года пишется
                                                -- f/t, в примере 2026 года false/true
    value_text   text,                          -- значение_датчика как пришло
    value_num    real,                          -- то же число, если текст разобрался
    -- Из какого файла строка. Удалить пакет, чьи показания уже в базе, нельзя
    -- (NO ACTION по умолчанию): пропадёт след, откуда взялась строка.
    source_batch bigint REFERENCES load.batch(id),
    PRIMARY KEY (journal_id, read_time)
) PARTITION BY RANGE (read_time);

COMMENT ON TABLE smvu.reading IS
    'Журнал показаний каналов СМВУ: одна строка файла выгрузки = одна строка таблицы';

-- Расхождение денормализации ловим ночной сверкой:
--   SELECT count(*) FROM smvu.reading r JOIN smvu.channel c USING (channel_id)
--    WHERE r.section_id IS DISTINCT FROM c.section_id;   -- обязано быть 0

-- Партиции заводим ВСЕ СРАЗУ, а не по одной. Причина не в удобстве: пока партиция
-- default непуста, каждое присоединение новой партиции заставляет Postgres прочитать
-- её целиком под блокировкой ACCESS EXCLUSIVE — база встаёт на минуты, и так каждый
-- месяц. Дешевле создать девяносто пустых партиций один раз.
--
-- Девяносто — это январь 2019 … июнь 2026, весь присланный архив: 313 546 016 строк,
-- в среднем 4,63 млн на месяц, примерно 477 МБ кучи на партицию. Раньше 2019 года
-- данных заказчик не прислал.
DO $$
DECLARE
    m date := date '2019-01-01';
BEGIN
    WHILE m < date '2026-07-01' LOOP
        EXECUTE format(
            'CREATE TABLE smvu.reading_%s PARTITION OF smvu.reading '
            'FOR VALUES FROM (%L) TO (%L)',
            to_char(m, 'YYYY_MM'), m, m + interval '1 month');
        m := m + interval '1 month';
    END LOOP;
END $$;

-- default оставляем, но он обязан быть ПУСТЫМ. Строка, попавшая сюда, означает либо
-- данные за неожиданный период, либо битую метку времени. Ночная проверка:
--   SELECT count(*) FROM smvu.reading_default;   -- обязано быть 0
CREATE TABLE smvu.reading_default PARTITION OF smvu.reading DEFAULT;

-- ---------------------------------------------------------------------------
-- 3. Индексы на показаниях
-- ---------------------------------------------------------------------------
-- Индексы создаём НА РОДИТЕЛЕ: Postgres 11+ каскадирует их на все партиции, включая
-- будущие. При первичной заливке их надо снять и создать заново после COPY — иначе
-- загрузка идёт втрое дольше.

-- 3.1. BRIN по времени. Таблица append-only, строки ложатся почти в хронологическом
-- порядке, корреляция физического порядка со временем близка к 1 — ровно тот случай,
-- под который BRIN сделан. Замер Cybertec на 5 млрд строк: btree 105 ГБ против BRIN 7 МБ.
-- У нас на 21 млн строк одного 2019 года это примерно 600 МБ btree против 35 КБ BRIN.
-- pages_per_range = 32 вместо дефолтных 128: Crunchy намерили, что сужение диапазона
-- ускорило точечную выборку с 11 мс до 4 мс, а на широких диапазонах разницы нет.
CREATE INDEX reading_time_brin ON smvu.reading USING brin (read_time) WITH (pages_per_range = 32);

-- 3.2. «Показания по каналу за период» — сценарий карточки датчика и ряда под графиком.
-- BRIN тут не работает: строки одного канала размазаны по всей таблице.
CREATE INDEX reading_channel_time_idx ON smvu.reading (channel_id, read_time DESC);

-- 3.3. «Показания по участку за период» — сценарий карточки участка и сборки признаков.
CREATE INDEX reading_section_time_idx ON smvu.reading (section_id, read_time DESC);

-- 3.4. Частичный индекс под тревоги. Их мало: 0,58 % в файле за 2019 год и 0,12 %
-- в примере за август 2026. Индекс выходит в двести раз меньше таблицы, а сценарий
-- «все тревоги участка за год» — основной и в интерфейсе, и в сборке признаков.
CREATE INDEX reading_alarm_idx ON smvu.reading (section_id, read_time DESC)
    WHERE is_alarm;

