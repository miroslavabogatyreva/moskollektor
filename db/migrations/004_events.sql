-- ---------------------------------------------------------------------------
-- 4. Эпизоды неисправности — целевая переменная модели
-- ---------------------------------------------------------------------------
-- Долго считалось, что факта отказа в выгрузке нет и надо ждать журналы ОДС. Это
-- неверно: отказ пишется прямо в значении канала словом «Неисправен». По всему архиву
-- (2019 — июнь 2026) таких записей 1 500 298 на 4 821 канале, и они есть во всех
-- 90 месяцах без пропусков.
--
-- Считать их надо ЭПИЗОДАМИ, а не записями, и это принципиально. Журнал пишет смену
-- состояния, и неисправный канал мигает: один канал за 2025 год дал «Норма» 22 167 раз
-- и «Неисправен» 22 156 раз. Если считать записями, этот единственный канал перевесит
-- половину парка и модель выучит его, а не отказы. Эпизод — это непрерывный отрезок,
-- когда канал находился в неисправности, независимо от того, сколько раз он моргнул.
--
-- Отрезок закрывается первым показанием с любым другим значением. Эпизод без закрытия
-- (канал ушёл в неисправность и больше ничего не сказал) остаётся с ended_at = NULL:
-- это цензурированное наблюдение, и для оценки наработки по Вейбуллу оно годится,
-- а для обучения на «отказ случился» — нет. Разделять их обязан тот, кто учит модель.
-- Что считать отказом. Держим справочником по типу датчика, а не константой в коде:
-- слово отказа зависит от типа (обычное — «Неисправен», но тепловой датчик дребезжит
-- словом «Неопределен»), а порог длительности будет править инженер строкой в таблице,
-- а не мы пересборкой образа.
--
-- ПОЧЕМУ ПОРОГ ДЛИТЕЛЬНОСТИ, А НЕ ПОРОГ СКЛЕЙКИ. Сначала здесь стояла колонка
-- gap_minutes: предполагалось, что неисправный канал мигает, и два эпизода, разделённые
-- коротким возвратом в норму, надо считать одним отказом. Прогон по всем 313 546 016
-- строкам это опроверг. Эпизодов вышло 1 497 064 на 4 819 каналах, и в 1 493 894 из них
-- (99,79 %) внутри ровно ОДНА запись «Неисправен». Склеивать нечего: «Неисправен» —
-- не состояние, которое длится, а мгновенное событие. Медиана длительности эпизода
-- 56 секунд, три четверти короче 148 секунд.
--
-- Хуже того, склейка по паузе даёт немонотонный счётчик и потому не годится под метрику:
-- при пороге час эпизодов длиннее часа выходит 6505, при четырёх часах 12 589,
-- при сутках 16 510. Два двухчасовых эпизода с паузой 30 минут сливаются в один
-- и счётчик падает, а две пятиминутки с паузой 100 минут дают стодесятиминутный
-- и счётчик растёт. На таком определении нельзя строить ни Precision, ни Recall.
--
-- Поэтому целевая переменная — эпизод ДЛИННЕЕ порога, а не склеенная серия.
-- Сколько их при разных порогах:
--   длиннее часа    11 454 эпизода на 2314 каналах   0,77 % всех
--   длиннее суток    1 611 на 792 каналах            0,11 %
--   длиннее недели     918                           0,06 %
-- Час выбран за стартовое значение: 11 454 отказа за восемь лет это около 1430 в год
-- на 825 км коллекторов — правдоподобный поток. Миллион двухсекундных морганий целевой
-- переменной быть не может: на них модель выучит дребезг контакта, а не отказ. Канал
-- 228571 «ТЕМП ПК275+9» тому пример: у него «Неисправен» сменяется «Нормой» в 22 071
-- случае из 22 156, медиана промежутка 2 секунды.
CREATE TABLE smvu.fault_rule (
    sensor_kind text    NOT NULL REFERENCES smvu.sensor_kind,
    fault_value text    NOT NULL,              -- значение_датчика, означающее отказ
    -- Эпизод короче этого порога отказом не считается: это дребезг, а не поломка.
    -- 3600 секунд — стартовое значение, обоснование выше. Порог по типу, а не общий:
    -- замер по типам ещё не разложен, и когда он придёт, менять надо здесь.
    min_duration_seconds integer NOT NULL DEFAULT 3600,
    PRIMARY KEY (sensor_kind, fault_value)
);

-- «Неисправен» действует для всех девятнадцати типов, поэтому заполняем из справочника
-- типов, а не девятнадцатью строками руками.
INSERT INTO smvu.fault_rule (sensor_kind, fault_value)
SELECT sensor_kind, 'Неисправен' FROM smvu.sensor_kind;

