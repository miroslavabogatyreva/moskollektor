CREATE TABLE smvu.fault_episode (
    episode_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id  integer     NOT NULL REFERENCES smvu.channel,
    section_id  integer,                        -- копия channel.section_id на момент эпизода
    started_at  timestamptz NOT NULL,           -- первое показание отказа в отрезке
    -- Конец эпизода: первое показание с нормальным значением. NULL означает, что канал
    -- ушёл в отказ и больше ничего не сказал. Это цензурированное наблюдение: для оценки
    -- наработки по Вейбуллу оно годится, для обучения на «отказ случился» — нет.
    -- Разделять их обязан тот, кто учит модель.
    ended_at    timestamptz,
    -- Сколько записей журнала вошло в эпизод. Почти всегда ровно одна: 99,79 %
    -- эпизодов состоят из единственной записи «Неисправен».
    rows_cnt    integer     NOT NULL DEFAULT 1,
    -- Чем эпизод закрылся. Распределение по всему архиву: «Норма» 86,2 %,
    -- «Обесточен» 9,0 %, «Затоплен» 3,7 %, «Неопределен» 1,1 %. Держим значение,
    -- потому что «канал вернулся в норму» и «канал обесточен» — разные исходы,
    -- и для обучения их придётся различать.
    closed_by   text,
    -- Два эпизода одного канала не могут пересекаться по времени. Ошибка склейки
    -- иначе тихо удвоит число отказов, а с ним и Recall. tstzrange с NULL сверху —
    -- это открытый справа промежуток, незакрытый эпизод проверкой тоже покрыт.
    EXCLUDE USING gist (channel_id WITH =, tstzrange(started_at, ended_at) WITH &&)
);

CREATE INDEX fault_episode_section_idx ON smvu.fault_episode (section_id, started_at DESC);
CREATE INDEX fault_episode_open_idx    ON smvu.fault_episode (channel_id)
    WHERE ended_at IS NULL;

COMMENT ON TABLE smvu.fault_episode IS
    'Эпизоды неисправности канала: целевая переменная модели. Строится из smvu.reading по smvu.fault_rule';

