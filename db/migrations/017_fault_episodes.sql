-- ---------------------------------------------------------------------------
-- 2. Две колонки в smvu.fault_episode
-- ---------------------------------------------------------------------------

-- Каким значением эпизод открылся. Без неё эпизоды «Неисправен» и «Неопределен»
-- в таблице неразличимы, а они значат разное и порог у них может быть разный:
-- smvu.fault_rule ключуется парой (sensor_kind, fault_value).
--
-- Отдельная причина, важная прямо сейчас: эталонный счёт 10 416 эпизодов
-- (analysis/episodes.py, docs/for-ml-team.md разд. 2) сделан ТОЛЬКО по «Неисправен» —
-- в скрипте буквально val='Неисправен'. Правило же схемы считает отказом ещё
-- и «Неопределен» у «Теплового датчика» (472 канала) и «Датчика температуры» (600).
-- Без этой колонки сверить наш итог с эталоном нельзя в принципе: мы считаем
-- по более широкому определению и обязаны уметь выделить из него эталонное
-- подмножество.
ALTER TABLE smvu.fault_episode ADD COLUMN fault_value text;

COMMENT ON COLUMN smvu.fault_episode.fault_value IS
    'Значение_датчика, которым эпизод открылся. Ссылается на smvu.fault_rule.fault_value';

-- Эпизод пересекает окно тишины из smvu.data_outage.
--
-- ПОЧЕМУ ПОМЕТКА, А НЕ ВЫБРОС. Среди пересекающих тишину есть настоящие отказы:
-- канал мог сломаться 5 апреля и остаться сломанным 12-го. Выбросив их, мы потеряем
-- настоящие отказы; оставив без пометки — отдадим модели выдуманную длительность.
-- Пометка оставляет решение тому, кто учит модель, — ровно так же, как эта таблица
-- уже поступает с ended_at IS NULL: DDL называет это цензурированным наблюдением
-- и разделять их велит тому же человеку.
ALTER TABLE smvu.fault_episode
    ADD COLUMN spans_outage boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN smvu.fault_episode.spans_outage IS
    'Длительность эпизода включает окно тишины выгрузки и потому завышена: для обучения такой эпизод брать нельзя';

-- Выбирать «эпизоды, годные для обучения» придётся на каждом запросе обучающей
-- выборки: закрытые и не пересекающие тишину, в порядке времени.
CREATE INDEX fault_episode_trainable_idx ON smvu.fault_episode (started_at)
    WHERE ended_at IS NOT NULL AND NOT spans_outage;
