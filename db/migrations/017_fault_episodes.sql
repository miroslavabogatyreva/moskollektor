-- 017. Что нужно построителю эпизодов отказа. Часть задачи Q2.16 (MOS-96).
--
-- `smvu.fault_episode` лежит в схеме с 15.09.2026 пустая: DDL есть в 004_events.sql,
-- строителя нет ни одного. Пока она пуста, два признака контракта из 22 — fault_30d
-- и neighbor_fault_7d — уходят в модель как NULL у всех 3 173 участков, а целевую
-- переменную нечем предъявить на приёмке. Здесь добавляется то, чего построителю
-- не хватает в схеме; сам построитель — backend/app/ingest/fault_episodes.py.

-- ---------------------------------------------------------------------------
-- 1. Окна тишины выгрузки
-- ---------------------------------------------------------------------------
-- ЗАЧЕМ. Канал записал «Неисправен» 6 апреля 2024, следующая его запись — 9 апреля.
-- По журналу это отказ длиной трое суток, на деле СМВУ в эти дни не написала ни строки
-- по всему парку: 7 и 8 апреля 2024 в базе нет вовсе. Без этой таблицы такие эпизоды
-- попадают в обучение как самые длинные отказы архива, и модель выучит сбой выгрузки.
--
-- ПОЧЕМУ ТАБЛИЦА, А НЕ ДВА ЗНАЧЕНИЯ В КОДЕ. Придёт следующая выгрузка со своей дырой —
-- добавится строка, а код останется прежним. То же решение, по которому уставки
-- лежат в ref.setpoint, а не в условиях запросов.
--
-- ГРАНИЦЫ ИЗМЕРЕНЫ ПО БАЗЕ 16.09.2026, а не переписаны из документа: это последняя
-- запись перед тишиной и первая после неё, то есть сама тишина лежит строго внутри
-- промежутка. Пересчитать можно так (по одной партиции, иначе это скан 313 млн строк):
--     SELECT пред, read_time, extract(epoch FROM read_time - пред)::bigint
--       FROM (SELECT read_time, lag(read_time) OVER (ORDER BY read_time) AS пред
--               FROM smvu.reading_2024_04) t
--      ORDER BY read_time - пред DESC NULLS LAST LIMIT 3;
-- Тишина на границе месяца видна только через две соседние партиции сразу: промежуток
-- 1 июня 2026 идёт от последней записи мая к первой записи июня, и запрос по одной
-- партиции показывает вместо него 13 секунд.
CREATE TABLE smvu.data_outage (
    outage_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Последняя запись ПЕРЕД тишиной и первая ПОСЛЕ неё.
    started_at timestamptz NOT NULL,
    ended_at   timestamptz NOT NULL,
    note       text        NOT NULL,
    CONSTRAINT data_outage_order CHECK (ended_at > started_at)
);

COMMENT ON TABLE smvu.data_outage IS
    'Окна, когда СМВУ не написала ни строки по всему парку. Эпизод отказа, пересекающий такое окно, помечается smvu.fault_episode.spans_outage';

