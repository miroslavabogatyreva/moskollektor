-- 023_refresh_run.sql — журнал прогонов свёртки feat.refresh_section_daily.
--
-- ЗАЧЕМ. До 21.09.2026 свёртка не оставляла в базе ничего: `тик_свёртка`
-- в backend/app/worker/scheduler.py звал функцию и печатал «свёртка: обновила
-- N строк» в журнал контейнера, который живёт до пересоздания. Значит пропуск
-- свёртки не видела ни одна проверка, а её задержку нельзя было померить
-- запросом: в feat.section_daily тринадцать колонок, и ни одной временнóй,
-- кроме `day` — а `day` это дата показания, а не время расчёта.
--
-- ЧЕГО ЭТА ТАБЛИЦА НЕ ДЕЛАЕТ. Она не закрывает строку приёмки НФ-73 («показание
-- доходит до расчёта не позднее 300 секунд»). НФ-73 не выполняется по устройству:
-- полный расчёт часовой, и показание, пришедшее в :06, ждёт 3 540 секунд при
-- нормативе 300 — промах в двенадцать раз. Журнал нужен для того, чтобы будущая
-- починка НФ-73 была проверяема числом, а не словами.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ КОЛОНКА В СВЁРТКЕ. Колонка `refreshed_at`
-- в feat.section_daily писалась бы на каждую из 255 635 строк и отвечала бы
-- на вопрос «когда обновилась эта строка», а спрашиваем мы другое — «когда
-- свёртка работала в последний раз и не пропустила ли слот». Прогон, не
-- обновивший ни одной строки, колонкой не виден вовсе, а это и есть самый
-- интересный случай. Писать в pred.run тоже нельзя: её читают проверки М-21
-- и НФ-72, и строки свёртки испортили бы им счёт прогонов.
--
-- РАЗМЕР. При интервале 5 минут это 288 строк в сутки, 105 тыс. в год —
-- меньше мегабайта. Чистку не заводим: журнал за всю историю стенда дешевле,
-- чем ещё одно задание планировщика, которое само может не запуститься.

CREATE TABLE feat.refresh_run (
    refresh_id   bigserial   PRIMARY KEY,
    started_at   timestamptz NOT NULL DEFAULT now(),
    finished_at  timestamptz,
    rows_updated integer,
    -- 'done' — свёртка отработала, 'failed' — упала. Строку пишем В ОБОИХ
    -- случаях: свёртка, которая исправно запускается и каждый раз падает,
    -- без этого выглядела бы точно так же, как не запускавшаяся вовсе.
    status       text        NOT NULL DEFAULT 'running',
    error_text   text,
    CONSTRAINT refresh_run_status_chk CHECK (status IN ('running', 'done', 'failed'))
);

CREATE INDEX refresh_run_started_idx ON feat.refresh_run (started_at DESC);

COMMENT ON TABLE feat.refresh_run IS
    'Журнал прогонов свёртки: когда запускалась, сколько строк обновила, чем кончилась';
