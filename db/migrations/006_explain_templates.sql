-- 006_explain_templates.sql — справочник шаблонов фраз для объяснения прогноза.
-- Задача MOS-69 (Q7.6). Накатывается после 001…005, схему ref не создаёт заново
-- в других файлах, только проверяет её наличие.
--
-- Зачем. Модель Николая вклады признаков не отдаёт (решение блока Q7, docs/plan.md:
-- строка Ф-08 части III на приёмке не проверяется, вторая версия контракта посреди
-- обучения того не стоит). Вместо этого бэкенд сам берёт три признака, сильнее
-- всего отклонившихся от собственной нормы объекта (задача 7.7), и подставляет их
-- в эти шаблоны. Требование приёмки Ф-73 — система называет СОСТОЯНИЕ, вызвавшее
-- рекомендацию, а не имя признака: диспетчер не знает, что такое bad7 или chatter_7d.
--
-- Место в схеме — ref, рядом с другими справочниками (ref.criticality,
-- ref.priority в 001_assets.sql): это данные, а не код, инженер должен уметь
-- поправить формулировку без пересборки образа бэкенда.
--
-- Формат подстановки значения. Колонка phrase_ru может содержать токен {value}
-- не более одного раза. Бэкенд (задача 7.7, backend/app/domain/explain.py)
-- подставляет туда значение признака, отформатированное по его типу
-- из contracts/features.v1.yaml:
--   * type: int (bad7, chatter_7d) -> целое число без разделителей разрядов: "34";
--   * type: float, unit «доля 0..1» (undefined_share_7d) -> проценты, округление
--     до целого со знаком %: "18%";
--   * type: bool (neighbor_fault_7d, fault_30d, freeze_3) -> токена {value}
--     в шаблоне нет. «Отклонение от нормы» для bool-признака и есть true —
--     если признак попал в тройку, он сработал; отдельное значение не нужно.
--
-- rate_ratio_7d и rate_ratio_year — особый случай: у них не одна строка,
-- а две, с суффиксом .up/.down в feature_code. Причина — фраза с одним числом
-- на оба направления звучит не по-русски: «отличается в 0.3 раза» приходится
-- пояснять скобкой «меньше 1 — реже, больше 1 — чаще», а диспетчер читает фразу
-- между вызовами и скобку разбирать не будет. Поэтому feature_code для этих
-- двух признаков — это имя из контракта плюс суффикс:
--   * rate_ratio_7d.up / rate_ratio_7d.down
--   * rate_ratio_year.up / rate_ratio_year.down
-- Суффикс выбирает 7.7 по сырому значению признака: ratio >= 1 -> .up,
-- ratio < 1 -> .down. Подставляемое число — ВСЕГДА отношение в ту сторону,
-- о которой говорит фраза, один знак после запятой:
--   * .up -> ratio как есть (ratio 3.3 -> "3.3");
--   * .down -> 1/ratio, а не ratio (ratio 0.3 -> 1/0.3 = "3.3", а не "0.3" —
--     иначе фраза «писал в 0.3 раза реже» тоже не по-русски).
--
-- ДВА КРАЯ, на которых 1/ratio ломается. Их обязана обработать задача 7.7,
-- здесь их не закрыть: шаблон принимает готовое число, а не формулу.
--   * ratio = 0 — канал за неделю не написал НИ РАЗУ. Деление на ноль. И это
--     не редкий случай на краю, а самый интересный: замолчавший датчик.
--   * ratio близко к нулю — число выходит огромным и фраза становится нелепой.
--     Пример из contracts/features.v1.yaml: канал 213785 (газовый) при недельной
--     норме 1 521 запись написал за неделю до 07.11.2025 всего 4, отношение 0,003.
--     1/0,003 = 333, и «писал в 333 раза реже» человек не читает как число.
-- Предложение для 7.7: завести одиннадцатый шаблон с суффиксом .silent на оба
-- признака и брать его вместо .down, когда ratio меньше 0,05 — фраза там будет
-- без числа вовсе, «датчик почти перестал писать». Сейчас его нет намеренно:
-- порог 0,05 взят с потолка, а формула выбора нормы в 7.7 ещё не написана,
-- и подбирать число под ненаписанный расчёт — гадание.
--
-- Две оговорки контракта смягчают формулировку, чтобы фраза не соврала диспетчеру:
--   * freeze_3 почти не совпадает с настоящей неисправностью: 1435 срабатываний
--     за 2025 год на 314 каналах, из них на значении «Неисправен» — только 5.
--     Остальное — «Выключен», «Включен», «Норма». Фраза не называет это отказом,
--     только просит проверить канал.
--   * undefined_share_7d есть почти у всего парка: 479180 записей за 2025 год
--     на 10817 каналах из 11483 (94,2%, contracts/features.v1.yaml). Присутствие
--     значения «Неопределен» само по себе не редкость и не аномалия. Фраза
--     сравнивает долю с нормой ЭТОГО ЖЕ канала, а не подаёт как общепарковую
--     редкость — иначе диспетчер примет фоновый шум за тревогу.

CREATE SCHEMA IF NOT EXISTS ref;   -- уже есть после 001_assets.sql, но файл обязан быть самодостаточным

CREATE TABLE ref.explain_template (
    id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    feature_code    text         NOT NULL UNIQUE,  -- имя признака дословно из contracts/features.v1.yaml features[].name, у rate_ratio_7d/rate_ratio_year — с суффиксом .up/.down
    phrase_ru       text         NOT NULL          -- фраза для диспетчера, {value} — необязательный токен подстановки, не больше одного раза
);
COMMENT ON TABLE  ref.explain_template IS 'Шаблоны фраз объяснения прогноза (приёмка Ф-73): признак -> фраза для диспетчера. Заполняет 7.6, читает 7.7';
COMMENT ON COLUMN ref.explain_template.feature_code IS 'Имя признака из contracts/features.v1.yaml — ключ подстановки в задаче 7.7; для rate_ratio_7d и rate_ratio_year с суффиксом .up/.down, суффикс выбирает 7.7';
COMMENT ON COLUMN ref.explain_template.phrase_ru IS 'Готовая фраза на русском; {value} заменяется отформатированным значением признака, формат — в шапке файла миграции';
