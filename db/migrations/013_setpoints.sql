-- ============================================================================
-- ref.setpoint — уставки параметров среды (Регламент п. 28.2.12 и журнал СМВУ)
-- ============================================================================
--
-- Форма — главное решение задачи. Порог обязан быть машиночитаемым: приёмка
-- проверяет `SELECT ... WHERE param = 'вода'` и ждёт число + единицу + знак
-- сравнения, а не строку «вода выше 200 мм».
--
-- Строю по образцу из code/setpoints_example.json (карта уставок НИ ТЭЦ) —
-- этот файл сам предупреждает, что он не данные, а ШАБЛОН СХЕМЫ («нужно как
-- шаблон схемы таблицы порогов для датчиков СМВУ»). Оттуда беру приём:
-- одна и та же уставка может иметь нижнюю границу (low_value), верхнюю
-- границу (high_value) или обе сразу в ОДНОЙ строке — там же так устроена
-- строка «Включение ИПК» (low=133 закрытие, high=148 открытие, один прибор).
--
-- Зачем нужна отдельная колонка direction, если low/high и так показывают
-- сторону. У нас есть строка третьего рода — «норма» (журнал СМВУ пишет
-- «В норме от +3 до +40», см. сид), где обе границы заполнены, но смысл
-- противоположный: между ними НЕ тревога, а рабочий диапазон. Без явной
-- колонки direction это неотличимо от строки, где обе границы — два разных
-- порога тревоги (как в примере с ИПК). Три значения: above_bad (плохо выше
-- high_value), below_bad (плохо ниже low_value), normal_range (норма МЕЖДУ
-- границами, обе обязательны).
--
-- Зачем inclusive. Регламент разными глаголами задаёт строгость:
--   * «превышает 200 мм» / «превышает 45 °C» / «выше 1 %» — строго (>),
--     inclusive = false;
--   * «менее 20 %» — тоже строго, но по нижней границе (<), inclusive = false;
--   * «1,0 % и более» (указание вывести людей, п. 24.4.10) — НЕ строго (>=),
--     inclusive = true, и это ДРУГАЯ строка, чем «выше 1 %» (п. 28.2.12):
--     одно и то же число 1 %, два разных действия системы, приёмка НФ-59
--     проверяет их порознь (на 1,0 % ровно — только указание, без запрета
--     допуска; на 1,01 % — запрет допуска).
-- Журнальные уставки (ниже 3 / выше 40) беру строгими по коду:
-- code/thermal_anomaly_rules.py r1_absolute() сравнивает `temp <= setpoint_low`
-- и `temp >= setpoint`, то есть по факту в СМВУ обе границы НЕ строгие —
-- inclusive = true, в отличие от строгих регламентных.
--
-- Отдельного числового значения без границы не бывает: CHECK ниже требует
-- хотя бы одну из low_value/high_value, а normal_range — обе сразу.
CREATE SCHEMA IF NOT EXISTS ref;   -- уже есть после 001_assets.sql, но файл обязан быть самодостаточным (см. 006_explain_templates.sql)

CREATE TABLE ref.setpoint (
    id          bigint  GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    code        text    NOT NULL UNIQUE,   -- стабильный ключ строки, для ON CONFLICT при повторной заливке сида
    param       text    NOT NULL,          -- параметр среды дословно: вода, температура воды, кислород, метан, температура (журнал СМВУ)
    low_value   numeric,                   -- нижняя граница уставки; при direction='below_bad' — порог тревоги, при 'normal_range' — нижняя граница нормы
    high_value  numeric,                   -- верхняя граница уставки; при direction='above_bad' — порог тревоги, при 'normal_range' — верхняя граница нормы
    unit        text    NOT NULL,          -- единица измерения: мм, °C, %
    direction   text    NOT NULL CHECK (direction IN ('above_bad', 'below_bad', 'normal_range')),
    inclusive   boolean NOT NULL DEFAULT false,  -- true — граница входит в область (>=, <=), false — строго (>, <)
    action      text    NOT NULL,          -- что делает/показывает система при срабатывании (для normal_range — что считается нормой)
    source      text    NOT NULL,          -- пункт регламента либо файл и число из журнала СМВУ, подтверждающее уставку
    CHECK (low_value IS NOT NULL OR high_value IS NOT NULL),
    CHECK (direction <> 'normal_range' OR (low_value IS NOT NULL AND high_value IS NOT NULL))
);
COMMENT ON TABLE  ref.setpoint IS 'Уставки параметров среды коллектора (приёмка НФ-56…НФ-60, Ф-30): порог, единица, направление сравнения, источник — машиночитаемо, не строка';
COMMENT ON COLUMN ref.setpoint.direction IS 'above_bad — плохо выше high_value; below_bad — плохо ниже low_value; normal_range — норма МЕЖДУ границами (обе колонки обязательны)';
COMMENT ON COLUMN ref.setpoint.inclusive IS 'Строгость сравнения: true — граница входит в область срабатывания (>=,<=), false — строго (>,<). Регламент почти everywhere строгий, кроме «1,0 % и более» (п. 24.4.10)';
COMMENT ON COLUMN ref.setpoint.source IS 'Пункт Регламента (класс Б, docs/acceptance-test.md разд. II.1) или файл журнала СМВУ с числом записей/каналов, подтверждающим уставку фактически, а не только по нормативу';

-- ============================================================================
-- ref.norm_period — нормативная периодичность ТО/ТР/КР по системам Регламента
-- ============================================================================
--
-- Источник данных — code/reglament_to_schedule.json, массив "schedule": это
-- прямая расшифровка глав 10-17, 21, 24 Регламента (ОПС, АКМ, СДУК, СКУД,
-- видео, оповещение, телевидение, информационные системы включая СМВУ, КИП,
-- контроль газовоздушной среды переносными приборами). Естественный ключ id
-- строки уже устойчивый (например 'skud-eq-to'), беру его как PRIMARY KEY —
-- отдельный суррогат и UNIQUE давали бы то же самое вторым столбцом.
--
-- periodicity_days — numeric, не integer: у переносного контроля ГВС в
-- колодце периодичность «каждый час» и заказчик посчитал её как 0.0417 суток,
-- а у контроля рядом с газовыми сетями — «2 раза в неделю» = 3.5 суток
-- (code/reglament_to_schedule.json, id gvs-kolodec и gvs-noakm-gas). Округли
-- я до integer — обе периодичности слились бы в «0» и «4», то есть исчезли
-- бы из плана-графика или сдвинулись на день.
--
-- periodicity_days бывает NULL: часть строк регламент не задаёт числом,
-- а отдаёт «по графику, утверждённому техническим руководством Общества»
-- (например id gvs-o2-co-co2 — кислород/СО/СО2 при переносном контроле,
-- или id kip-poverka — межповерочный интервал средств измерений, его
-- устанавливают органы государственной метрологической службы). Текст
-- в periodicity_text остаётся всегда — NOT NULL, это единственный источник
-- истины, когда числа нет.
CREATE TABLE ref.norm_period (
    id                text    PRIMARY KEY,     -- id строки code/reglament_to_schedule.json, например 'skud-eq-to'
    system_name       text    NOT NULL,        -- система по регламенту: «СКУД», «АКМ: АТ3-1 / АСКМ»
    equipment         text    NOT NULL,         -- узел/прибор внутри системы
    work_type         text    NOT NULL,        -- вид работы по регламенту: ТО, ТР, КР, ЭК и т.п. — термин регламента, не наш справочник видов работ (permit.permit_work_type — другое: наряды-допуски)
    periodicity_days  numeric,                 -- периодичность в сутках; NULL — регламент не даёт числа, см. periodicity_text
    periodicity_text  text    NOT NULL,        -- периодичность словами регламента, например «1 раз в 2 месяца»
    clause            text    NOT NULL,        -- пункт регламента
    note              text                     -- оговорка составителя выгрузки (неоднозначность распознавания PDF), если есть — не выдумываем точность там, где её не было в скане
);
COMMENT ON TABLE  ref.norm_period IS 'Нормативная периодичность ТО/ТР/КР по системам Регламента (приёмка НФ-66, Ф-67): план-график ППР и база для отклонения предиктивной заявки от плановой даты в днях';
COMMENT ON COLUMN ref.norm_period.periodicity_days IS 'Периодичность в сутках, numeric — среди строк есть дробные (2 раза в неделю = 3.5, ежечасно = 0.0417), integer их бы обнулил или исказил';
COMMENT ON COLUMN ref.norm_period.work_type IS 'Вид работы дословно из Регламента (ТО/ТР/КР/ЭК/поверка) — не путать с permit.permit_work_type, тем справочником нарядов-допуска на огневые/газоопасные работы';
