-- 030. Отказ в определении модели v3: словарь значений и эпизоды по нему.
--
-- ЗАЧЕМ. Модель v3 (lgbm-v3-bag-2026.09.21) обучена на метке D5: отказ — эпизод
-- длиннее часа из любого значения словаря «Неисправен», «Батарея неисправна»,
-- «Много неисправных устройств», «Не определено», инциденты склеены окном 60 минут.
-- Определение лежит в contracts/failure.v3.json. Наша проверка М-18…М-20
-- (code/check_metrics.py) до этой миграции считала только эпизоды «Неисправен»
-- из smvu.fault_episode, то есть судила модель по более узкой цели, чем та,
-- на которой её учили. Эпизодов трёх остальных значений в базе не было вовсе:
-- smvu.fault_rule (004_events.sql) их не называет, и построитель их не собирал.
--
-- ПОЧЕМУ ОТДЕЛЬНЫЕ ТАБЛИЦЫ, А НЕ СТРОКИ В smvu.fault_rule И smvu.fault_episode.
-- Ни один из пяти читателей smvu.fault_episode не фильтрует по fault_value:
-- карточка участка (backend/app/api/objects.py), веса участков
-- (028_section_weight.sql), признаки fault_30d и neighbor_fault_7d
-- (backend/app/worker/features.py), code/check_spread.py и сверка с эталоном
-- в построителе. Положи мы эпизоды модели в ту же таблицу — у всех пяти молча
-- выросли бы счётчики. Хуже того, эпизод D5 перекрывает эпизод «Неисправен»
-- того же канала по времени, и ограничение EXCLUDE таблицы отвергло бы вставку.
-- Отдельная пара таблиц не меняет ни одной строки, которую читает экран.
--
-- Построитель — backend/app/ingest/model_failure_episodes.py; его вызывает
-- и backend/app/ingest/fault_episodes.py после построения эпизодов экрана.

-- ---------------------------------------------------------------------------
-- 1. Словарь значений модели
-- ---------------------------------------------------------------------------
-- Правило не зависит от типа датчика, в отличие от smvu.fault_rule: модель
-- ставит метку по значению журнала у любого канала, включая 1 142 заглушки
-- без типа. Поэтому ключ — одно значение, а не пара (тип, значение).
CREATE TABLE smvu.model_failure_value (
    fault_value          text    PRIMARY KEY,
    -- Какая модель учится на этом значении. Сменится модель — строки
    -- перезаводятся новой миграцией вместе с contracts/failure.vN.json.
    model_version        text    NOT NULL,
    -- Код метки у ML-команды (D5). Не ключ: справочника определений у нас нет.
    definition           text    NOT NULL,
    -- Эпизод короче порога — дребезг, а не отказ. Порог в контракте один
    -- на всё определение; здесь он повторён в каждой строке, чтобы построитель
    -- соединялся по значению так же, как с smvu.fault_rule.
    min_duration_seconds integer NOT NULL CHECK (min_duration_seconds > 0)
);

COMMENT ON TABLE smvu.model_failure_value IS
    'Значения журнала, которые модель v3 считает отказом (метка D5). Источник — contracts/failure.v3.json. Экранное правило — smvu.fault_rule, эта таблица его не меняет';

