-- ---------------------------------------------------------------------------
-- 2. Эпизоды по словарю модели
-- ---------------------------------------------------------------------------
-- Форма та же, что у smvu.fault_episode (004 и 017): одинаковые колонки
-- позволяют сверять таблицы одним запросом. Плюс model_version — по ней
-- code/check_metrics.py берёт эпизоды ровно той модели, что названа в контракте.
CREATE TABLE smvu.model_failure_episode (
    episode_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id    integer     NOT NULL REFERENCES smvu.channel,
    section_id    integer     REFERENCES ref.object_xref(section_id),
    started_at    timestamptz NOT NULL,
    -- NULL — эпизод не закрыт к концу архива. Модель такой эпизод считает
    -- отказом (keep_open в src/ml/failure_defs.py), если он уже длиннее порога.
    ended_at      timestamptz,
    rows_cnt      integer     NOT NULL DEFAULT 1,
    closed_by     text,
    -- Значение первой записи эпизода; внутри эпизода значения словаря могут
    -- сменять друг друга.
    fault_value   text        NOT NULL REFERENCES smvu.model_failure_value,
    spans_outage  boolean     NOT NULL DEFAULT false,
    model_version text        NOT NULL,
    EXCLUDE USING gist (channel_id WITH =, tstzrange(started_at, ended_at) WITH &&)
);

CREATE INDEX model_failure_episode_started_idx
    ON smvu.model_failure_episode (started_at);

COMMENT ON TABLE smvu.model_failure_episode IS
    'Эпизоды отказа по словарю модели v3 (smvu.model_failure_value). Цель М-18…М-20. Экран читает smvu.fault_episode, эту таблицу — нет';
