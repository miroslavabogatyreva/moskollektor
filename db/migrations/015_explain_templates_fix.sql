-- 015. Починить три фразы объяснения. Часть задачи Q7.7 (MOS-70).
--
-- Шаблоны завела миграция 006_explain_templates.sql, править её нельзя: она
-- накатана, и app.migrate падает на расхождении sha256. Поэтому правка — новый
-- файл. Номер 015, а не 014: тот сегодня уже был заведён как 014_smvu_ref.sql
-- и снят, а переиспользовать номер с историей — значит однажды получить разговор
-- «а какой 014 ты имеешь в виду». Разрыв в нумерации накату не мешает, он берёт
-- файлы глобом и сортирует по имени.
--
-- ОТКУДА ВЗЯЛИСЬ ЭТИ ТРИ. Не из вычитки, а из боевого прогона 16.09.2026: расчёт
-- собрал факторы по всем 3 173 участкам, и на трёх самых опасных фразы прочитались
-- так, что диспетчер не поверил бы ни одной. Задача 7.6 писала шаблоны до того,
-- как появились числа, и предположила, что до этих краёв дело не дойдёт.
--
-- Правим не переписыванием фразы, а разведением случаев по строкам справочника:
-- одна строка — один случай, и выбор строки делает код по стороне отклонения.
-- Фраза, которая пытается обслужить оба случая сразу, обслуживает их одинаково
-- плохо: именно так и вышло с bad7.

-- ---------------------------------------------------------------------------
-- 1. bad7: у признака не было сторон, и низкое значение получало фразу про высокое
-- ---------------------------------------------------------------------------
-- Было: «За последние 7 суток по всему коллектору — {value} записей «Неисправен»,
-- это больше, чем обычно» — без вариантов .up/.down.
-- В прогоне 7 участок 2477 получил bad7 = 0 с отклонением ВНИЗ, и фраза сказала
-- «0.0 записей «Неисправен», это больше, чем обычно». Диспетчер читает
-- противоречие в одной строке и перестаёт верить остальным двум.
UPDATE ref.explain_template SET feature_code = 'bad7.up' WHERE feature_code = 'bad7';

INSERT INTO ref.explain_template (feature_code, phrase_ru) VALUES
    ('bad7.down',
     'По всему коллектору за 7 суток — {value} записей «Неисправен», это меньше обычного.');
-- Строка .down заведена не для того, чтобы её показывать: тихий коллектор —
-- хорошая новость, а объяснять ею высокий риск нельзя, и код такие отклонения
-- отбрасывает. Она нужна, чтобы отбор шёл по данным, а не по наличию строки:
-- отсутствие фразы означало бы «признак необъясним», а он объясним, просто
-- в эту сторону не тревожен.

-- ---------------------------------------------------------------------------
-- 2. chatter_7d: ноль записей объявлялся дребезгом
-- ---------------------------------------------------------------------------
-- Было: «У этого датчика за 7 суток {value} записей «Неисправен» — показания
-- дребезжат, значение прыгает туда и обратно». При {value} = 0 это ложь дважды:
-- записей нет вовсе, и дребезга нет тем более.
UPDATE ref.explain_template SET feature_code = 'chatter_7d.up' WHERE feature_code = 'chatter_7d';

INSERT INTO ref.explain_template (feature_code, phrase_ru) VALUES
    ('chatter_7d.down',
     'Записей «Неисправен» у этого датчика за 7 суток нет.');

-- ---------------------------------------------------------------------------
-- 3. rate_ratio_*: нулевое отношение давало «в 0,0 раза реже»
-- ---------------------------------------------------------------------------
-- Q7.6 предсказала этот край в шапке своей миграции: «при нулевом отношении это
-- деление на ноль, а при 0,003 выходит „в 333 раза реже"». Теперь он посчитан:
-- rate_ratio_year = 0 у 2 681 участка из 3 173, то есть у большинства парка,
-- и «писал в 0.0 раза реже» — это не край, а обычный случай.
--
-- Нулевое отношение означает ровно одно: за неделю не было ни одной записи.
-- Так и пишем, без арифметики. Код выбирает эту строку, когда значение равно нулю.
INSERT INTO ref.explain_template (feature_code, phrase_ru) VALUES
    ('rate_ratio_7d.zero',
     'За последнюю неделю датчик не написал ни одной строки, хотя за предыдущие два месяца писал регулярно. Замолчавший датчик об аварии не сообщит.'),
    ('rate_ratio_year.zero',
     'За последнюю неделю датчик не написал ни одной строки, хотя за год у него набирается устойчивая норма. Замолчавший датчик об аварии не сообщит.');

-- Второй край из той же шапки — «в 333 раза реже» при отношении 0,003 — фразой
-- не лечится, он лечится тем, КАК подставляется число: backend/app/domain/explain.py
-- показывает отношение меньше единицы как «в N раз реже», считая N = 1/отношение
-- и округляя до целого, а не печатает 0,003. Здесь для этого ничего не нужно.

