-- 025_forecast_current_as_of.sql — одно имя computed_at перестаёт значить разное.
--
-- ЗАЧЕМ. До 21.09.2026 колонка pred.forecast_current.computed_at хранила срез
-- данных: backend/app/worker/publish.py кладёт в неё `as_of` прогона, то есть
-- момент, на который посчитаны признаки. При этом GET /api/forecasts отдаёт под
-- тем же именем `computed_at` совсем другую величину — `pred.run.started_at`,
-- время работы расчёта. Клиент, читающий оба метода, получал две даты с одним
-- именем и сравнивал несравнимое.
--
-- ПОЧЕМУ ЭТО СТАЛО ВИДНО ИМЕННО СЕЙЧАС. До задачи MOS-142 расчёт брал срез по
-- текущей дате (`as_of = datetime.now()`), и обе даты у свежего прогона
-- совпадали с точностью до долей секунды: на стенде 21.09.2026 прогон 147 дал
-- as_of 06:37:35.905103 и started_at 06:37:35.905229, разница 124 микросекунды.
-- После MOS-142 расчёт берёт срез по краю выгрузки — 2026-06-30 20:59:59, — и те
-- же две даты разъезжаются на 83 суток. Ошибка, которую раньше было не отличить
-- от исправной работы, становится заметной на экране.
--
-- ЧТО ДЕЛАЕМ. Колонка называется `as_of` — тем же словом, что и `pred.run.as_of`,
-- откуда её значение и берётся. Имя `computed_at` остаётся ровно за одной
-- величиной — временем работы расчёта (`pred.run.started_at`), и в ответах API
-- встречается только в этом смысле.
--
-- ПОЧЕМУ ПЕРЕИМЕНОВАНИЕ, А НЕ ВТОРАЯ КОЛОНКА. Второе имя рядом со старым
-- оставило бы старое читаемым: клиент, который и сегодня берёт `computed_at`,
-- продолжил бы получать дату — только теперь не ту, что раньше, и молча.
-- Переименование ломает такого клиента громко, при первом же запросе.
--
-- ВЫКЛАДКА ИДЁТ С ОКНОМ В НЕСКОЛЬКО СЕКУНД, И ЭТО РЕШЕНИЕ, А НЕ НЕДОСМОТР.
-- Между `migrate` и пересозданием контейнеров старый образ API просит колонку
-- `computed_at`, которой уже нет, и отвечает 500 на GET /api/risks. Закрываем это
-- порядком: `migrate`, сразу следом пересоздание `api` и `worker`.
--
-- Цена другой стороны. Бесшовно переименование делается двумя способами: совместимым
-- представлением поверх таблицы или двухшаговой миграцией — добавить колонку, писать
-- в обе, выложить код, удалить старую следующей миграцией. Оба дают вдвое больше кода
-- и вдвое больше мест, где можно ошибиться: пока живут две колонки, любая запись мимо
-- одной из них расходится молча — ровно тот дефект, от которого эта миграция и лечит.
-- Цена нашей стороны — несколько секунд ошибок на стенде, где сегодня работают только
-- наши же проверки. Решение приняли 21.09.2026 с оркестратором. Появятся живые
-- пользователи — способ меняется на двухшаговый, и вот тогда он стоит своих денег.
--
-- НОМЕР 025, А НЕ 024. Номер берётся из таблицы «Миграции базы» в docs/plan.md,
-- а не «следующим свободным в каталоге»: 024 там уже занят задачей Q6.9
-- (`024_ack.sql`, квитирование заявок), файл которой ещё не написан.
--
-- ДАННЫЕ НЕ ТРОГАЕМ. RENAME COLUMN не переписывает таблицу и не трогает
-- 3 173 строки: Постгрес меняет только имя в каталоге, indexes и FK остаются.

ALTER TABLE pred.forecast_current RENAME COLUMN computed_at TO as_of;

COMMENT ON COLUMN pred.forecast_current.as_of IS
    'Срез данных: момент, на который посчитаны признаки (копия pred.run.as_of). Не время расчёта';

COMMENT ON COLUMN pred.run.as_of IS
    'Срез данных: до какого момента брались показания. После MOS-142 — край выгрузки, а не now()';

COMMENT ON COLUMN pred.run.started_at IS
    'Время работы расчёта: когда прогон начался. В ответах API едет под именем computed_at';
