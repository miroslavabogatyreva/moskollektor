-- 031. Где стоит канал: на участке коллектора, в охранной зоне, в здании или неизвестно.
--
-- ЧТО БЫЛО. У 765 каналов из 11 485 (6,7 %) в названии нет пикета «ПК<n>», и до
-- 21.09.2026 загрузчик ставил им NULL сразу в трёх колонках: picket, section_id
-- и collector. Первые два NULL правильные — участка у канала нет. Третий — потеря:
-- коллектор даёт префикс тега ("16-1.1.4096.6." -> 16), и тег есть у всех каналов.
-- Хуже того, NULL в section_id один на все случаи: по нему не отличить охранную
-- зону от датчика температуры в диспетчерской и от канала, про который мы просто
-- ничего не знаем.
--
-- ЧТО СТАЛО. Коллектор загрузчик пишет из тега всегда (backend/app/ingest/smvu_csv.py),
-- а место канала — в новую колонку location_kind. Правила по порядку, первое
-- сработавшее побеждает (tag_to_section.location_kind):
--   section  — в названии есть пикет: "КД АВ ПК106 ур.3", и один без «ПК» — "ОД АВ 185+5";
--   zone     — в теге адрес .4096. или групповой узел -g<n>. ("884-g1."), либо
--              название начинается с «Охранная зона» / «[Охранная зона]»;
--   building — ид_объект канала ведёт на controlHouse в smvu.object_tree:
--              "Темп. диспетчерская ДП", "КД вход в ДП";
--   unknown  — ничего из этого: "ИПР ДП Зап. выход" на guardObject.
-- На выгрузке от 15.09.2026: section 10 721, zone 44, building 717, unknown 3.
--
-- ПОЧЕМУ DEFAULT 'unknown' И NOT NULL. Каналы-заглушки (1 143 штуки, их нет
-- в справочнике заказчика) заводит загрузчик журнала без тега и названия, и про их
-- место мы честно не знаем ничего. На уже залитой базе все строки после наката тоже
-- получат 'unknown': правила живут в Python, вторую их копию на SQL мы не пишем.
-- Настоящие значения проставляет повторный запуск загрузчика с --channels —
-- справочник он не перезаливает, а дозаполняет collector и location_kind
-- (backend/app/ingest/channel_place.py).
--
-- ПОРЯДОК С 030. Файл заводит одну новую колонку smvu.channel.location_kind и больше
-- ничего не читает и не меняет, поэтому накатывается и после 030, и на базу без неё.
-- Проверено 21.09.2026 на пустой базе без 030 (она живёт в другой ветке): накат
-- 001…028, заливка справочников, накат 029 и 031; и отдельно 031 поверх 001…028.

ALTER TABLE smvu.channel
    ADD COLUMN location_kind text NOT NULL DEFAULT 'unknown'
        CONSTRAINT channel_location_kind_check
        CHECK (location_kind IN ('section', 'zone', 'building', 'unknown'));

COMMENT ON COLUMN smvu.channel.location_kind IS
    'Где стоит канал: section — участок коллектора (есть пикет), zone — охранная зона, '
    'building — здание диспетчерской (controlHouse), unknown — не определено. '
    'Правила — backend/app/ingest/tag_to_section.py, location_kind.';
