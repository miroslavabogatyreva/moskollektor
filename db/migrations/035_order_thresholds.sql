-- 035. Пороги автозаявки и отбор худших участков коллектора. Задача 3.20, MOS-166.
--
-- ЗАЧЕМ. С переходом worker на модель v3 правило заявки перестаёт срабатывать вовсе.
-- Пороги 0,97 / 0,98 / 0,99 (backend/app/domain/order_rules.py) подобраны под заглушку,
-- которая давала участкам разные числа вплоть до 0,9991. Модель v3 даёт ОДНО число
-- на коллектор, и её максимум по парку — 0,8676. Замер на стенде 22.09.2026, прогон 487:
-- выше 0,97 — ноль участков из 3 173, то есть ни одной заявки никогда.
--
-- ОПУСТИТЬ ПОРОГ ДО МОДЕЛЬНОГО 0,63 НЕЛЬЗЯ ПРОСТО ТАК. Тем же замером: выше 0,63
-- оказываются 2 167 участков из 3 173. Это все участки шести коллекторов разом —
-- модель не различает участки внутри коллектора, и порог либо пропускает всех,
-- либо никого. Диспетчер получит список, который невозможно отработать.
--
-- ЧТО ДЕЛАЕМ. Две настройки вместо зашитых констант:
--
--   order_threshold_a/b/c — пороги по классу критичности. Значения по умолчанию
--   те же, что были в коде, поэтому поведение прежнего пути не меняется ни на строку.
--
--   order_top_sections_per_object — сколько худших участков коллектора получают
--   заявку, когда коллектор прошёл порог. Ноль — правило выключено, заявка идёт
--   каждому участку выше порога, как было. Больше нуля — из участков коллектора
--   берутся N с наибольшим весом в pred.section_weight, то есть с самой тяжёлой
--   историей отказов.
--
-- ПОЧЕМУ ВЕС БЕРЁТСЯ ДЛЯ ПОРЯДКА, А НЕ ДЛЯ ДЕЛЕНИЯ ВЕРОЯТНОСТИ. Разнос из MOS-150
-- делит число коллектора между участками, и при p = 0,87 максимум по парку падает
-- до 0,076 — порог становится недостижим, а карточка показывает «риск 2 %» там,
-- где модель говорит 87 %. Здесь вес отвечает на другой вопрос: не «какова
-- вероятность участка», а «с какого участка коллектора начинать обход». Ответ
-- на второй вопрос весом обоснован, на первый — нет.

INSERT INTO ref.app_setting (key, value, unit) VALUES
    ('order_threshold_a',             0.97, NULL),
    ('order_threshold_b',             0.98, NULL),
    ('order_threshold_c',             0.99, NULL),
    -- Ноль — правило выключено, поведение прежнее. Включаем вместе с переводом
    -- worker на выдачу модели, одной строкой из админки.
    ('order_top_sections_per_object',    0, 'участков');

COMMENT ON TABLE ref.app_setting IS
    'Настройки, которые администратор правит без пересборки образа. Пороги автозаявки '
    'и число худших участков коллектора добавлены миграцией 035 (MOS-166)';

-- Самопроверка накатом: четыре строки легли, и пороги остались теми же числами,
-- что стоят в коде. Разошлись — значит правило заявки поехало молча.
DO $$
DECLARE легло int; а numeric;
BEGIN
  SELECT count(*) INTO легло FROM ref.app_setting
   WHERE key IN ('order_threshold_a', 'order_threshold_b', 'order_threshold_c',
                 'order_top_sections_per_object');
  ASSERT легло = 4, format('настроек заявки в справочнике %s, а вставили 4', легло);

  SELECT value INTO а FROM ref.app_setting WHERE key = 'order_threshold_a';
  ASSERT а = 0.97,
    format('порог класса A стал %s вместо 0.97 — правило заявки изменилось молча', а);

  RAISE NOTICE '035: настроек заявки %, пороги прежние, отбор худших выключен', легло;
END $$;
