-- 033. Временный мост от ключа модели v3 к нашему ключу коллектора. Задача 3.20, MOS-166.
--
-- ЭТО НЕ ОТМЕНА РЕШЕНИЯ ИЗ 029. Шапка 029_ml_readonly.sql говорит: «перевода
-- „префикс -> коллектор" нет и быть не может… чинится только тем, что Николай берёт
-- ключ там же, где берём мы». Это по-прежнему верно, и правильное решение остаётся
-- за ML-командой — она переводит ключ после гейта 22.09.2026. До тех пор `score.json`
-- приходит с ключом `pfx`, и без моста worker не запускается вовсе, а М-01 стоит.
--
-- Разница между «починкой» и «мостом» в том, что мост называет свою цену числом.
--
-- ЧТО ТЕРЯЕМ, ЗАМЕР 22.09.2026 НА СТЕНДЕ. Префиксов 32, коллекторов 16, пар
-- «префикс — коллектор» 34: два префикса ведут к разным коллекторам. Мост относит
-- префикс туда, где у него больше каналов, и меньшинство уезжает не туда:
--
--   163 -> коллектор 4356 (44 канала), теряет 1 канал коллектора 15
--   798 -> коллектор 12   (139 каналов), теряет 25 каналов коллектора 6
--
-- Итого **26 каналов из 11 485, 0,23 %**. Это не потеря прогноза: все 16 коллекторов
-- прогноз получают, потому что у каждого есть свои префиксы. Это потеря точности —
-- отказы этих 26 каналов модель посчитала в соседнем коллекторе.
--
-- ПОЧЕМУ БОЛЬШИНСТВО, А НЕ ОБА. Отдать вероятность префикса обоим коллекторам
-- значит поднять риск коллектора 15 из-за одного канала из 1 040 — предупреждение
-- без причины хуже, чем его отсутствие: диспетчер поедет не туда.
--
-- ПОЧЕМУ ПРЕДСТАВЛЕНИЕ, А НЕ ТАБЛИЦА. Ровно по той же причине, что и в 029: таблица
-- устареет молча в тот день, когда заказчик пришлёт справочник заново, а представление
-- устареть не может — оно и есть запрос. Придёт ключ от ML-команды — представление
-- перестанут читать, и удалить его будет одной строкой.

CREATE VIEW pred.pfx_collector AS
WITH пары AS (
    SELECT split_part(tag, '-', 1) AS pfx, collector_id, count(*) AS каналов
      FROM smvu.channel_collector
     GROUP BY 1, 2
)
SELECT DISTINCT ON (pfx)
       pfx,
       collector_id,
       каналов                                   AS channels_here,
       (SELECT sum(в.каналов) FROM пары в
         WHERE в.pfx = п.pfx AND в.collector_id <> п.collector_id)::int AS channels_lost
  FROM пары п
 ORDER BY pfx, каналов DESC;

COMMENT ON VIEW pred.pfx_collector IS
    'Временный мост «префикс тега -> коллектор» для ключа score.json модели v3 (MOS-166). '
    'Префикс относится к коллектору, где у него больше каналов; channels_lost — сколько '
    'каналов префикса остались в другом коллекторе. Настоящий ключ придёт от ML-команды, '
    'тогда представление станет ненужным';

-- Самопроверка накатом. На пустой базе справочника ещё нет — пропускаем вслух,
-- ровно как в 029 (задача 1.16): накат должен доходить до конца на чистой установке.
DO $$
DECLARE строк int; коллекторов int; потеряно int;
BEGIN
  SELECT count(*), count(DISTINCT collector_id), coalesce(sum(channels_lost), 0)
    INTO строк, коллекторов, потеряно FROM pred.pfx_collector;

  IF строк = 0 THEN
    RAISE NOTICE '033: справочник каналов пуст — три проверки пропущены; '
                 'повторите накат после заливки справочников';
    RETURN;
  END IF;

  -- Каждый префикс ровно один раз: DISTINCT ON обязан оставить одну строку.
  ASSERT строк = (SELECT count(DISTINCT split_part(tag, '-', 1)) FROM smvu.channel_collector),
    format('префиксов в мосте %s, а в справочнике другое число', строк);

  -- Ни один коллектор не остался без прогноза — иначе мост не годится вовсе.
  ASSERT коллекторов = (SELECT count(*) FROM smvu.object_tree WHERE level = 2),
    format('прогноз получат %s коллекторов из %s — мост теряет коллектор целиком',
           коллекторов, (SELECT count(*) FROM smvu.object_tree WHERE level = 2));

  -- Цена моста названа в шапке числом 26. Выросла втрое — справочник изменился
  -- так, что мост пора пересматривать, а не молча возить дальше.
  ASSERT потеряно <= 80,
    format('мост уводит %s каналов не в свой коллектор, в замере 22.09.2026 было 26 — '
           'справочник изменился, решение пора пересматривать', потеряно);

  RAISE NOTICE '033: мост готов, префиксов %, коллекторов %, каналов не в свой коллектор %',
               строк, коллекторов, потеряно;
END $$;
