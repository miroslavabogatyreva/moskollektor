-- act_share_7d: доля каналов коллектора, писавших хоть что-то за неделю.
('act_share_7d.up',
 'Из каналов коллектора за последнюю неделю писали {value}.');

-- Самопроверка накатом: двенадцать фраз легли, и ни в одной нет слова после {value}.
-- Второе — ловушка миграции 016: слово, стоящее и в шаблоне, и в коде, удваивается
-- в тексте, который читает диспетчер.
DO $$
DECLARE легло int; со_словом int;
BEGIN
  SELECT count(*) INTO легло FROM ref.explain_template
   WHERE feature_code LIKE 'ev\_%' OR feature_code LIKE 'n\_%' OR feature_code LIKE 'act\_%';
  ASSERT легло = 12, format('фраз v3 в справочнике %s, а вставили 12', легло);

  -- Ловим не любое слово после {value} — «{value} со значением «Неисправен»» это
  -- законное продолжение фразы, — а именно ЕДИНИЦУ, которую подставляет _число()
  -- в backend/app/domain/explain.py. Миграция 016 чинила «молчат 110 суток суток
  -- подряд»: удваивается только слово-единица, и проверять надо его.
  SELECT count(*) INTO со_словом FROM ref.explain_template
   WHERE phrase_ru ~ '\{value\}\s+(суток|сутки|записей|записи|запись|каналов|канала|канал|аварий|аварии|авария|раз|раза|%)\M';
  ASSERT со_словом = 0,
    format('в %s шаблонах после {value} стоит единица измерения — код подставит '
           'свою, и она удвоится, как «110 суток суток» в миграции 016', со_словом);

  RAISE NOTICE '034: фраз для признаков v3 %, слово после {value} нигде не стоит', легло;
END $$;
