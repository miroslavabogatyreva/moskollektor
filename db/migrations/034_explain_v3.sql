-- 034. Объяснение риска для признаков модели v3. Задача 3.20, MOS-166.
--
-- ЗАЧЕМ. До 22.09.2026 экран объяснял риск девятью признаками `feat.v1`, и на них
-- написаны 15 фраз (миграции 006 и 016). Модель v3 считает сорок два других признака,
-- и пересечение имён с нашими девятью — **ноль**. В день перехода worker на выдачу
-- модели диспетчер увидел бы голое число вероятности, а строка приёмки Ф-73 требует,
-- чтобы система называла, какое состояние вызвало рекомендацию.
--
-- ПОЧЕМУ ДВЕНАДЦАТЬ ФРАЗ, А НЕ СОРОК ДВЕ. Модель сама отдаёт вклады признаков
-- (`POST /predict`, поле `factors`), и в тройку главных попадают далеко не все.
-- Замер 22.09.2026 на живом `score.json` по всем 32 префиксам: в тройку вошли
-- **12 признаков из 42**, и первый — `ev_h_since_prev` — все 32 раза. Остальные
-- тридцать за весь парк не всплыли ни разу, и фраза для них была бы работой впрок.
--
-- ПОЧЕМУ ТОЛЬКО СТОРОНА `.up`. У вклада есть знак: положительный поднял риск,
-- отрицательный снизил. Диспетчер спрашивает «почему опасно», а не «почему
-- спокойно», поэтому фразы написаны только для признаков, поднявших риск.
-- Это решение того же рода, что и ОПАСНАЯ_СТОРОНА в backend/app/domain/explain.py,
-- и живёт оно там же — здесь только текст.
--
-- ФРАЗА НАЗЫВАЕТ ФАКТ, А НЕ ТОЛКОВАНИЕ. Модель нелинейна: один и тот же признак
-- поднимает риск и большим значением, и малым, в зависимости от остального. Поэтому
-- ни одна фраза ниже не говорит «слишком часто» или «подозрительно мало» — она
-- называет измеренное число и то, что оно значит по определению.
--
-- СЛОВО К ЧИСЛУ СОБИРАЕТ КОД, НЕ ШАБЛОН. В шаблоне только {value}; «3 канала»,
-- «12 записей», «84 суток» составляет _число() в explain.py. Миграция 016 уже
-- убирала слово из шаблонов после того, как настоящий прогон дал «молчат 110 суток
-- суток подряд».
--
-- ОПРЕДЕЛЕНИЯ ВЗЯТЫ ИЗ КОДА МОДЕЛИ, а не из имён признаков: `autoresearch_v3/train.py`
-- строки 84-115 (событийные) и `src/ml/features_pfx.py` строки 45-60 (суточные),
-- прочитаны внутри образа `moskollektor/ml-score:lgbm-v3-bag-2026.09.21b` 22.09.2026.

INSERT INTO ref.explain_template (feature_code, phrase_ru) VALUES

-- ev_h_since_prev: часы от момента решения до ПОЗАПРОШЛОГО инцидента коллектора
-- (train.py:103, `(t - prev) / HOUR`). Не до последнего — до того, что был перед ним.
('ev_h_since_prev.up',
 'С позапрошлой аварии на этом коллекторе прошло {value}. Модель смотрит на ритм аварий, а не только на последнюю.'),

-- ev_gap_last: промежуток между последним и позапрошлым инцидентом (train.py:104).
('ev_gap_last.up',
 'Между двумя последними авариями на этом коллекторе прошло {value}.'),

-- ev_relapse_rate: доля прошлых инцидентов коллектора, за которыми в пределах
-- горизонта (720 ч) шёл следующий; сглажена как (hit+1)/(n+2) (train.py:110).
('ev_relapse_rate.up',
 'После {value} прошлых аварий этого коллектора в течение месяца приходила следующая.'),

-- n_dying_ch: каналы, у которых недельная запись в пересчёте на год заметно ниже
-- годовой — канал замолкает (features_pfx.py:57).
('n_dying_ch.up',
 'На коллекторе {value}, которые за последнюю неделю писали заметно реже, чем за год до этого: они замолкают.'),

-- ev_open_ch: каналы коллектора с незакрытым отказом на момент расчёта.
('ev_open_ch.up',
 'Сейчас на коллекторе {value} с незакрытым отказом.'),

-- ev_inc_72h / ev_inc_168h: инциденты коллектора за трое суток и за неделю.
('ev_inc_72h.up',
 'За последние трое суток на этом коллекторе {value}.'),
('ev_inc_168h.up',
 'За последнюю неделю на этом коллекторе {value}.'),

-- n_alarm_7d / n_alarm_28d: записи с поднятым флагом «тревожное» по коллектору.
-- Флаг ставит настройка прибора, а не человек, поэтому фраза называет его флагом,
