-- n_rows_28d: сколько всего строк прислал коллектор за 28 суток.
('n_rows_28d.up',
 'За 28 суток коллектор прислал {value} — модель сравнивает этот объём с обычным для него.'),

-- n_undef_28d: записи со значением «Неопределен» за 28 суток. В метку отказа
-- это значение не входит (contracts/failure.v3.json), но модель видит его признаком.
('n_undef_28d.up',
