-- 018. Связь канала с деревом объектов диспетчера. Закрывает ОВ-46.
--
-- ЧТО ПРОИЗОШЛО. 16.09.2026 заказчик прислал справочник каналов заново, с шестой
-- колонкой `ид_объект`: dataset/справочник_каналов_датчиков.csv, выгрузка от 15.09.2026.
-- Колонка заполнена у всех 11 485 каналов, пустых нет ни одного, и все 78 различных
-- значений находятся в smvu.object_tree. Это ровно то, о чём мы спрашивали в ОВ-46,
-- и до этого дня связи между каналом и деревом не существовало: комментарий
-- в 004_events.sql («связи заказчик не прислал») описывает выгрузку от 09.09.2026
-- и с 16.09.2026 верен только для неё.
--
-- ПОЧЕМУ КОЛОНКА В smvu.channel, А НЕ СТРОКА В ref.object_xref. Заказчик даёт объект
-- на канал, а не на участок, и одно из другого не выводится: из 3 173 участков
-- (коллектор, пикет) у 564 — это 17,8 % — каналы висят на разных объектах третьего
-- уровня. Пример: участок «15:28» держит 4 канала объекта Фита, 19 каналов
-- ДП объекта Бета и 2 канала шкафа ОПС объекта Бета. Положив object_id в object_xref,
-- мы бы выбрали один объект из трёх и потеряли остальные два.
--
-- ЧТО ЭТО ЗА ОБЪЕКТЫ. Каналы висят только на третьем уровне дерева — 78 узлов
-- (guardObject 29, controlHouse 49): ПС, ОС, ДУ, ДП, шкафы ОПС, охранные зоны.
-- Второй уровень, 16 узлов с греческими именами, — это коллекторы, и добираться
-- до них надо через parent_id. Первый уровень — один «Район по эксплуатации».
-- Каналов нет у 17 объектов: у корня, у всех 16 коллекторов второго уровня.
--
-- ПОЧЕМУ ЭТО ВАЖНЕЕ, ЧЕМ КАЖЕТСЯ. Наша прежняя гипотеза «префикс тега = объект»
-- (analysis/prefix_to_object.md, 32 строки) держалась на семи угаданных строках
-- и не сходится с фактом дважды. Первое: префиксов 32, а объектов-коллекторов 16 —
-- у 11 коллекторов из 16 по нескольку префиксов. Второе: два префикса ведут
-- к РАЗНЫМ коллекторам. Префикс 798 отдаёт 139 каналов объекту Зита и 25 каналов
-- ДП объекта Бета («ФАО3 Андр наб», «ГРО11 ПК81-70 (каб.) Гагар-2»); префикс 163
-- отдаёт 44 канала ПС объекта Ро и 1 канал («Темп. ПК790») объекту Каппа.
-- Если бы мы проставили объект по префиксу большинством голосов, 26 каналов
-- из 11 485 получили бы чужой объект, и найти это было бы нечем.
--
-- ЧТО НЕ МЕНЯЕТСЯ. section_id остаётся единицей расчёта признаков: участок
-- (коллектор, пикет) по-прежнему собирается из тега и названия, привязка та же
-- 10 720 каналов из 11 485 (93,3 %), 3 173 участка на 30 коллекторах. Новая колонка
-- лежит рядом и отвечает на другой вопрос — под каким узлом дерева диспетчер
-- ищет этот канал в своём интерфейсе.
--
-- ЧЕГО ЭТА КОЛОНКА НЕ ДАЁТ. Координат. В справочнике объектов пять колонок
-- (ид_объект, иерархия_уровень, родитель, вид_объекта, диспетчерское_название_объекта),
-- широты и долготы нет ни одной, и пикеты в названиях стоят у 3 объектов из 95.
-- Вопрос ОВ-53 «как показать объекты на местности» остаётся открытым, схема
-- коллектора по оси пикетов остаётся тем, что мы рисуем.

ALTER TABLE smvu.channel
    ADD COLUMN object_id integer REFERENCES smvu.object_tree(object_id) ON DELETE SET NULL;

COMMENT ON COLUMN smvu.channel.object_id IS
    'ид_объект из справочника каналов (выгрузка от 15.09.2026): узел дерева диспетчера, '
    'третий уровень. NULL у 1 142 заглушек — их в справочнике заказчика нет.';

-- Индекс нужен экрану «Карта объектов»: диспетчер выбирает узел дерева и ждёт его
-- каналы. Без индекса это seq scan по 12 627 строкам на каждый клик.
CREATE INDEX channel_object_idx ON smvu.channel (object_id) WHERE is_active;
