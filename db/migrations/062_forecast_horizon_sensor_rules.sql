-- 062. Горизонт прогноза в настройках — 24 ч, как у правил датчика.
--
-- ЗАЧЕМ. С 28.09.2026 прогноз участков считают правила датчика
-- (backend/app/worker/run_sensors.py), и горизонт у них один — 24 ч, из
-- backend/app/domain/sensor_rules.json: балл — частота отказа именно за 24 ч.
-- Worker берёт горизонт оттуда и ref.app_setting.forecast_horizon_h не читает.
-- В настройке с миграции 037 стояло 720 — под модель коллектора, которой в прогнозе
-- больше нет, — и экран «Настройки» показывал бы администратору горизонт, которого
-- расчёт не использует.
--
-- На стенде значение уже 24 — его поставили руками раньше (проверено 28.09.2026
-- прогоном 062 в BEGIN…ROLLBACK на схеме стенда: UPDATE 1, после отката читается 24).
-- 720 остаётся у свежей установки после 037, её миграция и чинит; повторный
-- накат безвреден.

UPDATE ref.app_setting SET value = 24 WHERE key = 'forecast_horizon_h';

DO $$
BEGIN
  ASSERT (SELECT value FROM ref.app_setting WHERE key = 'forecast_horizon_h') = 24,
    'горизонт в настройках не 24 ч';
END $$;
