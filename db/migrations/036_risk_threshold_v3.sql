-- 036. Порог высокого риска под модель v3. Задача 5.25, MOS-106, строка приёмки М-05.
--
-- ЗАЧЕМ. Порог 0,97 недостижим по построению. Модель v3 даёт по парку максимум
-- 0,8676, а класс `high` поднимается при `p >= порог + risk_class_hysteresis`
-- (backend/app/worker/publish.py, класс_риска), то есть требует 0,99. Замер
-- на стенде 22.09.2026: участков с классом `high` — ноль из 3 173, все `normal`.
-- Схема коллектора при этом одноцветна, и строка приёмки М-05 («уровень риска
-- виден на самой карте, а не только в списке») не закрывается ничем.
--
-- ЭТО ДОДЕЛКА, А НЕ НОВОЕ РЕШЕНИЕ. Пороги автозаявки под ту же модель опустили
-- вчера миграцией 035 (MOS-166): 0,97/0,98/0,99 давали ноль заявок навсегда.
-- Порог риска остался от заглушки и уехал вместе с ней.
--
-- ПОЧЕМУ 0,80, А НЕ 0,85 И НЕ 0,75. Число назвала Слава 22.09.2026; замер под него
-- такой. Вероятностей у модели всего 16 разных на 3 173 участка, и они стоят
-- сгустками:
--     0,867559 — 303 участка   ← верхняя группа
--     0,773631 — 267
--     0,766229 — 400
--     0,735259 — 521
-- При 0,80 граница проходит по ПУСТОМУ МЕСТУ: между 0,773631 и 0,867559 зазор
-- 0,094, и значений там нет ни одного. При 0,75 граница попала бы в щель
-- 0,0074 между 0,766229 и 0,773631 — сдвиг модели на сотую перекинул бы через
-- неё 400 участков разом. При 0,85 порог снова недостижим: подъём шёл бы
-- с 0,87 при максимуме 0,8676, то есть `high` опять ноль.
--
-- ГИСТЕРЕЗИС ЗДЕСЬ НИ НА ЧТО НЕ ВЛИЯЕТ, и это довод в пользу 0,80: между 0,80
-- и 0,82 у модели нет ни одного значения, значит результат одинаков с мёртвой
-- зоной и без неё. У порога, попавшего в сгусток, так не бывает.
--
-- ЧЕГО ЭТА МИГРАЦИЯ НЕ ДЕЛАЕТ. Она не трогает `risk_class_hysteresis` (0,02)
-- и `risk_class_hold_min` (10 минут). Второе означает, что после наката класс
-- на экране сменится не раньше чем через 10 минут и только на следующем прогоне
-- (они идут раз в 4 минуты) — до 14 минут экран честно показывает прежнее.
-- Это удержание от дребезга, а не запаздывание правки.

UPDATE ref.app_setting
   SET value = 0.80, changed_by = NULL, changed_at = now()
 WHERE key = 'risk_threshold_high';

-- Самопроверка накатом. Первое условие проверяет значение, второе — смысл:
-- порог обязан быть ДОСТИЖИМ на тех числах, которые модель отдаёт сегодня.
-- Порог, который никто не может перешагнуть, проходит любую проверку «значение
-- записалось» и при этом не красит на карте ни одного участка.
DO $$
DECLARE порог numeric; гистерезис numeric; максимум real; высоких int; всего int;
BEGIN
  SELECT value INTO порог FROM ref.app_setting WHERE key = 'risk_threshold_high';
  ASSERT порог = 0.80, format('порог высокого риска стал %s вместо 0.80', порог);

  SELECT value INTO гистерезис FROM ref.app_setting WHERE key = 'risk_class_hysteresis';
  SELECT count(*), max(probability) INTO всего, максимум FROM pred.forecast_current;

  IF всего = 0 THEN
    -- Накат с нуля: прогонов ещё не было, проверять достижимость не на чем.
    RAISE NOTICE '036: порог 0.80 записан; pred.forecast_current пуста, достижимость проверит первый прогон';
  ELSE
    SELECT count(*) INTO высоких FROM pred.forecast_current
     WHERE probability >= порог + COALESCE(гистерезис, 0);
    ASSERT высоких > 0, format(
      'порог %s при гистерезисе %s недостижим: максимум модели %s, участков выше порога 0 из %s — '
      'карта останется одноцветной, ровно как до этой миграции',
      порог, гистерезис, максимум, всего);
    RAISE NOTICE '036: порог 0.80, гистерезис %, подъём с %; выше порога % участков из % (максимум модели %)',
      гистерезис, порог + COALESCE(гистерезис, 0), высоких, всего, максимум;
  END IF;
END $$;
