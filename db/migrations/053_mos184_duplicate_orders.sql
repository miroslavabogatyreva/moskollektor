-- MOS-184: удаляем автозаявки-дубли, которые завелись до исправления 050.
--
-- 22.09.2026 миграция 038 пересчитала вес участков, тройка худших участков
-- у шести предупреждений сменилась, и прогоны завели на те же предупреждения
-- ещё 11 заявок: 44 вместо 33, у предупреждений 1051, 15, 257, 418, 847, 915
-- по 4–6 при лимите 3. Решение Мирославы 27.09.2026 — удалить.
--
-- Предупреждение — ключ заявки без последнего поля: warn:<pfx>:<открытие>,
-- так же группирует code/check_orders.py (М-10). Оставляем три заявки
-- с наименьшим id: их завёл первый прогон, увидевший открытие, по весам
-- на тот момент. Остальные удаляем вместе с заказами; операции заказа
-- и позиции заявки уходят каскадом. Если на лишнюю заявку сослались
-- замена узла, монтаж или ресурс оборудования, DELETE упадёт и откатит
-- всю миграцию — такую заявку руками не трогали бы вслепую.
--
-- В пустой базе (свежая установка) удалять нечего, миграция ничего не делает.
DO $$
DECLARE
    лишние bigint[];
    заказов int;
BEGIN
    SELECT coalesce(array_agg(id), '{}') INTO лишние
    FROM (
        SELECT id, row_number() OVER (
                   PARTITION BY regexp_replace(source_key, ':[^:]*$', '')
                   ORDER BY id) AS n
        FROM maint.notification
        WHERE source_system = 'forecast' AND source_key LIKE 'warn:%'
    ) t
    WHERE n > 3;

    -- На стенде 22.09 их было 11. Сотни значили бы, что правило понято
    -- неверно, — тогда лучше уронить выкладку, чем удалить лишнее.
    ASSERT cardinality(лишние) <= 50,
        format('MOS-184: дублей %s, ждали около 11 — проверьте руками', cardinality(лишние));

    DELETE FROM maint.work_order WHERE notification_id = ANY(лишние);
    GET DIAGNOSTICS заказов = ROW_COUNT;
    DELETE FROM maint.notification WHERE id = ANY(лишние);
    RAISE NOTICE 'MOS-184: удалено заявок %, заказов %', cardinality(лишние), заказов;
END $$;
