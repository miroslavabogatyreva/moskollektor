-- 040. Третье окно в smvu.data_outage — весь 2021 год — и колонка причины окна.
-- Задача 2.12 плана, MOS-87.
--
-- ЗАЧЕМ. Заказчик письменно 19.09.2026 (docs/meetings/2026-09-19-ответы-заказчика.md,
-- сводный 4): всплеск тревог 2021 года — переход на новую систему мониторинга,
-- «Этот период рекомендуется исключить из анализа». Николай должен видеть границы
-- этого окна в базе рядом с двумя окнами тишины, а не искать их в переписке.
--
-- ПОЧЕМУ НЕЛЬЗЯ ПРОСТО ВСТАВИТЬ СТРОКУ. Оба построителя эпизодов
-- (backend/app/ingest/fault_episodes.py, model_failure_episodes.py) ставят
-- spans_outage любому эпизоду, пересекающему любое окно таблицы, а spans_outage
-- значит «длительность завышена тишиной» (017_fault_episodes.sql). В 2021 году
-- тишины нет, данные идут. Без фильтра пересборка пометила бы 4 750 эпизодов
-- smvu.fault_episode из 25 440, и частичный индекс fault_episode_trainable_idx
-- выбросил бы их из годных для обучения; в smvu.model_failure_episode флаг встал бы
-- у 3 566 из 12 139 (замер на стенде 23.09.2026).
-- Поэтому окну нужна причина, а построители берут только export_gap.
--
-- ГРАНИЦЫ — календарный 2021 год по Москве: 01.01.2021 00:00 мск … 01.01.2022
-- 00:00 мск. Заказчик назвал год целиком, без дат, так что край берём по календарю,
-- а не по данным. У окон тишины границы — последняя запись до и первая после
-- (017), у этого окна — полуинтервал года; tstzrange у построителей и так [).
--
-- ЭПИЗОДЫ НЕ ПЕРЕСОБИРАЕМ: spans_outage у лежащих строк не меняется.

ALTER TABLE smvu.data_outage
    ADD COLUMN reason text NOT NULL DEFAULT 'export_gap',
    ADD CONSTRAINT data_outage_reason CHECK (reason IN ('export_gap', 'vendor_migration'));

COMMENT ON COLUMN smvu.data_outage.reason IS
    'export_gap — СМВУ не написала ни строки, длительность эпизода завышена (spans_outage); '
    'vendor_migration — данные есть, но заказчик рекомендует период исключить из анализа';

COMMENT ON TABLE smvu.data_outage IS
    'Окна времени, которые нельзя брать в анализ как есть. export_gap — тишина выгрузки, '
    'эпизод поверх неё помечается spans_outage; vendor_migration — переход на новую '
    'систему мониторинга в 2021 году, решение о выбросе за тем, кто учит модель';

INSERT INTO smvu.data_outage (started_at, ended_at, reason, note) VALUES
    ('2020-12-31 21:00:00+00', '2021-12-31 21:00:00+00', 'vendor_migration',
     'Всплеск тревог в 2021 году вызван переходом на новую версию системы мониторинга - '
     'сотрудники не могли полноценно работать в двух системах одновременно, и тревоги '
     'не снимались с охраны во время профилактики. Этот период рекомендуется исключить '
     'из анализа.');
