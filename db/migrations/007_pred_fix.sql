-- ---------------------------------------------------------------------------
-- 1. model_version: прогон заводится раньше, чем модель успевает представиться
-- ---------------------------------------------------------------------------
-- HLD разд. 8.2, стадия 0: сначала INSERT INTO pred.run (status='running')
-- RETURNING run_id, и только потом GET http://ml:8100/model. Порядок не прихоть:
-- номер прогона едет в запрос к модели полем run_id, без него запрос не собрать.
--
-- Улов, а не рассуждение. 16.09.2026 на стенде:
--     INSERT INTO pred.run (status) VALUES ('running') RETURNING run_id;
--     NotNullViolationError: null value in column "model_version" of relation "run"
--     violates not-null constraint
--
-- Цена этой строки — условие готовности блока Q3 «недоступная модель не роняет
-- систему: расчёт падает С ЗАПИСЬЮ в pred.run». Пока колонка NOT NULL, записи
-- не будет вовсе: контейнер ml не ответил, версии нет, строку завести нечем,
-- и на приёмке мы показываем пустой журнал вместо строки со status='failed'.
--
-- Почему NULL, а не DEFAULT 'unknown'. Строка 'unknown' — это утверждение,
-- что модель назвалась так. NULL — «модель ещё не отвечала». Разница видна
-- в протоколе М-02, где требуется назвать, чем именно посчитан прогноз.
ALTER TABLE pred.run ALTER COLUMN model_version DROP NOT NULL;

COMMENT ON COLUMN pred.run.model_version IS
    'Версия модели из GET /model. NULL — модель не ответила: строку прогона заводит стадия 0, а модель представляется на стадии 0-бис';

-- ---------------------------------------------------------------------------
-- 2. as_of: на какой момент считали
-- ---------------------------------------------------------------------------
-- started_at отвечает на вопрос «когда запустили», а признакам нужен другой
-- вопрос — «по какой момент читать журнал». На стенде это сегодня разные даты,
-- и разница не маленькая: выгрузка заказчика кончается 30.06.2026, а сегодня
-- 16.09.2026. Окна признаков отсчитываются от as_of, и без этой колонки
-- расчёт на срезе 30.06 выглядит в журнале прогонов как расчёт на сегодня —
-- то самое «показать вчерашнее под видом сегодняшнего», которое HLD разд. 6.6
-- называет обманом, а не деградацией.
--
-- Проверено 16.09.2026: max(read_time) в smvu.reading_2026_06 = 30.06.2026 23:59:59 MSK,
-- партиции reading_2026_07 … reading_2026_12 заведены и пусты.
--
-- DEFAULT now() — обычный рабочий случай, когда поток живой. Расчёт на срезе
-- передаёт значение явно.
ALTER TABLE pred.run ADD COLUMN as_of timestamptz NOT NULL DEFAULT now();

COMMENT ON COLUMN pred.run.as_of IS
    'Момент среза: по этот час читается журнал и от него отсчитываются окна признаков. Отличается от started_at, когда считаем по исторической выгрузке';

-- ---------------------------------------------------------------------------
-- 3. objects_scored: «посчитано N из M»
-- ---------------------------------------------------------------------------
-- objects_total в 004 один, а чисел у расчёта два: сколько участков он взял
-- и по скольким получил вероятность. Они расходятся законным образом —
-- участок под действующим нарядом-допуском из расчёта выпадает (Ф-10),
-- а участок без покрытия свёрткой выпасть не имеет права молча.
--
-- HLD разд. 6.6, «чего делать нельзя»: молча исключать часть объектов.
-- Строка приёмки Ф-57 требует оба числа в ответе API, и лежит она в части III —
-- то есть на приёмке её не спросят. Колонку всё равно завожу: расчёт эти два
-- числа и так знает, а без места для второго оно теряется, и следующая сессия
-- напишет восьмую миграцию ради одного integer.
ALTER TABLE pred.run ADD COLUMN objects_scored integer;

COMMENT ON COLUMN pred.run.objects_scored IS
    'По скольким участкам получена вероятность. Меньше objects_total — часть участков исключена, причина в error_text';
COMMENT ON COLUMN pred.run.objects_total IS
    'Сколько участков расчёт взял в работу на стадии «выбор объектов»';
