-- 029. Николай ходит в нашу базу: ключ коллектора и учётка только на чтение.
-- Задача Q7.x (MOS-145). Снимает расхождение ключей, найденное 21.09.2026.
--
-- ЗАЧЕМ. Модель v3 группирует каналы в коллекторы по префиксу тега, мы — по дереву
-- объектов заказчика. Числа при этом совпадают по форме и расходятся по смыслу:
-- его «884» — коллектор, наш 884 — участок 360:246 на коллекторе 360. Я проверил
-- все 32 его префикса против ref.object_xref: каждый попадает в существующий
-- section_id. Значит склейка напрямую не даёт ни 404, ни 422 — она молча кладёт
-- прогноз на чужой участок, и увидеть это можно только счётом, а не ошибкой.
--
-- ПОЧЕМУ ПЕРЕВОДА «ПРЕФИКС -> КОЛЛЕКТОР» НЕТ И БЫТЬ НЕ МОЖЕТ. Префиксов 32,
-- коллекторов 16, и два префикса ведут к РАЗНЫМ коллекторам: 798 отдаёт 139 каналов
-- объекту Зита и 25 каналов ДП объекта Бета, 163 отдаёт 44 канала ПС объекта Ро
-- и 1 канал объекту Каппа (docs/acceptance-test.md, строка ОВ-46). Переводной
-- таблицей это не чинится — чинится только тем, что Николай берёт ключ там же,
-- где берём мы: из справочника заказчика.
--
-- ПОЧЕМУ ПРЕДСТАВЛЕНИЕ, А НЕ ВЫГРУЗКА CSV. Файл канал->участок мы Николаю уже
-- отдавали (contracts/examples/section_xref.csv, MOS-158, 10 720 строк), и он
-- устареет молча в тот день, когда заказчик пришлёт справочник заново — как прислал
-- 16.09.2026. Представление устареть не может: оно и есть запрос.
--
-- ПОЧЕМУ parent_id БЕЗ ВЕТВЛЕНИЙ. Проверено на стенде 21.09.2026: все 11 485
-- справочных каналов висят на узлах третьего уровня (level=3), и у всех 78 узлов
-- третьего уровня родитель лежит на втором. Ни одного канала прямо под коллектором
-- нет, поэтому COALESCE тут был бы обороной от случая, которого в данных нет.
-- Если он появится, ASSERT ниже покраснеет при следующем накате.
--
-- 1 142 КАНАЛА-ЗАГЛУШКИ СЮДА НЕ ПОПАДАЮТ. Это каналы, которых нет в справочнике
-- заказчика: у них нет ни объекта, ни участка. Отдать их Николаю с NULL вместо
-- коллектора значит предложить ему склеить их в один фиктивный коллектор — ровно
-- ту ловушку, которую code/predictive_metrics.py обходит отдельной веткой.

CREATE OR REPLACE VIEW smvu.channel_collector AS
SELECT c.channel_id,
       c.tag,
       c.object_id                      AS node_id,      -- узел диспетчера, 78 штук
       n.name                           AS node_name,
       p.object_id                      AS collector_id, -- коллектор, 16 штук: ЭТО КЛЮЧ
       p.name                           AS collector_name,
       c.section_id                                      -- участок, 3 173 штуки
  FROM smvu.channel c
  JOIN smvu.object_tree n ON n.object_id = c.object_id
  JOIN smvu.object_tree p ON p.object_id = n.parent_id AND p.level = 2
 WHERE c.is_active;

COMMENT ON VIEW smvu.channel_collector IS
  'Ключ коллектора для ML-команды (MOS-145): канал -> узел диспетчера -> коллектор. '
  'Группировать инциденты надо по collector_id, а не по префиксу тега: префиксов 32, '
  'коллекторов 16, и префиксы 163 и 798 ведут к разным коллекторам.';

-- Учётка только на чтение. Пароль здесь не задаётся намеренно: в git он не поедет,
-- ставится на стенде одной строкой (docs/server.md, раздел про доступ ML-команды).
-- Без пароля роль существует, но войти по ней нельзя.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'ml_ro') THEN
    CREATE ROLE ml_ro LOGIN;
  END IF;
END $$;

GRANT USAGE ON SCHEMA smvu, ref TO ml_ro;
GRANT SELECT ON ALL TABLES IN SCHEMA smvu, ref TO ml_ro;
-- Партиции smvu.reading за будущие месяцы создаются заранее, а таблицы схемы ref
-- ещё будут появляться. Без этой строки роль перестала бы видеть их молча.
ALTER DEFAULT PRIVILEGES IN SCHEMA smvu, ref GRANT SELECT ON TABLES TO ml_ro;

-- Самопроверка накатом: три утверждения, каждое про своё.
--
-- ПУСТОЙ СПРАВОЧНИК — НЕ ПОВОД ПАДАТЬ, и это не послабление, а починка установки
-- с нуля (задача 1.16, MOS-165). Заказчик распаковывает пакет и запускает накат
-- на пустой базе, справочники заливаются после него. До 22.09.2026 второй ASSERT
-- сравнивал число коллекторов с литералом 16 и получал 0, накат вставал на 029,
-- а `api` и `worker` не поднимались вовсе: они ждут контейнер `migrate` через
-- `condition: service_completed_successfully`. Проверено на пустой базе: накат
-- доезжал до 028 и возвращал код 1.
--
-- Поэтому на пустом справочнике три проверки пропускаются вслух, а не молча.
-- Что они при этом теряют: на чистой установке 029 запишется в журнал зелёной
-- и больше не выполнится никогда — `migrate.py` накатанный файл не повторяет.
-- Долговременное место для этих счётчиков — приёмочный скрипт, который ходит
-- в живую базу, а не миграция.
DO $$
DECLARE к_всего int; к_видно int; коллекторов int; сирот int;
BEGIN
  SELECT count(*) INTO к_всего  FROM smvu.channel WHERE is_active AND object_id IS NOT NULL;
  IF к_всего = 0 THEN
    RAISE NOTICE '029: справочник каналов пуст — три проверки пропущены. Залейте '
                 'справочники (deploy/README.md, «Залить выгрузку СМВУ») и повторите накат';
    RETURN;
  END IF;
  SELECT count(*), count(DISTINCT collector_id) INTO к_видно, коллекторов FROM smvu.channel_collector;
  SELECT count(*) INTO сирот FROM smvu.object_tree WHERE level = 3
     AND parent_id NOT IN (SELECT object_id FROM smvu.object_tree WHERE level = 2);

  ASSERT к_видно = к_всего,
    format('канал потерялся по дороге к коллектору: в справочнике %s, в представлении %s', к_всего, к_видно);
  ASSERT коллекторов = 16,
    format('коллекторов должно быть 16, а вышло %s — дерево объектов изменилось, проверьте ключ', коллекторов);
  ASSERT сирот = 0,
    format('%s узлов третьего уровня висят не под коллектором — JOIN без COALESCE их теряет', сирот);
END $$;
