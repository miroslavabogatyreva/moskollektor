-- 050. Три участка на одно предупреждение модели. Задача 6.14, MOS-184.
--
-- ЗАЧЕМ. Миграция 035 завела настройку order_top_sections_per_object со значением
-- ноль, и ноль значит «заявка на каждый участок коллектора». В коллекторе от 9 до
-- 521 участка, в середине ряда 212: одно предупреждение дало бы сотни заявок, и
-- диспетчер их не отработает. Решение Славы 22.09.2026 и повторно 26.09.2026 (Jira
-- MOS-184, комментарий 14685): три самых ломких участка по весу pred.section_weight.
--
-- Номер 050 зарезервирован под эту задачу с 23.09.2026 (см. шапки 051 и 052).
--
-- ЧТО ЕЩЁ ЧИНИТ MOS-184 — В КОДЕ, НЕ ЗДЕСЬ. Участки предупреждения выбираются один
-- раз: у предупреждения (pfx, момент открытия), на которое заявки уже заведены,
-- новых не будет, как бы ни пересчитался вес (backend/app/domain/order_rules.py,
-- заявки_по_предупреждениям). Без этого 22.09.2026 на стенде после миграции 038
-- стало 44 заявки вместо 33.

UPDATE ref.app_setting SET value = 3, changed_at = now()
 WHERE key = 'order_top_sections_per_object';

DO $$
DECLARE н numeric;
BEGIN
  SELECT value INTO н FROM ref.app_setting WHERE key = 'order_top_sections_per_object';
  ASSERT н = 3, format('order_top_sections_per_object = %s, ждали 3 — нет строки из 035?', н);
  RAISE NOTICE '050: заявки по предупреждению — на три худших участка';
END $$;
