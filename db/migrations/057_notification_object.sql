-- 057. Объект у автозаявки прежнего пути с разносом. Строка плана 6.10, MOS-154.
--
-- ЗАЧЕМ. С включённым разносом (forecast_spread_enabled = 1) у участка лежит доля
-- вероятности объекта, и прежний путь заявок сравнивает порог не с ней, а с
-- вероятностью объекта — узла второго уровня smvu.object_tree (коллектор Мю,
-- Тау, Сигма). Заявка одна на объект и стоит на участке с наибольшей долей. План
-- требует, чтобы заявка несла оба ключа: участок у неё уже есть (func_location_id
-- -> ref.object_xref.section_id), объекта не было. Без него по заявке не сказать,
-- что порог прошёл объект, а не этот пикет.
--
-- ГДЕ ЗАПОЛНЕНО. Только у заявок прежнего пути при включённом разносе. На пути
-- модели v3 (стенд) заявку заводит открытие предупреждения по префиксу тега, и
-- объект там NULL: префикс и объект дерева — разные ключи (миграция 033).

ALTER TABLE maint.notification
    ADD COLUMN object_id integer REFERENCES smvu.object_tree(object_id);

COMMENT ON COLUMN maint.notification.object_id IS
    'Объект (узел 2-го уровня smvu.object_tree), чья вероятность прошла порог заявки '
    'при включённом разносе по участкам; NULL у остальных заявок. MOS-154';
