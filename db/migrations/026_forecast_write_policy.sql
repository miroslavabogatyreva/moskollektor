-- 026_forecast_write_policy.sql — журнал прогнозов пишет события, а не тиканье часов.
--
-- ЗАЧЕМ. Задача MOS-147, строка плана Q3.13. Сегодня расчёт идёт раз в час и пишет
-- 3 173 строки за прогон — 76 152 строки в сутки. MOS-146 переводит расчёт на четыре
-- минуты, это 360 прогонов в сутки и 1 142 280 строк, за неделю 8 млн. Сам по себе
-- объём мы бы пережили, но журнал при этом перестаёт быть журналом: в нём лежит не
-- то, что менялось, а то, что часы тикали.
--
-- ОТКУДА ВЗЯТ ПОДХОД. Не придуман нами: это «отчёт по исключению» из OPC UA часть 11
-- (Historical Access), тип HistoricalDataConfigurationType — там рядом стоят два
-- свойства, ExceptionDeviation («минимальная величина, на которую данные должны
-- измениться, чтобы попасть в базу истории») и MaxTimeInterval («максимальный
-- интервал между точками независимо от изменения»). В BACnet (ANSI/ASHRAE 135) то же
-- самое зовётся COV_Increment. Ключевое здесь — что свойств ДВА: порог сам по себе
-- молча теряет всплески, и это померено — инженеры Aramco (arXiv:2510.26868) дают
-- 35 % пропущенных кратковременных аномалий при агрессивном сжатии, а кратковременный
-- всплеск вероятности перед отказом — это ровно то, из чего складывается наш Recall.
-- Поэтому вместе с порогом идёт безусловный «пульс».
--
-- ЧЕГО НЕ БЕРЁМ. Swinging door (алгоритм PI, стандарт де-факто историзаторов) обещает
-- восстановить выброшенную точку интерполяцией. Нам этого мало: на приёмке надо
-- предъявить, что система показывала диспетчеру в момент T. Интерполированный прогноз
-- прогнозом не является. Срок хранения («сырьё 30 суток, дальше свёртки») не берём
-- тоже: он уничтожает окно приёмки апрель–июнь 2026, по которому считаются М-18 и М-19.

-- 1. Почему строка попала в журнал. Колонка отвечает не «полная строка или
--    разреженная», а «что её вызвало» — на приёмке это разные ответы.
ALTER TABLE pred.forecast ADD COLUMN write_reason text NOT NULL DEFAULT 'change';
ALTER TABLE pred.forecast ADD CONSTRAINT forecast_write_reason_chk
    CHECK (write_reason IN ('first', 'change', 'heartbeat', 'full'));

COMMENT ON COLUMN pred.forecast.write_reason IS
    'Почему строка записана: first — первый прогноз объекта, change — вероятность или класс риска изменились, heartbeat — безусловная запись по времени, full — прогон с полным журналом (обучение, замер метрик)';

-- 2. Прогон, который пишет всё подряд. Замер метрик М-18 и М-19 идёт по журналу
--    (code/check_metrics.py, запрос «прогнозы удачных прогонов, чей срез попал
--    в окно»), поэтому прогоны на историческом срезе обязаны писать каждую строку.
--    Признак на прогоне, а не окно дат в настройках: окно приёмки не константа —
--    эксперт вправе назвать своё, и тогда дата в настройке начнёт врать.
ALTER TABLE pred.run ADD COLUMN full_log boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN pred.run.full_log IS
    'true — прогон пишет в журнал каждый объект без мёртвой зоны: обратный расчёт для замера метрик. false — рабочий прогон по расписанию, пишет изменения и пульс';

-- 3. Состояние, от которого считается «изменилось». Сравнивать надо с последним
--    ЗАПИСАННЫМ значением, а не с последним посчитанным: иначе медленный дрейф
--    по пол-процента за прогон не запишется никогда, сколько бы он ни накопил.
--    Место выбрано не новое: pred.forecast_current и так одна строка на участок.
ALTER TABLE pred.forecast_current ADD COLUMN logged_probability real;
ALTER TABLE pred.forecast_current ADD COLUMN logged_at timestamptz;
ALTER TABLE pred.forecast_current ADD COLUMN risk_class text;
ALTER TABLE pred.forecast_current ADD COLUMN risk_class_since timestamptz;

COMMENT ON COLUMN pred.forecast_current.logged_probability IS
    'Вероятность последней строки, ушедшей в pred.forecast. Мёртвая зона меряется от неё, а не от прошлого расчёта';
COMMENT ON COLUMN pred.forecast_current.risk_class IS
    'Класс риска с гистерезисом: high | normal. ISA-18.2 зовёт дребезгом переход туда-обратно три раза за 60 секунд; при расчёте раз в 4 минуты объект у порога прыгал бы 15 раз в час';

-- 4. Четыре настройки. Значения по умолчанию названы ниже вместе с причиной;
--    мёртвую зону сегодня подобрать не по чему — заглушка модели выдаёт одно
--    и то же число на участок, и распределение изменений вероятности будет
--    известно только на весах Николая (MOS-145). Поэтому это настройка,
--    а не константа, и меняется она через PUT /api/settings/{key}.
INSERT INTO ref.app_setting (key, value, unit) VALUES
    -- 0,02 — два процента вероятности. Взято по верхней границе рекомендации
    -- ISA-18.2 для мёртвой зоны аналогового аларма (2–5 % диапазона), нижняя
    -- граница выбрана сознательно: пропустить настоящее изменение дороже,
    -- чем записать лишнюю строку.
    ('forecast_deadband',      0.02, NULL),
    -- 60 минут — «пульс» OPC UA MaxTimeInterval. При 3 173 объектах это
    -- 76 152 строки в сутки, то есть ровно сегодняшний объём при часовом
    -- расчёте: нижняя граница журнала не растёт от учащения расчёта вовсе.
    ('forecast_heartbeat_min', 60,   'мин'),
    -- Гистерезис класса: поднимаем при пороге + 0,02, снимаем при пороге − 0,02.
    ('risk_class_hysteresis',  0.02, NULL),
    -- Минимальное время удержания класса, ISA-18.2 называет это задержкой.
    ('risk_class_hold_min',    10,   'мин');
