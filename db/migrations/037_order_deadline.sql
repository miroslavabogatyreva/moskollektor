-- 037. Заявка по предупреждению модели: ключ вместо суток, срок от обнаружения,
-- горизонт 720. Задачи Q6.12 (MOS-180) и Q6.11 (MOS-179), приёмка М-10, М-11, М-13, М-20.
--
-- ЗАЧЕМ. Ревью Codex 22.09.2026 нашло три пути, по которым открытое предупреждение
-- модели не становилось заявкой, и срок, который считался от выдуманного момента
-- отказа. Здесь схема под все четыре правки, код — backend/app/domain/order_rules.py.
--
-- 1. СУТОЧНЫЙ ИНДЕКС → ИНДЕКС ПО КЛЮЧУ. uq_notif_forecast_daily пускал одну автозаявку
--    на объект в московские сутки, и предупреждение, закрывшееся утром и открывшееся
--    вечером, второй заявки не давало — ON CONFLICT DO NOTHING пропускал её молча.
--    Теперь повтор определяет source_key: на пути v3 это
--    warn:<префикс>:<момент открытия>:<участок>, на прежнем — day:<место>:<дата>,
--    то есть прежнее «одна в сутки» переехало в ключ и работает, как работало.
--    На стенде 22.09.2026 у 259 автозаявок 259 различных source_key и ни одного
--    пустого — индекс ляжет на живые данные без правки строк.
--
-- 2. ПРИЧИНА ЗАПИСИ 'warning'. Кандидаты в заявки — строки журнала этого прогона,
--    а мёртвая зона журнала пропускала участок без изменения: на стенде из прогонов
--    621…639 строки есть только у 633 (пульс, 3 173 строки), у 634–639 ноль. Участок,
--    на который заводится заявка по новому предупреждению, теперь пишется всегда,
--    с этой причиной (backend/app/worker/publish.py, причина_записи).
--
-- 3. СРОК ОТ ОБНАРУЖЕНИЯ. Модель говорит «отказ возможен в ближайшие horizon_h
--    часов», а срок считался от as_of + horizon_h как от момента отказа: при
--    горизонте 720 заявка получала срок через 29,5 суток. Теперь срок — момент
--    обнаружения (reported_at: срез прогона, который заметил предупреждение) плюс
--    меньшее из норматива реакции ref.priority.response_hours и потолка (п. 4а).
--    Момент открытия предупреждения — отдельной колонкой: срок от него родил бы
--    заявку просроченной, если предупреждение открылось до выкладки. Две новые
--    колонки хранят то, что раньше выводилось формулой:
--      warning_opened_at — момент открытия предупреждения модели, NULL на прежнем пути;
--      risk_window_end   — конец окна риска: warning_expires_at модели или as_of + horizon_h.
--
-- 4. НОРМАТИВЫ РЕАКЦИИ — ИЗ РЕГЛАМЕНТА, А НЕ СВОИ. До этой миграции в ref.priority
--    стояли 24 / 72 / 168 ч без источника. Принцип: превентивная заявка отработана
--    не позже, чем Регламент велит устранить саму неисправность, случись она
--    в момент открытия предупреждения. Предупреждение обещает потерю связи с каналом,
--    а не аварию всей системы, поэтому категория I (3 ч) не берётся.
--      приоритет 2 (класс A, пожарная и газовая охрана) — 16 ч: docs/reglament.pdf,
--        п. 10.3.7, табл. 10.2 «Сроки устранения неисправностей систем ОПС»,
--        категория II «неработоспособность групп извещателей», стр. 64 (63 в PDF);
--      приоритет 3 (класс B, охрана и диспетчерский контроль) — 48 ч: там же,
--        категория III, и табл. 12.4 «Сроки устранения неисправностей систем СДУК»,
--        п. 12.5.13, категория II, стр. 92 (91 в PDF);
--      приоритет 4 (класс C, температура и диагностика) — 72 ч: табл. 12.4,
--        категория III «прочие неисправности системы СДУК», стр. 92 (91 в PDF).
--    Приоритет 1 (аварийный, 4 ч) эта миграция не трогает: автозаявкам он
--    не достаётся. У заведённых раньше заявок due_at остаётся как был — задним
--    числом историю не переписываем; карточка показывает срок самой заявки рядом
--    с нормативом, и у старых они разойдутся (docs/order-rules.md).
--
-- 4а. ПОТОЛОК ПРЕВЕНТИВНОСТИ. Срок заявки — reported_at + меньшее из норматива
--    приоритета и order_preventive_cap_h. Норматив Регламента говорит, за сколько
--    устранить уже случившуюся неисправность; превентивная заявка обязана успеть
--    раньше отказа, а отказ после предупреждения модели обычно наступает через
--    медиану упреждения. Со сроком +72 ч класс C опоздал бы к большинству отказов.
--    16 ч — два обоснования, и они сошлись:
--      медиана упреждения 16,7 ч: 128 отказов D5, о которых модель предупредила
--        заранее в окне 0…168 ч (code/check_metrics_report.py:140, docs/metrics-report.md:164,
--        PR #4). При потолке 16 ч раньше срока приходят 62 отказа из 128, позже 66 —
--        бригада успевает к 52 % предупреждённых отказов. При 6 ч раньше пришли бы 49,
--        при 12 ч — 59, при 24 ч — 75 (разбор в docs/order-rules.md);
--      норматив класса A по Регламенту, табл. 10.2, кат. II — тоже 16 ч.
--    Значит, у автозаявки модели срок +16 ч при любом классе, а норматив 48 и 72 ч
--    классов B и C остаётся в справочнике для ручных заявок и для карточки.
--
-- 5. ГОРИЗОНТ 720 (М-20). Модель v3 обучена на окне 720 ч (MOS-145), а справочник
--    говорил 24: подпись горизонта в API и на экране была неправдой. Умолчание
--    в backend/app/worker/run.py (ГОРИЗОНТ_Ч) поднято до того же числа.

-- 2. Причина записи журнала.
ALTER TABLE pred.forecast DROP CONSTRAINT forecast_write_reason_chk;
ALTER TABLE pred.forecast ADD CONSTRAINT forecast_write_reason_chk
    CHECK (write_reason IN ('first', 'change', 'heartbeat', 'full', 'legacy', 'warning'));
COMMENT ON COLUMN pred.forecast.write_reason IS
    'Почему строка попала в журнал: first, change, heartbeat, full, legacy (до 026), '
    'warning — участок, на который в этом прогоне заводится заявка по новому '
    'предупреждению модели (037, MOS-180)';

-- 3. Колонки заявки.
ALTER TABLE maint.notification
    ADD COLUMN warning_opened_at timestamptz,
    ADD COLUMN risk_window_end   timestamptz;
COMMENT ON COLUMN maint.notification.warning_opened_at IS
    'Момент открытия предупреждения модели, по которому заведена автозаявка; '
    'NULL у заявок прежнего пути и ручных (037, MOS-179)';
COMMENT ON COLUMN maint.notification.risk_window_end IS
    'Конец окна риска прогноза: warning_expires_at модели или as_of + horizon_h. '
    'Это граница, до которой прогноз обещает риск, а не предсказанный момент отказа';

-- У заведённых раньше заявок конец окна выводится тем же выражением, каким его
-- выводил код: as_of прогона плюс горизонт прогноза. Это заполнение новой колонки
-- фактом, а не правка истории: due_at и reported_at не трогаются.
UPDATE maint.notification n
   SET risk_window_end = r.as_of + make_interval(hours => f.horizon_h)
  FROM pred.forecast f
  JOIN pred.run r ON r.run_id = f.run_id
 WHERE n.forecast_id = f.forecast_id AND n.risk_window_end IS NULL;

-- 1. Ключ вместо суток.
ALTER TABLE maint.notification ADD CONSTRAINT notif_forecast_key_chk
    CHECK (source_system <> 'forecast' OR source_key IS NOT NULL);
DROP INDEX maint.uq_notif_forecast_daily;
CREATE UNIQUE INDEX uq_notif_forecast_key
    ON maint.notification (source_key)
    WHERE source_system = 'forecast';
COMMENT ON INDEX maint.uq_notif_forecast_key IS
    'Одна автозаявка на ключ: warn:<префикс>:<открытие>:<участок> или day:<место>:<дата>. '
    'Под этот индекс написан ON CONFLICT в backend/app/domain/order_rules.py';

-- 4. Нормативы реакции.
UPDATE ref.priority SET response_hours = 16 WHERE code = '2';
UPDATE ref.priority SET response_hours = 48 WHERE code = '3';
UPDATE ref.priority SET response_hours = 72 WHERE code = '4';
COMMENT ON COLUMN ref.priority.response_hours IS
    'Норматив реакции, ч; срок автозаявки = reported_at + min(это число, '
    'ref.app_setting.order_preventive_cap_h). 2 → 16 ч: Регламент '
    'п. 10.3.7, табл. 10.2 ОПС, кат. II, стр. 64. 3 → 48 ч: табл. 10.2, кат. III, и '
    'табл. 12.4 СДУК, кат. II, п. 12.5.13, стр. 92. 4 → 72 ч: табл. 12.4, кат. III, '
    'стр. 92. Страницы печатные, в PDF на одну меньше (037, MOS-179)';

-- 4а. Потолок превентивности: медиана упреждения 16,7 ч и норматив класса A 16 ч
-- (шапка, пункт 4а). Правится через PUT /api/settings/order_preventive_cap_h.
INSERT INTO ref.app_setting (key, value, unit) VALUES ('order_preventive_cap_h', 16, 'ч');

-- 5. Горизонт.
UPDATE ref.app_setting SET value = 720 WHERE key = 'forecast_horizon_h';

-- Самопроверка накатом: каждое из пяти изменений на месте, иначе накат падает.
DO $$
DECLARE часов int[]; горизонт numeric; пустых int; потолок numeric;
BEGIN
  ASSERT to_regclass('maint.uq_notif_forecast_daily') IS NULL,
    'суточный индекс остался — повторное открытие предупреждения снова пропадёт молча';
  ASSERT to_regclass('maint.uq_notif_forecast_key') IS NOT NULL, 'индекса по ключу нет';

  SELECT array_agg(response_hours ORDER BY code) INTO часов
    FROM ref.priority WHERE code IN ('2', '3', '4');
  ASSERT часов = ARRAY[16, 48, 72], format('нормативы реакции %s вместо {16,48,72}', часов);

  SELECT value INTO горизонт FROM ref.app_setting WHERE key = 'forecast_horizon_h';
  ASSERT горизонт = 720, format('горизонт %s вместо 720', горизонт);

  SELECT value INTO потолок FROM ref.app_setting WHERE key = 'order_preventive_cap_h';
  ASSERT потолок > 0, format('потолок превентивности %s', потолок);

  SELECT count(*) INTO пустых FROM maint.notification
   WHERE forecast_id IS NOT NULL AND risk_window_end IS NULL;
  ASSERT пустых = 0, format('%s автозаявок без конца окна риска', пустых);

  RAISE NOTICE '037: индекс по ключу, нормативы %, потолок % ч, горизонт %, конец окна у всех',
    часов, потолок, горизонт;
END $$;
