-- 028. Вес участка внутри объекта: чем разносить вероятность объекта по пикетам.
-- Задача Q3.16 (MOS-150). Закрывает приёмку М-04 и М-05 в части «числа участков
-- одного объекта различаются».
--
-- ЗАЧЕМ. Модель Николая v3 даёт одно число НА ОБЪЕКТ, объектов 16. Экраны показывают
-- 3 173 участка. Множитель между уровнями до 521 (объект Мю): без разноса плитки
-- одного коллектора красятся одним цветом, и диспетчер не узнает, куда посылать
-- бригаду. Разносим весом из истории отказов: доля эпизодов участка внутри объекта.
--
-- ПОЧЕМУ ПРЕДСТАВЛЕНИЕ, А НЕ ТАБЛИЦА. Таблица весов требует пересчёта и расходится
-- с эпизодами молча — между пересчётами она врёт, и никто этого не видит. Здесь
-- считать нечего: 20 670 эпизодов сворачиваются за миллисекунды, а вес по
-- определению всегда соответствует тому, что лежит в smvu.fault_episode.
-- Представление переживает пересоздание контейнера так же, как таблица: оно лежит
-- в схеме, а не в памяти процесса. Понадобится материализация ради скорости —
-- MATERIALIZED VIEW добавляется одной строкой, а колонку computed_at тогда
-- заменит время REFRESH.
--
-- СГЛАЖИВАНИЕ, А НЕ ЧИСТАЯ ДОЛЯ. Отказы были на 1 354 участках из 3 173 — на 57 %
-- парка за 4,5 года не случилось ни одного. При чистой доле отказов эти участки
-- получают ровный ноль, то есть «риска нет» там, где мы просто ничего не видели.
-- Внутри объекта это большинство плиток: у объекта Мю отказывали 266 участков
-- из 521, у объекта Каппа — 50 из 350. Поэтому в числитель и знаменатель идёт
-- добавка alpha (сглаживание Лапласа): участок без отказов получает малую, но
-- ненулевую долю, а сумма долей внутри объекта остаётся равной единице тождественно
-- при любой истории — включая объект, где не отказывал никто, там все получают 1/N.
--
-- ЧТО ТАКОЕ ОТКАЗ. Дословно то же определение, что в backend/app/api/objects.py:180
-- и в code/check_metrics.py:353: эпизод закрытый (ended_at IS NOT NULL), длиннее
-- часа, и не 2021 год. Три условия, и каждое отсекает своё — сколько именно,
-- печатает code/check_spread.py. Год исключён по письменному ответу заказчика
-- от 19.09.2026: «Всплеск тревог в 2021 году вызван переходом на новую версию
-- системы мониторинга... Этот период рекомендуется исключить из анализа»
-- (docs/meetings/2026-09-19-ответы-заказчика.md). Год лежит в настройке, а не
-- в тексте запроса: Николай учит модель на своём периоде, и когда он назовёт его
-- в MOS-74, мы меняем одну строку в ref.app_setting, а не пересобираем образ.
--
-- ПОСЛЕДСТВИЕ ИСКЛЮЧЕНИЯ, КОТОРОЕ ВИДНО В ДАННЫХ. У 35 участков отказы были ТОЛЬКО
-- в 2021 году. Их вес считается как у участка без отказов, но это разные вещи:
-- «не отказывал» и «отказы вычеркнули». Колонка excluded_cnt показывает второе,
-- чтобы участок с историей не выглядел чистым.

INSERT INTO ref.app_setting (key, value, unit) VALUES
    -- 0 — разнос выключен, вероятность модели идёт на участок как есть (так сегодня
    -- работает заглушка, дающая каждому участку своё число). 1 — включён.
    -- Выключен по умолчанию НАРОЧНО: включение меняет шкалу вероятностей на два
    -- порядка и обязано ехать вместе с новыми порогами автозаявок в
    -- backend/app/domain/order_rules.py — см. code/check_spread.py, раздел про пороги.
    ('forecast_spread_enabled',     0,    NULL),
    -- Сглаживание Лапласа. Чем больше, тем ближе друг к другу крайние плитки объекта.
    -- Замер 21.09.2026 на объекте Мю (521 участок, 1 455 эпизодов, максимум 54
    -- на участке): при alpha=0,1 самая красная плитка относится к плитке без
    -- отказов как 541:1, при 0,5 — как 109:1, при 1,0 — как 55:1, при 2,0 — как 28:1.
    -- Взяли 1,0: при 0,1 тихий участок получает 0,000066 и в четвёртом знаке
    -- неотличим от нуля, ради ухода от которого сглаживание и заводилось,
    -- а при 2,0 самый опасный перестаёт выделяться.
    --
    -- ЭТИ ЧЕТЫРЕ ЧИСЛА УСТАРЕЮТ САМИ, И ПРАВИТЬ ИХ ЗДЕСЬ БУДЕТ НЕЛЬЗЯ. Они
    -- посчитаны на определении отказа «эпизод закрытый, длиннее часа, не 2021
    -- год», а определение пересматривает MOS-153: две трети наших эпизодов
    -- построены на значении «Неопределен», и если оно окажется штатным режимом
    -- теплового датчика, история отказов станет другой. Сам ВЫБОР alpha от этого
    -- не меняется — 1,0 держится тем, что отношение крайних плиток остаётся
    -- в десятках, а не в сотнях, при любой правдоподобной истории. Живые числа
    -- на сегодняшних данных всегда печатает `python3 code/check_spread.py`,
    -- он считает их из базы; здесь они как след замера, по которому выбирали.
    -- Накатанную миграцию править запрещает backend/app/migrate.py:63 — он
    -- сверяет sha256 с записанным в public.schema_migration и падает ДО старта
    -- api и worker, поэтому расхождение выглядит не как «миграция не применилась»,
    -- а как «служба не поднялась».
    ('forecast_weight_alpha',       1.0,  NULL),
    -- Год, который не идёт в вес. 0 — не исключать ни одного.
    ('forecast_weight_exclude_year', 2021, 'год');

-- ---------------------------------------------------------------------------
-- Участок -> объект второго уровня
-- ---------------------------------------------------------------------------
-- Прямой колонки нет: заказчик даёт объект НА КАНАЛ (smvu.channel.object_id,
-- миграция 018), и это третий уровень дерева — ПС, ОС, ДУ, ДП, шкафы ОПС.
-- Коллектор, на котором стоит модель, — второй уровень, до него идём через parent_id.
--
-- ПРАВИЛО ДЛЯ УЧАСТКА 1490 НАПИСАНО ЯВНО, И ВОТ ПОЧЕМУ. Из 3 173 участков 3 172
-- висят ровно на одном объекте второго уровня. Участок 1490 (ключ 798:0, нулевой
-- пикет) висит на двух: 13 активных каналов уходят к объекту Зита, 3 — к объекту
-- Бета. Похоже на стык коллекторов. Без явного правила объект выбрался бы порядком
-- строк — то есть случайно и молча, а при следующей заливке мог бы смениться.
-- Берём объект, на котором у участка больше АКТИВНЫХ каналов; при равенстве —
-- меньший object_id, чтобы выбор не зависел от порядка чтения. Для 1490 это Зита.
CREATE VIEW pred.section_object AS
SELECT section_id, object_id, channels_cnt
  FROM (SELECT c.section_id,
               t3.parent_id AS object_id,
               count(*) FILTER (WHERE c.is_active) AS channels_cnt,
               row_number() OVER (PARTITION BY c.section_id
                                  ORDER BY count(*) FILTER (WHERE c.is_active) DESC,
                                           t3.parent_id) AS rn
          FROM smvu.channel c
          JOIN smvu.object_tree t3 ON t3.object_id = c.object_id
         WHERE c.section_id IS NOT NULL
         GROUP BY c.section_id, t3.parent_id) z
 WHERE rn = 1;

COMMENT ON VIEW pred.section_object IS
    'Участок -> коллектор (второй уровень smvu.object_tree) большинством активных каналов; при равенстве меньший object_id. Единственный спорный участок — 1490 (798:0): 13 каналов Зита против 3 Бета';

-- ---------------------------------------------------------------------------
-- Вес участка внутри объекта
-- ---------------------------------------------------------------------------
-- В разнос идут только участки, попавшие в суточную свёртку feat.section_daily:
-- признаки модель берёт оттуда, и участок без строк в свёртке предсказывать нечем.
-- Таких семь из 3 173, все на объекте Йота; шесть из них имеют эпизоды отказа
-- 2023 года и замолчали 03.03.2025, за четыре месяца до начала окна свёртки.
-- Их отказы НЕ идут и в знаменатель объекта: иначе доля ушла бы участку, которому
-- нечего показать, и сумма опубликованных вероятностей объекта стала бы меньше
-- той, что дала модель. Тихо, без единой ошибки в журнале.
CREATE VIEW pred.section_weight AS
WITH nastroiki AS (
    SELECT coalesce(max(value) FILTER (WHERE key = 'forecast_weight_alpha'), 1.0) AS alpha,
           coalesce(max(value) FILTER (WHERE key = 'forecast_weight_exclude_year'), 2021) AS excl_year
      FROM ref.app_setting
), uchastki AS (
    SELECT so.section_id, so.object_id
      FROM pred.section_object so
     WHERE EXISTS (SELECT 1 FROM feat.section_daily d WHERE d.section_id = so.section_id)
), epizody AS (
    SELECT e.section_id,
           count(*) FILTER (WHERE extract(year FROM e.started_at) <> n.excl_year) AS episodes_cnt,
           count(*) FILTER (WHERE extract(year FROM e.started_at)  = n.excl_year) AS excluded_cnt
      FROM smvu.fault_episode e CROSS JOIN nastroiki n
     WHERE e.section_id IS NOT NULL
       AND e.ended_at IS NOT NULL
       AND e.ended_at - e.started_at > interval '1 hour'
     GROUP BY e.section_id
), po_obiektu AS (
    SELECT u.object_id,
           count(*) AS sections_cnt,
           sum(coalesce(ep.episodes_cnt, 0)) AS object_episodes
      FROM uchastki u LEFT JOIN epizody ep ON ep.section_id = u.section_id
     GROUP BY u.object_id
)
SELECT u.section_id,
       u.object_id,
       coalesce(ep.episodes_cnt, 0)::bigint AS episodes_cnt,
       coalesce(ep.excluded_cnt, 0)::bigint AS excluded_cnt,
       o.sections_cnt,
       -- (отказы участка + alpha) / (отказы объекта + alpha * число участков объекта).
       -- Знаменатель строго положителен при alpha > 0, поэтому деления на ноль нет
       -- даже у объекта, где не отказывал никто: там каждый участок получает 1/N.
       ((coalesce(ep.episodes_cnt, 0) + n.alpha)
        / (o.object_episodes + n.alpha * o.sections_cnt))::numeric AS weight
  FROM uchastki u
  CROSS JOIN nastroiki n
  JOIN po_obiektu o ON o.object_id = u.object_id
  LEFT JOIN epizody ep ON ep.section_id = u.section_id;

COMMENT ON VIEW pred.section_weight IS
    'Доля вероятности объекта, приходящаяся на участок: (отказы+alpha)/(отказы объекта+alpha*N). Сумма weight внутри object_id равна 1 тождественно. Только участки, попавшие в feat.section_daily';
