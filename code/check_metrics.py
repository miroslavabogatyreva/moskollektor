def строки_качества(
    эпизодов, инцидентов, без_тега, m24, m0, порог, версии, участков_без_коллектора
):
    """Три строки приёмки по готовым числам. Без базы — поэтому проверяема assert'ом.

    m24 — прогон evaluate_alerts с горизонтом 24 ч, из него берём precision и recall.
    m0  — прогон с горизонтом 0, только он измеряет упреждение: при горизонте 24
    функция сначала выбрасывает все поздние предупреждения, а потом считает минимум
    по оставшимся, и провалиться такая проверка не может.
    """
    итог = []
    фон = (
        f"{ч(инцидентов)} инцидентов из {ч(эпизодов)} эпизодов, "
        f"порог вероятности {ч(порог, 2) if порог is not None else 'не задан'}"
    )

    # Отказ по умолчанию: пока нечего считать или считала заглушка, метрики
    # приёмочными числами не являются, какими бы они ни вышли.
    заглушки = [v for v in версии if v is None or v.startswith("stub")]
    отказ = None
    if порог is None:
        отказ = (
            "порог вероятности не задан (--threshold), решающее правило "
            "модели не зафиксировано — считать precision не из чего"
        )
    elif эпизодов == 0:
        отказ = f"в окне нет ни одного эпизода отказа: {фон}"
    elif инцидентов == 0:
        отказ = f"склейка дала ноль инцидентов при {ч(эпизодов)} эпизодах"
    elif инцидентов > эпизодов:
        отказ = (
            f"склейка сломана: инцидентов {ч(инцидентов)} больше, "
            f"чем эпизодов {ч(эпизодов)}"
        )
    elif not версии:
        отказ = "в окне выборки нет ни одного удачного прогона, прогнозов не существует"
    elif заглушки:
        отказ = (
            f"прогнозы в окне сделала заглушка модели ({', '.join(sorted(set(заглушки)))}), "
            f"файла весов обученной модели нет; {фон}"
        )

    if отказ:
        return [("М-18", False, отказ), ("М-19", False, отказ), ("М-20", False, отказ)]

    # Precision и recall — через precision_recall() (MOS-116), не заново: та же
    # формула стояла здесь отдельной копией и могла разойтись с verdict() молча.
    # Считаем из tp/fp/fn самой evaluate_alerts, а не из её же округлённых полей:
    # она округляет до трёх знаков, и настоящие 0,7004 приехали бы как 0,700
    # и провалили бы строгое «больше 0,7» на ровном месте.
    tp, fp, fn = m24["tp"], m24["fp"], m24["fn"]
    precision, recall = precision_recall(tp, fp, fn)
    хвост = (
        f" | эпизодов без тега канала {ч(без_тега)}, "
        f"участков без коллектора {ч(участков_без_коллектора)}"
        if (без_тега or участков_без_коллектора)
        else ""
    )

    итог.append(
        (
            "М-18",
            precision > PRECISION_МИН,
            f"precision {ч(precision)} {'больше' if precision > PRECISION_МИН else 'не больше'} "
            f"{ч(PRECISION_МИН, 1)} на {фон} (tp {ч(tp)}, fp {ч(fp)}), "
            f"модель {', '.join(sorted(set(версии)))}{хвост}",
        )
    )

    итог.append(
        (
            "М-19",
            recall > RECALL_МИН,
            f"recall {ч(recall)} {'больше' if recall > RECALL_МИН else 'не больше'} "
            f"{ч(RECALL_МИН, 1)} на {фон} (tp {ч(tp)}, fn {ч(fn)})",
        )
    )

    # Ловушка М-20 ловится здесь: verdict() возвращает None, когда горизонт прогона
    # сам гарантировал порог. None — это «не измерено», и на приёмку оно не идёт.
    _, проверки = verdict(
        m0, min_lead_hours=ГОРИЗОНТ_Ч, max_under_share=ДОЛЯ_ПОЗДНИХ_МАКС
    )
    ок_горизонт = проверки["lead_time"]
    медиана, доля, минимум = (
        m0["median_lead_hours"],
        m0["lead_under_24h_share"],
        m0["min_lead_hours"],
    )
    if ок_горизонт is None:
        итог.append(
            (
                "М-20",
                False,
                f"упреждение НЕ ИЗМЕРЕНО: прогон сделан с горизонтом "
                f"{m0['horizon_hours']} ч, а он выбрасывает поздние предупреждения "
                f"до подсчёта. Мерить обязан прогон с horizon_hours=0",
            )
        )
    elif медиана is None:
        итог.append(
            (
                "М-20",
                False,
                f"ни одно предупреждение не попало в инцидент: упреждение мерить не на чем, "
                f"{фон}",
            )
        )
    else:
        итог.append(
            (
                "М-20",
                bool(ок_горизонт),
                f"медиана упреждения {ч(медиана, 1)} ч при пороге {ГОРИЗОНТ_Ч}, "
                f"доля прогнозов короче {ГОРИЗОНТ_Ч} ч {ч(доля)} при пределе "
                f"{ч(ДОЛЯ_ПОЗДНИХ_МАКС, 2)}, минимум {ч(минимум, 1)} ч, "
                f"пойманных инцидентов {ч(m0['tp'])} из {ч(инцидентов)}",
            )
        )
    return итог


def строка_времени(прогон, участков_всего, строк_журнала, строк_свёртки):
    """Строка М-21 по одному прогону. Без двух чисел объёма замер не засчитывается."""
    if прогон is None:
        return (
            "М-21",
            False,
            "в pred.run нет ни одного завершённого прогона — замерять нечего",
        )
    секунд = (прогон["finished_at"] - прогон["started_at"]).total_seconds()
    посчитано = прогон["objects_scored"] or 0
    версия = прогон["model_version"] or "не названа"
    объём = (
        f"окно {ОКНО_РАСЧЁТА_СУТОК} суток до среза — {ч(строк_журнала)} строк "
        f"smvu.reading и {ч(строк_свёртки)} строк feat.section_daily, "
        f"участков в расчёте {ч(посчитано)} из {ч(участков_всего)} в ref.object_xref"
    )
    общее = (
        f"прогон {прогон['run_id']} от {мск(прогон['finished_at']):%d.%m.%Y %H:%M} мск, "
        f"срез {мск(прогон['as_of']):%d.%m.%Y %H:%M} мск, модель {версия}, {объём}"
    )

    # Две величины, а не одна: время расчёта само по себе ничего не доказывает,
    # если он шёл по сотне участков из трёх тысяч или его считала заглушка.
    if посчитано < участков_всего:
        return ("М-21", False, f"расчёт шёл не по всему парку: {общее}")
    if версия.startswith("stub"):
        return (
            "М-21",
            False,
            f"расчёт {ч(секунд, 1)} с, но считала заглушка модели: {общее}",
        )
    if строк_журнала == 0:
        return ("М-21", False, f"в окне расчёта нет ни одной строки журнала: {общее}")
    ок = секунд < РАСЧЁТ_СЕК_МАКС
    return (
        "М-21",
        ок,
        f"полный расчёт {ч(секунд, 1)} с "
        f"{'быстрее' if ок else 'не быстрее'} {РАСЧЁТ_СЕК_МАКС} с: {общее}",
    )


# ------------------------------------------------------------------ живой прогон


async def собрать(dsn, окно_от, окно_до, порог):
    import asyncpg  # локально: самопроверка обязана работать без базы и без пакета

    conn = await asyncpg.connect(dsn)
    try:
        # 1. Эпизоды отказа. Определение из docs/acceptance-test.md: значение
        # «Неисправен», эпизод длиннее часа. Тег канала берём для склейки, а каналу
        # без тега даём собственный ключ без дефиса: 1 142 канала из журнала в справочник
        # заказчика не попали, и молча выкинуть их джойном нельзя.
        эпизоды = await conn.fetch(
            """SELECT coalesce(c.tag, 'ch' || e.channel_id) AS tag,
                      e.started_at, c.tag IS NULL AS без_тега
                 FROM smvu.fault_episode e JOIN smvu.channel c USING (channel_id)
                WHERE e.fault_value = 'Неисправен'
                  AND e.started_at >= $1 AND e.started_at < $2
                  AND e.ended_at IS NOT NULL
                  AND e.ended_at - e.started_at > interval '1 hour'""",
            окно_от,
            окно_до,
        )

        # 2. Участок -> коллектор. Тот же префикс тега, что и у отказов: сравнивать
        # предупреждение по участку с инцидентом по коллектору иначе нечем.
        карта = {
            r["section_id"]: r["pfx"]
            for r in await conn.fetch(
                """SELECT section_id, split_part(tag, '-', 1) AS pfx
                 FROM smvu.channel
                WHERE tag IS NOT NULL AND section_id IS NOT NULL
                GROUP BY 1, 2"""
            )
        }

        # 3. Предупреждения: прогнозы удачных прогонов, чей срез попал в окно.
        прогнозы = await conn.fetch(
            """SELECT r.as_of, f.section_id, f.probability
                 FROM pred.forecast f JOIN pred.run r USING (run_id)
                WHERE f.direction = $3 AND r.status = 'done'
                  AND r.as_of >= $1 AND r.as_of < $2
                  AND f.probability >= $4""",
            окно_от,
            окно_до,
            НАПРАВЛЕНИЕ,
            порог if порог is not None else 2.0,
        )

        версии = [
            r["model_version"]
            for r in await conn.fetch(
                """SELECT DISTINCT model_version FROM pred.run
                WHERE status = 'done' AND as_of >= $1 AND as_of < $2""",
                окно_от,
                окно_до,
            )
        ]

        # 4. Замер времени: последний завершённый прогон и объём, который он читал.
        прогон = await conn.fetchrow(
            """SELECT run_id, as_of, started_at, finished_at, model_version,
                      objects_total, objects_scored
                 FROM pred.run
                WHERE status = 'done' AND finished_at IS NOT NULL
                ORDER BY run_id DESC LIMIT 1"""
        )
        участков_всего = await conn.fetchval("SELECT count(*) FROM ref.object_xref")
        строк_журнала = строк_свёртки = 0
        if прогон:
            срез = прогон["as_of"]
            строк_журнала = await conn.fetchval(
                """SELECT count(*) FROM smvu.reading
                    WHERE read_time > $1::timestamptz - make_interval(days => $2::int)
                      AND read_time <= $1""",
                срез,
                ОКНО_РАСЧЁТА_СУТОК,
            )
            строк_свёртки = await conn.fetchval(
                """SELECT count(*) FROM feat.section_daily
                    WHERE day > ($1::timestamptz)::date - $2::int
                      AND day <= ($1::timestamptz)::date""",
                срез,
                ОКНО_РАСЧЁТА_СУТОК,
            )
    finally:
        await conn.close()

    отказы = [(r["tag"], r["started_at"]) for r in эпизоды]
    без_тега = sum(1 for r in эпизоды if r["без_тега"])

    # Одно предупреждение на коллектор и срез — худшая вероятность среди его участков.
    # Считать каждый участок отдельным предупреждением нельзя по той же причине,
    # по которой пачка из 75 каналов — один инцидент: диспетчер видит одно событие.
    лучшее, без_коллектора = {}, set()
    for r in прогнозы:
        pfx = карта.get(r["section_id"])
        if pfx is None:
            без_коллектора.add(r["section_id"])
            continue
        ключ = (pfx, r["as_of"])
        лучшее[ключ] = max(лучшее.get(ключ, 0.0), r["probability"])
    предупреждения = [(pfx, t) for pfx, t in лучшее]

    return dict(
        отказы=отказы,
        без_тега=без_тега,
        предупреждения=предупреждения,
        версии=версии,
        без_коллектора=len(без_коллектора),
        прогон=прогон,
        участков_всего=участков_всего,
        строк_журнала=строк_журнала,
        строк_свёртки=строк_свёртки,
    )


def отчёт(данные, порог):
    инциденты = group_incidents(
        данные["отказы"], window_minutes=ОКНО_СКЛЕЙКИ_МИН, group_key=пфх
    )
    m24 = evaluate_alerts(данные["предупреждения"], инциденты, horizon_hours=ГОРИЗОНТ_Ч)
    m0 = evaluate_alerts(данные["предупреждения"], инциденты, horizon_hours=0)
    строки = строки_качества(
        len(данные["отказы"]),
        len(инциденты),
        данные["без_тега"],
        m24,
        m0,
        порог,
        данные["версии"],
        данные["без_коллектора"],
    )
    строки.append(
        строка_времени(
            данные["прогон"],
            данные["участков_всего"],
            данные["строк_журнала"],
            данные["строк_свёртки"],
        )
    )
    return строки


# ---------------------------------------------------------------- самопроверка


def _selfcheck():
    d = datetime.fromisoformat

    # Ловушка М-20, ради которой скрипт и написан. Пять инцидентов, у одного
    # упреждение 6 часов. Прогон с горизонтом 24 обязан сказать «не измерено»,
    # прогон с нулевым горизонтом — показать настоящие медиану, минимум и долю.
    алерты, отказы = [], []
    for i, lead in enumerate([72, 48, 36, 30, 6]):
        отказ = d("2026-04-10 00:00")
        алерты.append((f"S{i}", отказ - timedelta(hours=lead)))
        отказы.append((f"S{i}", отказ))
    m24 = evaluate_alerts(алерты, отказы, horizon_hours=24)
    m0 = evaluate_alerts(алерты, отказы, horizon_hours=0)
    assert m0["median_lead_hours"] == 36.0 and m0["min_lead_hours"] == 6.0, m0

    сл = dict(
        эпизодов=587,
        инцидентов=176,
        без_тега=0,
        порог=0.8,
        версии=["rf-1.2"],
        участков_без_коллектора=0,
    )
    по24 = {
        n: (ok, t) for n, ok, t in строки_качества(m24=m24, m0=m24, **сл)
    }  # подсунут прогон с горизонтом 24
    assert по24["М-20"][0] is False, по24["М-20"]
    assert "НЕ ИЗМЕРЕНО" in по24["М-20"][1], по24["М-20"]

    по0 = {n: (ok, t) for n, ok, t in строки_качества(m24=m24, m0=m0, **сл)}
    assert по0["М-20"][0] is True, по0["М-20"]  # медиана 36 ч, доля 0,2
    assert "36,0 ч" in по0["М-20"][1] and "0,200" in по0["М-20"][1], по0["М-20"]

    # Шестой инцидент с упреждением 10 часов: медиана всё ещё выше 24, а доля
    # поздних 2 из 6 — порог пробит. Проверка обязана связывать два числа, а не одно.
    алерты.append(("S5", d("2026-04-10 00:00") - timedelta(hours=10)))
    отказы.append(("S5", d("2026-04-10 00:00")))
    хуже = evaluate_alerts(алерты, отказы, horizon_hours=0)
    assert строки_качества(m24=m24, m0=хуже, **сл)[2][1] is False, хуже

    # Строгое неравенство М-18: ровно 0,700 постановку не закрывает.
    ровно = {
        "tp": 7,
        "fp": 3,
        "fn": 0,
        "precision": 0.7,
        "recall": 1.0,
        "median_lead_hours": 48.0,
        "min_lead_hours": 48.0,
        "lead_under_24h_share": 0.0,
        "horizon_hours": 0,
    }
    строки = {n: (ok, t) for n, ok, t in строки_качества(m24=ровно, m0=ровно, **сл)}
    assert строки["М-18"][0] is False, строки["М-18"]
    assert строки["М-19"][0] is True, строки["М-19"]
    assert "176 инцидентов из 587 эпизодов" in строки["М-18"][1], строки["М-18"]
    # Чуть выше порога — уже OK, и округление до трёх знаков этому не мешает.
    выше = dict(ровно, tp=7001, fp=2999)
    assert строки_качества(m24=выше, m0=выше, **сл)[0][1] is True

    # Отказ по умолчанию: без порога, без инцидентов, на заглушке — красное.
    assert all(
        not ok
        for _, ok, _ in строки_качества(m24=ровно, m0=ровно, **dict(сл, порог=None))
    )
    assert all(
        not ok
        for _, ok, _ in строки_качества(m24=ровно, m0=ровно, **dict(сл, инцидентов=0))
    )
    на_заглушке = строки_качества(m24=ровно, m0=ровно, **dict(сл, версии=["stub-0.1"]))
    assert all(not ok for _, ok, _ in на_заглушке) and "заглушка" in на_заглушке[0][2]

    # М-21: те же две величины. Уложился по времени, но не по парку — это СБОЙ.
    прогон = {
        "run_id": 51,
        "as_of": d("2026-06-30 23:59:59"),
        "started_at": d("2026-09-16 10:39:57"),
        "finished_at": d("2026-09-16 10:40:53"),
        "model_version": "rf-1.2",
        "objects_total": 3173,
        "objects_scored": 3173,
    }
    ок, текст = строка_времени(прогон, 3173, 60096602, 255635)[1:]
    assert ок is True and "3 173" in текст and "60 096 602" in текст, текст
    assert строка_времени(dict(прогон, objects_scored=50), 3173, 1, 1)[1] is False
    assert (
        строка_времени(dict(прогон, model_version="stub-0.1"), 3173, 1, 1)[1] is False
    )
    медленный = dict(прогон, finished_at=d("2026-09-16 10:46:00"))
    assert строка_времени(медленный, 3173, 60096602, 255635)[1] is False
    assert строка_времени(None, 3173, 0, 0)[1] is False

    print("самопроверка ok: ловушка М-20, строгий порог М-18, отказ по умолчанию, М-21")


# ----------------------------------------------------------------------- запуск


def main():
    р = argparse.ArgumentParser(description="Проверка метрик М-18…М-21")
    р.add_argument(
        "--threshold",
        type=float,
        help="порог вероятности, выше которого прогноз считается "
        "предупреждением; фиксируется протоколом до испытаний",
    )
    р.add_argument(
        "--from", dest="от", default=ОКНО_ОТ, help="начало отложенной выборки"
    )
    р.add_argument("--to", dest="до", default=ОКНО_ДО, help="конец выборки, не включая")
    р.add_argument("--selfcheck", action="store_true", help="только самопроверка")
    а = р.parse_args()

    _selfcheck()
    if а.selfcheck:
        return 0

    dsn = os.environ.get("DATABASE_URL")
    try:
        if not dsn:
            raise RuntimeError("не задан DATABASE_URL")
        данные = asyncio.run(
            собрать(
                dsn,
                datetime.fromisoformat(а.от),
                datetime.fromisoformat(а.до),
                а.threshold,
            )
        )
        строки = отчёт(данные, а.threshold)
    except Exception as e:
        # Нет базы — нет доказательства. Это отказ по всем четырём строкам,
        # а не повод промолчать.
        строки = [
            (n, False, f"проверка не выполнена: {type(e).__name__}: {e}")
            for n in ("М-18", "М-19", "М-20", "М-21")
        ]

    for номер, ок, текст in строки:
        print(f"{номер} {'OK' if ок else 'СБОЙ'} {текст}")
    return 0 if all(ок for _, ок, _ in строки) else 1


if __name__ == "__main__":
    sys.exit(main())
