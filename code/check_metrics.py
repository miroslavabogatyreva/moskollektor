async def собрать(dsn, окно_от, окно_до, порог):
    import asyncpg  # локально: самопроверка обязана работать без базы и без пакета

    conn = await asyncpg.connect(dsn)
    try:
        # Пороги читает администратор через PUT /api/settings (MOS-110, Q4.12).
        # Пропавшая ТАБЛИЦА — отказ на общих основаниях (упадёт ниже вместе
        # с остальными запросами, поймает except Exception в main()). Пропавшая
        # СТРОКА — не то же самое: это «нечем мерить», а не сломанный расчёт
        # (58, 57, 18.09.2026), поэтому .get() и None, а не KeyError; строки_качества()
        # превращает None в ПРОПУСК с объяснением, а не в СБОЙ.
        пороги = {
            r["key"]: float(r["value"])
            for r in await conn.fetch(
                "SELECT key, value FROM ref.app_setting "
                "WHERE key IN ('precision_min', 'recall_min')"
            )
        }
        precision_min = пороги.get("precision_min")
        recall_min = пороги.get("recall_min")

        # 1. Эпизоды отказа. Определение из docs/acceptance-test.md: значение
        # «Неисправен», эпизод длиннее часа.
        #
        # КАКОЕ ИЗ ДВУХ УСЛОВИЙ ЗДЕСЬ РАБОТАЕТ, а какое холостое — знать стоит,
        # иначе спор «а если порог сделать полчаса» будет вестись в уверенности,
        # что запрос это учтёт. Пара чисел на 17.09.2026: `ended_at IS NOT NULL`
        # отсекает 57 незакрытых эпизодов, а `> interval '1 hour'` не отсекает
        # НИ ОДНОГО — закрытых эпизодов короче часа в таблице ноль, самый короткий
        # длится 3 601 секунду, следующий 3 602. Порог в час уже применён при
        # построении smvu.fault_episode, и запрос повторяет его вхолостую.
        # Условие всё равно оставлено: оно записывает определение эпизода прямо
        # в запросе и начнёт работать в тот день, когда порог построения сдвинут.
        # Нашла это проверяющая сессия, разложив 10 476 эпизодов на 10 419
        # закрытых и 57 незакрытых. Тег канала берём для склейки, а каналу
        # без тега даём собственный ключ без дефиса: 1 142 канала из журнала в справочник
        # заказчика не попали, и молча выкинуть их джойном нельзя.
        эпизоды = await conn.fetch(
            """SELECT e.channel_id, e.started_at, t2.object_id AS collector_id
                 FROM smvu.fault_episode e JOIN smvu.channel c USING (channel_id)
                 LEFT JOIN smvu.object_tree t3 ON t3.object_id = c.object_id
                 LEFT JOIN smvu.object_tree t2 ON t2.object_id = t3.parent_id
                WHERE e.fault_value = 'Неисправен'
                  AND e.started_at >= $1 AND e.started_at < $2
                  AND e.ended_at IS NOT NULL
                  AND e.ended_at - e.started_at > interval '1 hour'""",
            окно_от,
            окно_до,
        )

        # 2. Участок -> коллектор. Тот же префикс тега, что и у отказов: сравнивать
        # предупреждение по участку с инцидентом по коллектору иначе нечем.
        # Коллектор участка — тот же узел дерева, что и у отказов: сравнивать
        # предупреждение по участку с инцидентом по коллектору иначе нечем.
        # Участок берёт коллектор, на котором висит БОЛЬШЕ его каналов. Такой выбор
        # нужен ровно одному участку из 3 173 — 1490, ключ СМВУ «798:0», его каналы
        # разделены между объектами Бета и Зита (проверено 17.09.2026). Число
        # спорных участков возвращается наружу и печатается: молчаливый max()
        # спрятал бы его, а завтра их станет десять.
        строки_карты = await conn.fetch(
            """SELECT c.section_id, t2.object_id AS collector_id, count(*) AS каналов
                 FROM smvu.channel c
                 JOIN smvu.object_tree t3 ON t3.object_id = c.object_id
                 JOIN smvu.object_tree t2 ON t2.object_id = t3.parent_id
                WHERE c.section_id IS NOT NULL
                GROUP BY 1, 2"""
        )
        карта, вариантов = {}, {}
        for r in sorted(строки_карты, key=lambda r: -r["каналов"]):
            вариантов[r["section_id"]] = вариантов.get(r["section_id"], 0) + 1
            карта.setdefault(r["section_id"], f"obj:{r['collector_id']}")
        спорных_участков = sum(1 for n in вариантов.values() if n > 1)

        # 3. Предупреждения: прогнозы удачных прогонов, чей срез попал в окно.
        прогнозы = await conn.fetch(
            """SELECT r.as_of, f.section_id, f.probability
                 FROM pred.forecast f JOIN pred.run r USING (run_id)
                WHERE f.direction = $3 AND r.status = 'done'
                  AND r.as_of >= $1 AND r.as_of < $2
                  AND f.probability >= $4""",
            окно_от,
            окно_до,
            НАПРАВЛЕНИЕ,
            порог if порог is not None else 2.0,
        )

        версии = [
            r["model_version"]
            for r in await conn.fetch(
                """SELECT DISTINCT model_version FROM pred.run
                WHERE status = 'done' AND as_of >= $1 AND as_of < $2""",
                окно_от,
                окно_до,
            )
        ]

        # 4. Замер времени: последний ПОЛНЫЙ прогон и объём, который он читал.
        #
        # Именно полный, а не просто последний. Прогоны по одному объекту мы
        # делаем нарочно — их требует строка НФ-72, — и такой прогон забирал
        # себе строку М-21: 17.09.2026 проверка покраснела словами «расчёт шёл
        # не по всему парку, участков в расчёте 1 из 3 173», хотя полные прогоны
        # лежали в журнале рядом, соседними номерами.
        #
        # Запасной запрос без условия оставлен нарочно. Убери его — и когда
        # полного прогона нет вовсе, fetchrow вернёт None, а проверка скажет
        # «в pred.run нет ни одного завершённого прогона», хотя прогоны есть
        # и они неполные. Это разные диагнозы, и вторая ветка ниже умеет назвать
        # второй. Дата прогона печатается в отчёте: зелёная строка на вчерашнем
        # замере видна глазами.
        ПРОГОН = """SELECT run_id, as_of, started_at, finished_at, model_version,
                           objects_total, objects_scored
                      FROM pred.run
                     WHERE status = 'done' AND finished_at IS NOT NULL {}
                     ORDER BY run_id DESC LIMIT 1"""
        прогон = await conn.fetchrow(
            ПРОГОН.format("AND objects_scored = (SELECT count(*) FROM ref.object_xref)")
        ) or await conn.fetchrow(ПРОГОН.format(""))
        участков_всего = await conn.fetchval("SELECT count(*) FROM ref.object_xref")
        строк_журнала = строк_свёртки = 0
        if прогон:
            срез = прогон["as_of"]
            строк_журнала = await conn.fetchval(
                """SELECT count(*) FROM smvu.reading
                    WHERE read_time > $1::timestamptz - make_interval(days => $2::int)
                      AND read_time <= $1""",
                срез,
                ОКНО_РАСЧЁТА_СУТОК,
            )
            строк_свёртки = await conn.fetchval(
                """SELECT count(*) FROM feat.section_daily
                    WHERE day > ($1::timestamptz)::date - $2::int
                      AND day <= ($1::timestamptz)::date""",
                срез,
                ОКНО_РАСЧЁТА_СУТОК,
            )
    finally:
        await conn.close()

    # Ключ группы даёт словарь «канал -> коллектор», а не разбор строки тега.
    коллектор_канала = {r["channel_id"]: r["collector_id"]
                        for r in эпизоды if r["collector_id"] is not None}
    отказы = [(r["channel_id"], r["started_at"]) for r in эпизоды]
    без_узла = sum(1 for r in эпизоды if r["collector_id"] is None)

    # Одно предупреждение на коллектор и срез — худшая вероятность среди его участков.
    # Считать каждый участок отдельным предупреждением нельзя по той же причине,
    # по которой пачка из 75 каналов — один инцидент: диспетчер видит одно событие.
    лучшее, без_коллектора = {}, set()
    for r in прогнозы:
        коллектор = карта.get(r["section_id"])
        if коллектор is None:
            без_коллектора.add(r["section_id"])
            continue
        ключ = (коллектор, r["as_of"])
        лучшее[ключ] = max(лучшее.get(ключ, 0.0), r["probability"])
    предупреждения = [(коллектор, t) for коллектор, t in лучшее]

    return dict(
        отказы=отказы,
        коллектор_канала=коллектор_канала,
        без_узла=без_узла,
        спорных_участков=спорных_участков,
        предупреждения=предупреждения,
        версии=версии,
        без_коллектора=len(без_коллектора),
        прогон=прогон,
        участков_всего=участков_всего,
        строк_журнала=строк_журнала,
        строк_свёртки=строк_свёртки,
        precision_min=precision_min,
        recall_min=recall_min,
    )


def отчёт(данные, порог):
    инциденты = group_incidents(
        данные["отказы"], window_minutes=ОКНО_СКЛЕЙКИ_МИН,
        group_key=collector_key(данные["коллектор_канала"]),
    )
    m24 = evaluate_alerts(данные["предупреждения"], инциденты, horizon_hours=ГОРИЗОНТ_Ч)
    m0 = evaluate_alerts(данные["предупреждения"], инциденты, horizon_hours=0)
    строки = строки_качества(
        len(данные["отказы"]),
        len(инциденты),
        данные["без_узла"],
        m24,
        m0,
        порог,
        данные["версии"],
        данные["без_коллектора"],
        precision_min=данные["precision_min"],
        recall_min=данные["recall_min"],
    )
    строки.append(
        строка_времени(
            данные["прогон"],
            данные["участков_всего"],
            данные["строк_журнала"],
            данные["строк_свёртки"],
        )
    )
    return строки


# ---------------------------------------------------------------- самопроверка


def _selfcheck():
    d = datetime.fromisoformat

    # Ловушка М-20, ради которой скрипт и написан. Пять инцидентов, у одного
    # упреждение 6 часов. Прогон с горизонтом 24 обязан сказать «не измерено»,
    # прогон с нулевым горизонтом — показать настоящие медиану, минимум и долю.
    алерты, отказы = [], []
    for i, lead in enumerate([72, 48, 36, 30, 6]):
        отказ = d("2026-04-10 00:00")
        алерты.append((f"S{i}", отказ - timedelta(hours=lead)))
        отказы.append((f"S{i}", отказ))
    m24 = evaluate_alerts(алерты, отказы, horizon_hours=24)
    m0 = evaluate_alerts(алерты, отказы, horizon_hours=0)
    assert m0["median_lead_hours"] == 36.0 and m0["min_lead_hours"] == 6.0, m0

    сл = dict(
        эпизодов=587,
        инцидентов=176,
        без_узла=0,
        порог=0.8,
        версии=["rf-1.2"],
        участков_без_коллектора=0,
    )
    по24 = {
        n: (ok, t) for n, ok, t in строки_качества(m24=m24, m0=m24, **сл)
    }  # подсунут прогон с горизонтом 24
    assert по24["М-20"][0] is False, по24["М-20"]
    assert "НЕ ИЗМЕРЕНО" in по24["М-20"][1], по24["М-20"]

    по0 = {n: (ok, t) for n, ok, t in строки_качества(m24=m24, m0=m0, **сл)}
    assert по0["М-20"][0] is True, по0["М-20"]  # медиана 36 ч, доля 0,2
    assert "36,0 ч" in по0["М-20"][1] and "0,200" in по0["М-20"][1], по0["М-20"]

    # Шестой инцидент с упреждением 10 часов: медиана всё ещё выше 24, а доля
    # поздних 2 из 6 — порог пробит. Проверка обязана связывать два числа, а не одно.
    алерты.append(("S5", d("2026-04-10 00:00") - timedelta(hours=10)))
    отказы.append(("S5", d("2026-04-10 00:00")))
    хуже = evaluate_alerts(алерты, отказы, horizon_hours=0)
    assert строки_качества(m24=m24, m0=хуже, **сл)[2][1] is False, хуже

    # Строгое неравенство М-18: ровно 0,700 постановку не закрывает.
    ровно = {
        "tp": 7,
        "fp": 3,
        "fn": 0,
        "precision": 0.7,
        "recall": 1.0,
        "median_lead_hours": 48.0,
        "min_lead_hours": 48.0,
        "lead_under_24h_share": 0.0,
        "horizon_hours": 0,
    }
    строки = {n: (ok, t) for n, ok, t in строки_качества(m24=ровно, m0=ровно, **сл)}
    assert строки["М-18"][0] is False, строки["М-18"]
    assert строки["М-19"][0] is True, строки["М-19"]
    assert "176 инцидентов из 587 эпизодов" in строки["М-18"][1], строки["М-18"]
    # Чуть выше порога — уже OK, и округление до трёх знаков этому не мешает.
    выше = dict(ровно, tp=7001, fp=2999)
    assert строки_качества(m24=выше, m0=выше, **сл)[0][1] is True

    # Отказ по умолчанию: без порога, без инцидентов, на заглушке — красное.
    assert all(
        not ok
        for _, ok, _ in строки_качества(m24=ровно, m0=ровно, **dict(сл, порог=None))
    )
    assert all(
        not ok
        for _, ok, _ in строки_качества(m24=ровно, m0=ровно, **dict(сл, инцидентов=0))
    )
    # Заглушка — это ПРОПУСК, а не СБОЙ, и проверять надо именно `is None`:
    # `not ok` прошло бы и на False, то есть не отличило бы третий исход от второго.
    на_заглушке = строки_качества(m24=ровно, m0=ровно, **dict(сл, версии=["stub-0.1"]))
    assert all(ok is None for _, ok, _ in на_заглушке), на_заглушке
    assert "заглушка" in на_заглушке[0][2], на_заглушке[0][2]
    # А пустые данные остаются СБОЕМ: иначе мёртвый расчёт даст зелёный прогон.
    пусто = строки_качества(m24=ровно, m0=ровно, **dict(сл, эпизодов=0, инцидентов=0))
    assert all(ok is False for _, ok, _ in пусто), пусто

    # MOS-110 (Q4.12), пункт 3 у 58: пропавший порог в ref.app_setting — тоже
    # ПРОПУСК, не СБОЙ, тем же способом, что заглушка модели.
    без_precision = строки_качества(m24=ровно, m0=ровно, precision_min=None, **сл)
    assert all(ok is None for _, ok, _ in без_precision), без_precision
    assert "ref.app_setting" in без_precision[0][2], без_precision[0][2]
    без_recall = строки_качества(m24=ровно, m0=ровно, recall_min=None, **сл)
    assert all(ok is None for _, ok, _ in без_recall), без_recall

    # Порог из базы обязан реально решать исход, не только доходить до функции:
    # precision 0,65 красная при дефолтном 0,7 и зелёная при админском 0,6.
    ниже_дефолта = dict(
        tp=13, fp=7, fn=0, precision=0.65, recall=1.0,
        median_lead_hours=48.0, min_lead_hours=48.0,
        lead_under_24h_share=0.0, horizon_hours=0,
    )
    по_дефолту = строки_качества(m24=ниже_дефолта, m0=ниже_дефолта, **сл)
    assert по_дефолту[0][1] is False, по_дефолту[0]
    assert "понижен" not in по_дефолту[0][2], по_дефолту[0]  # дефолт не подписываем
    с_админским_порогом = строки_качества(
        m24=ниже_дефолта, m0=ниже_дефолта, precision_min=0.6, **сл
    )
    assert с_админским_порогом[0][1] is True, с_админским_порогом[0]
    # Зелёная строка обязана сама сказать, что порог ниже постановочного (58,
    # 18.09.2026): без подписи «М-18 OK» читается как «постановка закрыта»,
    # хотя закрыт только пониженный, ещё не обоснованный в описании MVP порог.
    assert "понижен" in с_админским_порогом[0][2] and "0,7" in с_админским_порогом[0][2], (
        с_админским_порогом[0]
    )

    # М-21: те же две величины. Уложился по времени, но не по парку — это СБОЙ.
    прогон = {
        "run_id": 51,
        "as_of": d("2026-06-30 23:59:59"),
        "started_at": d("2026-09-16 10:39:57"),
        "finished_at": d("2026-09-16 10:40:53"),
        "model_version": "rf-1.2",
        "objects_total": 3173,
        "objects_scored": 3173,
    }
    ок, текст = строка_времени(прогон, 3173, 60096602, 255635)[1:]
    assert ок is True and "3 173" in текст and "60 096 602" in текст, текст
    assert строка_времени(dict(прогон, objects_scored=50), 3173, 1, 1)[1] is False
    # Заглушка модели строку М-21 не валит — но обязана быть названа в тексте.
    на_заглушке21 = строка_времени(
        dict(прогон, model_version="stub-0.1"), 3173, 60096602, 255635
    )
    assert на_заглушке21[1] is True, на_заглушке21
    assert "инференс заглушки" in на_заглушке21[2], на_заглушке21[2]
    медленный = dict(прогон, finished_at=d("2026-09-16 10:46:00"))
    assert строка_времени(медленный, 3173, 60096602, 255635)[1] is False
    assert строка_времени(None, 3173, 0, 0)[1] is False

    print("самопроверка ok: ловушка М-20, строгий порог М-18, отказ по умолчанию, М-21")


# ----------------------------------------------------------------------- запуск


def main():
    р = argparse.ArgumentParser(description="Проверка метрик М-18…М-21")
    р.add_argument(
        "--threshold",
        type=float,
        help="порог вероятности, выше которого прогноз считается "
        "предупреждением; фиксируется протоколом до испытаний",
    )
    р.add_argument(
        "--from", dest="от", default=ОКНО_ОТ, help="начало отложенной выборки"
    )
    р.add_argument("--to", dest="до", default=ОКНО_ДО, help="конец выборки, не включая")
    р.add_argument("--selfcheck", action="store_true", help="только самопроверка")
    а = р.parse_args()

    _selfcheck()
    if а.selfcheck:
        return 0

    dsn = os.environ.get("DATABASE_URL")
    try:
        if not dsn:
            raise RuntimeError("не задан DATABASE_URL")
        данные = asyncio.run(
            собрать(
                dsn,
                datetime.fromisoformat(а.от),
                datetime.fromisoformat(а.до),
                а.threshold,
            )
        )
        строки = отчёт(данные, а.threshold)
    except Exception as e:
        # Нет базы — нет доказательства. Это отказ по всем четырём строкам,
        # а не повод промолчать.
        строки = [
            (n, False, f"проверка не выполнена: {type(e).__name__}: {e}")
            for n in ("М-18", "М-19", "М-20", "М-21")
        ]

    for номер, ок, текст in строки:
        исход = "ПРОПУСК" if ок is None else ("OK" if ок else "СБОЙ")
        print(f"{номер} {исход} {текст}")
    # ПРОПУСК не роняет прогон: измерить не удалось — это не «не сошлось».
    # Роняет только False.
    return 1 if any(ок is False for _, ок, _ in строки) else 0


if __name__ == "__main__":
    sys.exit(main())
