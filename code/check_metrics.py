def строки_качества(
    эпизодов, инцидентов, без_узла, m24, m0, порог, версии, участков_без_коллектора,
    precision_min=PRECISION_МИН, recall_min=RECALL_МИН,
):
    """Три строки приёмки по готовым числам. Без базы — поэтому проверяема assert'ом.

    m24 — прогон evaluate_alerts с горизонтом 24 ч, из него берём precision и recall.
    m0  — прогон с горизонтом 0, только он измеряет упреждение: при горизонте 24
    функция сначала выбрасывает все поздние предупреждения, а потом считает минимум
    по оставшимся, и провалиться такая проверка не может.

    precision_min и recall_min по умолчанию — константы постановки, тем же
    значением их вызывает самопроверка без базы. С базой отчёт() передаёт то,
    что реально лежит в ref.app_setting (MOS-110, Q4.12): администратор мог
    их поправить через PUT /api/settings, и приёмка обязана мерить против
    живого порога, а не против того, что было на момент сборки образа.
    """
    итог = []
    фон = (
        f"{ч(инцидентов)} инцидентов из {ч(эпизодов)} эпизодов, "
        f"порог вероятности {ч(порог, 2) if порог is not None else 'не задан'}"
    )

    # Отказ по умолчанию: пока нечего считать или считала заглушка, метрики
    # приёмочными числами не являются, какими бы они ни вышли.
    заглушки = [v for v in версии if v is None or v.startswith("stub")]

    # Три исхода, а не два. ПРОПУСК — когда мерить нечем: нет решающего порога,
    # прогнозы сделала заглушка. Такие строки не красные и не зелёные, и красить
    # их в красное вредно — проверка, которая краснеет всегда, не отличает
    # исправное от сломанного.
    #
    # Пустые данные в этот список НЕ входят нарочно. «В окне нет ни одного
    # эпизода» и «склейка дала ноль инцидентов» выглядят как «нечего мерить»,
    # а означают обычно сломанную заливку или сломанную склейку. Отпусти их
    # в ПРОПУСК — и полностью мёртвый расчёт даст зелёный прогон.
    непроверяемо = None
    отказ = None
    if порог is None:
        непроверяемо = (
            "решающий порог не зафиксирован (--threshold): это решение Николая, "
            "без него precision считать не из чего"
        )
    elif precision_min is None or recall_min is None:
        # Такая же «нечем мерить», как отсутствующий --threshold (58, 57,
        # 18.09.2026) — пропавшая строка в ref.app_setting это чужая, внешняя
        # причина, а не поломка расчёта, и красить её в СБОЙ вместе с реально
        # разошедшимися числами нельзя: два разных происшествия выглядели бы
        # одинаково красными на приёмке.
        непроверяемо = (
            "precision_min и/или recall_min не заданы в ref.app_setting — "
            "миграция 020_app_setting.sql не накатана или строки удалены"
        )
    elif эпизодов == 0:
        отказ = f"в окне нет ни одного эпизода отказа: {фон}"
    elif инцидентов == 0:
        отказ = f"склейка дала ноль инцидентов при {ч(эпизодов)} эпизодах"
    elif инцидентов > эпизодов:
        отказ = (
            f"склейка сломана: инцидентов {ч(инцидентов)} больше, "
            f"чем эпизодов {ч(эпизодов)}"
        )
    elif not версии:
        отказ = "в окне выборки нет ни одного удачного прогона, прогнозов не существует"
    elif заглушки:
        непроверяемо = (
            f"прогнозы в окне сделала заглушка модели ({', '.join(sorted(set(заглушки)))}), "
            f"файла весов обученной модели нет — метрики не измеримы до модели "
            f"Николая; {фон}"
        )

    if отказ:
        return [("М-18", False, отказ), ("М-19", False, отказ), ("М-20", False, отказ)]
    if непроверяемо:
        return [("М-18", None, непроверяемо), ("М-19", None, непроверяемо),
                ("М-20", None, непроверяемо)]

    # Precision и recall — через precision_recall() (MOS-116), не заново: та же
    # формула стояла здесь отдельной копией и могла разойтись с verdict() молча.
    # Считаем из tp/fp/fn самой evaluate_alerts, а не из её же округлённых полей:
    # она округляет до трёх знаков, и настоящие 0,7004 приехали бы как 0,700
    # и провалили бы строгое «больше 0,7» на ровном месте.
    tp, fp, fn = m24["tp"], m24["fp"], m24["fn"]
    precision, recall = precision_recall(tp, fp, fn)
    хвост = (
        f" | эпизодов у каналов без узла дерева {ч(без_узла)}, "
        f"участков без коллектора {ч(участков_без_коллектора)}"
        if (без_узла or участков_без_коллектора)
        else ""
    )

    # Порог можно понизить админкой, но платно (CLAUDE.md): «в описании MVP
    # вы даёте указание на то, почему такие значения». Зелёная строка сама
    # по себе этого не говорит — 58 поймала на собственной самопроверке, что
    # М-18 OK при 0,65 читается как «постановка закрыта», хотя закрыт только
    # пониженный порог. Подпись — только при фактическом понижении, чтобы
    # обычный прогон на дефолте не оброс лишним текстом.
    понижен_precision = (
        f" — порог понижен с постановочных {ч(PRECISION_МИН, 1)}, "
        f"обоснование в описании MVP"
        if precision_min < PRECISION_МИН else ""
    )
    понижен_recall = (
        f" — порог понижен с постановочных {ч(RECALL_МИН, 1)}, "
        f"обоснование в описании MVP"
        if recall_min < RECALL_МИН else ""
    )

    итог.append(
        (
            "М-18",
            precision > precision_min,
            f"precision {ч(precision)} {'больше' if precision > precision_min else 'не больше'} "
            f"{ч(precision_min, 1)} на {фон} (tp {ч(tp)}, fp {ч(fp)}), "
            f"модель {', '.join(sorted(set(версии)))}{хвост}{понижен_precision}",
        )
    )

    итог.append(
        (
            "М-19",
            recall > recall_min,
            f"recall {ч(recall)} {'больше' if recall > recall_min else 'не больше'} "
            f"{ч(recall_min, 1)} на {фон} (tp {ч(tp)}, fn {ч(fn)}){понижен_recall}",
        )
    )

    # Ловушка М-20 ловится здесь: verdict() возвращает None, когда горизонт прогона
    # сам гарантировал порог. None — это «не измерено», и на приёмку оно не идёт.
    _, проверки = verdict(
        m0, min_lead_hours=ГОРИЗОНТ_Ч, max_under_share=ДОЛЯ_ПОЗДНИХ_МАКС
    )
    ок_горизонт = проверки["lead_time"]
    медиана, доля, минимум = (
        m0["median_lead_hours"],
        m0["lead_under_24h_share"],
        m0["min_lead_hours"],
    )
    if ок_горизонт is None:
        итог.append(
            (
                "М-20",
                False,
                f"упреждение НЕ ИЗМЕРЕНО: прогон сделан с горизонтом "
                f"{m0['horizon_hours']} ч, а он выбрасывает поздние предупреждения "
                f"до подсчёта. Мерить обязан прогон с horizon_hours=0",
            )
        )
    elif медиана is None:
        итог.append(
            (
                "М-20",
                False,
                f"ни одно предупреждение не попало в инцидент: упреждение мерить не на чем, "
                f"{фон}",
            )
        )
    else:
        итог.append(
            (
                "М-20",
                bool(ок_горизонт),
                f"медиана упреждения {ч(медиана, 1)} ч при пороге {ГОРИЗОНТ_Ч}, "
                f"доля прогнозов короче {ГОРИЗОНТ_Ч} ч {ч(доля)} при пределе "
                f"{ч(ДОЛЯ_ПОЗДНИХ_МАКС, 2)}, минимум {ч(минимум, 1)} ч, "
                f"пойманных инцидентов {ч(m0['tp'])} из {ч(инцидентов)}",
            )
        )
    return итог


def строка_времени(прогон, участков_всего, строк_журнала, строк_свёртки):
    """Строка М-21 по одному прогону. Без двух чисел объёма замер не засчитывается."""
    if прогон is None:
        return (
            "М-21",
            False,
            "в pred.run нет ни одного завершённого прогона — замерять нечего",
        )
    секунд = (прогон["finished_at"] - прогон["started_at"]).total_seconds()
    посчитано = прогон["objects_scored"] or 0
    версия = прогон["model_version"] or "не названа"
    объём = (
        f"окно {ОКНО_РАСЧЁТА_СУТОК} суток до среза — {ч(строк_журнала)} строк "
        f"smvu.reading и {ч(строк_свёртки)} строк feat.section_daily, "
        f"участков в расчёте {ч(посчитано)} из {ч(участков_всего)} в ref.object_xref"
    )
    общее = (
        f"прогон {прогон['run_id']} от {мск(прогон['finished_at']):%d.%m.%Y %H:%M} мск, "
        f"срез {мск(прогон['as_of']):%d.%m.%Y %H:%M} мск, модель {версия}, {объём}"
    )

    # Две величины, а не одна: время расчёта само по себе ничего не доказывает,
    # если он шёл по сотне участков из трёх тысяч или его считала заглушка.
    if посчитано < участков_всего:
        return ("М-21", False, f"расчёт шёл не по всему парку: {общее}")
    # Заглушка модели строку М-21 больше не валит. Строка приёмки (:371) меряет
    # время от старта до статуса «Завершён», то есть НАШ конвейер: чтение,
    # свёртка, признаки, запись. Инференс заглушки — 1,2 мс из 32,7 с, и с моделью
    # Николая прибавится её инференс, а не переделается весь замер. Но факт
    # заглушки остаётся в тексте строки: зелёное число без него читалось бы
    # как «померено с настоящей моделью».
    хвост_заглушки = (
        " (инференс заглушки 1,2 мс; с моделью Николая прибавится её инференс)"
        if версия.startswith("stub")
        else ""
    )
    if строк_журнала == 0:
        return ("М-21", False, f"в окне расчёта нет ни одной строки журнала: {общее}")
    ок = секунд < РАСЧЁТ_СЕК_МАКС
    return (
        "М-21",
        ок,
        f"полный расчёт {ч(секунд, 1)} с "
        f"{'быстрее' if ок else 'не быстрее'} {РАСЧЁТ_СЕК_МАКС} с{хвост_заглушки}: {общее}",
    )


