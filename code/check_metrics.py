# Функции пфх() здесь больше нет: ключ группы даёт collector_key() из
# predictive_metrics.py по словарю «канал -> узел коллектора», а словарь собирается
# запросом к дереву объектов. Разбор строки тегом ключом быть перестал.


def мск(t):
    """Момент в московском времени. Наивное время в самопроверке оставляем как есть."""
    return t.astimezone(МСК) if t.tzinfo else t


def ч(x, знаков=3):
    """Число по-русски: запятая вместо точки, пробел между тысячами."""
    if isinstance(x, int):
        return f"{x:,}".replace(",", " ")
    return f"{x:.{знаков}f}".replace(".", ",")


