#!/usr/bin/env python3
"""Исполняемая проверка четырёх метрик программы минимум: М-18…М-21.

Строки приёмки — `docs/acceptance-test.md`, часть 0, раздел 0.5. Скрипт печатает
по строке на требование в виде «М-NN OK <числа>» или «М-NN СБОЙ <что не так>»
и выходит с кодом 1, если хоть одна строка красная.

Методику не изобретаем: считают `group_incidents()` и `evaluate_alerts()`
из `code/predictive_metrics.py`. Одна методика, посчитанная двумя кусками кода,
уже дала в этом проекте 166 инцидентов вместо 176.

Скрипт по умолчанию ОТКАЗЫВАЕТ. Нет базы, нет выборки, ноль инцидентов, прогноз
сделал не обученная модель, а заглушка — всё это СБОЙ, а не «проверить нечего».
Красный ответ на неготовом продукте — правильный ответ.

Запуск (нужна база стенда, asyncpg лежит в .venv):
    DATABASE_URL=postgresql://... .venv/bin/python code/check_metrics.py --threshold 0.8

Самопроверка идёт первой на каждом запуске и базы не требует.
"""

import argparse
import asyncio
import os
import sys
from datetime import datetime, timedelta
from zoneinfo import ZoneInfo

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from predictive_metrics import (  # noqa: E402
    evaluate_alerts, group_incidents, precision_recall, verdict,
)

# Пороги из постановки, дословно. Строго больше, а не «не ниже»: 0,700 постановку
# не закрывает (docs/acceptance-test.md, пояснение «Про строгое неравенство»).
PRECISION_МИН = 0.7
RECALL_МИН = 0.5
ГОРИЗОНТ_Ч = 24
ДОЛЯ_ПОЗДНИХ_МАКС = 0.20
РАСЧЁТ_СЕК_МАКС = 300

# Склейка отказов в инциденты: окно из строки М-18, ключ — префикс тега до дефиса,
# то есть коллектор. Считаем аварии, а не датчики.
ОКНО_СКЛЕЙКИ_МИН = 10

# Отложенная выборка по умолчанию — апрель-июнь 2026. На ней замерены 587 эпизодов
# и 176 инцидентов, с которыми сверяется протокол.
ОКНО_ОТ = "2026-04-01"
ОКНО_ДО = "2026-07-01"

# Самое длинное окно чтения расчёта: сборка признаков читает feat.section_daily
# и smvu.reading за 365 суток назад от среза (backend/app/worker/features.py).
# М-21 требует назвать это окно строками, иначе замер не засчитывается.
ОКНО_РАСЧЁТА_СУТОК = 365

НАПРАВЛЕНИЕ = "sensor_failure"

# База отдаёт время в UTC, а протокол читают в Москве: 10:40 мск и 07:40 UTC —
# это один момент, но в протоколе должен стоять тот, что назовёт диспетчер.
МСК = ZoneInfo("Europe/Moscow")


def пфх(tag):
    """Ключ группы для group_incidents: коллектор — это префикс тега до дефиса."""
    return tag.split("-")[0]


def мск(t):
    """Момент в московском времени. Наивное время в самопроверке оставляем как есть."""
    return t.astimezone(МСК) if t.tzinfo else t


def ч(x, знаков=3):
    """Число по-русски: запятая вместо точки, пробел между тысячами."""
    if isinstance(x, int):
        return f"{x:,}".replace(",", " ")
    return f"{x:.{знаков}f}".replace(".", ",")


