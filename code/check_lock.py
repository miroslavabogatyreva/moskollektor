#!/usr/bin/env python3
"""Приёмка блокировки расчёта: строка НФ-11.

**Зачем отдельный скрипт, когда самопроверка планировщика уже зелёная.**
`app.worker.scheduler --selfcheck` берёт свой ключ 48218 и доказывает, что
advisory lock в Постгресе исключает вторую сессию, снимается по `unlock`
и отпускается сам при обрыве соединения. Это проверка механизма. НФ-11
требует другого: чтобы боевой расчёт эту блокировку БРАЛ. Боевой ключ 48217
стоит в `backend/app/worker/run.py` строками 55, 163 и 288, и до этого файла
самопроверка планировщика не дотягивается вовсе — убери из `прогон()` строку
163, и она останется зелёной.

Поэтому здесь проверка идёт через сам расчёт: держу 48217 в одном соединении
и зову `run.прогон()` во втором. Он обязан вернуть `status="занято"` и не
начать работу.

**Почему эта проверка ничего не пишет в базу.** Если блокировка сломана,
`прогон()` пойдёт считать по-настоящему: заведёт строку в `pred.run`, сходит
в модель, напишет прогнозы. Приёмочная проверка такого делать не должна,
поэтому вызов обёрнут в транзакцию, которая ВСЕГДА откатывается, и зовётся
с `предел=1`: сломанный случай успевает сделать минимум работы и не оставляет
следа. На зелёном пути откатывать нечего — `прогон()` выходит на первой же
строке, до всякой записи.

Проверка по умолчанию отказывает. Нет `DATABASE_URL`, нет ответа базы,
`прогон()` вернул не «занято» — всё это СБОЙ, а не молчаливый ноль.

Запуск:
    DATABASE_URL=postgresql://... PYTHONPATH=backend python3 code/check_lock.py
"""

import asyncio
import os
import sys

import asyncpg

from app.worker import run


class _Откат(Exception):
    """Несёт итог прогона наружу и откатывает транзакцию заодно."""

    def __init__(self, строка):
        self.строка = строка


async def главная() -> int:
    dsn = os.environ.get("DATABASE_URL")
    if not dsn:
        print("СБОЙ: нет DATABASE_URL")
        return 1

    взял = False
    держит = await asyncpg.connect(dsn)
    зовёт = await asyncpg.connect(dsn, command_timeout=10)
    try:
        # Ключ мог уже держать настоящий часовой расчёт — и это не помеха, а тот же
        # случай: условие проверки «ключ занят», а кем — неважно. Раньше здесь
        # стоял отказ, и проверка краснела бы от расписания, а не от дефекта —
        # ровно та беда, из-за которой самопроверка планировщика ушла на свой 48218.
        взял = await держит.fetchval("SELECT pg_try_advisory_lock($1)", run.БЛОКИРОВКА)
        if not взял:
            print(f"ключ {run.БЛОКИРОВКА} держит другой процесс — проверяем на нём")

        строка = None
        try:
            async with зовёт.transaction():
                raise _Откат(await run.прогон(зовёт, предел=1))
        except _Откат as о:
            строка = о.строка
        except Exception as e:
            # Исключение вместо ответа — тоже отказ, и печатать его надо фактом,
            # не выводом. «Прогон упал» не значит «блокировка сломана»: 17.09.2026
            # эта ветка поймала совсем другое — чтение ref.app_setting, которое
            # в прогоне стоит ВЫШЕ блокировки, а таблицы на стенде ещё нет. Скажи
            # здесь «расчёт не берёт блокировку» — и читающий пойдёт чинить не то.
            print(f"СБОЙ: ключ {run.БЛОКИРОВКА} занят, прогон обязан был вернуть "
                  f"«занято», а упал — {type(e).__name__}: {e}")
            return 1

        status = строка.get("status")
        if status != "занято":
            print(f'СБОЙ: ключ {run.БЛОКИРОВКА} занят, а прогон вернул status="{status}" '
                  f"вместо «занято» — расчёт не берёт блокировку (run.py:163)")
            return 1
        print(f"ok: ключ {run.БЛОКИРОВКА} занят — прогон отказался считать, status=занято")
        return 0
    finally:
        # Снимаем только свой замок: чужой держит идущий расчёт, и снять его
        # означало бы пустить второй прогон поверх первого.
        if взял:
            await держит.fetchval("SELECT pg_advisory_unlock($1)", run.БЛОКИРОВКА)
        await держит.close()
        await зовёт.close()


if __name__ == "__main__":
    sys.exit(asyncio.run(главная()))
