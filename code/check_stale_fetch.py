"""Ответ ушедшего экрана не должен дописываться в состояние нового.

Разбор 22.09.2026. Карточка объекта показывала **не тот участок, что в адресной
строке**: адрес `/objects/2157`, на экране «Участок 426», окно дат 29.04–05.05.
Окно при этом верное — для 426: его последняя запись 05.05.2026, семь суток
назад это 29.04. Всё на карточке сходилось между собой, не сходился только адрес.

Как это выходит. Эффект по смене участка чистит состояние и шлёт запрос. Ушли
с участка A на B, ответ A приехал позже ответа B — `setData` кладёт данные A
поверх данных B. Дальше соседний эффект честно пересчитывает окно дат по тому,
что лежит в `data`, и карточка A встаёт целиком под адресом B. Ни ошибки,
ни пустого места, ни подсказки: диспетчер читает чужую карточку.

Почему это НЕ ловится ни браузером, ни глазами. Окно гонки — доли миллисекунды
между приходом ответа и пересчётом окна; у меня оно поймалось 2 раза из 9 серий
по шесть переходов. Проверка «блок на месте и консоль чиста» его пропускает
целиком: блок на месте, консоль чиста, данные согласованы. Поэтому сторожим
не поведение, а **устройство кода**: у эффекта, который шлёт запрос и
перезапускается при смене чего-либо, обязан быть выключатель на ответ.

Что считается выключателем: флажок в замыкании со сбросом в уборке эффекта
(`let отменено = false … return () => { отменено = true }`) или `AbortController`.

Эффект с ПУСТЫМ списком зависимостей проверка не трогает: он выполняется один
раз за жизнь экрана и обгонять ему некого. Это не поблажка, а причина —
измерено по дереву: на фронте пять эффектов с запросом, два из них (обе загрузки
на экране схемы) пустые, и гонки у них нет.

Запуск:  python3 code/check_stale_fetch.py
         python3 code/check_stale_fetch.py --selfcheck
"""

import io
import os
import re
import sys

КОРЕНЬ = "frontend/src"
ЗАЩИТА = ("отменено", "cancelled", "AbortController", "signal")

# Номер задачи рядом с красной строкой — правило бригады: без него проверку
# начнут «чинить» ослаблением, а не работой. Файла нет в списке — пишем это
# словами, а не молчим.
ЗАДАЧИ = {
    "ObjectCard.tsx": "закроет MOS-131",
    "ForecastCard.tsx": "закроет MOS-175",
    # Три экрана, которых первая редакция проверки не видела вовсе: они зовут
    # обёртки из api.ts, а отбор шёл по подстроке `fetch(`.
    "index.tsx": "закроет MOS-178",
    "OrderCard.tsx": "закроет MOS-178",
}


def тело_эффекта(текст, начало):
    """Кусок от `useEffect(` до его закрывающей скобки — по счётчику скобок.

    Резать по `}, [` нельзя: такая строка встречается и внутри самого эффекта
    (объект в массиве), и первый же вложенный `useMemo` съел бы половину тела.
    """
    глубина = 0
    i = начало
    while i < len(текст):
        if текст[i] == "(":
            глубина += 1
        elif текст[i] == ")":
            глубина -= 1
            if глубина == 0:
                return текст[начало : i + 1]
        i += 1
    return текст[начало:]


ЗАВИСИМОСТИ = re.compile(r",\s*\[(.*?)\]\s*\)\s*$", re.S)


def есть_запрос(тело):
    """Эффект уходит в сеть? Ищем `.then(`, а не слово `fetch`.

    Первая редакция отбирала по подстроке `fetch(` — и не видела двух экранов
    из трёх. Журнал и заявки зовут обёртки из своего `api.ts`:
    `fetchForecasts({...})`, `fetchOrders(offset)`. Подстроки `fetch(` там нет:
    после `fetch` идёт `F`, а не скобка. Проверка печатала «OK у всех 5», когда
    эффектов было девять, — врала уверенно и с верным на вид знаменателем.
    Нашла `49` 22.09.2026 при сдаче дел, ровно по этому числу 5.

    Список известных обёрток из `api.ts` был бы хуже подстроки: он устареет так же
    молча, при первом же новом имени. `.then(` переживает переименование, потому
    что это не имя, а место, куда приезжает ответ, — и именно оно нас интересует.
    `fetch(` оставляю рядом на случай `await` без цепочки: сегодня таких нет
    (проверила по дереву — ни одного `await` в эффектах), но признак дешёвый.
    """
    return ".then(" in тело or "fetch(" in тело



def разобрать(путь, текст):
    """Список (путь, номер, зависимости, есть_запрос, есть_защита, тело)."""
    найдено = []
    номер = 0
    место = текст.find("useEffect(")
    while место != -1:
        номер += 1
        тело = тело_эффекта(текст, место + len("useEffect"))
        м = ЗАВИСИМОСТИ.search(тело)
        зависимости = м.group(1).strip() if м else None
        найдено.append(
            (
                путь,
                номер,
                зависимости,
                есть_запрос(тело),
                any(з in тело for з in ЗАЩИТА),
                тело,
            )
        )
        место = текст.find("useEffect(", место + 1)
    return найдено


ФЛАГ = re.compile(r"let\s+([A-Za-zА-Яа-я_$][\w$А-Яа-я]*)\s*=\s*false")
ЗОВ_СЕТТЕРА = re.compile(r"\bset[A-ZА-Я]\w*\s*\(")


def половинчатая_защита(тело):
    """Флажок объявлен, но прикрывает не все ответы — вернуть текст беды или None.

    Одного упоминания слова мало, и это не придирка. 22.09.2026 я ломала
    `ForecastCard.tsx` в копии дерева, чтобы снять улов: убрала объявление
    флажка и уборку, а одну проверку `if (!отменено)` в теле не заметила —
    и проверка назвала файл защищённым. Считать надо не слово, а **каждый
    ответ**: `.then` и `.catch`, которые пишут в состояние, обязаны спрашивать
    флажок порознь. Половина ответов под флажком — это гонка на второй половине.
    """
    м = ФЛАГ.search(тело)
    if not м:
        return None
    имя = м.group(1)
    if f"{имя} = true" not in тело:
        return f"флажок `{имя}` объявлен, но не сбрасывается в уборке эффекта"
    открытые = []
    # Режем каждый ответ по скобкам, а не по следующему `.then`. Наивный split
    # даёт последнему куску хвост всего тела — вместе с `отменено = true` из
    # уборки, — и незащищённый `.catch` выглядит защищённым. На этом я и
    # попалась, когда писала случай «ошибку пишут мимо флажка».
    for м in re.finditer(r"\.(?:then|catch)(?=\()", тело):
        часть = тело_эффекта(тело, м.end())
        зов = ЗОВ_СЕТТЕРА.search(часть)
        if зов and имя not in часть:
            открытые.append(зов.group(0).rstrip("( "))
    if открытые:
        return f"флажок `{имя}` спрашивают не везде: без него пишут " + ", ".join(
            sorted(set(открытые))
        )
    return None


def опасные(эффекты):
    """Эффекты, где ответ ушедшего экрана может дописаться в состояние нового.

    Три причины попасть сюда: выключателя нет вовсе; флажок объявлен, но не
    сбрасывается в уборке; флажок сбрасывается, но его спрашивают не у всех
    ответов. Третью я добавила, наступив на неё сама (см. `половинчатая_защита`).
    """
    беда = []
    for путь, номер, зависимости, запрос, защита, тело in эффекты:
        if not запрос:
            continue
        # Пустой список зависимостей: эффект отрабатывает один раз за жизнь
        # экрана, обгонять ему некого.
        if зависимости == "":
            continue
        if not защита:
            беда.append((путь, номер, зависимости, "ответ не выключается"))
            continue
        щель = половинчатая_защита(тело)
        if щель:
            беда.append((путь, номер, зависимости, щель))
    return беда


def собрать(корень=КОРЕНЬ):
    эффекты = []
    for путь, _, файлы in os.walk(корень):
        if "node_modules" in путь:
            continue
        for ф in sorted(файлы):
            if not ф.endswith((".ts", ".tsx")) or ".selfcheck." in ф:
                continue
            п = os.path.join(путь, ф)
            эффекты += разобрать(п, io.open(п, encoding="utf-8").read())
    return эффекты


def самопроверка():
    беда = False

    def проверить(условие, что):
        nonlocal беда
        if not условие:
            print(f"СБОЙ: {что}")
            беда = True

    без_защиты = """
      useEffect(() => {
        if (!sectionId) return
        setData(null)
        fetch(`/api/objects/${sectionId}`).then((d) => setData(d))
      }, [sectionId])
    """
    с_флагом = """
      useEffect(() => {
        let отменено = false
        fetch(`/api/objects/${sectionId}`).then((d) => { if (!отменено) setData(d) })
        return () => { отменено = true }
      }, [sectionId])
    """
    однократный = """
      useEffect(() => {
        fetch('/data/sections.json').then(setSections)
      }, [])
    """
    без_запроса = """
      useEffect(() => {
        setViewRange(null)
      }, [collector])
    """
    проверить(
        len(опасные(разобрать("a.tsx", без_защиты))) == 1,
        "запрос без выключателя — беда",
    )
    проверить(not опасные(разобрать("b.tsx", с_флагом)), "флажок `отменено` засчитан")
    проверить(
        not опасные(разобрать("c.tsx", однократный)), "пустые зависимости — не беда"
    )
    проверить(
        not опасные(разобрать("d.tsx", без_запроса)), "эффект без запроса — не беда"
    )

    # Вложенный useMemo внутри эффекта не должен обрывать разбор тела: режем
    # по счётчику скобок, а не по первой строке вида `}, [`.
    с_вложенным = """
      useEffect(() => {
        const t = items.map((x) => ({ a: 1 }), [])
        let отменено = false
        fetch('/api/x').then((d) => { if (!отменено) setD(d) })
        return () => { отменено = true }
      }, [id])
    """
    проверить(
        not опасные(разобрать("e.tsx", с_вложенным)),
        "вложенные скобки не рвут тело эффекта",
    )

    # AbortController — тоже выключатель, хотя слово другое.
    с_аборт = """
      useEffect(() => {
        const ac = new AbortController()
        fetch('/api/x', { signal: ac.signal }).then(setD)
        return () => ac.abort()
      }, [id])
    """
    проверить(not опасные(разобрать("f.tsx", с_аборт)), "AbortController засчитан")

    # Эффект зовёт обёртку из api.ts, а не `fetch` напрямую. Ровно этого случая
    # тут не было — и потому первая редакция не видела трёх экранов из шести
    # и печатала «OK у всех 5» при девяти эффектах (нашла `49`, 22.09.2026).
    через_обёртку = """
      useEffect(() => {
        fetchForecasts({ from, to, offset })
          .then((r) => { setItems(r.items) })
          .catch((e) => setError(e))
      }, [dateFrom, dateTo, offset])
    """
    н = опасные(разобрать("k.tsx", через_обёртку))
    проверить(len(н) == 1, "обёртка вместо fetch — эффект виден и не защищён")
    проверить(
        разобрать("k.tsx", через_обёртку)[0][3], "обёртка засчитана как запрос"
    )

    обёртка_с_флагом = """
      useEffect(() => {
        let отменено = false
        fetchOrders(offset)
          .then((r) => { if (!отменено) setItems(r.items) })
          .catch((e) => { if (!отменено) setError(e) })
        return () => { отменено = true }
      }, [offset])
    """
    проверить(not опасные(разобрать("l.tsx", обёртка_с_флагом)), "обёртка под флажком — не беда")

    проверить(
        разобрать("g.tsx", без_защиты)[0][2] == "sectionId", "зависимости прочитаны"
    )

    # Половинчатая защита. Ломая ForecastCard в копии дерева, чтобы снять улов,
    # я убрала объявление флажка и уборку, а одну проверку `if (!отменено)`
    # в теле не заметила — и проверка назвала файл защищённым. Считать надо
    # не слово, а каждый ответ порознь.
    флаг_без_уборки = """
      useEffect(() => {
        let отменено = false
        fetch('/api/x').then((d) => { if (!отменено) setD(d) })
      }, [id])
    """
    н = опасные(разобрать("h.tsx", флаг_без_уборки))
    проверить(len(н) == 1 and "не сбрасывается" in н[0][3], "флажок без уборки — беда")

    прикрыт_наполовину = """
      useEffect(() => {
        let отменено = false
        fetch('/api/x')
          .then((d) => { if (!отменено) setD(d) })
          .catch((e) => { setError(e) })
        return () => { отменено = true }
      }, [id])
    """
    н = опасные(разобрать("i.tsx", прикрыт_наполовину))
    проверить(len(н) == 1 and "setError" in н[0][3], "ошибку пишут мимо флажка — беда")

    прикрыт_целиком = """
      useEffect(() => {
        let отменено = false
        fetch('/api/x')
          .then((r) => { if (r.status === 404) { if (!отменено) setNF(true); return null }
                         return r.json() })
          .then((d) => { if (!отменено && d) setD(d) })
          .catch((e) => { if (!отменено) setError(e) })
        return () => { отменено = true }
      }, [id])
    """
    проверить(not опасные(разобрать("j.tsx", прикрыт_целиком)), "все три ответа под флажком — не беда")

    print("check_stale_fetch: ЕСТЬ ОШИБКИ" if беда else "check_stale_fetch: OK")
    return 1 if беда else 0


def main():
    if "--selfcheck" in sys.argv:
        return самопроверка()
    if not os.path.isdir(КОРЕНЬ):
        print(f"СБОЙ нет каталога {КОРЕНЬ} — запускать из корня репозитория")
        return 1
    эффекты = собрать()
    с_запросом = [э for э in эффекты if э[3]]
    беда = опасные(эффекты)
    # Знаменатель называем всегда: «0 опасных из 0» значит, что проверка
    # ничего не нашла и ничего не доказала, и это надо видеть.
    if not с_запросом:
        print(f"СБОЙ ни одного эффекта с запросом в {КОРЕНЬ} — проверять нечего")
        return 1
    if беда:
        for путь, номер, зависимости, причина in беда:
            задача = ЗАДАЧИ.get(os.path.basename(путь), "задачи ещё нет")
            print(
                f"        {путь} эффект #{номер} по [{зависимости}] — "
                f"{причина}; {задача}"
            )
        print(
            f"СБОЙ ответ ушедшего экрана дописывается в состояние нового: "
            f"{len(беда)} эффектов из {len(с_запросом)} с запросом. "
            f"Нужен флажок со сбросом в уборке эффекта или AbortController"
        )
        return 1
    print(
        f"OK у всех {len(с_запросом)} эффектов с запросом ответ выключается при уходе"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
