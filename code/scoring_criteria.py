"""Скоринг поставщиков / самопроверка продукта по модели «приоритет x значимость x балл».

Модель взята из файла Эн+/РУСАЛ «20220803_Свод_Критерии выбора вендора (ПО).xlsx»,
лист «Платформа». В Excel там стоят ровно две формулы:

    итог  = SUMPRODUCT(приоритет, значимость, балл)
    охват = ROUNDUP(итог / SUMPRODUCT(приоритет, значимость * 3), 2)

Балл выставляют по шкале 0..3, где 3 = «из коробки и отработано», 2 = «есть,
но с оговорками», 1 = «делается в рамках проекта», 0 = «нет».
Приоритет — 1 (обязательно) или 0.5 (желательно). Значимость — 1..3.

Функция score() ниже воспроизводит обе формулы; self-check в конце файла
пересчитывает реальные итоги пяти вендоров из того самого листа.

Запуск: python3 scoring_criteria.py
"""

import math
from collections import namedtuple

Criterion = namedtuple("Criterion", "group name priority significance")

MAX_MARK = 3.0


def score(criteria, marks):
    """Возвращает (итог, максимум, охват).

    criteria — список Criterion, marks — список баллов той же длины (0..3).
    """
    if len(criteria) != len(marks):
        raise ValueError("баллов %d, критериев %d" % (len(marks), len(criteria)))
    total = 0.0
    ceiling = 0.0
    for c, m in zip(criteria, marks):
        if not 0 <= m <= MAX_MARK:
            raise ValueError("балл %r вне шкалы 0..%s (%s)" % (m, MAX_MARK, c.name))
        total += c.priority * c.significance * m
        ceiling += c.priority * c.significance * MAX_MARK
    if ceiling == 0:
        raise ValueError("нулевой максимум: все приоритеты или значимости нулевые")
    coverage = math.ceil(total / ceiling * 100) / 100  # Excel ROUNDUP(...;2)
    return round(total, 2), round(ceiling, 2), coverage


def by_group(criteria, marks):
    """Тот же расчёт, но в разрезе групп — видно, где именно продукт проседает."""
    acc = {}
    for c, m in zip(criteria, marks):
        got, cap = acc.get(c.group, (0.0, 0.0))
        acc[c.group] = (got + c.priority * c.significance * m,
                        cap + c.priority * c.significance * MAX_MARK)
    return {g: (round(got, 2), round(cap, 2), math.ceil(got / cap * 100) / 100)
            for g, (got, cap) in acc.items()}


def report(criteria, marks, title="Оценка"):
    total, ceiling, cov = score(criteria, marks)
    lines = ["%s: %.2f из %.2f — охват %d%%" % (title, total, ceiling, round(cov * 100))]
    for g, (got, cap, c) in sorted(by_group(criteria, marks).items(),
                                   key=lambda kv: kv[1][2]):
        lines.append("  %-28s %6.2f / %6.2f  %3d%%" % (g, got, cap, round(c * 100)))
    weak = [c.name for c, m in zip(criteria, marks) if c.priority == 1 and m < 2]
    if weak:
        lines.append("  Провалы по обязательным критериям:")
        lines += ["    - " + w for w in weak]
    return "\n".join(lines)


