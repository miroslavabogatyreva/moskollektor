def _selfcheck():
    crit = [Criterion("РУСАЛ-2022", "к%02d" % i, p, z)
            for i, (p, z, _, _) in enumerate(_RUSAL_2022)]

    total, ceiling, cov = score(crit, [row[2] for row in _RUSAL_2022])
    assert (total, ceiling, cov) == (403.75, 439.5, 0.92), (total, ceiling, cov)

    total_z, _, cov_z = score(crit, [row[3] for row in _RUSAL_2022])
    assert (total_z, cov_z) == (392.25, 0.9), (total_z, cov_z)

    # Идеальный вендор берёт ровно максимум и 100%.
    assert score(crit, [3] * len(crit)) == (439.5, 439.5, 1.0)
    # Нулевой — ноль.
    assert score(crit, [0] * len(crit)) == (0.0, 439.5, 0.0)

    # Приоритет 0.5 действительно вдвое дешевле приоритета 1.
    a = Criterion("g", "обязательный", 1, 2)
    b = Criterion("g", "желательный", 0.5, 2)
    assert score([a], [3])[0] == 2 * score([b], [3])[0]

    # Разрезы по группам суммируются в общий итог.
    marks = [2] * len(MOSKOLLEKTOR_CRITERIA)
    t, c, _ = score(MOSKOLLEKTOR_CRITERIA, marks)
    g = by_group(MOSKOLLEKTOR_CRITERIA, marks)
    assert abs(sum(v[0] for v in g.values()) - t) < 1e-9
    assert abs(sum(v[1] for v in g.values()) - c) < 1e-9

    # Балл вне шкалы и рассинхрон длин должны падать, а не молча считаться.
    for bad in ([4], [-1]):
        try:
            score([a], bad); raise AssertionError("не упало на " + repr(bad))
        except ValueError:
            pass
    try:
        score([a, b], [3]); raise AssertionError("не упало на разной длине")
    except ValueError:
        pass

    print("self-check ok: Индасофт %.2f/%.2f = %d%%, Цифра %.2f = %d%%"
          % (total, ceiling, round(cov * 100), total_z, round(cov_z * 100)))


