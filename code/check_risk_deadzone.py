"""Мёртвая зона порога риска: участок, чей класс замер навсегда.

Условие прислала сессия `fe` 22.09.2026, числа тоже её; я написала проверку
и перемерила всё своими запросами.

**Что сторожим.** Класс риска считает `класс_риска` в `backend/app/worker/publish.py`:

    if p >= порог + гистерезис: return "high"
    if p <= порог - гистерезис: return "normal"
    return прошлый or "normal"

Между границами класс не меняется — остаётся прежним. Это защита от дребезга,
и она нужна: без неё участок с вероятностью около порога прыгал бы из high
в normal и обратно каждые четыре минуты. Но если вероятность участка застрянет
ВНУТРИ интервала (порог − гистерезис, порог + гистерезис), его класс замрёт
насовсем: он не поднимется и не опустится, сколько бы прогонов ни прошло.
Ни ошибки, ни строки в журнале при этом не будет — участок просто перестанет
слушаться данных, а на схеме останется тем цветом, каким его застало.

Сегодня порог `risk_threshold_high` = 0,80, гистерезис `risk_class_hysteresis`
= 0,02, оба лежат в `ref.app_setting`; мёртвая зона — интервал от 0,78 до 0,82.

**Порога терпимости нет намеренно.** Любое число внутри интервала — это уже
замерший класс, и «сколько замерших допустимо» обосновать нечем.

**Самопроверка миграции `036_risk_threshold_v3.sql` эту сторону не закрывает:**
она требует, чтобы хоть один участок дотягивался до `порог + гистерезис`, то
есть сторожит верхнюю границу. Нижнюю не сторожил никто.

Запуск:  python3 code/check_risk_deadzone.py
         python3 code/check_risk_deadzone.py --selfcheck
"""

import asyncio
import os
import sys

# Запрос нарочно без GROUP BY: с группировкой пустая `pred.forecast_current`
# вернула бы НОЛЬ СТРОК, и проверка упала бы по IndexError вместо того, чтобы
# сказать «текущего прогноза нет». Пустая таблица — это отдельная беда, и она
# обязана называться своим именем, а не прятаться за ошибкой разбора.
ЗАПРОС = """
WITH п AS (
  SELECT max(value) FILTER (WHERE key = 'risk_threshold_high')   AS порог,
         max(value) FILTER (WHERE key = 'risk_class_hysteresis') AS гистерезис
    FROM ref.app_setting
)
SELECT п.порог, п.гистерезис,
       (SELECT count(*) FROM pred.forecast_current fc
         WHERE fc.probability > п.порог - п.гистерезис
           AND fc.probability < п.порог + п.гистерезис)                    AS в_зоне,
       (SELECT count(*) FROM pred.forecast_current)                        AS всего,
       (SELECT max(probability) FROM pred.forecast_current fc
         WHERE fc.probability <= п.порог - п.гистерезис)                   AS ближайший_снизу,
       (SELECT min(probability) FROM pred.forecast_current fc
         WHERE fc.probability >= п.порог + п.гистерезис)                   AS ближайший_сверху
  FROM п
"""


def вердикт(порог, гистерезис, в_зоне, всего, ближайший_снизу, ближайший_сверху):
    """Чистая функция: по шести числам — (прошла ли, что печатать).

    Зазоры печатаем всегда, а не только при беде. Нижний зазор сегодня шесть
    тысячных, и он один отделяет группу участков от замороженного класса:
    сдвинется модель на сотую вверх — они окажутся внутри. Число, которое
    печатают только при сбое, никто не увидит заранее.
    """
    if порог is None or гистерезис is None:
        return (
            False,
            "в ref.app_setting нет risk_threshold_high или risk_class_hysteresis",
        )
    if всего == 0:
        return False, "pred.forecast_current пуста — сравнивать не с чем"

    низ, верх = порог - гистерезис, порог + гистерезис
    зазор_снизу = None if ближайший_снизу is None else низ - float(ближайший_снизу)
    зазор_сверху = None if ближайший_сверху is None else float(ближайший_сверху) - верх

    def зазор(имя, значение, край):
        if значение is None:
            return f"{имя} зазора нет: ни один участок не лежит {край}"
        return f"{имя} зазор {значение:.6f}"

    хвост = (
        f"мёртвая зона {низ:.2f}…{верх:.2f} (порог {порог}, гистерезис {гистерезис}); "
        + зазор("снизу", зазор_снизу, "ниже границы")
        + ", "
        + зазор("сверху", зазор_сверху, "выше границы")
    )
    if в_зоне:
        return False, f"в мёртвой зоне {в_зоне} участков из {всего}: {хвост}"
    return True, f"в мёртвой зоне 0 участков из {всего}: {хвост}"


async def проверить():
    import asyncpg

    conn = await asyncpg.connect(os.environ["DATABASE_URL"])
    try:
        строка = await conn.fetchrow(ЗАПРОС)
    finally:
        await conn.close()
    return вердикт(
        float(строка["порог"]) if строка["порог"] is not None else None,
        float(строка["гистерезис"]) if строка["гистерезис"] is not None else None,
        строка["в_зоне"],
        строка["всего"],
        строка["ближайший_снизу"],
        строка["ближайший_сверху"],
    )


def самопроверка():
    случаи = [
        # Замер на стенде 22.09.2026 после наката 036: зазоры 0,006369 и 0,047559.
        (
            "стенд как есть",
            (0.80, 0.02, 0, 3173, 0.773631, 0.867559),
            True,
            "0 участков из 3173",
        ),
        # Порог 0,79 затягивает в зону группу 0,773631 — 267 участков из 3173.
        (
            "порог 0,79",
            (0.79, 0.02, 267, 3173, 0.766229, 0.867559),
            False,
            "267 участков из 3173",
        ),
        # Один участок внутри — это уже беда, порога терпимости нет.
        (
            "один внутри",
            (0.80, 0.02, 1, 3173, 0.773631, 0.867559),
            False,
            "1 участков из 3173",
        ),
        # Пустая таблица не должна выглядеть как «всё хорошо».
        (
            "пустой прогноз",
            (0.80, 0.02, 0, 0, None, None),
            False,
            "pred.forecast_current пуста",
        ),
        # Настройки не завели — тоже сбой, а не зелёная строка.
        (
            "нет настроек",
            (None, None, 0, 3173, 0.7, 0.9),
            False,
            "нет risk_threshold_high",
        ),
        # Все участки выше верхней границы: снизу сравнивать не с чем, но зоны нет.
        ("никого снизу", (0.80, 0.02, 0, 3173, None, 0.9), True, "снизу зазора нет"),
    ]
    беда = False
    for имя, аргументы, ждём_ок, ждём_кусок in случаи:
        ок, текст = вердикт(*аргументы)
        if ок is not ждём_ок or ждём_кусок not in текст:
            print(f"СБОЙ: {имя} — получено ({ок}) {текст!r}")
            беда = True

    # Зазоры считаются от границ, а не от порога. Проверяем арифметикой:
    # ближайший снизу 0,773631 при границе 0,78 даёт ровно 0,006369.
    _, текст = вердикт(0.80, 0.02, 0, 3173, 0.773631, 0.867559)
    for ожидаемое in ("снизу зазор 0.006369", "сверху зазор 0.047559", "0.78…0.82"):
        if ожидаемое not in текст:
            print(f"СБОЙ: в строке отчёта нет {ожидаемое!r}; строка: {текст}")
            беда = True

    print("check_risk_deadzone: ЕСТЬ ОШИБКИ" if беда else "check_risk_deadzone: OK")
    return 1 if беда else 0


if __name__ == "__main__":
    if "--selfcheck" in sys.argv:
        sys.exit(самопроверка())
    ок, текст = asyncio.run(проверить())
    print(текст)
    sys.exit(0 if ок else 1)
