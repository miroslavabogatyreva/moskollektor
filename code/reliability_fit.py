#!/usr/bin/env python3
"""Надёжность по цензурированным данным: Вейбулл, Каплан-Мейер, критерий прогнозируемости.

Зачем. По журналу ремонтов надо ответить на вопрос «по каким типам оборудования
прогноз вообще имеет смысл». Если отказы случайные, Recall 0,5 не возьмёт никакая
модель, и узнать это надо ДО обучения, а не через два месяца.

Цензура. Объект, который ещё не сломался, — это не «отказа не было», а «прожил
уже столько-то, а сколько всего, неизвестно». Считать среднее только по сломавшимся
нельзя: выкинем долгожителей и занизим ресурс. В примере ниже — вдвое с лишним.

Библиотеки не берём намеренно. lifelines весит 297 МБ и под MIT, reliability 286 МБ
и под LGPL, scikit-survival 274 МБ и под GPL. Все три дают те же числа, что этот
файл. Подробности — docs/toir-libs-verdict.md.

Формат данных везде одинаковый: список пар (наработка, отказ), где отказ = 1,
если объект сломался, и 0, если он ещё работает.
"""

import math
from statistics import mean, pstdev

# --------------------------------------------------------------- Вейбулл


def fit_weibull(data, lo=0.05, hi=20.0, iters=300):
    """Подгоняет Вейбулла методом максимального правдоподобия с учётом цензуры.

    Возвращает (beta, eta): beta — форма, eta — масштаб в тех же единицах,
    что наработка.

    beta < 1  — ломается молодым: брак, плохой монтаж. Плановая замена не помогает.
    beta ~ 1  — риск не зависит от возраста, отказы случайные. Замена по графику
                бесполезна, и прогноз по наработке тоже.
    beta > 1  — износ накапливается. Превентивная замена работает.

    Решаем уравнение правдоподобия по beta делением отрезка пополам: функция
    монотонна, поэтому сходится всегда и без производных.
    """
    fails = sum(c for _, c in data)
    if fails == 0:
        raise ValueError("нет ни одного отказа — подгонять не по чему")
    if any(t <= 0 for t, _ in data):
        raise ValueError("наработка должна быть положительной")
    ln_fail = sum(math.log(t) for t, c in data if c) / fails

    for _ in range(iters):
        b = (lo + hi) / 2
        s_b = sum(t ** b for t, _ in data)
        s_lb = sum((t ** b) * math.log(t) for t, _ in data)
        g = s_lb / s_b - 1 / b - ln_fail
        if g > 0:
            hi = b
        else:
            lo = b

    beta = (lo + hi) / 2
    eta = (sum(t ** beta for t, _ in data) / fails) ** (1 / beta)
    return beta, eta


def weibull_mean(beta, eta):
    """Средняя наработка до отказа по параметрам Вейбулла."""
    return eta * math.gamma(1 + 1 / beta)


def weibull_failure_prob(beta, eta, age, horizon):
    """Вероятность отказа на горизонте для объекта, прожившего age.

    Это условная вероятность: объект дожил до age, какова вероятность,
    что он не доживёт до age + horizon. Прямо ложится на наш горизонт 24 часа.
    """
    s = lambda t: math.exp(-((t / eta) ** beta))
    s_now = s(age)
    return 0.0 if s_now == 0 else 1 - s(age + horizon) / s_now


# --------------------------------------------------------- Каплан-Мейер


def kaplan_meier(data):
    """Непараметрическая оценка функции выживания.

    Возвращает список (время, доля выживших) в точках отказов. Ничего не
    предполагает о форме распределения — полезно, когда Вейбулл ложится плохо,
    и как проверка самого Вейбулла.
    """
    pts = sorted(data)
    n = len(pts)
    out, surv, at_risk = [], 1.0, n
    i = 0
    while i < n:
        t = pts[i][0]
        same = [p for p in pts[i:] if p[0] == t]
        d = sum(c for _, c in same)          # отказов в этот момент
        if d:
            surv *= (at_risk - d) / at_risk
            out.append((t, surv))
        at_risk -= len(same)
        i += len(same)
    return out


def survival_at(km, t):
    """Доля выживших к моменту t по ступенчатой кривой Каплана-Мейера."""
    s = 1.0
    for time, val in km:
        if time <= t:
            s = val
        else:
            break
    return s


# ----------------------------------------------- критерий прогнозируемости


def predictability_k(data):
    """k = [1 - (s/m)^2] / [1 + (s/m)^2] по полным наработкам до отказа.

    Прогноз имеет смысл при k >= 0.5. Если разброс наработок сравним со средним,
    отказы близки к случайным, и предсказывать нечего.

    Считаем только по сломавшимся: цензурированные записи разброса времени
    до отказа не дают. Если отказов мало, число неустойчиво — смотри n в ответе.

    ОТРИЦАТЕЛЬНЫЙ k ЧИТАЕТСЯ ОСОБО. Формула уходит в минус, когда разброс наработок
    больше среднего (s/m > 1). Это не «объект очень плохой», а «поток событий вообще
    не похож на наработку до отказа»: так выглядит дребезг, а не биография узла.
    На выгрузке 15.09.2026 k вышел отрицательным по всем шести типам сразу — вентилятор
    −0,356, насос −0,409, датчик дыма −0,523, фаза −0,405, газовый −0,344,
    температура −0,506. Виноват был не парк, а определение отказа: наработки строились
    между мгновенными эпизодами «Неисправен», которых миллион и медиана длительности
    у которых 56 секунд. Прежде чем читать такой k как приговор оборудованию, проверьте,
    что события на входе — это отказы, а не моргания контакта.
    """
    ttf = [t for t, c in data if c]
    if len(ttf) < 2:
        raise ValueError("нужно хотя бы два отказа")
    m, s = mean(ttf), pstdev(ttf)
    cv2 = (s / m) ** 2
    return (1 - cv2) / (1 + cv2), len(ttf)


def verdict(data, name=""):
    """Сводка по одному типу оборудования: считать прогноз или не тратить время."""
    beta, eta = fit_weibull(data)
    k, n = predictability_k(data)
    if beta < 0.9:
        wear = "ломается молодым, плановая замена не поможет"
    elif beta < 1.15:
        wear = "отказы случайные, возраст ни при чём"
    else:
        wear = "износ накапливается, превентивная замена работает"
    out = {
        "объект": name,
        "beta": round(beta, 3),
        "eta": round(eta, 1),
        "средняя наработка": round(weibull_mean(beta, eta), 1),
        "k": round(k, 3),
        "отказов в выборке": n,
        "прогноз имеет смысл": k >= 0.5,
        "характер отказов": wear,
    }
    if k < 0:
        # Словесный вывод по beta при отрицательном k вводит в заблуждение: он скажет
        # «ломается молодым, плановая замена не поможет», хотя на входе вообще не
        # наработки. Заменяем его прямым предупреждением, а не оставляем красивую фразу.
        out["характер отказов"] = (
            "наработка не описывается Вейбуллом: разброс больше среднего. "
            "Проверьте, что на входе отказы, а не дребезг")
    return out


# ------------------------------------------------------------ самопроверка


def _demo():
    # Десять насосов: пять сломались, пять работают до сих пор.
    pumps = [(320, 1), (410, 1), (505, 1), (610, 1), (700, 1),
             (900, 0), (950, 0), (1100, 0), (1200, 0), (1400, 0)]

    naive = mean([t for t, c in pumps if c])
    beta, eta = fit_weibull(pumps)
    m = weibull_mean(beta, eta)

    # Дребезг вместо отказов: наработки с разбросом больше среднего дают k < 0,
    # и словесный вывод обязан сказать об этом прямо, а не рассуждать про износ.
    chatter = [(1, 1), (2, 1), (3, 1), (5, 1), (900, 1)]
    k_bad, _ = predictability_k(chatter)
    assert k_bad < 0, k_bad
    v_bad = verdict(chatter, "дребезг")
    assert v_bad["прогноз имеет смысл"] is False
    assert "не описывается Вейбуллом" in v_bad["характер отказов"], v_bad

    assert abs(naive - 509.0) < 0.5, naive
    assert abs(beta - 1.50) < 0.01, beta
    assert abs(eta - 1342) < 2, eta
    assert abs(m - 1211) < 3, m
    assert m / naive > 2.3, "цензура должна поднимать оценку ресурса заметно"

    print(f"наивно, только по сломавшимся: {naive:.0f} дней")
    print(f"Вейбулл с учётом цензуры:      beta={beta:.2f} eta={eta:.0f} "
          f"средняя={m:.0f} дней")
    print(f"наивная оценка занижена в {m / naive:.1f} раза")

    # Каплан-Мейер: до первого отказа выживаемость единица, после последнего падает
    km = kaplan_meier(pumps)
    assert len(km) == 5, km
    assert survival_at(km, 300) == 1.0
    assert survival_at(km, 700) < 0.6
    print(f"Каплан-Мейер: S(700) = {survival_at(km, 700):.3f}")

    # Вероятность отказа на горизонте
    p = weibull_failure_prob(beta, eta, age=800, horizon=24)
    assert 0 < p < 0.05, p
    print(f"насос прожил 800 дней, вероятность отказа за сутки: {p * 100:.2f} %")

    # Случайные отказы: одинаковая интенсивность, k должен упасть
    random_like = [(100, 1), (50, 1), (400, 1), (20, 1), (250, 1), (700, 1),
                   (15, 1), (330, 1), (90, 1), (180, 1)]
    k_rand, _ = predictability_k(random_like)
    k_pumps, _ = predictability_k(pumps)
    assert k_rand < k_pumps, (k_rand, k_pumps)
    print(f"\nk у насосов {k_pumps:.2f} — {'прогнозируем' if k_pumps >= .5 else 'нет'}")
    print(f"k у разбросанной выборки {k_rand:.2f} — "
          f"{'прогнозируем' if k_rand >= .5 else 'отказы случайные, прогноз бесполезен'}")

    print("\nсводка по насосам:")
    for key, val in verdict(pumps, "насос водоудаления").items():
        print(f"  {key}: {val}")
    print("\nOK")


if __name__ == "__main__":
    _demo()
