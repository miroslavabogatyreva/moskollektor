import sys
from datetime import datetime, timedelta
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(КОРЕНЬ / "code"))

import check_metrics  # noqa: E402
import check_metrics_report as отчёт  # noqa: E402
import model_failure  # noqa: E402
from predictive_metrics import evaluate_alerts  # noqa: E402

d = datetime.fromisoformat


def test_дубль_считается_отдельно_от_tp_и_fp():
    # Два предупреждения в окне одного отказа: одно зачтено, второе — дубль,
    # третье далеко от отказа — ложное. Три слагаемых, по одному в каждом.
    алерты = [("A", d("2026-04-08 00:00")), ("A", d("2026-04-09 00:00")),
              ("A", d("2026-05-20 00:00"))]
    m = evaluate_alerts(алерты, [("A", d("2026-04-10 00:00"))], 24, 168)
    assert (m["tp"], m["fp"], m["dup"], m["alerts"]) == (1, 1, 1, 3)


def test_тождество_на_доказательствах_стенда():
    склейка = model_failure.загрузить_контракт()["incident"]["merge_minutes"]
    m = отчёт.замер(отказы_файл=отчёт.ОТКАЗЫ_D5, склейка=склейка)
    текст, сходится = отчёт.тождество(m)
    assert сходится, текст
    # 169 — то же число, что check_metrics.py напечатал на стенде 22.09.2026
    # запросом к smvu.model_failure_episode; пересчёт из выгрузки обязан совпасть.
    assert m["инцидентов"] == 169
    assert m["предупреждений_на_коллекторах"] == m["tp"] + m["fp"] + m["дублей"]


def test_узкая_цель_по_умолчанию_не_сдвинулась():
    # check_write_policy.py зовёт замер() без аргументов и сверяется с 0,600 / 0,528.
    m = отчёт.замер()
    assert (m["инцидентов"], m["tp"], m["fp"], m["fn"]) == (176, 93, 62, 83)


def test_срезы_после_инцидентов_дают_пропуск():
    инциденты = [("obj:7", d("2026-06-30 12:28:37"))]
    поздно = [(548, d("2026-06-30 23:59:59"))]
    assert "выдачи модели по окну нет" in check_metrics.без_выдачи_по_окну(поздно, инциденты)
    # Срез ровно за сутки до инцидента — уже есть чем мерить.
    вовремя = [(1, d("2026-06-30 12:28:37") - timedelta(hours=24))]
    assert check_metrics.без_выдачи_по_окну(вовремя, инциденты) is None
    # Пустые списки решает строки_качества(), не эта функция.
    assert check_metrics.без_выдачи_по_окну([], инциденты) is None
