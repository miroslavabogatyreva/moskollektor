#!/usr/bin/env python3
"""Привязка канала к участку: сверка contracts/examples/section_xref.csv с базой.

Файл отдан Николаю (MOS-158, Q7.13) как контрактный пример: 10 720 строк
«канал, участок, ключ коллектор:пикет». Строки приёмки у задачи нет, но у файла
есть свойство, из-за которого проверка нужна: он выгружен из базы один раз
и с этого мгновения живёт сам по себе. Перезаливка журнала, новый справочник
каналов или правка разборщика тега меняют `smvu.channel.section_id` — и файл
разойдётся с базой молча, а Николай будет обучать модель на вчерашней привязке
и увидит расхождение только по метрике, где оно уже ни на что не укажет.

Что проверяем: форму файла (три колонки, непустые поля, ключ вида «847:106»)
и полное совпадение множества троек с базой — все три поля, а не только состав
`channel_id`. Хеш одной колонки прошёл бы и при подменённом `smvu_key`.

Каждая строка вывода называет знаменатель: «совпало 10 720 из 10 720» вместо
«совпало». Ноль расхождений на пустой выборке — не доказательство.

Код возврата: 1, если хоть одна строка красная.

Запуск:  DATABASE_URL=postgresql://... python3 code/check_section_xref.py
Самопроверка без базы:  python3 code/check_section_xref.py --demo
"""

import asyncio
import csv
import os
import re
import sys
from pathlib import Path

try:
    import asyncpg
except ImportError:  # локально пакет живёт в .venv, в образе — в системном питоне
    asyncpg = None

CSV_ПУТЬ = (
    Path(__file__).resolve().parent.parent
    / "contracts"
    / "examples"
    / "section_xref.csv"
)
ЗАГОЛОВОК = ["channel_id", "section_id", "smvu_key"]
КЛЮЧ = re.compile(r"^[0-9]+:[0-9]+$")

ЗАПРОС = """
    SELECT c.channel_id, c.section_id, x.smvu_key
    FROM smvu.channel c
    JOIN ref.object_xref x USING (section_id)
"""


def разобрать(строки):
    """Читает CSV и возвращает (множество троек, список жалоб на форму)."""
    жалобы = []
    ряды = list(csv.reader(строки))
    if not ряды:
        return set(), ["файл пуст"]
    if ряды[0] != ЗАГОЛОВОК:
        жалобы.append(f"заголовок {ряды[0]}, ожидался {ЗАГОЛОВОК}")
    тройки = set()
    for номер, ряд in enumerate(ряды[1:], start=2):
        if len(ряд) != 3:
            жалобы.append(f"строка {номер}: полей {len(ряд)}, а не 3")
            continue
        канал, участок, ключ = (поле.strip() for поле in ряд)
        if not канал.isdigit() or not участок.isdigit():
            жалобы.append(
                f"строка {номер}: канал «{канал}» или участок «{участок}» не число"
            )
            continue
        if not КЛЮЧ.match(ключ):
            жалобы.append(f"строка {номер}: ключ «{ключ}» не вида «коллектор:пикет»")
            continue
        тройки.add((int(канал), int(участок), ключ))
    if len(тройки) + len(жалобы) != len(ряды) - 1:
        жалобы.append(
            f"повторы: строк данных {len(ряды) - 1}, различных троек {len(тройки)}"
        )
    return тройки, жалобы


def сверить(из_файла, жалобы, из_базы):
    """Печатает строки отчёта, возвращает True, если всё зелёное."""
    зелено = True

    if жалобы:
        print(f"X-01 СБОЙ форма файла: {len(жалобы)} нарушений, первые три:")
        for жалоба in жалобы[:3]:
            print(f"       {жалоба}")
        зелено = False
    else:
        print(
            f"X-01 OK   форма: {len(из_файла)} строк, три колонки, ключ вида «коллектор:пикет» у всех"
        )

    лишние = из_файла - из_базы
    недостающие = из_базы - из_файла
    if лишние or недостающие:
        print(
            f"X-02 СБОЙ файл разошёлся с базой: в базе {len(из_базы)}, в файле {len(из_файла)}; "
            f"лишних в файле {len(лишние)}, недостающих {len(недостающие)}"
        )
        for тройка in list(лишние)[:3]:
            print(f"       лишняя: {тройка}")
        for тройка in list(недостающие)[:3]:
            print(f"       недостающая: {тройка}")
        зелено = False
    else:
        print(
            f"X-02 OK   совпало {len(из_файла)} троек из {len(из_базы)} в базе, все три поля"
        )

    return зелено


async def из_базы():
    conn = await asyncpg.connect(os.environ["DATABASE_URL"])
    try:
        ряды = await conn.fetch(ЗАПРОС)
    finally:
        await conn.close()
    return {(р["channel_id"], р["section_id"], р["smvu_key"]) for р in ряды}


def демо():
    """Самопроверка: разбор обязан краснеть на трёх видах порчи."""
    добрый = ["channel_id,section_id,smvu_key", "1,10,847:106", "2,11,847:107"]
    тройки, жалобы = разобрать(добрый)
    assert not жалобы, жалобы
    assert тройки == {(1, 10, "847:106"), (2, 11, "847:107")}
    assert сверить(тройки, жалобы, set(тройки)) is True

    # Битая строка: четыре поля вместо трёх.
    _, жалобы = разобрать(добрый + ["3,12,847:108,лишнее"])
    assert any("полей 4" in ж for ж in жалобы), жалобы

    # Пустой ключ.
    _, жалобы = разобрать(добрый + ["3,12,"])
    assert any("не вида" in ж for ж in жалобы), жалобы

    # Лишняя строка, которой нет в базе.
    тройки, жалобы = разобрать(добрый + ["3,12,847:108"])
    assert not жалобы, жалобы
    assert сверить(тройки, жалобы, {(1, 10, "847:106"), (2, 11, "847:107")}) is False

    # Подменённый smvu_key при том же составе каналов: хеш колонки channel_id
    # это пропустил бы, сверка троек обязана поймать.
    подмена, жалобы = разобрать(
        ["channel_id,section_id,smvu_key", "1,10,847:106", "2,11,999:999"]
    )
    assert сверить(подмена, жалобы, {(1, 10, "847:106"), (2, 11, "847:107")}) is False

    print("демо: разбор краснеет на четырёх видах порчи, зелёный на добром файле")


def main():
    if "--demo" in sys.argv:
        демо()
        return 0

    if not CSV_ПУТЬ.exists():
        print(f"X-01 СБОЙ файла нет: {CSV_ПУТЬ}")
        return 1
    тройки, жалобы = разобрать(CSV_ПУТЬ.read_text(encoding="utf-8").splitlines())

    if not os.environ.get("DATABASE_URL") or asyncpg is None:
        print(
            f"ПРОПУСК сверка с базой: задайте DATABASE_URL (форма файла: {len(тройки)} строк, нарушений {len(жалобы)})"
        )
        return 1 if жалобы else 0

    # База названа, но не отвечает — это СБОЙ, а не пропуск: DATABASE_URL задали
    # нарочно, значит сверку ждали. Строкой, а не трассировкой стека: скрипт
    # едет в образ и на приёмке его читает человек, а не разработчик.
    try:
        из_базы_тройки = asyncio.run(из_базы())
    except OSError as ошибка:
        print(f"X-02 СБОЙ база не ответила: {ошибка}")
        return 1

    return 0 if сверить(тройки, жалобы, из_базы_тройки) else 1


if __name__ == "__main__":
    sys.exit(main())
