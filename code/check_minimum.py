#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Сводка по части 0 приёмки — 21 строка М-01…М-21 из docs/acceptance-test.md.

Запуск — тем же питоном, где стоит asyncpg (у нас это .venv, а не системный):
    .venv/bin/python code/check_minimum.py
    BASE_URL=https://135.106.216.101 CURL_OPTS=-k .venv/bin/python code/check_minimum.py

Дочерние проверки зовутся через sys.executable, а не через "python3": под
системным питоном все четыре падали с ModuleNotFoundError: No module named
'asyncpg', то есть 12 строк из 21 краснели от окружения, а не от дефекта.

Скрипт сам ничего не проверяет. Он запускает четыре чужие проверки, собирает
их строки и печатает вердикт по каждой из 21 строки части 0 плюс таблицу
блоков, как в разделе 0.6.

Итог по строке — одно из четырёх, код возврата — по худшему:
  OK             условие строки проверено машиной и выполнено;          код 0
  РУЧНАЯ <путь>  строка ручная по природе (таблица РУЧНЫЕ), машинная
                 часть в OK, доказательство — названный файл;           код 0
  ОТКРЫТА MOS-N  строка не в OK, и в таблице ОТКРЫТЫЕ стоит задача,
                 которая её закроет;                                    код 2
  СБОЙ           строка не в OK, а задачи на неё нет.                   код 1
Итог печатает четыре счёта порознь, а не одно «закрыто»: РУЧНАЯ с кодом 0
не имеет права сливаться с машинным OK.
До 22.09.2026 здесь было иначе: РУЧНАЯ и ПРОПУСК давали код 0, и check-all.sh
печатал «OK сводка части 0» при пяти незакрытых строках из 21. Вечная красная
строка тоже плоха — её перестают запускать, — поэтому незакрытая строка с
задачей получает свой код 2, а не 1. Вид от нижней проверки (СБОЙ, РУЧНАЯ,
ПРОПУСК) печатается рядом: ОТКРЫТА не прячет, что именно сломано.

Почему это отдельный файл, а не пункт в README: приёмочную сводку читает
комиссия, и она не должна зависеть от того, вспомнил ли человек про четвёртый
скрипт. Ненаписанная проверка обязана гореть красным, а не выпадать из списка —
молчаливый пропуск выглядит как зелень, и именно так приёмка и обманывается.
"""

import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Все 21 строка части 0 известны заранее и держатся здесь списком: только так
# можно поймать строку, которую не напечатал ни один скрипт. Разбивка на блоки
# повторяет разделы 0.1…0.5 и даёт таблицу раздела 0.6.
BLOCKS = [
    ("ML-модель", ["М-01", "М-02"]),
    ("Веб-интерфейс: три экрана", ["М-03", "М-04", "М-05", "М-06", "М-07", "М-08"]),
    ("Модуль заявок", ["М-09", "М-10", "М-11", "М-12", "М-13"]),
    ("REST API", ["М-14", "М-15", "М-16", "М-17"]),
    ("Метрики", ["М-18", "М-19", "М-20", "М-21"]),
]
ROWS = [row for _, rows in BLOCKS for row in rows]

# Кто какие строки обязан закрыть. Для examples.sh список держим здесь, потому
# что скрипт написан на bash до этой сводки и печатает по-своему («OK <метка>»),
# без номеров приёмки, — его вердикт мы берём по коду возврата.
CHECKERS = [
    (
        ["bash", "contracts/examples/api/examples.sh"],
        [
            "М-03",
            "М-04",
            "М-06",
            "М-07",
            "М-08",
            "М-12",
            "М-14",
            "М-15",
            "М-16",
            "М-17",
        ],
        "по коду возврата",
    ),
    (
        [sys.executable, "code/check_orders.py"],
        ["М-09", "М-10", "М-11", "М-12", "М-13"],
        "по строкам",
    ),
    (
        [sys.executable, "code/check_metrics.py"],
        ["М-18", "М-19", "М-20", "М-21"],
        "по строкам",
    ),
    (
        [sys.executable, "code/check_model_and_objects.py"],
        ["М-01", "М-02", "М-05"],
        "по строкам",
    ),
    # Экран М-05 браузером: метки по каждому коллектору, риск на схеме, клик.
    (
        ["node", "delivery/check-map.mjs"],
        ["М-05"],
        "по строкам",
    ),
]

# Строка вида «М-09 СБОЙ заявок в базе нет». Хвост — доказательство с числами.
# ПРОПУСК тут наравне с остальными: check_metrics.py печатает им три строки
# («решающий порог не зафиксирован»), и без него сводка писала про М-18…М-20
# «скрипт отработал, но строку не напечатал» — неверная причина при верном
# цвете. Причину читает комиссия, и чинить она пойдёт не то.
LINE_RE = re.compile(r"^(М-\d{2})\s+(OK|СБОЙ|РУЧНАЯ|ПРОПУСК)\b[ \t]*(.*)$")

# Незакрытые строки части 0 и задачи, которые их закроют. Держим здесь, а не
# в выводе проверок: номер задачи — решение оркестратора, а не свойство проверки.
# Строка ушла в OK — её отсюда убирают; забытую запись сводка назовёт сама.
ОТКРЫТЫЕ = {
    "М-05": "MOS-181",  # схема группирует по префиксу тега, а не по коллектору
    "М-10": "MOS-180, MOS-184",  # заявки нет; после 038 их больше предела top
    "М-13": "MOS-179",  # срок от конца окна риска, горизонт 24 вместо 720
    "М-18": "MOS-167",  # методика метрик: выдача v3 — открытие предупреждения
    "М-19": "MOS-167",
    "М-20": "MOS-179",  # горизонт в прогнозе 24, модель обучена на 720
}

# Строки, ручные по своей природе, и файл, который предъявляет человек. Подпись
# на бумаге машина не проверит; задачи на такую строку нет и не будет.
РУЧНЫЕ = {
    "М-02": "docs/protocol-directions.md",  # протокол направлений с подписями
}

# Чем хуже вердикт, тем больше вес. Одну строку могут закрывать два скрипта
# (М-12 проверяют и examples.sh, и check_orders.py) — берём худший из двух,
# иначе зелёный HTTP-код перекроет настоящую поломку связи заявка ↔ прогноз.
WEIGHT = {"OK": 0, "РУЧНАЯ": 1, "ПРОПУСК": 2, "СБОЙ": 3}


def parse_rows(text):
    """Достать из вывода чужого скрипта вердикты по строкам приёмки."""
    found = {}
    for line in text.splitlines():
        m = LINE_RE.match(line.strip())
        # Скрипт может напечатать одну строку приёмки несколько раз — побеждает
        # худшая, а не последняя. check_model_and_objects.py печатает М-05 трижды
        # (OK, СБОЙ, РУЧНАЯ), и до 22.09.2026 РУЧНАЯ последней строкой прятала СБОЙ.
        if m and (
            m.group(1) not in found or WEIGHT[m.group(2)] > WEIGHT[found[m.group(1)][0]]
        ):
            found[m.group(1)] = (m.group(2), m.group(3).strip())
    return found


def итог(вид, строка, открытые=ОТКРЫТЫЕ, ручные=РУЧНЫЕ):
    """Вид нижней проверки -> итог строки: OK, «РУЧНАЯ путь», «ОТКРЫТА MOS-N», СБОЙ.

    РУЧНАЯ только поверх OK или РУЧНОЙ снизу: сломанная машинная часть ручной
    строки — СБОЙ или ОТКРЫТА, как у всех.
    """
    if вид == "OK" and строка not in ручные:
        return "OK"
    if вид in ("OK", "РУЧНАЯ") and строка in ручные:
        return "РУЧНАЯ " + ручные[строка]
    return "ОТКРЫТА " + открытые[строка] if строка in открытые else "СБОЙ"


def свод(verdicts, открытые=ОТКРЫТЫЕ, ручные=РУЧНЫЕ):
    """Итог по каждой строке и код возврата.

    Возвращает (итоги, код): итоги — {строка: итог}, код — 1 при хоть одном
    СБОЕ, 2 при хоть одной ОТКРЫТОЙ без сбоев, 0 когда все в OK или РУЧНАЯ.
    Ненапечатанная строка — СБОЙ нижней проверки, дальше как все.
    """
    итоги = {
        строка: итог(verdicts.get(строка, ("СБОЙ", ""))[0], строка, открытые, ручные)
        for строка in ROWS
    }
    if "СБОЙ" in итоги.values():
        return итоги, 1
    if any(и.startswith("ОТКРЫТА") for и in итоги.values()):
        return итоги, 2
    return итоги, 0


def last_line(text, prefer=None):
    """Последняя непустая строка — то, чем закончился упавший скрипт.

    С prefer сначала ищем последнюю строку с этим началом: examples.sh всегда
    допечатывает в конце тело /api/audit, и без prefer доказательством стала бы
    подпись «--- тело последнего успешного ... ---», которая ни о чём не говорит.
    """
    lines = [s.strip() for s in text.splitlines() if s.strip()]
    if prefer:
        hits = [s for s in lines if s.startswith(prefer)]
        if hits:
            return hits[-1]
    return lines[-1] if lines else "(вывода нет)"


def run(cmd):
    """Запустить чужой скрипт. Переменные окружения (BASE_URL, CURL_OPTS)
    уходят насквозь: subprocess по умолчанию отдаёт потомку os.environ."""
    try:
        p = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, timeout=900)
        return p.returncode, p.stdout + p.stderr
    except subprocess.TimeoutExpired:
        return 124, "проверка не уложилась в 900 секунд"
    except OSError as e:  # нет bash, нет python3 — тоже отказ, а не падение сводки
        return 127, "не удалось запустить: %s" % e


def collect():
    """Собрать вердикты со всех четырёх скриптов.

    Возвращает (verdicts, printed) — вердикты по строкам и множество строк,
    которые скрипты напечатали сами. Разница между 21 и len(printed) — это
    вторая половина пары чисел в сводке.
    """
    verdicts = {}
    printed = set()

    def put(row, status, note):
        old = verdicts.get(row)
        if old is None or WEIGHT[status] > WEIGHT[old[0]]:
            verdicts[row] = (status, note)

    for cmd, rows, mode in CHECKERS:
        path = cmd[-1]
        name = os.path.basename(path)
        if not os.path.exists(os.path.join(ROOT, path)):
            # Отсутствие файла — это СБОЙ его строк, а не повод их пропустить.
            for row in rows:
                put(row, "СБОЙ", "проверка не написана: нет файла %s" % path)
            continue

        code, out = run(cmd)
        found = parse_rows(out)
        printed.update(found)

        if mode == "по коду возврата":
            ok_n = len(re.findall(r"^OK\b", out, re.M))
            bad_n = len(re.findall(r"^РАСХОЖДЕНИЕ\b", out, re.M))
            if code == 0:
                note = "%s: %d проверок, расхождений нет, код возврата 0" % (name, ok_n)
                for row in rows:
                    put(row, "OK", note)
            else:
                note = (
                    "%s: код возврата %d, расхождений %d из %d проверок; последнее: %s"
                    % (
                        name,
                        code,
                        bad_n,
                        ok_n + bad_n,
                        last_line(out, prefer="РАСХОЖДЕНИЕ"),
                    )
                )
                for row in rows:
                    put(row, "СБОЙ", note)
            continue

        if not found:
            # Скрипт есть, но не напечатал ни одной строки приёмки: упал
            # с трассировкой или напечатал что-то своё. Падение чужого скрипта
            # не имеет права ронять сводку — печатаем его последнюю строку.
            for row in rows:
                put(
                    row,
                    "СБОЙ",
                    "проверка упала, код возврата %d; последняя строка: %s"
                    % (code, last_line(out)),
                )
            continue

        for row in rows:
            if row in found:
                status, note = found[row]
                put(row, status, "%s: %s" % (name, note or "(без доказательства)"))
            else:
                put(
                    row,
                    "СБОЙ",
                    "%s отработал (код %d), но строку не напечатал" % (name, code),
                )

    return verdicts, printed


def main():
    verdicts, printed = collect()

    base_url = os.environ.get("BASE_URL", "http://127.0.0.1:8000 (по умолчанию)")
    print("Часть 0, программа минимум: 21 строка М-01…М-21 (docs/acceptance-test.md)")
    print(
        "BASE_URL = %s, CURL_OPTS = %s"
        % (base_url, os.environ.get("CURL_OPTS", "(пусто)"))
    )
    print()

    итоги, код = свод(verdicts)
    for row in ROWS:
        status, note = verdicts.get(
            row, ("СБОЙ", "строку не напечатал ни один скрипт, и ни один её не заявил")
        )
        # Вид нижней проверки печатаем, когда он не совпадает с итогом: у ОТКРЫТОЙ
        # строки видно, СБОЙ под ней, РУЧНАЯ или ПРОПУСК.
        снизу = "" if status == итоги[row].split()[0] else "[%s] " % status
        print("%s %s %s%s" % (row, итоги[row], снизу, note))

    def счёт(rows, вид):
        return sum(1 for r in rows if итоги[r].split()[0] == вид)

    print()
    print("| Блок | Строк | Машинно OK | Вручную | Открыто | Сбой |")
    print("|---|---|---|---|---|---|")
    for name, rows in BLOCKS:
        print("| %s | %d | %d | %d | %d | %d |" % (
            name, len(rows), счёт(rows, "OK"), счёт(rows, "РУЧНАЯ"),
            счёт(rows, "ОТКРЫТА"), счёт(rows, "СБОЙ")))
    print("| **Всего** | **%d** | **%d** | **%d** | **%d** | **%d** |" % (
        len(ROWS), счёт(ROWS, "OK"), счёт(ROWS, "РУЧНАЯ"),
        счёт(ROWS, "ОТКРЫТА"), счёт(ROWS, "СБОЙ")))

    print()
    # Пара чисел, а не один счётчик: сколько строк ждали и сколько из них
    # скрипты действительно напечатали. Расхождение указывает на ненаписанную
    # или молчащую проверку раньше, чем это заметит комиссия.
    print("Ждали 21 строку, скрипты напечатали %d." % len(printed))
    print("Машинно OK %d, вручную %d, открыто %d, сбой %d — из %d." % (
        счёт(ROWS, "OK"), счёт(ROWS, "РУЧНАЯ"), счёт(ROWS, "ОТКРЫТА"),
        счёт(ROWS, "СБОЙ"), len(ROWS)))

    # Строка в OK, а задача на неё всё ещё в таблице — запись устарела.
    for row, задача in ОТКРЫТЫЕ.items():
        if итоги[row] == "OK":
            print("ВНИМАНИЕ: %s в OK, а в ОТКРЫТЫЕ за ней стоит %s — убрать запись" % (row, задача))

    открытые = [r for r in ROWS if итоги[r].startswith("ОТКРЫТА")]
    сбои = [r for r in ROWS if итоги[r] == "СБОЙ"]
    if открытые:
        print("ОТКРЫТА %d: %s" % (len(открытые), ", ".join("%s %s" % (r, итоги[r][8:]) for r in открытые)))
    if сбои:
        print(
            "ВЕРДИКТ: программа минимум НЕ пройдена, в СБОЕ %d строк без задачи: %s"
            % (len(сбои), ", ".join("%s [%s]" % (r, verdicts.get(r, ("СБОЙ",))[0]) for r in сбои))
        )
    elif открытые:
        print("ВЕРДИКТ: сбоев без задачи нет, открыто %d строк — у каждой своя задача." % len(открытые))
    else:
        print("ВЕРДИКТ: машинно закрыто %d, остальные %d — ручные с доказательством." % (
            счёт(ROWS, "OK"), счёт(ROWS, "РУЧНАЯ")))
    return код


def demo():
    """Самопроверка разбора: одна OK, одна СБОЙ, одна пропущенная строка."""
    text = (
        "запускаю проверку заявок\n"
        "М-09 OK раздел заявок есть, 14 заявок в maint.notification\n"
        "М-10 СБОЙ ни одной заявки с source_system='forecast'\n"
        "М-11 РУЧНАЯ глазами открыть карточку заявки на стенде\n"
        "М-12 ПРОПУСК решающий порог не зафиксирован (--threshold)\n"
        "Traceback (most recent call last):\n"
        "ValueError: что-то пошло не так\n"
    )
    found = parse_rows(text)
    assert found["М-09"] == (
        "OK",
        "раздел заявок есть, 14 заявок в maint.notification",
    ), found
    assert found["М-10"][0] == "СБОЙ", found
    assert found["М-11"][0] == "РУЧНАЯ", found
    assert found["М-12"] == (
        "ПРОПУСК",
        "решающий порог не зафиксирован (--threshold)",
    ), found
    assert "М-13" not in found, "пропущенная строка не должна появиться из ниоткуда"
    assert len(found) == 4, found
    # Одна строка приёмки трижды: худшая побеждает, где бы ни стояла.
    трижды = parse_rows("М-05 OK дерево\nМ-05 СБОЙ схема\nМ-05 РУЧНАЯ глазами\n")
    assert трижды["М-05"] == ("СБОЙ", "схема"), трижды
    assert last_line(text) == "ValueError: что-то пошло не так"
    # prefer вытаскивает нужную строку из хвоста, а не последнюю подряд.
    assert last_line(
        "РАСХОЖДЕНИЕ GET /docs -> 200 вместо 404\nхвост", prefer="РАСХОЖДЕНИЕ"
    ).startswith("РАСХОЖДЕНИЕ GET /docs")
    # Худший вердикт побеждает: OK от examples.sh не перекрывает СБОЙ по М-12.
    assert WEIGHT["СБОЙ"] > WEIGHT["ПРОПУСК"] > WEIGHT["РУЧНАЯ"] > WEIGHT["OK"]
    # Все 21 строка на месте и без дублей.
    assert len(ROWS) == 21 and len(set(ROWS)) == 21
    # Три итога. Своя таблица задач, а не ОТКРЫТЫЕ: самопроверка не должна
    # меняться от того, какие строки сегодня открыты.
    задачи = {"М-05": "MOS-1", "М-10": "MOS-2"}
    ручные = {"М-02": "протокол.md"}
    все_ок = dict.fromkeys(ROWS, ("OK", ""))
    итоги, код = свод(все_ок, задачи, ручные)
    # Ручная строка не становится OK даже при зелёной машинной части, но и не валит.
    assert (итоги["М-02"], итоги["М-01"], код) == ("РУЧНАЯ протокол.md", "OK", 0), итоги

    # Не в OK и есть задача — ОТКРЫТА с кодом 2, какой бы вид ни дала проверка.
    открыто = dict(все_ок)
    открыто["М-05"] = ("РУЧНАЯ", "")
    открыто["М-10"] = ("СБОЙ", "")
    итоги, код = свод(открыто, задачи, ручные)
    assert (итоги["М-05"], итоги["М-10"], код) == ("ОТКРЫТА MOS-1", "ОТКРЫТА MOS-2", 2)

    # Не в OK без задачи — СБОЙ с кодом 1, и ПРОПУСК тоже: чужое решение
    # без задачи — это дыра, а не ожидание. Сломанная машинная часть ручной
