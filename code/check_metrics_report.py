#!/usr/bin/env python3
"""Исполняемая проверка отчёта о замере метрик: строки М-18, М-19, М-20а.

Строки приёмки — `docs/acceptance-test.md`, часть 0, раздел 0.5. Скрипт печатает
по строке на требование в виде «М-NN OK <числа>» или «М-NN СБОЙ <что не так>»
и выходит с кодом 1, если хоть одна строка красная.

**Чем эта проверка отличается от `code/check_metrics.py`.** Тот мерит прогнозы,
лежащие в базе стенда, и на 21.09.2026 мерил бы заглушку: все 425 183 строки
`pred.forecast` несут `model_version = stub-0.1`. Замер модели Николая сделан
бэктестом на историческом окне, его доказательства лежат в
`docs/proof/2026-09-21-metrics/our-metric/`, а числа — в `docs/metrics-report.md`.
Здесь проверяется ровно это: числа отчёта пересчитываются из доказательств
и должны совпасть посимвольно.

**Что она НЕ доказывает.** Что Precision взял порог 0,7 — он его не берёт, замер
даёт 0,600. Строки М-18 и М-19 эта проверка закрывает наполовину: замер предъявлен
и воспроизводится, порог не взят, обоснование заказчик разрешил письменно
19.09.2026. Поэтому пониженный порог тут не «ОК», а отдельная строка отчёта,
и она требует, чтобы обоснование в документе было — три вещи, которых требует М-18.

Методику не изобретаем: считают `group_incidents()` и `evaluate_alerts()`
из `code/predictive_metrics.py` — те же функции, что зовёт приёмочный замер.

Запуск:
    python3 code/check_metrics_report.py              # проверка отчёта
    python3 code/check_metrics_report.py --selfcheck  # только самопроверка
"""

import argparse
import csv
import os
import re
import sys
from datetime import datetime

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from predictive_metrics import (
    collector_key,
    evaluate_alerts,
    group_incidents,
)

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ДОКАЗАТЕЛЬСТВА = os.path.join(КОРЕНЬ, "docs/proof/2026-09-21-metrics/our-metric")
ОТЧЁТ = os.path.join(КОРЕНЬ, "docs/metrics-report.md")

# Окно замера и параметры методики — те же, что в code/check_metrics.py.
ОКНО_ОТ, ОКНО_ДО = "2026-04-01", "2026-07-01"
ОКНО_СКЛЕЙКИ_МИН = 10
ГОРИЗОНТ_Ч = 24
ВЕРХ_ОКНА_Ч = 168

# Корзины гистограммы упреждений. Границы неравные нарочно: половина попаданий
# укладывается в первые шесть часов, и равномерная шкала слепила бы их в один столбик.
КОРЗИНЫ = [(0, 1), (1, 6), (6, 12), (12, 24), (24, 48), (48, 72), (72, 120), (120, 168)]

# Три вещи, которых требует М-18 от обоснования пониженного порога. Ищем не слова
# «обоснование», а сами разделы: заголовок легко написать, не назвав ни одного числа.
ОБЯЗАТЕЛЬНЫЕ_РАЗДЕЛЫ = [
    "## Какое значение мы взяли",
    "## На каких данных и за какое окно",
    "## Почему данные не дали больше",
]


def ч(x, знаков=3):
    """Число по-русски: запятая вместо точки."""
    if isinstance(x, int):
        return str(x)
    return f"{x:.{знаков}f}".replace(".", ",")


def замер(каталог=ДОКАЗАТЕЛЬСТВА):
    """Пересчёт метрик из доказательств. Возвращает словарь чисел отчёта.

    Читает три файла каталога: связку «канал -> коллектор», отказы из базы
    и предупреждения модели. Ни одного числа не берёт готовым — все считаются
    здесь, иначе проверка сверяла бы отчёт сам с собой.
    """
    путь = lambda имя: os.path.join(каталог, имя)
    время = lambda s: datetime.fromisoformat(s)

    ch2col, pfx2col = {}, {}
    with open(путь("ch2collector.csv"), encoding="utf-8") as f:
        for r in csv.DictReader(f):
            if r["collector"]:
                ch2col[int(r["channel_id"])] = int(r["collector"])
                pfx2col.setdefault(r["pfx"], set()).add(int(r["collector"]))
    if not ch2col:
        raise ValueError("связка «канал -> коллектор» пуста: мерить нечем")

    with open(путь("fails_db.csv"), encoding="utf-8") as f:
        отказы = [(int(r["channel_id"]), время(r["t_start"])) for r in csv.DictReader(f)]
    with open(путь("alerts.csv"), encoding="utf-8") as f:
        предупреждения = [(r["pfx"], время(r["t"])) for r in csv.DictReader(f)]
    if not отказы or not предупреждения:
        raise ValueError("пустые отказы или предупреждения: мерить нечем")

    от, до = время(ОКНО_ОТ), время(ОКНО_ДО)
    инциденты = [
        (k, t)
        for k, t in group_incidents(отказы, ОКНО_СКЛЕЙКИ_МИН, collector_key(ch2col))
        if от < t < до
    ]
    # Предупреждение модели приходит на префикс тега, а инцидент — на коллектор.
    # Префикс 163 ведёт к двум коллекторам, 798 тоже: такое предупреждение кладём
    # на оба, иначе его пришлось бы выбросить или угадать нужный.
    на_коллекторах = [
        (f"obj:{c}", t) for p, t in предупреждения for c in sorted(pfx2col.get(p, ()))
    ]

    m24 = evaluate_alerts(на_коллекторах, инциденты, ГОРИЗОНТ_Ч, ВЕРХ_ОКНА_Ч)
    m0 = evaluate_alerts(на_коллекторах, инциденты, 0, ВЕРХ_ОКНА_Ч)

    гистограмма = [
        (lo, hi, sum(1 for x in m0["lead_hours"] if lo <= x < hi)) for lo, hi in КОРЗИНЫ
    ]
    # Сумма корзин обязана сойтись с числом попаданий. Условие не холостое: корзины
    # заданы руками, и стоит кому-то сдвинуть границу — часть попаданий провалится
    # мимо всех столбиков, а гистограмма останется нарисованной и правдоподобной.
    в_корзинах = sum(n for _, _, n in гистограмма)
    if в_корзинах != m0["tp"]:
        raise ValueError(
            f"корзины не покрывают все упреждения: попаданий {m0['tp']}, "
            f"в корзинах {в_корзинах}; границы {КОРЗИНЫ}"
        )

    return {
        "инцидентов": len(инциденты),
        "предупреждений": len(предупреждения),
        "предупреждений_на_коллекторах": len(на_коллекторах),
        "префиксов": len({p for p, _ in предупреждения}),
        "коллекторов_всего": len(set(ch2col.values())),
        "коллекторов_с_предупреждениями": len({k for k, _ in на_коллекторах}),
        "коллекторов_с_инцидентами": len({k for k, _ in инциденты}),
        "precision": m24["precision"], "recall": m24["recall"],
        "tp": m24["tp"], "fp": m24["fp"], "fn": m24["fn"],
        "медиана_ч": m0["median_lead_hours"],
        "мин_ч": m0["min_lead_hours"],
        "попаданий_при_нуле": m0["tp"],
        # Доля «не меньше 24 часов» — дополнение доли поздних. evaluate_alerts
        # считает поздние, потому что в приёмке порогом ограничены именно они.
        "доля_от24": round(1 - m0["lead_under_24h_share"], 3),
        # Гистограмма строится из того же списка упреждений, из которого
        # evaluate_alerts взяла медиану: второй отбор пар «отказ — предупреждение»
        # разошёлся бы с первым молча.
        "гистограмма": гистограмма,
    }


def _ячейка(текст, метка, число):
    """Строка таблицы «| метка | число |» с этим самым числом. Пробелы внутри
    ячейки любые, но число должно стоять ровно то: иначе правка отчёта пройдёт молча."""
    шаблон = rf"\|\s*{re.escape(метка)}\s*\|\s*{re.escape(число)}\s*\|"
    return re.search(шаблон, текст) is not None


def строки(m, текст):
    """Три строки приёмки по готовым числам. Без файлов — поэтому проверяема assert'ом."""
    out = []

    выборка = (f"{m['инцидентов']} инцидентов, {m['предупреждений']} предупреждений, "
               f"TP {m['tp']} / FP {m['fp']} / FN {m['fn']}")

    # Объём выборки и матрица ошибок. Без них проверка сверяла бы только итоговые
    # доли: 90/(90+65) тоже даёт 0,581, а 93/(93+62) — 0,600, и подменённая матрица
    # прошла бы молча. Нашла эту дыру проверяющая сессия 21.09.2026, подменив разом
    # TP 93 → 90, FP 62 → 65, инцидентов 176 → 200 и предупреждений 166 → 999:
    # все три строки остались зелёными.
    объём = [
        ("Инцидентов после склейки по коллектору", str(m["инцидентов"])),
        ("Предупреждений модели", str(m["предупреждений"])),
        ("Предупреждений после раскладки на коллекторы",
         str(m["предупреждений_на_коллекторах"])),
        ("Префиксов тегов под предупреждениями", str(m["префиксов"])),
        ("Коллекторов под предупреждениями",
         f"{m['коллекторов_с_предупреждениями']} из {m['коллекторов_всего']}"),
        ("Коллекторов с инцидентами",
         f"{m['коллекторов_с_инцидентами']} из {m['коллекторов_всего']}"),
        ("TP — попадание", str(m["tp"])),
        ("FP — ложная тревога", str(m["fp"])),
        ("FN — пропуск", str(m["fn"])),
        ("Пойманных инцидентов при горизонте 0",
         f"{m['попаданий_при_нуле']} из {m['инцидентов']}"),
    ]
    разошлись = [f"{метка} = {значение}" for метка, значение in объём
                 if not _ячейка(текст, метка, значение)]
    if разошлись:
        # Красим все три строки, а не одну М-18: разошедшийся объём выборки означает,
        # что отчёт описывает не тот прогон, и доверять его долям и упреждениям
        # не больше оснований, чем его матрице.
        текст_сбоя = ("отчёт разошёлся с пересчётом по объёму выборки и матрице "
                      "ошибок: " + "; ".join(разошлись))
        return [(n, False, текст_сбоя) for n in ("М-18", "М-19", "М-20а")]

    for номер, имя, ключ in (("М-18", "Precision", "precision"),
                             ("М-19", "Recall", "recall")):
        значение = ч(m[ключ])
        есть = _ячейка(текст, f"{имя} ({номер})", значение)
        порог_взят = m[ключ] > (0.7 if ключ == "precision" else 0.5)
        if not есть:
            out.append((номер, False,
                        f"в отчёте нет строки «| {имя} ({номер}) | {значение} |»: "
                        f"пересчёт даёт {значение}, {выборка}"))
        elif порог_взят:
            out.append((номер, True, f"{значение} — порог взят, {выборка}"))
        else:
            # Третий исход, не OK и не СБОЙ. Зелёный здесь прочитался бы как
            # «постановка закрыта», хотя закрыт только замер; красный каждый прогон
            # означал бы поломку, а замер исправен — метрика ниже планового значения,
            # и заказчик разрешил это письменно. Роняем только когда обоснования нет:
            # без него пониженный порог защищать на приёмке нечем.
            разделы = [р for р in ОБЯЗАТЕЛЬНЫЕ_РАЗДЕЛЫ if р not in текст]
            if разделы:
                out.append((номер, False,
                            f"{значение} ниже порога, и в отчёте нет разделов "
                            f"обоснования: {', '.join(разделы)}; {выборка}"))
            else:
                out.append((номер, None,
                            f"{значение} ниже планового {ч(0.7 if ключ == 'precision' else 0.5)} "
                            f"— замер сходится с доказательствами, обоснование на месте "
                            f"(три раздела М-18); {выборка}"))

    # М-20а: порога нет, но требуются три величины и гистограмма — все четыре
    # вещи проверяем в отчёте, а не на слово.
    медиана, доля = ч(m["медиана_ч"], 1), ч(m["доля_от24"] * 100, 1)
    нет = []
    if not _ячейка(текст, "Медиана упреждения (М-20а)", f"{медиана} ч"):
        нет.append(f"медиана {медиана} ч")
    if not _ячейка(текст, "Доля упреждений ≥ 24 ч (М-20а)", f"{доля} %"):
        нет.append(f"доля ≥ 24 ч {доля} %")
    if not _ячейка(текст, "Метрики при упреждении ≥ 24 ч (М-20а)",
                   f"{ч(m['precision'])} / {ч(m['recall'])}"):
        нет.append(f"метрики при требовании {ч(m['precision'])} / {ч(m['recall'])}")
    промах = [f"{lo}–{hi} ч = {n}" for lo, hi, n in m["гистограмма"]
              if not _ячейка(текст, f"{lo}–{hi} ч", str(n))]
    if промах:
        нет.append("корзины гистограммы: " + ", ".join(промах))
    if нет:
        out.append(("М-20а", False, "отчёт разошёлся с пересчётом — " + "; ".join(нет)))
    else:
        out.append(("М-20а", True,
                    f"медиана {медиана} ч, доля ≥ 24 ч {доля} %, метрики при этом "
                    f"требовании {ч(m['precision'])} / {ч(m['recall'])}, "
                    f"гистограмма из {len(КОРЗИНЫ)} корзин на "
                    f"{m['попаданий_при_нуле']} попаданиях"))
    return out


def _selfcheck():
    """Четыре случая: верный отчёт, подменённое число, пропавшее обоснование,
    пустые доказательства. Проверка, которая не умеет краснеть, ничего не проверяет."""
    m = {"инцидентов": 176, "предупреждений": 166, "предупреждений_на_коллекторах": 170,
         "precision": 0.6, "recall": 0.528, "tp": 93, "fp": 62, "fn": 83,
         "префиксов": 15, "коллекторов_всего": 16,
         "коллекторов_с_предупреждениями": 12, "коллекторов_с_инцидентами": 13,
         "медиана_ч": 12.1, "мин_ч": 0.1, "попаданий_при_нуле": 116,
         "доля_от24": 0.388, "гистограмма": [(0, 1, 21), (1, 6, 27)]}
    хороший = (
        "| Precision (М-18) | 0,600 | \n| Recall (М-19) | 0,528 |\n"
        "| Медиана упреждения (М-20а) | 12,1 ч |\n"
        "| Доля упреждений ≥ 24 ч (М-20а) | 38,8 % |\n"
        "| Метрики при упреждении ≥ 24 ч (М-20а) | 0,600 / 0,528 |\n"
        "| 0–1 ч | 21 |\n| 1–6 ч | 27 |\n"
        "| Инцидентов после склейки по коллектору | 176 |\n"
        "| Предупреждений модели | 166 |\n"
        "| Предупреждений после раскладки на коллекторы | 170 |\n"
        "| TP — попадание | 93 | модель предупредила |\n"
        "| FP — ложная тревога | 62 |\n| FN — пропуск | 83 |\n"
        "| Пойманных инцидентов при горизонте 0 | 116 из 176 |\n"
        "| Префиксов тегов под предупреждениями | 15 |\n"
        "| Коллекторов под предупреждениями | 12 из 16 |\n"
        "| Коллекторов с инцидентами | 13 из 16 |\n"
        + "\n".join(ОБЯЗАТЕЛЬНЫЕ_РАЗДЕЛЫ)
    )
    д = {n: (ок, т) for n, ок, т in строки(m, хороший)}
    # Порог не взят -> М-18 и М-19 красные даже при верном отчёте, и это правильно.
    assert д["М-18"][0] is None and "ниже планового" in д["М-18"][1], д["М-18"]
    assert "обоснование на месте" in д["М-18"][1], д["М-18"]
    # Recall 0,528 плановое значение 0,5 БЕРЁТ — строка зелёная. Пара метрик
    # с разным исходом здесь нарочно: проверка, красящая обе одинаково, не отличила бы
    # «ни одна не дошла» от «полнота дошла, точность нет».
    assert д["М-19"][0] is True and "порог взят" in д["М-19"][1], д["М-19"]
    assert д["М-20а"][0] is True, д["М-20а"]

    # Подменённое число в отчёте: 0,600 -> 0,700. Пересчёт даёт 0,600, и строка
    # обязана покраснеть словами «в отчёте нет строки», а не промолчать.
    подмена = хороший.replace("| Precision (М-18) | 0,600 |", "| Precision (М-18) | 0,700 |")
    д2 = {n: (ок, т) for n, ок, т in строки(m, подмена)}
    assert д2["М-18"][0] is False and "в отчёте нет строки" in д2["М-18"][1], д2["М-18"]

    # Подмена матрицы ошибок: TP 93 -> 90. Доли в отчёте при этом остаются
    # прежними, и до 21.09.2026 такая подделка проходила зелёной.
    д_tp = {n: (ок, т) for n, ок, т in
            строки(m, хороший.replace("| TP — попадание | 93 |", "| TP — попадание | 90 |"))}
    assert д_tp["М-18"][0] is False, д_tp["М-18"]
    assert "TP — попадание = 93" in д_tp["М-18"][1], д_tp["М-18"]

    # Та же подмена в гистограмме: корзина 1–6 ч с 27 на 28.
    д3 = {n: (ок, т) for n, ок, т in строки(m, хороший.replace("| 1–6 ч | 27 |", "| 1–6 ч | 28 |"))}
    assert д3["М-20а"][0] is False and "1–6 ч = 27" in д3["М-20а"][1], д3["М-20а"]

    # Обоснование пропало: числа сходятся, но пониженный порог защищать нечем.
    без = хороший.replace(ОБЯЗАТЕЛЬНЫЕ_РАЗДЕЛЫ[2], "## Про погоду")
    д4 = {n: (ок, т) for n, ок, т in строки(m, без)}
    assert д4["М-18"][0] is False and "нет разделов обоснования" in д4["М-18"][1], д4["М-18"]
    # И обратный случай той же пары: с обоснованием та же цифра не роняет прогон.
    assert {n: ок for n, ок, _ in строки(m, хороший)}["М-18"] is None

    # Взятый порог читается зелёным — иначе проверка не отличала бы хорошую модель.
    взят = dict(m, precision=0.71, recall=0.55)
    д5 = {n: (ок, т) for n, ок, т in
          строки(взят, хороший.replace("0,600 | ", "0,710 | ").replace("| Recall (М-19) | 0,528 |",
                                                                      "| Recall (М-19) | 0,550 |"))}
    assert д5["М-18"][0] is True and "порог взят" in д5["М-18"][1], д5["М-18"]

    # Корзины, не покрывающие все упреждения: гистограмма молча потеряла бы
    # попадания, а сумма столбиков перестала бы сходиться с tp. Подменяем список
    # корзин на заведомо дырявый и ждём отказа с числами.
    global КОРЗИНЫ
    целые, КОРЗИНЫ = КОРЗИНЫ, [(0, 1), (1, 6)]
    try:
        замер()
        raise AssertionError("должно было упасть: корзины покрывают не все упреждения")
    except ValueError as e:
        assert "корзины не покрывают" in str(e), e
    finally:
        КОРЗИНЫ = целые

    # Пустые доказательства — отказ, а не «проверить нечего».
    try:
        замер(os.path.join(os.path.dirname(__file__), "нет-такого-каталога"))
        raise AssertionError("должно было упасть: каталога доказательств нет")
    except (FileNotFoundError, NotADirectoryError):
        pass

    print("самопроверка ok: подмена числа, подмена матрицы ошибок, пропавшее "
          "обоснование, дырявые корзины, пустые доказательства")


def main():
    р = argparse.ArgumentParser(description="Проверка отчёта о замере: М-18, М-19, М-20а")
    р.add_argument("--selfcheck", action="store_true", help="только самопроверка")
    р.add_argument("--report", default=ОТЧЁТ, help="путь к отчёту")
    р.add_argument("--proof", default=ДОКАЗАТЕЛЬСТВА, help="каталог доказательств")
    а = р.parse_args()

    _selfcheck()
    if а.selfcheck:
        return 0

    try:
        with open(а.report, encoding="utf-8") as f:
            текст = f.read()
        результат = строки(замер(а.proof), текст)
    except Exception as e:
        # Нет отчёта или нет доказательств — нет замера. Это отказ по всем трём
        # строкам, а не повод промолчать.
        результат = [(n, False, f"проверка не выполнена: {type(e).__name__}: {e}")
                     for n in ("М-18", "М-19", "М-20а")]

    for номер, ок, текст_строки in результат:
        исход = "НИЖЕ ПОРОГА" if ок is None else ("OK" if ок else "СБОЙ")
        print(f"{номер} {исход} {текст_строки}")
    return 1 if any(ок is False for _, ок, _ in результат) else 0


if __name__ == "__main__":
    sys.exit(main())
