"""Забрать почасовую погоду по Москве из Open-Meteo и положить в CSV.

Зачем. ТЗ разд. 13, стр. 11 («Внешние источники») требует четыре величины:
температуру, влажность, осадки, атмосферное давление, «интеграция через открытые
API». Строка приёмки — Ф-85. Модель учится на истории, поэтому нам нужен не только
живой прогноз, но и архив на весь период выгрузки СМВУ: 01.01.2019 — 30.06.2026.

Почему Open-Meteo. Ключ не нужен, регистрации нет, архив с 1940 года, лимит
бесплатного тарифа 10 000 вызовов в сутки при наших 24. Источник данных — реанализ
ERA5 от ECMWF. Проверено 15.09.2026: весь наш период приходит одним запросом
за 2 секунды, 2,4 МБ, 65 712 часов, ни одного пропуска в четырёх колонках.
Яндекс.Погода и Гисметео отпали: архив там платный.

**Чего этот файл не делает и почему.** Он не ходит в сеть по расписанию и не пишет
в базу. История скачивается ОДИН раз и дальше лежит файлом: обучение модели не должно
зависеть от того, выпустил ли заказчик наш сервер в интернет. Живой почасовой опрос —
отдельная задача Q3.6, там же решается вопрос межсетевого экрана (ОВ-49).

Некоммерческий тариф. Для хакатона годится, для поставки заказчику нужна либо
подписка, либо своя копия сервера — код Open-Meteo открыт. Это надо назвать
в протоколе приёмки, а не умолчать.

Запуск:
    python3 code/load_weather.py                 # самопроверка на трёх сутках
    python3 code/load_weather.py dataset/weather.csv   # весь период в файл
"""

import csv
import json
import os
import sys
import urllib.request
from datetime import date, datetime, timedelta

ТОЧКА = (55.75, 37.62)          # центр Москвы; коллекторы разбросаны по городу,
                                # но разница температуры внутри МКАД меньше ошибки ERA5
ВЕЛИЧИНЫ = "temperature_2m,relative_humidity_2m,precipitation,surface_pressure"
НАЧАЛО, КОНЕЦ = "2019-01-01", "2026-06-30"   # ровно период выгрузки СМВУ


def забрать(начало, конец):
    """Один запрос к архиву. Возвращает словарь колонок из поля hourly."""
    ш, д = ТОЧКА
    url = ("https://archive-api.open-meteo.com/v1/archive"
           f"?latitude={ш}&longitude={д}&start_date={начало}&end_date={конец}"
           f"&hourly={ВЕЛИЧИНЫ}&timezone=Europe%2FMoscow")
    with urllib.request.urlopen(url, timeout=120) as ответ:
        return json.load(ответ)["hourly"]


def проверить(часы, начало, конец):
    """Проверка обязана поймать неполную выгрузку, а не просто «ответ пришёл».

    Два отказа, которые она ловит. Первый: API молча отдаёт меньше часов, чем
    запрошено, — тогда признаки за недостающие сутки посчитаются по пустому окну.
    Второй: колонка приходит с null вместо числа, и это не ноль осадков, а «нет
    данных»; сложить одно с другим — получить неверную норму.
    """
    ожидаем = (date.fromisoformat(конец) - date.fromisoformat(начало) + timedelta(days=1)).days * 24
    факт = len(часы["time"])
    assert факт == ожидаем, f"часов пришло {факт}, ждали {ожидаем}"
    assert часы["time"][0] == f"{начало}T00:00", f"первый час {часы['time'][0]}, ждали {начало}T00:00"
    assert часы["time"][-1] == f"{конец}T23:00", f"последний час {часы['time'][-1]}, ждали {конец}T23:00"
    for имя, значения in часы.items():
        if имя == "time":
            continue
        пусто = sum(1 for з in значения if з is None)
        assert пусто == 0, f"в колонке {имя} пропусков {пусто} из {факт}"
    # Шаг ровно час: API может вернуть нужное число строк с дырой внутри,
    # если сдвинется часовой пояс. Считаем разрывы между соседними метками.
    метки = [datetime.fromisoformat(т) for т in часы["time"]]
    разрывы = [(a, b) for a, b in zip(метки, метки[1:]) if b - a != timedelta(hours=1)]
    assert not разрывы, f"разрывов в ряду {len(разрывы)}, первый: {разрывы[0]}"


def записать(часы, путь):
    # Каталог создаём сами: dataset/ лежит в .gitignore, и на свежем клоне
    # репозитория его нет вовсе. Без этой строки команда из инструкции падает
    # с FileNotFoundError у любого, кто клонировал проект и сразу запустил скрипт.
    каталог = os.path.dirname(путь)
    if каталог:
        os.makedirs(каталог, exist_ok=True)
    колонки = ["time", "temperature_2m", "relative_humidity_2m", "precipitation", "surface_pressure"]
    with open(путь, "w", encoding="utf-8", newline="") as ф:
        писатель = csv.writer(ф)
        писатель.writerow(колонки)
        писатель.writerows(zip(*(часы[к] for к in колонки)))


def самопроверка():
    """Гоняем на трёх сутках, чтобы не тянуть 65 712 часов ради проверки кода."""
    часы = забрать("2024-04-06", "2024-04-08")
    проверить(часы, "2024-04-06", "2024-04-08")
    assert len(часы["time"]) == 72
    print("самопроверка: 72 часа за 6–8 апреля 2024, пропусков нет, ряд без разрывов")
    # Эти же трое суток СМВУ молчала (задача MOS-87). Погода тогда была обычной
    # весенней: от -2,7 до +17,6 °C, осадков не больше 2 мм в сутки. То есть тишину
    # в журнале погодой не объяснить — версия «аномалия» проверена и отброшена.
    т = часы["temperature_2m"]
    print(f"  температура в дни тишины СМВУ: от {min(т)} до {max(т)} °C, "
          f"осадков за трое суток {sum(часы['precipitation']):.1f} мм")


if __name__ == "__main__":
    if len(sys.argv) == 1:
        самопроверка()
    else:
        часы = забрать(НАЧАЛО, КОНЕЦ)
        проверить(часы, НАЧАЛО, КОНЕЦ)
        записать(часы, sys.argv[1])
        print(f"записано: {sys.argv[1]}, часов {len(часы['time'])}, "
              f"с {часы['time'][0]} по {часы['time'][-1]}")
