"""Сверяет счётчики файлов у каталогов в docs/project-structure.md с git ls-tree.

Разбор 22.09.2026 (MOS-176, строка плана 9.21). Число у каталога никого не
останавливает и ничего не ломает, поэтому стареет молча: никто не замечает
расхождения, пока не сядет считать. В тот день code/ отстал на десять файлов —
почти четверть каталога, — а документ идёт заказчику в составе поставки.

Способ счёта один и записан в самом документе: число файлов каталога в git
целиком, `git ls-tree -r --name-only HEAD -- <каталог>/`. По истории файла
видно, что раньше считали разноспособно: docs/ — всё дерево, code/ — похоже,
с диска, dataset/ — точно с диска. Отсюда и расхождения при каждом пересчёте.

Считаем по git, а не по диску нарочно: на диске лежит незакоммиченная работа
соседних сессий и служебный мусор (22.09.2026 в code/ было 66 файлов на диске
против 42 в HEAD), и проверка с диска краснела бы у всякого, у кого есть
незакоммиченное, — то есть всегда.

Запуск: python3 code/check_structure.py
"""

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "project-structure.md"

# Число стоит только у каталогов верхнего уровня дерева. Вложенные строки
# начинаются с «│   » и под проверку не попадают — там чисел нет.
СТРОКА = re.compile(r"^[├└]── ([\w.\-]+)/\s+(\d+)\b")

# Каталоги, которых в git нет по правилу .gitignore: число в документе про
# диск, и сверять его с git ls-tree бессмысленно — расхождение там не дефект,
# а устройство поставки. Печатаем ПРОПУСК с причиной, а не молчим.
ПРОПУСК = {
    "dataset": "выгрузка заказчика в git не идёт (.gitignore) — число про диск",
}


def в_git(каталог):
    """Число файлов каталога в HEAD, всё дерево."""
    out = subprocess.run(
        ["git", "ls-tree", "-r", "--name-only", "HEAD", "--", f"{каталог}/"],
        capture_output=True,
        text=True,
        cwd=ROOT,
        check=True,
    ).stdout
    return len([стр for стр in out.splitlines() if стр.strip()])


def main():
    if not DOC.exists():
        print(f"СБОЙ нет файла {DOC} — запускать из корня репозитория")
        return 1
    найдено = 0
    беда = 0
    for строка in DOC.read_text(encoding="utf-8").splitlines():
        м = СТРОКА.match(строка)
        if not м:
            continue
        найдено += 1
        каталог, в_документе = м.group(1), int(м.group(2))
        if каталог in ПРОПУСК:
            print(f"ПРОПУСК {каталог}/ — {ПРОПУСК[каталог]}")
            continue
        факт = в_git(каталог)
        метка = "OK     " if факт == в_документе else "РАЗОШЛОСЬ"
        print(f"{метка} {каталог}/ — в документе {в_документе}, в git ls-tree {факт}")
        if факт != в_документе:
            беда += 1
    if not найдено:
        print(f"СБОЙ ни одного счётчика в {DOC} — проверять нечего")
        return 1
    if беда:
        print(f"СБОЙ счётчики устарели: {беда} из {найдено} каталогов")
        return 1
    print(f"OK счётчики всех {найдено} каталогов совпадают с git ls-tree")
    return 0


if __name__ == "__main__":
    sys.exit(main())
