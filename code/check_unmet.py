"""Список невыполненных требований сверяется с приёмкой: строка НФ-90 (MOS-229, план 9.23).

Заказчик 19.09.2026 разрешил сдать MVP с невыполненными обязательными пунктами, «при
условии, что команда четко объяснит причину» (docs/meetings/2026-09-19-ответы-заказчика.md,
сводный 8). Список лежит в docs/unmet-requirements.md. Проверка следит, чтобы он не
разошёлся с docs/acceptance-test.md: номера незакрытых строк частей 0 и I должны
совпадать с номерами в таблице списка, в обе стороны.

Незакрытая строка — та, у которой в последней ячейке нет ✓. Одиннадцать строк раздела I.14
в части I стоят указателями («разд. III.x»), их статус берём из той же строки в части III.
Часть II (Регламент) в список не входит: НФ-90 говорит о требованиях ТЗ.

    python3 code/check_unmet.py             # сверка, код 1 при расхождении
    python3 code/check_unmet.py --selftest  # ловит пропущенную и лишнюю строку
"""

import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
ПРИЁМКА = КОРЕНЬ / "docs" / "acceptance-test.md"
СПИСОК = КОРЕНЬ / "docs" / "unmet-requirements.md"

СТРОКА = re.compile(r"^\|\s*((?:М|Ф|НФ)-\d+а?)\s*\|")


def части(текст: str) -> dict[str, list[str]]:
    """Строки файла по частям: '0', 'I', 'II', 'III' — по заголовкам «# ЧАСТЬ …»."""
    итог: dict[str, list[str]] = {}
    текущая = None
    for line in текст.splitlines():
        m = re.match(r"^# ЧАСТЬ (0|I|II|III)\.", line)
        if m:
            текущая = m.group(1)
            итог[текущая] = []
        elif line.startswith("# "):
            текущая = None
        elif текущая:
            итог[текущая].append(line)
    return итог


def закрыта(line: str) -> bool:
    ячейки = [c.strip() for c in line.rstrip().strip("|").split("|")]
    return "✓" in ячейки[-1]


def открытые(текст: str) -> set[str]:
    ч = части(текст)
    статус_iii = {}
    for line in ч.get("III", []):
        m = СТРОКА.match(line)
        if m:
            статус_iii[m.group(1)] = закрыта(line)
    итог = set()
    for имя in ("0", "I"):
        for line in ч.get(имя, []):
            m = СТРОКА.match(line)
            if not m:
                continue
            номер = m.group(1)
            if re.search(r"\|\s*разд\. III\.\d+\s*\|\s*$", line):
                if номер not in статус_iii:
                    raise SystemExit(f"СБОЙ указатель {номер} ведёт в часть III, а строки там нет")
                if not статус_iii[номер]:
                    итог.add(номер)
            elif not закрыта(line):
                итог.add(номер)
    return итог


ШАПКА = re.compile(r"^\|\s*№\s*\|\s*Требование\s*\|\s*Причина\s*\|")
ВИДЫ = {"нет данных", "противоречие в ТЗ", "не успели"}


def в_списке(текст: str) -> tuple[set[str], list[str]]:
    """Номера из таблиц списка и ошибки строк. Берём только таблицы с шапкой
    «| № | Требование | Причина | …» — ссылка «| Ф-76 |» в чужой таблице не засчитывается."""
    номера, ошибки, в_таблице = set(), [], False
    for line in текст.splitlines():
        if ШАПКА.match(line):
            в_таблице = True
            continue
        if not line.startswith("|"):
            в_таблице = False
            continue
        m = СТРОКА.match(line)
        if not (в_таблице and m):
            continue
        ячейки = [c.strip() for c in line.strip().strip("|").split("|")]
        номер = m.group(1)
        номера.add(номер)
        if len(ячейки) < 4 or ячейки[2] not in ВИДЫ:
            ошибки.append(f"СБОЙ {номер}: причина «{ячейки[2] if len(ячейки) > 2 else ''}» — не из трёх видов НФ-90")
        elif not ячейки[3]:
            ошибки.append(f"СБОЙ {номер}: причина не объяснена словами")
    return номера, ошибки


def сверить(приёмка: str, список: str) -> list[str]:
    надо, (есть, ошибки) = открытые(приёмка), в_списке(список)
    if not надо:
        return ["СБОЙ в приёмке не найдено ни одной незакрытой строки — разбор сломан"]
    ошибки += [f"СБОЙ {н} не закрыта в приёмке, а в списке её нет" for н in sorted(надо - есть)]
    ошибки += [f"СБОЙ {н} есть в списке, но в приёмке закрыта или отсутствует" for н in sorted(есть - надо)]
    return ошибки


def selftest() -> None:
    приёмка = "\n".join([
        "# ЧАСТЬ 0. ПРОГРАММА МИНИМУМ",
        "| М-01 | a | b | c | ✓ |",
        "| М-02 | a | b | c | ☐ |",
        "# ЧАСТЬ I. ОБЯЗАТЕЛЬНОЕ",
        "| Ф-01 | a | b | c | ☐ |",
        "| Ф-34 | вердикт | разд. 10 | разд. III.4 |",
        "| Ф-53 | журнал | ответ | разд. III.5 |",
        "# ЧАСТЬ II. НОРМАТИВНОЕ",
        "| НФ-56 | a | b | c | ☐ |",
        "# ЧАСТЬ III. РЕКОМЕНДАЦИИ",
        "| Ф-34 | a | b | c | ☐ |",
        "| Ф-53 | a | b | c | ✓ |",
        "# Сводка",
    ])
    шапка = "| № | Требование | Причина | Почему |\n|---|---|---|---|\n"
    полный = шапка + "| М-02 | x | нет данных | y |\n| Ф-01 | x | не успели | y |\n| Ф-34 | x | противоречие в ТЗ | y |\n"
    assert открытые(приёмка) == {"М-02", "Ф-01", "Ф-34"}, открытые(приёмка)
    assert сверить(приёмка, полный) == []
    без_строки = полный.replace("| Ф-01 | x | не успели | y |\n", "")
    assert any("Ф-01" in e for e in сверить(приёмка, без_строки))
    лишняя = полный + "| М-01 | x | не успели | y |\n"
    assert any("М-01" in e for e in сверить(приёмка, лишняя))
    пустая = полный.replace("| Ф-01 | x | не успели | y |", "| Ф-01 | x |  |  |")
    assert any("Ф-01" in e for e in сверить(приёмка, пустая))
    чужой_вид = полный.replace("не успели", "просто так")
    assert any("просто так" in e for e in сверить(приёмка, чужой_вид))
    без_слов = полный.replace("| не успели | y |", "| не успели |  |")
    assert any("словами" in e for e in сверить(приёмка, без_слов))
    чужая_таблица = без_строки + "\n| № | ссылка |\n|---|---|\n| Ф-01 | x |\n"
    assert any("Ф-01" in e for e in сверить(приёмка, чужая_таблица))
    assert сверить("# ЧАСТЬ 0. X\n| М-01 | a | ✓ |\n", полный)  # ноль открытых — не OK
    print("OK самопроверка: пропущенная и лишняя строка, указатель в часть III, ноль открытых, "
          "пустая причина, причина не из трёх видов, без объяснения, строка из чужой таблицы")


def main(argv: list[str]) -> int:
    if "--selftest" in argv:
        selftest()
        return 0
    приёмка = ПРИЁМКА.read_text(encoding="utf-8")
    ошибки = сверить(приёмка, СПИСОК.read_text(encoding="utf-8"))
    for e in ошибки:
        print(e)
    if not ошибки:
        print(f"OK НФ-90: все {len(открытые(приёмка))} незакрытых строк частей 0 и I названы в списке с причиной")
    return 1 if ошибки else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
