#!/usr/bin/env python3
"""Исполняемая проверка экранов и метода рисков: М-03, М-04, М-07, М-08, М-15.

Зачем она появилась 21.09.2026. Эти пять строк приёмки стояли закрытыми на разовом
`curl` от 16.09.2026, и ни одна не была привязана к `delivery/check-all.sh`. Хуже
того, сам способ доказательства не работает: `deploy/nginx/nginx.conf` отдаёт
`try_files $uri $uri/ /index.html`, то есть **код 200 на любой путь без `/api/`
впереди**. Улов: `GET /assets/net-takogo-fayla.js` отвечает 200, 424 байта,
`content-type: text/html`. Значит доказательство «путь отдал 200» прошло бы
и с удалённым фронтом, а записанный в М-08 бандл `index-DHc-qYt6.js` к 21.09
умер, и никто этого не заметил — мёртвый путь тоже отвечал 200.

Поэтому здесь ничего не проверяется кодом ответа. Проверяются тип содержимого,
размер и само содержимое: подписи экранов в бандле, число объектов в ответе
и свежесть расчёта. Имя бандла не зашито — оно читается из живого `index.html`,
потому что при каждой пересборке оно меняется.

Что каждая строка доказывает и чего не доказывает. Здесь не проверяется ни один
клик: подсветку текущего раздела, переход по клику и вид карточки смотрит человек
в браузере. Проверка отвечает на вопрос «на стенде лежит то, что мы сдаём»,
а не «экран удобен».

Три исхода, как в code/check_metrics_report.py: OK, СБОЙ (роняет прогон)
и ВНИМАНИЕ (не роняет). Третий нужен ровно одному факту — расчёт на стенде идёт
по срезу за границей выгрузки, и риски на дашборде посчитаны по пустому окну.
Это не поломка кода и требования на этот счёт у нас нет, но на защите спросят
именно про это, поэтому проверка называет оба числа вслух.

Запуск:
    BASE_URL=https://135.106.216.101 CURL_OPTS=-k python3 code/check_frontend.py
    BASE_URL=... CURL_OPTS=-k DATABASE_URL=... python3 code/check_frontend.py
    python3 code/check_frontend.py --selfcheck
"""

import argparse
import json
import os
import re
import ssl
import sys
import urllib.error
import urllib.request

ЛОГИН = "dispatcher1"

# Подписи, по которым узнаём экраны в минифицированном бандле. Берём текст,
# который виден пользователю, а не имена функций: имена минификатор переименует,
# а подпись на экране — нет. Список закрытый: каждая строка привязана к строке
# приёмки, и расти ему незачем.
ПОДПИСИ = {
    "М-07": ["/dashboard", "/map", "/log"],
    "М-08": ["/objects/", "Прогнозов по участку нет", "Почему такой риск"],
}

# Тип содержимого, которого мы ждём от ассета с таким расширением. Именно это
# отличает живой файл от SPA-заглушки: у заглушки тип text/html при коде 200.
ТИПЫ = {".js": "javascript", ".css": "css"}

# Меньше этого ассет считаем заглушкой, а не файлом: страница-заглушка стенда
# весит 424 байта, самый маленький настоящий ассет — 12 КБ.
МИН_РАЗМЕР = 2048

# `as_of` — срез данных, на котором считали; время работы самого расчёта зовётся
# `computed_at` и лежит в прогнозе (GET /api/forecasts). До 21.09.2026 оба смысла
# ходили под именем `computed_at`, и два метода отдавали под ним разные величины
# (MOS-118). Проверка требует здесь именно `as_of`: вернётся старое имя — строки
# М-04 и М-15 покраснеют «не у всех объектов есть поля».
ПОЛЯ_РИСКА = ("section_id", "probability", "risk_rank", "as_of", "is_stale")


def получить(url, заголовки=None, небезопасно=False):
    """Возвращает (код, тип содержимого, тело в байтах). Ошибку HTTP не глотает —
    отдаёт её тем же кортежем, потому что 404 здесь бывает законным ответом."""
    req = urllib.request.Request(url, headers=заголовки or {})
    ctx = ssl._create_unverified_context() if небезопасно else None
    try:
        r = urllib.request.urlopen(req, context=ctx, timeout=120)
        return r.status, r.headers.get("Content-Type", ""), r.read()
    except urllib.error.HTTPError as e:
        return e.code, e.headers.get("Content-Type", ""), e.read()


def ассеты(html):
    """Пути ассетов из index.html. Читаем из живого файла, а не из константы:
    имя бандла меняется при каждой пересборке (в М-08 записан index-DHc-qYt6.js,
    он умер 21.09.2026, и проверка по имени краснела бы на каждой выкладке)."""
    return re.findall(r'(?:src|href)="(/assets/[^"]+)"', html)


def строка_м03(корень, файлы, разделы):
    """М-03: интерфейс отдаётся браузеру как страница, ассеты — как файлы.

    корень   — (код, тип, тело) ответа на `/`
    файлы    — {путь: (код, тип, размер)} по ассетам из index.html
    разделы  — число участков в /data/sections.json или None, если он не прочёлся
    """
    код, тип, тело = корень
    беда = []
    if код != 200:
        беда.append(f"корень отдал {код}")
    if "html" not in тип:
        беда.append(f"тип корня {тип!r}, ждали html")
    if "<title>" not in тело:
        беда.append("в корне нет <title> — это не страница интерфейса")
    if not файлы:
        беда.append("index.html не ссылается ни на один ассет")
    for путь, (к, т, размер) in sorted(файлы.items()):
        ждём = ТИПЫ.get(os.path.splitext(путь)[1])
        if к != 200:
            беда.append(f"{путь} отдал {к}")
        elif ждём and ждём not in т:
            # Ровно тот случай, ради которого написана вся проверка: nginx отдал
            # SPA-заглушку вместо файла, и код у неё 200.
            беда.append(f"{путь} отдан как {т!r}, а не {ждём} — это заглушка, не файл")
        elif размер < МИН_РАЗМЕР:
            беда.append(f"{путь} весит {размер} Б — меньше {МИН_РАЗМЕР}, это не бандл")
    if разделы is None:
        беда.append("/data/sections.json не прочитался как JSON")
    elif not разделы:
        беда.append("/data/sections.json пуст — схеме нечего рисовать")
    if беда:
        return ("М-03", False, "; ".join(беда))
    размеры = ", ".join(f"{п} {р} Б" for п, (_, _, р) in sorted(файлы.items()))
    return (
        "М-03",
        True,
        f"страница с <title>, ассетов {len(файлы)} и каждый отдан своим типом "
        f"({размеры}), участков в sections.json {разделы}",
    )


def строка_подписей(номер, бандл, зачем):
    """М-07 и М-08: экраны и маршруты лежат в выложенном бандле.

    Ищем подписи, которые видит пользователь, и пути маршрутов. Пропавший экран
    иначе не отличить от живого: nginx отдаёт index.html на любой путь, поэтому
    `/map` вернёт 200 даже когда экрана карты в сборке не осталось.
    """
    нет = [п for п in ПОДПИСИ[номер] if п not in бандл]
    if нет:
        return (
            номер,
            False,
            f"в выложенном бандле нет: {', '.join(repr(п) for п in нет)} — "
            f"{зачем} в сборку не попал",
        )
    return (номер, True, f"{зачем}: все {len(ПОДПИСИ[номер])} подписи на месте")


def строка_рисков(номер, риски, участков, откуда):
    """М-04 и М-15: метод рисков отдаёт весь парк, а не пустой список.

    участков — число участков из независимого источника (sections.json или базы).
    Знаменатель обязателен: 16.09.2026 `GET /api/risks` отдавал `200 []`, и строка
    приёмки, проверенная по коду ответа, была зелёной именно на пустом парке.
    """
    if риски is None:
        return (номер, False, "ответ /api/risks не разобрался как список")
    if not риски:
        return (номер, False, "/api/risks отдал пустой список — риски показать нечем")
    беда = []
    if участков is not None and len(риски) != участков:
        беда.append(f"объектов в ответе {len(риски)}, а участков {участков} ({откуда})")
    без_полей = [п for п in ПОЛЯ_РИСКА if any(п not in р for р in риски)]
    if без_полей:
        беда.append(f"не у всех объектов есть поля: {', '.join(без_полей)}")
    ранги = [р.get("risk_rank") for р in риски]
    if len(set(ранги)) != len(ранги):
        беда.append(
            f"ранги повторяются: различных {len(set(ранги))} на {len(ранги)} объектов"
        )
    if беда:
        return (номер, False, "; ".join(беда))
    return (
        номер,
        True,
        f"{len(риски)} объектов — столько же, сколько участков ({откуда}); "
        f"у каждого {len(ПОЛЯ_РИСКА)} поля, ранги без дублей",
    )


def строка_свежести(as_of, край_данных, устаревших, всего):
    """Свежесть расчёта: два числа рядом, потому что порознь они вводят в заблуждение.

    `is_stale` в коде значит «расчёт по этому объекту не прошёл», а не «данные
    старые». 21.09.2026 на стенде `is_stale = false` у всех 3 173 участков, хотя
    выгрузка кончается 30.06.2026 и риски посчитаны по пустому окну: у всех 3 173
    прогнозов последнего прогона факторы пустые, а объяснение одно на всех —
    «датчики молчат 152 суток». Формально экран не врёт, а комиссия прочтёт
    «свежий». Требования на этот счёт у нас нет, поэтому строка не роняет прогон.
    """
    if as_of is None or край_данных is None:
        return ("свежесть", None, "не с чем сравнить: нужен DATABASE_URL")
    отставание = (as_of - край_данных).total_seconds() / 86400
    хвост = f"устаревшими помечены {устаревших} из {всего}"
    if отставание <= 0:
        return (
            "свежесть",
            True,
            f"срез расчёта {as_of:%d.%m.%Y %H:%M} внутри данных "
            f"(журнал до {край_данных:%d.%m.%Y %H:%M}), {хвост}",
        )
    return (
        "свежесть",
        None,
        f"срез расчёта {as_of:%d.%m.%Y %H:%M} на {отставание:.0f} суток "
        f"позже конца выгрузки ({край_данных:%d.%m.%Y %H:%M}) — окна признаков "
        f"пусты, и показанный риск посчитан не по данным; {хвост}",
    )


def _selfcheck():
    """Проверка проверки: каждая строка обязана краснеть на своей поломке.

    Зелёный случай здесь тоже нужен — проверка, которая краснеет всегда,
    не отличает исправное от сломанного.
    """
    живой = {
        "/assets/index-A.js": (200, "application/javascript", 45198),
        "/assets/index-A.css": (200, "text/css", 12000),
    }
    корень = (200, "text/html", "<html><title>Риски</title></html>")
    assert строка_м03(корень, живой, 3173)[1] is True

    # Заглушка вместо бандла: код 200, но тип text/html. Ради этого случая
    # проверка и написана — по коду ответа он неотличим от исправного.
    заглушка = dict(живой, **{"/assets/index-A.js": (200, "text/html", 424)})
    н, ок, т = строка_м03(корень, заглушка, 3173)
    assert ок is False and "заглушка, не файл" in т, т
    # Живой тип, но размер страницы-заглушки: ловим и это.
    мелкий = dict(живой, **{"/assets/index-A.js": (200, "application/javascript", 424)})
    assert строка_м03(корень, мелкий, 3173)[1] is False
    # Пустой sections.json — схеме нечего рисовать, а код ответа был бы 200.
    assert строка_м03(корень, живой, 0)[1] is False
    assert строка_м03(корень, {}, 3173)[1] is False

    # Подписи: пропал экран карты.
    бандл = "".join(ПОДПИСИ["М-07"] + ПОДПИСИ["М-08"])
    assert строка_подписей("М-07", бандл, "меню")[1] is True
    н, ок, т = строка_подписей("М-07", бандл.replace("/map", ""), "меню")
    assert ок is False and "'/map'" in т, т
    assert (
        строка_подписей("М-08", бандл.replace("Почему такой риск", ""), "карточка")[1]
        is False
    )

    # Риски: пустой список, недосчёт, повторяющиеся ранги, пропавшее поле.
    риски = [
        {
            "section_id": i,
            "probability": 0.5,
            "risk_rank": i,
            "as_of": "t",
            "is_stale": False,
        }
        for i in range(1, 11)
    ]
    assert строка_рисков("М-15", риски, 10, "sections.json")[1] is True
    н, ок, т = строка_рисков("М-15", [], 10, "sections.json")
    assert ок is False and "пустой список" in т, т
    н, ок, т = строка_рисков("М-15", риски, 3173, "базы")
    assert ок is False and "3173" in т, т
    повтор = [dict(р, risk_rank=1) for р in риски]
    assert строка_рисков("М-15", повтор, 10, "базы")[1] is False
    без_поля = [{k: v for k, v in р.items() if k != "as_of"} for р in риски]
    assert строка_рисков("М-15", без_поля, 10, "базы")[1] is False

    from datetime import datetime, timedelta

    край = datetime(2026, 6, 30, 23, 59)
    assert строка_свежести(край - timedelta(hours=1), край, 0, 3173)[1] is True
    н, ок, т = строка_свежести(край + timedelta(days=83), край, 0, 3173)
    assert ок is None and "83 суток позже" in т, т
    assert строка_свежести(None, край, 0, 3173)[1] is None

    print(
        "самопроверка ok: заглушка вместо бандла, мелкий ассет, пустой "
        "sections.json, пропавший экран, пустые риски, недосчёт объектов, "
        "повтор рангов, срез за границей данных"
    )


def снять(base, небезопасно):
    """Всё, что нужно строкам, одним заходом по сети."""
    заг = {"X-User-Login": ЛОГИН}
    корень_код, корень_тип, корень_тело = получить(base + "/", заг, небезопасно)
    html = корень_тело.decode("utf-8", "replace")

    файлы, бандл = {}, ""
    for путь in ассеты(html):
        к, т, тело = получить(base + путь, заг, небезопасно)
        файлы[путь] = (к, т, len(тело))
        if путь.endswith(".js"):
            бандл += тело.decode("utf-8", "replace")

    к, т, тело = получить(base + "/data/sections.json", заг, небезопасно)
    try:
        разделы = len(json.loads(тело))
    except Exception:
        разделы = None

    к, т, тело = получить(base + "/api/risks", заг, небезопасно)
    try:
        риски = json.loads(тело)
        if not isinstance(риски, list):
            риски = None
    except Exception:
        риски = None

    return (корень_код, корень_тип, html), файлы, бандл, разделы, риски


def из_базы():
    """Участков и край выгрузки. Без DATABASE_URL возвращает (None, None) —
    проверка тогда считает знаменатель по sections.json и говорит об этом."""
    dsn = os.environ.get("DATABASE_URL")
    if not dsn:
        return None, None
    import asyncio

    import asyncpg

    async def спросить():
        c = await asyncpg.connect(dsn)
        try:
            return (
                await c.fetchval("SELECT count(*) FROM ref.object_xref"),
                await c.fetchval("SELECT max(read_time) FROM smvu.reading"),
            )
        finally:
            await c.close()

    return asyncio.run(спросить())


def main():
    p = argparse.ArgumentParser(
        description="Проверка экранов: М-03, М-04, М-07, М-08, М-15"
    )
    p.add_argument("--selfcheck", action="store_true", help="только самопроверка")
    p.add_argument("--base-url", default=os.environ.get("BASE_URL"))
    а = p.parse_args()

    _selfcheck()
    if а.selfcheck:
        return 0
    if not а.base_url:
        print(
            "СБОЙ нет BASE_URL: проверять нечего. "
            "BASE_URL=https://135.106.216.101 CURL_OPTS=-k"
        )
        return 1

    # -k в CURL_OPTS — та же договорённость, что у contracts/examples/api/examples.sh:
    # у стенда самоподписанный сертификат (docs/server.md), и отдельной переменной
    # ради этого заводить не надо.
    небезопасно = "-k" in os.environ.get("CURL_OPTS", "")
    base = а.base_url.rstrip("/")

    try:
        корень, файлы, бандл, разделы, риски = снять(base, небезопасно)
        участков_в_базе, край = из_базы()
    except Exception as e:
        # Стенд не ответил — это отказ по всем строкам, а не повод промолчать.
        for n in ("М-03", "М-04", "М-07", "М-08", "М-15"):
            print(f"{n} СБОЙ проверка не выполнена: {type(e).__name__}: {e}")
        return 1

    участков, откуда = (
        (участков_в_базе, "ref.object_xref")
        if участков_в_базе
        else (разделы, "sections.json")
    )

    as_of, устаревших = None, None
    if риски:
        from datetime import datetime, timezone

        # Берём самый поздний срез, а не единственный: если расчёт по части
        # объектов не прошёл, `as_of` у них разные, и «нет одного значения»
        # молча превратилось бы в «не с чем сравнить».
        # Поле зовётся `as_of` с 21.09.2026 (MOS-118): под именем `computed_at`
        # этот же метод отдавал срез данных, а GET /api/forecasts — время расчёта.
        сроки = [
            datetime.fromisoformat(р["as_of"])
            for р in риски
            if р.get("as_of")
        ]
        # Оба конца приводим к UTC: база отдаёт timestamptz, API — строку ISO,
        # и вычитать их как есть питон откажется.
        в_utc = lambda д: (
            д.astimezone(timezone.utc).replace(tzinfo=None) if д.tzinfo else д
        )
        if сроки:
            as_of = в_utc(max(сроки))
        if край is not None:
            край = в_utc(край)
        устаревших = sum(1 for р in риски if р.get("is_stale"))

    результат = [
        строка_м03(корень, файлы, разделы),
        строка_подписей("М-07", бандл, "три раздела меню"),
        строка_подписей("М-08", бандл, "карточка объекта"),
        строка_рисков("М-04", риски, участков, откуда),
        строка_рисков("М-15", риски, участков, откуда),
        строка_свежести(as_of, край, устаревших, len(риски or ())),
    ]
    for номер, ок, текст in результат:
        исход = "ВНИМАНИЕ" if ок is None else ("OK" if ок else "СБОЙ")
        print(f"{номер} {исход} {текст}")
    return 1 if any(ок is False for _, ок, _ in результат) else 0


