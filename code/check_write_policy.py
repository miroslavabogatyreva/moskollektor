#!/usr/bin/env python3
"""Политика записи журнала не двигает метрику — исполняемая проверка (MOS-147, Q3.13).

ЗАЧЕМ. С MOS-147 журнал прогнозов пишет не каждый расчёт, а изменения плюс
безусловный «пульс». Вопрос, на который обязана ответить эта проверка, один:
не поехали ли от этого Precision и Recall. Отвечать на него рассуждением нельзя —
инженеры Aramco (arXiv:2510.26868) померили, что агрессивное сжатие ряда теряет
35 % кратковременных всплесков, а всплеск вероятности перед отказом — это ровно
то, из чего складывается наш Recall.

ПОЧЕМУ НЕ `check_metrics.py`. Он считает метрику по журналу стенда и по устройству
отказывается это делать, пока в журнале прогнозы заглушки: «прогнозы в окне сделала
заглушка модели (stub-0.1)… метрики не измеримы до модели Николая». То есть до
правки и после он ответит одинаково — ПРОПУСК, — и не устережёт ничего.

ЧТО МЕРИМ ВМЕСТО. Настоящий ряд предупреждений модели v3 из доказательств
`docs/proof/2026-09-21-metrics/our-metric/` — 166 предупреждений за 91 сутки.
Прогоняем его через политику записи и считаем метрики по прореженному ряду тем же
`evaluate_alerts()`, что и всегда. Методика одна, меняется только вход.

ПОЧЕМУ ЭТА ПРОВЕРКА СТРОЖЕ САМОГО МЕХАНИЗМА. В доказательствах лежат готовые
предупреждения, а не ряд вероятностей: сохранилась ли вероятность внутри мёртвой
зоны, по ним не видно. Поэтому фильтр здесь выбрасывает ВСЕ повторы объекта чаще
пульса — в том числе те, которые настоящая политика записала бы как «изменение».
Механизм пишет не меньше, чем этот фильтр оставляет: выдержала метрика здесь —
выдержит и там.

ТРИ СТРОКИ, И ПЕРВАЯ ЧЕСТНО ГОВОРИТ, ЧТО НИЧЕГО НЕ ДОКАЗЫВАЕТ. 28 померила
и показала: на этом ряду самый короткий повтор предупреждений одного объекта —
63,97 минуты, а пульс 60 минут, то есть фильтр не выбрасывает ни одного
предупреждения. Зелёная строка «метрика не поехала» была бы зелёной и при
сломанном фильтре, и при сломанной политике — прореживать было нечего. Поэтому
первая строка печатает, СКОЛЬКО выброшено, и при нуле выдаёт ВНИМАНИЕ, а не OK,
и называет запас: 3,97 минуты до первого выброшенного предупреждения.

Вторая строка проверяет, что замер вообще видит выброшенное: пульс на минуту
длиннее самого короткого повтора выбрасывает ровно одно предупреждение, и Recall
обязан шевельнуться (0,528 → 0,523). Не шевельнулся — первая строка зелёная
напрасно, и это СБОЙ.

Третья строка — красный случай: пульс 30 суток обязан метрику обрушить
(0,600 / 0,528 → 0,441 / 0,085, предупреждений 166 → 34).

ЧТО ИЗ ЭТОГО СЛЕДУЕТ ДЛЯ НАСТРОЙКИ. Метрика держится, пока пульс короче самого
короткого повтора предупреждений. Запас на ряду модели v3 — четыре минуты,
и это мало: на весах Николая повторы чаще часа появятся, и тогда пульс придётся
укорачивать вместе с интервалом расчёта. Эта проверка и покажет, когда.

Запуск: python3 code/check_write_policy.py
"""

import os
import sys
from datetime import timedelta

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from check_metrics_report import ДОКАЗАТЕЛЬСТВА, замер


def читать_предупреждения():
    """Ряд предупреждений модели v3 из доказательств: [(префикс, момент), ...]."""
    import csv
    from datetime import datetime

    путь = os.path.join(ДОКАЗАТЕЛЬСТВА, "alerts.csv")
    with open(путь, encoding="utf-8") as f:
        return [(r["pfx"], datetime.fromisoformat(r["t"])) for r in csv.DictReader(f)]


# Пульс политики: ref.app_setting.forecast_heartbeat_min, миграция 026.
ПУЛЬС_МИН = 60
# Заведомо губительное значение для красного случая: месяц вместо часа.
ГУБИТЕЛЬНЫЙ_ПУЛЬС_МИН = 30 * 24 * 60


def прореженные(предупреждения, пульс_мин):
    """Оставляет первое предупреждение объекта и повторы не чаще пульса.

    Порядок внутри объекта — по времени, иначе «повтор» определится от случайной
    строки файла. Объекты между собой не смешиваются: пульс у каждого свой.
    """
    последнее, итог = {}, []
    for ключ, t in sorted(предупреждения, key=lambda r: (r[0], r[1])):
        было = последнее.get(ключ)
        if было is None or t - было >= timedelta(minutes=пульс_мин):
            итог.append((ключ, t))
            последнее[ключ] = t
    return итог


def самый_короткий_повтор(предупреждения):
    """Минимальный зазор между двумя предупреждениями одного объекта, в минутах.

    Это и есть мерка для пульса: пока пульс короче этого зазора, фильтр
    не выбрасывает ни одного предупреждения, и метрика двигаться не может.
    """
    по_объектам = {}
    for ключ, t in предупреждения:
        по_объектам.setdefault(ключ, []).append(t)
    зазоры = [
        (b - a).total_seconds() / 60
        for ts in по_объектам.values()
        for a, b in zip(sorted(ts), sorted(ts)[1:])
    ]
    return min(зазоры) if зазоры else None


def проверить():
    базовый = замер()
    было = базовый["предупреждений"]
    короткий = самый_короткий_повтор(читать_предупреждения())

    # --- 1. Наш пульс. Главное здесь — назвать, СКОЛЬКО выброшено. -------------
    # Зелёная строка при нуле выброшенных не доказывает ничего: она была бы
    # зелёной и при сломанном фильтре, и при сломанной политике. Нашла 28.
    сжатый = замер(фильтр=lambda а: прореженные(а, ПУЛЬС_МИН))
    выброшено = было - сжатый["предупреждений"]
    запас = короткий - ПУЛЬС_МИН
    совпало = (
        базовый["precision"] == сжатый["precision"]
        and базовый["recall"] == сжатый["recall"]
        and базовый["tp"] == сжатый["tp"]
        and базовый["fp"] == сжатый["fp"]
    )
    if выброшено == 0:
        итог = [
            (
                "MOS-147 пульс",
                None,
                (
                    f"прорежено 0 из {было}: на этом ряду повторов чаще пульса нет, "
                    f"и метрика двигаться не могла — строка ничего не доказывает. "
                    f"Запас {запас:.2f} мин: самый короткий повтор предупреждений "
                    f"{короткий:.2f} мин при пульсе {ПУЛЬС_МИН} мин. Строка наполнится "
                    f"смыслом на ряду от обученной модели, где повторы чаще часа появятся"
                ),
            )
        ]
    else:
        итог = [
            (
                "MOS-147 пульс",
                совпало,
                (
                    f"прорежено {выброшено} из {было}, метрика "
                    f"{'не поехала' if совпало else 'ПОЕХАЛА'}: "
                    f"{базовый['precision']:.3f} / {базовый['recall']:.3f} → "
                    f"{сжатый['precision']:.3f} / {сжатый['recall']:.3f}, "
                    f"TP {базовый['tp']}→{сжатый['tp']}, FP {базовый['fp']}→{сжатый['fp']}"
                ),
            )
        ]

    # --- 2. Чувствительность: видит ли проверка выброшенное вообще -------------
    # Пульс на минуту длиннее самого короткого повтора выбрасывает ровно одно
    # предупреждение. Метрика обязана от этого шевельнуться — если не шевельнулась,
    # проверка выше смотрит не туда, и первая строка зелёная напрасно.
    чуть = int(короткий) + 1
    край = замер(фильтр=lambda а: прореженные(а, чуть))
    ушло = было - край["предупреждений"]
    увидела = ушло > 0 and (
        край["precision"] != базовый["precision"] or край["recall"] != базовый["recall"]
    )
    итог.append(
        (
            "MOS-147 чувствительность",
            увидела,
            f"пульс {чуть} мин (на минуту длиннее самого короткого повтора) выбрасывает "
            f"{ушло} предупреждение и двигает метрику: {базовый['precision']:.3f} / "
            f"{базовый['recall']:.3f} → {край['precision']:.3f} / {край['recall']:.3f} — "
            f"значит замер видит выброшенное"
            if увидела
            else f"пульс {чуть} мин выбросил {ушло} предупреждений, а метрика не изменилась "
            f"({базовый['precision']:.3f} / {базовый['recall']:.3f}) — замер не видит "
            f"выброшенного, и первая строка зелёная напрасно",
        )
    )

    # --- 3. Красный случай: проверка обязана уметь краснеть --------------------
    губительный = замер(фильтр=lambda а: прореженные(а, ГУБИТЕЛЬНЫЙ_ПУЛЬС_МИН))
    поехало = (
        губительный["precision"] != базовый["precision"]
        or губительный["recall"] != базовый["recall"]
    )
    итог.append(
        (
            "MOS-147 красный случай",
            поехало,
            f"губительный пульс в 30 суток метрику двигает, как и должен: "
            f"{базовый['precision']:.3f} / {базовый['recall']:.3f} → "
            f"{губительный['precision']:.3f} / {губительный['recall']:.3f}, "
            f"предупреждений {было} → {губительный['предупреждений']}"
            if поехало
            else (
                f"губительный пульс в 30 суток НЕ сдвинул метрику "
                f"({базовый['precision']:.3f} / {базовый['recall']:.3f}) — "
                f"значит проверка смотрит не туда; предупреждений "
                f"{было} → {губительный['предупреждений']}"
            ),
        )
    )
    return итог


def _selfcheck():
    """Фильтр проверяем на ряде, где ответ известен заранее."""
    from datetime import datetime

    # Время без часового пояса — такое же, как в файлах доказательств.
    t = datetime.fromisoformat("2026-04-01T12:00:00")

    def м(n):
        return t + timedelta(minutes=n)

    # Три предупреждения одного объекта подряд: два повтора внутри часа уходят.
    ряд = [("a", t), ("a", м(10)), ("a", м(20))]
    assert прореженные(ряд, 60) == [("a", t)], прореженные(ряд, 60)
    # Повтор ровно через пульс остаётся: граница включительная.
    assert прореженные([("a", t), ("a", м(60))], 60) == [("a", t), ("a", м(60))]
    # Разные объекты друг другу не мешают.
    assert len(прореженные([("a", t), ("b", м(1))], 60)) == 2
    # Пульс ноль не выбрасывает ничего.
    assert len(прореженные(ряд, 0)) == 3
    # Порядок внутри объекта восстанавливается: файл мог лежать вперемешку.
    вперемешку = [("a", м(20)), ("a", t), ("a", м(10))]
    assert прореженные(вперемешку, 60) == [("a", t)]
    print(
        "самопроверка ok: повторы внутри пульса, граница пульса, "
        "разные объекты, нулевой пульс, перемешанный порядок"
    )


