#!/usr/bin/env python3
"""Проверяет три строки программы минимум: М-01, М-02 и М-05.

Зачем. Эти три строки в `docs/acceptance-test.md` сегодня не проверяет ничто:
М-14…М-17 закрыты скриптом `contracts/examples/api/examples.sh`, а модель,
протокол направлений и связь канала с деревом объектов лежат вне API и до сих пор
подтверждались только текстом в документе. Текст расходится с базой молча.

Как запускать:

    DATABASE_URL=postgresql://... python3 code/check_model_and_objects.py
    python3 code/check_model_and_objects.py --self-check   # разбор отчёта, база не нужна

Скрипт по умолчанию отказывает: нет базы, нет файла, ноль строк — это СБОЙ,
а не тихий ноль. Код возврата 1, если хоть одна строка в СБОЙ. Строки РУЧНАЯ
печатаются всегда и прогон не валят: подписи под протоколом и вид экрана глазами
машина не проверит, и делать вид, что проверила, нельзя.

Зависимость одна — asyncpg, тот же, которым ходит в базу `backend/app/db.py`,
и та же переменная окружения DATABASE_URL. Своего способа подключения здесь нет.
"""

import asyncio
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Отчёт об обучении из строки М-01. Файла сегодня нет, путь назван в самой строке
# приёмки — она требует предъявить именно `docs/ml-training-report.md`.
ОТЧЁТ = ROOT / "docs" / "ml-training-report.md"

# Где искать файл весов. Расширения, а не путь, потому что ЗАФИКСИРОВАННОГО МЕСТА
# ДЛЯ ВЕСОВ В ПРОЕКТЕ НЕТ: `docs/HLD.md` разд. 6.5 говорит «модель запекается
# в образ ml при сборке», версия модели — это тег образа, и файла в дереве
# репозитория ни один документ не называет. `contracts/predict.v1.schema.json`
# знает только `model_version` и `model_sha256`, `docs/for-ml-team.md` — ничего.
# Поэтому ищем по расширениям обученных моделей и печатаем, сколько нашли.
ВЕСА_МАСКИ = ("*.pkl", "*.joblib", "*.cbm", "*.onnx", "*.ubj", "*.model", "*.lgb")
ВЕСА_МИМО = (".git", ".venv", "node_modules", "__pycache__", "dataset")

# Числа, с которыми связываем счёт из базы. Все три названы в документах проекта,
# а не придуманы здесь: 11 485 каналов в справочнике заказчика от 15.09.2026
# (`db/migrations/018_channel_object.sql`), 16 коллекторов второго уровня
# и 78 узлов третьего — строка М-05 в `docs/acceptance-test.md`.
КАНАЛОВ_В_СПРАВОЧНИКЕ = 11_485
УЗЛОВ_ВТОРОГО_УРОВНЯ = 16
УЗЛОВ_ТРЕТЬЕГО_УРОВНЯ = 78

# Единственное направление прогноза, зафиксированное протоколом 15.09.2026.
# CHECK в `db/migrations/004_events.sql` разрешает четыре значения, протокол — одно.
НАПРАВЛЕНИЕ_ПРОТОКОЛА = "sensor_failure"


def разделы_отчёта(текст):
    """Какие из пяти обязательных разделов есть в отчёте об обучении.

    Ищем по ключевым словам, а не по заголовкам: формат отчёта с Николаем
    не согласован, и требовать конкретное оглавление значит завалить строку
    на верстке, а не на содержании. Строка М-01 называет именно содержание.

    Отдельно разделены метрики на обучении и метрики на отложенной выборке:
    отчёт, где стоит одна пара чисел без указания, на какой выборке она получена,
    М-01 не закрывает — переобучение видно только по разнице этих двух пар.
    Поэтому ищем метрику и имя выборки в ОДНОЙ строке.
    """
    низ = текст.lower()
    строки = низ.splitlines()
    метрика = r"precision|recall|roc[- ]?auc|pr[- ]?auc|\bf1\b|точност|полнот"
    обучение = r"обуча|обучени|train"
    отложенная = r"отложен|holdout|провероч|тестов|валидац"
    найдено = []
    if re.search(r"алгоритм|catboost|lightgbm|xgboost|логистическ|градиентн", низ):
        найдено.append("алгоритм")
    if re.search(r"признак|feature", низ):
        найдено.append("список признаков")
    # Дат нужно минимум две: обучающее окно и проверочное — это два разных отрезка,
    # и одна дата означает, что названо только одно из них.
    даты = re.findall(r"\d{2}\.\d{2}\.\d{4}|\d{4}-\d{2}-\d{2}", низ)
    if re.search(обучение, низ) and re.search(отложенная, низ) and len(даты) >= 2:
        найдено.append("даты обучающего и проверочного окна")
    if any(re.search(метрика, с) and re.search(обучение, с) for с in строки):
        найдено.append("метрики на обучении")
    if any(re.search(метрика, с) and re.search(отложенная, с) for с in строки):
        найдено.append("метрики на отложенной выборке")
    return найдено


def файлы_весов():
    """Файлы весов модели в дереве проекта, непустые. Служебные каталоги пропускаем."""
    найдено = []
    for маска in ВЕСА_МАСКИ:
        for путь in ROOT.rglob(маска):
            if any(часть in ВЕСА_МИМО for часть in путь.parts):
                continue
            if путь.is_file() and путь.stat().st_size > 0:
                найдено.append(путь)
    return sorted(найдено)


def проверить_м01():
    """М-01: два предмета — файл весов и отчёт с пятью разделами. Отчёт без весов
    строку не закрывает, поэтому проверяем оба и печатаем оба числа."""
    веса = файлы_весов()
    сколько_весов = len(веса)

    if ОТЧЁТ.exists():
        разделы = разделы_отчёта(ОТЧЁТ.read_text(encoding="utf-8"))
    else:
        разделы = []
    нашлось = len(разделы)
    не_хватает = [
        имя
        for имя in (
            "алгоритм",
            "список признаков",
            "даты обучающего и проверочного окна",
            "метрики на обучении",
            "метрики на отложенной выборке",
        )
        if имя not in разделы
    ]

    описание_весов = (
        f"{сколько_весов} файлов весов ({', '.join(str(п.relative_to(ROOT)) for п in веса)})"
        if веса
        else "0 файлов весов по 7 расширениям во всём дереве проекта; "
        "места для них не фиксирует ни один документ — HLD разд. 6.5 запекает модель в образ ml"
    )
    состояние_отчёта = (
        f"{нашлось} разделов из 5 в docs/ml-training-report.md"
        if ОТЧЁТ.exists()
        else "docs/ml-training-report.md нет, 0 разделов из 5"
    )
    if не_хватает:
        состояние_отчёта += ", не найдено: " + "; ".join(не_хватает)

    if сколько_весов > 0 and нашлось == 5:
        return "OK", f"{описание_весов}, {состояние_отчёта}"
    return "СБОЙ", f"{описание_весов}; {состояние_отчёта}"


async def проверить_м02(conn):
    """М-02: в pred.forecast ровно одно направление, и это то, что в протоколе.
    Связываем два числа — сколько прогнозов всего и сколько из них на протокольном
    направлении. Ноль прогнозов — это СБОЙ: проверять нечего, значит не проверено."""
    строки = await conn.fetch(
        "SELECT direction, count(*) AS n FROM pred.forecast GROUP BY direction ORDER BY n DESC"
    )
    всего = sum(р["n"] for р in строки)
    if всего == 0:
        return "СБОЙ", "в pred.forecast 0 прогнозов — направление подтвердить нечем"
    свои = sum(р["n"] for р in строки if р["direction"] == НАПРАВЛЕНИЕ_ПРОТОКОЛА)
    чужие = [
        f"{р['direction']} {р['n']}"
        for р in строки
        if р["direction"] != НАПРАВЛЕНИЕ_ПРОТОКОЛА
    ]
    if чужие:
        return "СБОЙ", (
            f"{свои} из {всего} прогнозов на {НАПРАВЛЕНИЕ_ПРОТОКОЛА}, "
            f"сверх протокола: {', '.join(чужие)}"
        )
    return (
        "OK",
        f"{свои} из {всего} прогнозов, направление одно: {НАПРАВЛЕНИЕ_ПРОТОКОЛА}",
    )


async def проверить_м05(conn):
    """М-05: каждый канал справочника лежит под своим узлом дерева, и узлов столько,
    сколько названо в строке приёмки.

    Три пары чисел, а не три порога. Первая: каналов с объектом против 11 485
    из справочника заказчика. Вторая: узлов второго и третьего уровня против 16 и 78.
    Третья: сколько узлов реально занято каналами против 78 — узел, на котором
    не висит ни один канал, на экране будет пустым кружком.

    Про сирот. 018_channel_object.sql говорит, что object_id пуст у 1 142 заглушек:
    в smvu.channel 12 627 строк, а в справочнике заказчика 11 485. Поэтому ноль сирот
    здесь не ожидается, и требовать его значит требовать удаления заглушек. Число
    сирот печатаем всегда, а судим по числу каналов С объектом.
    """
    всего, с_объектом, узлов_занято = await conn.fetchrow(
        "SELECT count(*), count(object_id), count(DISTINCT object_id) FROM smvu.channel"
    )
    сирот = всего - с_объектом
    уровни = {
        р["level"]: р["n"]
        for р in await conn.fetch(
            "SELECT level, count(*) AS n FROM smvu.object_tree GROUP BY level"
        )
    }
    второй, третий = уровни.get(2, 0), уровни.get(3, 0)

    доказательство = (
        f"{с_объектом} каналов с объектом из {всего} ({сирот} сирот), "
        f"дерево: {второй} коллекторов второго уровня, {третий} узлов третьего, "
        f"каналы висят на {узлов_занято} узлах"
    )
    беды = []
    if всего == 0:
        беды.append("в smvu.channel 0 строк")
    if с_объектом != КАНАЛОВ_В_СПРАВОЧНИКЕ:
        беды.append(
            f"каналов с объектом {с_объектом}, а в справочнике {КАНАЛОВ_В_СПРАВОЧНИКЕ}"
        )
    if второй != УЗЛОВ_ВТОРОГО_УРОВНЯ:
        беды.append(
            f"коллекторов второго уровня {второй}, а М-05 называет {УЗЛОВ_ВТОРОГО_УРОВНЯ}"
        )
    if третий != УЗЛОВ_ТРЕТЬЕГО_УРОВНЯ:
        беды.append(
            f"узлов третьего уровня {третий}, а М-05 называет {УЗЛОВ_ТРЕТЬЕГО_УРОВНЯ}"
        )
    if узлов_занято != третий:
        беды.append(
            f"каналы висят на {узлов_занято} узлах из {третий} — остальные на экране пусты"
        )
    if беды:
        return "СБОЙ", доказательство + "; " + "; ".join(беды)
    return "OK", доказательство


async def прогон():
    итоги = [("М-01",) + проверить_м01()]

    url = os.environ.get("DATABASE_URL")
    if not url:
        # Отсутствие базы — это СБОЙ обеих строк, а не пропуск: непроверенное
        # требование на приёмке считается непройденным.
        итоги.append(("М-02", "СБОЙ", "DATABASE_URL не задан, базу не спросили"))
        итоги.append(("М-05", "СБОЙ", "DATABASE_URL не задан, базу не спросили"))
    else:
        import asyncpg

        try:
            conn = await asyncpg.connect(url)
        except Exception as ошибка:
            текст = f"база не отвечает: {type(ошибка).__name__}: {ошибка}"
            итоги.append(("М-02", "СБОЙ", текст))
            итоги.append(("М-05", "СБОЙ", текст))
        else:
            try:
                итоги.append(("М-02",) + await проверить_м02(conn))
                итоги.append(("М-05",) + await проверить_м05(conn))
            finally:
                await conn.close()

    итоги.append(
        (
            "М-02",
            "РУЧНАЯ",
            "человек предъявляет протокол фиксации направлений с подписями и датой РАНЬШЕ "
            "даты первого прогона: машина видит только содержимое pred.forecast и не знает, "
            "когда и кем направление было названо",
        )
    )
    итоги.append(
        (
            "М-05",
            "РУЧНАЯ",
            "человек открывает https://135.106.216.101/map и смотрит глазами, что узлы дерева "
            "нарисованы и уровень риска виден на самой схеме, а не только в списке рядом",
        )
    )

    for строка, исход, доказательство in итоги:
        print(f"{строка} {исход} {доказательство}")
    return 1 if any(исход == "СБОЙ" for _, исход, _ in итоги) else 0


def самопроверка():
    """Разбор отчёта на пяти разделах. Живая база не нужна.

    Проверяем на пяти случаях, а не на одном: полный отчёт, отчёт без одного
    раздела, отчёт с метриками без имени выборки и пустой текст. Проверка
    на одном полном отчёте зелёная даже у функции, которая всегда возвращает
    все пять имён.
    """
    полный = """
    # Отчёт об обучении
    Алгоритм: LightGBM, 200 деревьев глубиной 6.
    Признаки: 19 штук, список в contracts/features.v1.yaml.
    Обучающее окно: 01.01.2022 - 31.12.2025. Проверочное окно: 01.04.2026 - 30.06.2026.
    Метрики на обучении: Precision 0.83, Recall 0.71.
    Метрики на отложенной выборке: Precision 0.781, Recall 0.563.
    """
    assert len(разделы_отчёта(полный)) == 5, разделы_отчёта(полный)

    без_отложенной = полный.replace(
        "Метрики на отложенной выборке: Precision 0.781, Recall 0.563.", ""
    )
    assert "метрики на отложенной выборке" not in разделы_отчёта(без_отложенной)
    assert len(разделы_отчёта(без_отложенной)) == 4

    # Пара чисел без имени выборки не отвечает на вопрос «переобучилась ли модель»,
    # поэтому не засчитывается ни за один из двух разделов про метрики.
    безымянные_метрики = """
    Алгоритм: CatBoost. Признаки: 19.
    Обучающее окно 01.01.2022 - 31.12.2025, отложенная выборка 01.04.2026 - 30.06.2026.
    Precision 0.78, Recall 0.56.
    """
    найдено = разделы_отчёта(безымянные_метрики)
    assert "метрики на обучении" not in найдено, найдено
    assert "метрики на отложенной выборке" not in найдено, найдено
    assert len(найдено) == 3, найдено

    assert разделы_отчёта("") == []

    # Одна дата вместо двух не называет два окна.
    одна_дата = "Алгоритм LightGBM, признаки 19, обучение и holdout, дата 01.01.2022."
    assert "даты обучающего и проверочного окна" not in разделы_отчёта(одна_дата)

    print("самопроверка разбора отчёта: 5 случаев, все сошлись")


if __name__ == "__main__":
    if "--self-check" in sys.argv:
        самопроверка()
        sys.exit(0)
    sys.exit(asyncio.run(прогон()))
