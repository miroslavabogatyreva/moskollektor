#!/usr/bin/env python3
"""Постраничность журнала прогнозов и заявок: строка М-06.

**Зачем.** 16.09.2026 строку М-06 закрыли словами «задержки нет, замерено
performance.now()» — тогда GET /api/forecasts отдавал 12 692 прогноза.
18.09.2026 их 196 727, ответ весит 36 МБ и идёт 12 секунд (замер 76 в браузере
на стенде: 1 180 405 узлов в документе, 323 МБ кучи, страница перестаёт
слушаться). Галочка в приёмочном листе осталась от старого замера.

**Что проверяем и почему именно это.** Не время и не размер: и то и другое
зависит от сети и от того, сколько прогнозов накопилось, а порог пришлось бы
выдумывать — требования к размеру ответа у нас нет ни в постановке, ни в ТЗ.
Проверяем то, что от объёма не зависит: если клиент попросил `limit=10`,
ответ обязан содержать не больше десяти записей. Сейчас метод параметр молча
игнорирует и отдаёт всё — а молчаливое игнорирование хуже отказа: клиент
уверен, что взял страницу.

**Вторая проверка, добавлена 21.09.2026 (нашла 28).** У `GET /api/orders`
`total` считался оконной функцией `count(*) OVER()` внутри строк ответа —
за последней страницей строк нет, и `total` подставлялся нулём вместо
настоящего числа заявок. Сверяем `total` на `offset=0` с `total` далеко
за краем: числа обязаны совпасть, а не требовать жёсткой константы, которая
устареет вместе с ростом журнала — та же ошибка, что была у самой строки М-06.

Размер и время печатаются рядом как факты, без вердикта: они объясняют, почему
строка важна, но сами ничего не доказывают.

Запуск:
    BASE_URL=https://135.106.216.101 CURL_OPTS=-k python3 code/check_api_paging.py
    python3 code/check_api_paging.py --selfcheck
"""

import json
import os
import subprocess
import sys
import time

ROWS = "М-06"
ПУТЬ = "/api/forecasts"
ПУТЬ_ЗАЯВОК = "/api/orders"
ПРОСИМ = 10
ДАЛЕКО_ЗА_КРАЕМ = 10**6


def сколько_записей(тело):
    """Длина списка, как бы метод его ни завернул: голым списком или в items."""
    if isinstance(тело, list):
        return len(тело)
    if isinstance(тело, dict) and isinstance(тело.get("items"), list):
        return len(тело["items"])
    raise ValueError(f"не список и не {{items: [...]}}: ключи {list(тело)[:5]}")


def total_за_краем(тело_рядом, тело_далеко):
    """total не должен зависеть от offset: 21.09.2026 GET /api/orders брал total
    из count(*) OVER() внутри строк ответа, а за последней страницей строк нет —
    подставлялся 0 вместо настоящего числа заявок (нашла 28). Число заявок
    растёт с каждым прогоном, поэтому сверяем два total между собой,
    а не с константой."""
    total_рядом = тело_рядом.get("total") if isinstance(тело_рядом, dict) else None
    total_далеко = тело_далеко.get("total") if isinstance(тело_далеко, dict) else None
    if total_рядом is None or total_далеко is None:
        return False, f"нет поля total: рядом {total_рядом!r}, далеко {total_далеко!r}"
    if total_рядом != total_далеко:
        return False, (
            f"total за краем страницы разошёлся: рядом с началом {total_рядом}, "
            f"на offset={ДАЛЕКО_ЗА_КРАЕМ} — {total_далеко}. За последней страницей "
            f"total обязан остаться прежним, а не стать 0"
        )
    if сколько_записей(тело_далеко) != 0:
        return False, f"offset={ДАЛЕКО_ЗА_КРАЕМ} обязан вернуть пустую страницу"
    return True, f"total {total_рядом} не зависит от offset"


def вердикт(записей, просили):
    """Больше запрошенного — параметр не работает. Меньше или ровно — работает."""
    if записей > просили:
        return False, (
            f"limit={просили} не сработал: в ответе {записей} записей. "
            f"Метод отдаёт журнал целиком, постраничности нет — клиент, "
            f"попросивший страницу, получает всё и не узнаёт об этом"
        )
    return True, f"limit={просили} соблюдён: в ответе {записей} записей"


def _selfcheck():
    assert сколько_записей([1, 2, 3]) == 3
    assert сколько_записей({"total": 9, "items": [1, 2]}) == 2
    try:
        сколько_записей({"data": []})
    except ValueError:
        pass
    else:
        raise AssertionError("неизвестная форма ответа обязана быть ошибкой")
    assert вердикт(196727, 10)[0] is False
    assert вердикт(10, 10)[0] is True, "ровно столько, сколько просили, — это работает"
    assert вердикт(3, 10)[0] is True, "меньше запрошенного — тоже работает"
    assert total_за_краем({"total": 224, "items": [1]}, {"total": 224, "items": []})[0] is True
    assert total_за_краем({"total": 224, "items": [1]}, {"total": 0, "items": []})[0] is False, (
        "total упал до 0 за краем страницы — это и есть дефект orders.py от 21.09.2026"
    )
    assert total_за_краем({"total": 224, "items": [1]}, {"total": 224, "items": [1]})[0] is False, (
        "offset далеко за краем обязан вернуть пустую страницу, а не строки"
    )
    print("самопроверка ok: форма ответа, limit соблюдён и проигнорирован, total не зависит от offset")


def curl(url):
    cmd = ["curl", "-s", "-w", "\n%{size_download} %{time_total}"]
    cmd += os.environ.get("CURL_OPTS", "").split()
    cmd += ["-H", f"X-User-Login: {os.environ.get('API_LOGIN', 'admin1')}", url]
    out = subprocess.run(cmd, capture_output=True, text=True, timeout=120).stdout
    тело, _, хвост = out.rpartition("\n")
    байт, секунд = хвост.split()
    return тело, int(байт), float(секунд)


def main():
    if "--selfcheck" in sys.argv:
        _selfcheck()
        return 0
    _selfcheck()
    base = os.environ.get("BASE_URL")
    if not base:
        print(f"{ROWS} СБОЙ: не задан BASE_URL")
        return 1
    начало = time.time()
    тело, байт, секунд = curl(f"{base}{ПУТЬ}?limit={ПРОСИМ}")
    try:
        записей = сколько_записей(json.loads(тело))
    except Exception as e:
        print(f"{ROWS} СБОЙ: ответ не разобрался — {type(e).__name__}: {e}")
        return 1
    ок, текст = вердикт(записей, ПРОСИМ)
    print(f"{ROWS} {'OK' if ок else 'СБОЙ'} {текст}; "
          f"ответ {байт / 1048576:.1f} МБ за {секунд:.1f} с "
          f"(запрошено за {time.time() - начало:.1f} с)")

    тело_рядом, _, _ = curl(f"{base}{ПУТЬ_ЗАЯВОК}?limit=1&offset=0")
    тело_далеко, _, _ = curl(f"{base}{ПУТЬ_ЗАЯВОК}?offset={ДАЛЕКО_ЗА_КРАЕМ}")
    try:
        ок_края, текст_края = total_за_краем(json.loads(тело_рядом), json.loads(тело_далеко))
    except Exception as e:
        print(f"{ROWS} СБОЙ: /api/orders за краем страницы не разобрался — {type(e).__name__}: {e}")
        return 1
    print(f"{ROWS} {'OK' if ок_края else 'СБОЙ'} {ПУТЬ_ЗАЯВОК}?offset={ДАЛЕКО_ЗА_КРАЕМ}: {текст_края}")

    return 0 if (ок and ок_края) else 1


if __name__ == "__main__":
    sys.exit(main())
