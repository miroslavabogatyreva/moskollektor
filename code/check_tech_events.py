#!/usr/bin/env python3
"""Журнал технологических событий: строка Ф-89.

**Что здесь доказывается и как.** `backend/app/api/tech_events.py` берёт для
диапазона все тревоги (`is_alarm = true`) и для каждой — первую следующую
«Норму» того же канала внутри диапазона (LATERAL, с `DISTINCT` — см. пункт 3).
Проверка из трёх улик:

1. **Внутренняя арифметика метода.** `total` без фильтра обязан быть равен
   сумме `total` с `event_type=Предупреждение` и `event_type=Норма` — три
   вызова того же `СЧЁТ_SQL`, что и в самом методе (здесь его звать можно:
   проверяется алгебра метода на его же коде, а не факт правильности пар).
2. **Пары — независимо, без SQL вовсе (там, где это дёшево) и через настоящий
   `_MERGED_CTE` (там, где нужна точная граница окна).** Для горстки каналов
   читаем сырые строки (`channel_id IN (...)`, дешёвый запрос по индексу)
   и считаем пары «тревога → первая следующая Норма» простым Python-циклом
   (`найти_пары()`), который с `СЧЁТ_SQL`/LATERAL не имеет ничего общего.
   Три исхода на подобранных каналах (проверено на стенде 23.09.2026):
   пара есть (2866, 2868, 2870, 2874, 2876 — у всех 53 тревог за июнь пара
   нашлась); пары нет вовсе (канал 330610, тревога 21.06 23:24:53 — сутки
   21.06 дают ровно одну тревогу без пары, других тревог у канала в этот
   день нет); пара есть, но ЗА окном (канал 334685: все 18 тревог недели
   лежат 15.06, «Норма» одной из них — только 23.06. `_MERGED_CTE` берёт
   от/до как `date`, точную тревогу timestamp'ом не изолировать, поэтому
   сравниваем узкое окно 15–16.06 и широкое 15–24.06 — тревог поровну (18),
   а пар в широком строго больше: 15 против 16, разница — та самая пара
   за исходной границей).
3. **journal_id без повторов.** LATERAL цепляет одну «Норму» ко всем
   тревогам, для которых она первая следующая — без `DISTINCT` она едет
   в журнал по разу на каждую (нашла 5e, MOS-42: 10.06.2026 — 2735 строк
   вместо 2724 разных `journal_id`, 11 дублей).

**Почему не пересчитан агрегат за месяц независимо.** Пробовала: window-
функция и `EXISTS` вместо LATERAL — обе на порядок дороже LATERAL с
`jit=off` (тот отвечает за секунду) и обе упёрлись в 60-секундный
`statement_timeout` даже на неделе, не то что на месяце. Разбор с оркестратором
23.09.2026: агрегат 49 392/49 108 остаётся замером метода, независимая
проверка — на выборке каналов, а не на всей таблице.

**Safety.** Каждое соединение сразу ставит `SET statement_timeout` — с этой
минуты правило для любого тяжёлого запроса на общем стенде: сначала таймаут,
потом запрос (23.09.2026, после инцидента с нехваткой `/dev/shm`).

Запуск:
    DATABASE_URL=postgresql://... python3 code/check_tech_events.py
    python3 code/check_tech_events.py --selfcheck
"""

import asyncio
import os
import sys
from datetime import date

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "backend"))

try:
    import asyncpg
except ImportError:  # пакет живёт в образе бэкенда, локально его может не быть
    asyncpg = None

ROWS = "Ф-89"
ТАЙМАУТ = "30s"

ИЮНЬ_ОТ, ИЮНЬ_ДО = date(2026, 6, 1), date(2026, 7, 1)
НЕДЕЛЯ_ОТ, НЕДЕЛЯ_ДО = date(2026, 6, 9), date(2026, 6, 16)
ДЕНЬ_ОТ, ДЕНЬ_ДО = date(2026, 6, 10), date(2026, 6, 11)

# Подобраны на стенде 23.09.2026 (разбор — в докстроке модуля).
КАНАЛЫ_С_ПАРОЙ = (2866, 2868, 2870, 2874, 2876)
КАНАЛ_БЕЗ_ПАРЫ = 330610
КАНАЛ_ГРАНИЦА = 334685


def найти_пары(строки, до=None):
    """`строки` — [(read_time, is_alarm), ...], отсортированные по времени
    ОДНОГО канала. Возвращает (число тревог, число тревог с парой): парой
    считается первая следующая строка с `is_alarm=False`, если она раньше
    `до` (или без ограничения, если `до` не задано). Чистый Python, ничего
    общего с SQL/LATERAL из tech_events.py."""
    n = len(строки)
    тревог = пар = 0
    for i, (t, is_alarm) in enumerate(строки):
        if not is_alarm:
            continue
        тревог += 1
        for j in range(i + 1, n):
            t2, a2 = строки[j]
            if a2:
                continue
            if до is None or t2 < до:
                пар += 1
            break
    return тревог, пар


def _selfcheck():
    assert найти_пары([(1, True), (2, False)]) == (1, 1)
    assert найти_пары([(1, True)]) == (1, 0), "продолжения нет вовсе"
    assert найти_пары([(1, True), (5, False)], до=3) == (1, 0), "пара есть, но за окном"
    assert найти_пары([(1, True), (5, False)], до=None) == (1, 1), (
        "без окна та же пара есть"
    )
    assert найти_пары([(1, True), (2, True), (3, False)]) == (2, 2), (
        "одна Норма закрывает обе тревоги подряд"
    )
    assert найти_пары([]) == (0, 0)
    print(
        "самопроверка ok: пара есть, пары нет, пара за окном, две тревоги на одну норму"
    )


# ------------------------------------------------------------------ метод


СЧЁТ_ПОДСТРОКА = None  # заполняется при импорте — см. _импортировать_метод()
CTE_ПОДСТРОКА = None


def _импортировать_метод():
    global СЧЁТ_ПОДСТРОКА, CTE_ПОДСТРОКА
    from app.api.tech_events import _MERGED_CTE, СЧЁТ_SQL

    СЧЁТ_ПОДСТРОКА = СЧЁТ_SQL
    CTE_ПОДСТРОКА = _MERGED_CTE


async def _total(conn, от, до, event_type=None):
    # 7-й параметр — видимые_участки; None здесь всегда "видит весь парк",
    # проверка идёт без роли и без области видимости.
    return await conn.fetchval(
        СЧЁТ_ПОДСТРОКА, от, до, None, event_type, None, None, None
    )


async def _метод_тревог_и_пар_по_каналам(conn, каналы, от, до):
    """Тот же `_MERGED_CTE`, что в tech_events.py (импортирован, не переписан),
    только своя внешняя проекция — она добавляет `channel_id`, которого нет
    в готовых СЧЁТ_SQL/ВЫБОРКА_SQL. Проверяет саму пары-логику метода,
    а не алгебру количества сверху неё."""
    sql = f"""{CTE_ПОДСТРОКА}
    SELECT count(*) FILTER (WHERE is_alarm) AS тревог,
           count(*) FILTER (WHERE NOT is_alarm) AS пар
      FROM merged
     WHERE channel_id = ANY($3::int[])
    """
    row = await conn.fetchrow(sql, от, до, list(каналы))
    return row["тревог"], row["пар"]


async def проверить_без_дублей(conn, от, до):
    """journal_id в merged не должен повторяться — LATERAL цепляет одну «Норму»
    ко всем тревогам, у которых она первая следующая, и без DISTINCT она едет
    в журнал по разу на каждую (нашла 5e, MOS-42: 10.06.2026 — 2735 строк-Норм
    вместо 2724 разных journal_id, 11 дублей)."""
    sql = f"""{CTE_ПОДСТРОКА}
    SELECT count(*) AS всего, count(DISTINCT journal_id) AS разных FROM merged
    """
    row = await conn.fetchrow(sql, от, до)
    if row["всего"] != row["разных"]:
        return (
            False,
            f"{row['всего']} строк, {row['разных']} разных journal_id — {row['всего'] - row['разных']} дублей",
        )
    return True, f"{row['всего']} строк, все journal_id разные"


async def проверить_арифметику(conn, от, до):
    """total = Предупреждение + Норма, на том же СЧЁТ_SQL, что у метода."""
    всего = await _total(conn, от, до)
    тревог = await _total(conn, от, до, "Предупреждение")
    норм = await _total(conn, от, до, "Норма")
    if тревог + норм != всего:
        return False, f"{тревог} + {норм} != {всего}"
    return True, f"{тревог} + {норм} = {всего}"


async def _сырые_строки(conn, каналы, от, до):
    rows = await conn.fetch(
        """
        SELECT channel_id, read_time, is_alarm FROM smvu.reading
         WHERE channel_id = ANY($1::int[]) AND read_time >= $2 AND read_time < $3
         ORDER BY channel_id, read_time
        """,
        list(каналы),
        от,
        до,
    )
    по_каналу = {}
    for r in rows:
        по_каналу.setdefault(r["channel_id"], []).append(
            (r["read_time"], r["is_alarm"])
        )
    return по_каналу


async def проверить_пары_независимо(conn):
    """Три исхода — Python-цикл против метода на конкретных, заранее найденных
    строках, а не агрегатом по каналу: у наших каналов бывает не одна тревога
    за период, и сравнение по каналу целиком путает разные эпизоды."""
    ошибки = []

    # 1. Пара есть — агрегат по пяти каналам, у которых это единственный сюжет
    # (проверено вручную 23.09.2026: 53 тревоги, у всех есть пара).
    по_каналу = await _сырые_строки(conn, КАНАЛЫ_С_ПАРОЙ, ИЮНЬ_ОТ, ИЮНЬ_ДО)
    py_тревог = py_пар = 0
    for ch in КАНАЛЫ_С_ПАРОЙ:
        т, п = найти_пары(по_каналу.get(ch, []))
        py_тревог += т
        py_пар += п
    sql_тревог, sql_пар = await _метод_тревог_и_пар_по_каналам(
        conn, КАНАЛЫ_С_ПАРОЙ, ИЮНЬ_ОТ, ИЮНЬ_ДО
    )
    if py_тревог != py_пар:
        ошибки.append(
            f"пять каналов с парой: python нашёл {py_тревог - py_пар} тревог без пары, ждали 0"
        )
    if (py_тревог, py_пар) != (sql_тревог, sql_пар):
        ошибки.append(
            f"пять каналов с парой: python {py_тревог}/{py_пар}, метод {sql_тревог}/{sql_пар}"
        )

    # 2. Пары нет вовсе — конкретная тревога канала 330610, 21.06 23:24:53
    # (найдена LEFT JOIN LATERAL без верхней границы, т.е. до конца архива).
    строки_330610 = (
        await _сырые_строки(conn, (КАНАЛ_БЕЗ_ПАРЫ,), ИЮНЬ_ОТ, ИЮНЬ_ДО)
    ).get(КАНАЛ_БЕЗ_ПАРЫ, [])
    момент_без_пары = None
    for t, is_alarm in строки_330610:
        # asyncpg отдаёт timestamptz в UTC: 23:24:53+03 московского — это
        # 20:24:53 UTC, сравниваем по UTC, а не по строке московского времени.
        if is_alarm and t.strftime("%Y-%m-%d %H:%M:%S") == "2026-06-21 20:24:53":
            момент_без_пары = t
            break
    if момент_без_пары is None:
        ошибки.append(
            f"канал {КАНАЛ_БЕЗ_ПАРЫ}: тревога 21.06 23:24:53 не найдена в выборке июня"
        )
    else:
        py_есть_после = any(
            t > момент_без_пары and not is_alarm for t, is_alarm in строки_330610
        )
        if py_есть_после:
            ошибки.append(
                f"канал {КАНАЛ_БЕЗ_ПАРЫ}: python нашёл Норму после 21.06 23:24:53 в июне, а её быть не должно"
            )
        # _MERGED_CTE теперь берёт от/до как date (AT TIME ZONE 'Europe/Moscow'
        # считает сервер, а не точный момент) — точную тревогу timestamp'ом
        # не изолировать. Берём сутки 21.06: у канала есть ещё одна тревога
        # 19.06, но она раньше и в этот день не попадёт — тревог=1 ровно.
        sql_тревог, sql_пар = await _метод_тревог_и_пар_по_каналам(
            conn,
            (КАНАЛ_БЕЗ_ПАРЫ,),
            date(2026, 6, 21),
            ИЮНЬ_ДО,
        )
        if sql_тревог != 1:
            ошибки.append(
                f"канал {КАНАЛ_БЕЗ_ПАРЫ}: ждали ровно одну тревогу 21.06, метод дал {sql_тревог}"
            )
        elif sql_пар != 0:
            ошибки.append(
                f"канал {КАНАЛ_БЕЗ_ПАРЫ}: метод нашёл пару у тревоги 21.06 23:24:53, а не должен"
            )

    # 3. Пара есть, но за окном — тревога канала 334685, 15.06 14:56:55;
    # Норма нашлась только 23.06 — вне недели 09-15.06.
    строки_334685_расширенно = (
        await _сырые_строки(conn, (КАНАЛ_ГРАНИЦА,), НЕДЕЛЯ_ОТ, date(2026, 7, 1))
    ).get(КАНАЛ_ГРАНИЦА, [])
    момент_границы = None
    for t, is_alarm in строки_334685_расширенно:
        # 14:56:55 московского — 11:56:55 UTC, тем же приёмом, что выше.
        if is_alarm and t.strftime("%Y-%m-%d %H:%M:%S") == "2026-06-15 11:56:55":
            момент_границы = t
            break
    if момент_границы is None:
        ошибки.append(
            f"канал {КАНАЛ_ГРАНИЦА}: тревога 15.06 14:56:55 не найдена в выборке"
        )
    else:
        граница_недели_utc = await conn.fetchval(
            "SELECT $1::date::timestamptz", НЕДЕЛЯ_ДО
        )
        после_недели = [
            t for t, a in строки_334685_расширенно if t > момент_границы and not a
        ]
        внутри_недели = [t for t in после_недели if t < граница_недели_utc]
        if внутри_недели:
            ошибки.append(
                f"канал {КАНАЛ_ГРАНИЦА}: python нашёл Норму внутри недели — {внутри_недели}, а её быть не должно"
            )
        if not после_недели:
            ошибки.append(
                f"канал {КАНАЛ_ГРАНИЦА}: python не нашёл Норму вовсе даже без границы недели"
            )
        # _MERGED_CTE берёт от/до как date — точную тревогу timestamp'ом не
        # изолировать (все 18 тревог канала за неделю лежат внутри 15.06).
        # Проверяем иначе: узкое окно (сутки 15.06) против того же окна,
        # расширенного за пределы недели — тревог одно и то же (18, других
        # тревог у канала между 16.06 и 24.06 нет), а пар в расширенном
        # обязано стать больше — это и есть пара, найденная за исходным
        # окном (проверено на стенде 23.09.2026: 15/18 против 16/18).
        узкое_тревог, узкое_пар = await _метод_тревог_и_пар_по_каналам(
            conn,
            (КАНАЛ_ГРАНИЦА,),
            date(2026, 6, 15),
            НЕДЕЛЯ_ДО,
        )
        широкое_тревог, широкое_пар = await _метод_тревог_и_пар_по_каналам(
            conn,
            (КАНАЛ_ГРАНИЦА,),
            date(2026, 6, 15),
            date(2026, 6, 24),
        )
        if узкое_тревог != широкое_тревог:
            ошибки.append(
                f"канал {КАНАЛ_ГРАНИЦА}: тревог должно быть поровну в узком и широком окне, "
                f"получили {узкое_тревог} и {широкое_тревог}"
            )
        elif широкое_пар <= узкое_пар:
            ошибки.append(
                f"канал {КАНАЛ_ГРАНИЦА}: расширение окна за 16.06 обязано найти минимум одну "
                f"новую пару, узкое дало {узкое_пар}, широкое {широкое_пар}"
            )

    if ошибки:
        return False, "; ".join(ошибки)
    return True, (
        f"пара есть — {len(КАНАЛЫ_С_ПАРОЙ)} каналов, {py_пар} тревог с парой; "
        f"пары нет вовсе — канал {КАНАЛ_БЕЗ_ПАРЫ}, тревога 21.06 23:24:53; "
        f"пара за окном — канал {КАНАЛ_ГРАНИЦА}, тревога 15.06 14:56:55, Норма только 23.06"
    )


async def run(dsn):
    conn = await asyncpg.connect(dsn)
    try:
        await conn.execute(f"SET statement_timeout = '{ТАЙМАУТ}'")
        await conn.execute("SET jit = off")
        _импортировать_метод()
        ok1, text1 = await проверить_арифметику(conn, ИЮНЬ_ОТ, ИЮНЬ_ДО)
        ok2, text2 = await проверить_пары_независимо(conn)
        ok3, text3 = await проверить_без_дублей(conn, ДЕНЬ_ОТ, ДЕНЬ_ДО)
        return [
            ("арифметика метода", ok1, text1),
            ("пары независимо", ok2, text2),
            ("journal_id без повторов", ok3, text3),
        ]
    finally:
        await conn.close()


def main(argv):
    _selfcheck()
    if "--selfcheck" in argv:
        return 0
    if asyncpg is None:
        print(f"{ROWS} СБОЙ: не установлен asyncpg")
        return 1
    dsn = os.environ.get("DATABASE_URL")
    if not dsn:
        print(f"{ROWS} СБОЙ: не задана переменная DATABASE_URL")
        return 1
    try:
        results = asyncio.run(run(dsn))
    except (OSError, asyncio.TimeoutError) as e:
        print(f"{ROWS} СБОЙ: нет связи с базой — {type(e).__name__}: {e}")
        return 1
    ok = True
    for name, passed, text in results:
        print(f"{ROWS} {'OK' if passed else 'СБОЙ'} {name}: {text}")
        ok = ok and passed
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
