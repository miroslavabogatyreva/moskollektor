#!/usr/bin/env python3
"""Разметка отказа датчика по сырому временному ряду.

Правило вытащено из датасета хакатона En+ («Задача 1»): там разметка сделана
руками — из сырого листа убрали 523 строки из 37 339 (1,4 %), и я сравнил
сырой лист с обработанным, чтобы понять, по какому признаку их убирали.
Получилось два признака:

  1. значение вышло за физический диапазон датчика
     (в датасете чистые данные лежат в 534,5…621,9 °C, а в выброшенных
      встречаются 0, -30, 694,5 и совсем мусор вида -3,3e31 и 9,75e10);
  2. слишком быстрый скачок между соседними отсчётами
     (медиана максимального скачка за 10 мин: 0,8 °C на хороших строках
      и 3,3 °C на выброшенных, 95-й перцентиль — 4,3 против 485,2).

Для СМВУ то же самое: диапазон датчика + скорость изменения показания.
Третий признак из датасета я правилом не ловлю — «залипание» и медленный
уход в сторону (325 выброшенных строк остались внутри диапазона и без
скачка, их убрали целыми кусками по 4-5 часов). Это уже задача модели.

Я прогнал это правило по тому самому датасету и сравнил с ручной разметкой
(523 выброшенные строки — эталон). Получилось:
    только диапазон 534,5…621,9          precision 1,00   recall 0,38
    диапазон + скачок > 20 °C/10 мин     precision 0,75   recall 0,47
    диапазон + скачок > 10 °C/10 мин     precision 0,41   recall 0,61
    диапазон + скачок >  5 °C/10 мин     precision 0,21   recall 0,69
То есть голые пороги дают примерно половину ручной разметки. Целевые метрики
Москоллектора (P > 0,7, R > 0,5) правилом не берутся — порог закрывает
precision, а recall придётся добирать моделью.
"""

def label(series, lo, hi, max_step, freeze_n=None):
    """series: [(t, value), ...] по одному датчику, отсортировано по времени.

    Возвращает список меток той же длины:
      0 — норма
      1 — вне диапазона
      2 — скачок больше max_step за один отсчёт
      3 — залипание: freeze_n отсчётов подряд ровно одно и то же значение
      4 — значение не число: измерения в этой записи нет вовсе

    ПРО МЕТКУ 4, она появилась после первой настоящей выгрузки. Значение датчика
    приходит текстом и на одном и том же канале смешивает числа с состояниями:
    «28», «0.01», но и «Норма», «Не замкнут», «Обесточен». Раньше функция на таком
    значении падала с TypeError на первой же строке реальных данных. Заманчиво было
    обернуть сравнение в try и считать нечисло выбросом — но это худший из возможных
    вариантов: «Норма» получила бы метку «вне диапазона», и на числовых каналах
    за 2025 год так родилось бы 235 002 ложных отказа из 46 002 155 записей.
    Поэтому «не число» — отдельная метка, и аномалией она не считается.

    ЭТО ПРАВИЛО ЗАПУСКАТЬ ТОЛЬКО НА ЧИСЛОВЫХ КАНАЛАХ. Признак числового канала лежит
    в справочнике типов: smvu.sensor_kind.is_numeric. Из девятнадцати типов ряд чисел
    пишут два — «Датчик температуры» и «Газовый датчик». Остальные семнадцать отдают
    только состояния, и метка 4 будет у них в каждой записи. «Тепловой датчик»
    вопреки названию в их числе: это пороговый пожарный извещатель, а не термометр.

    ПОРОГИ lo/hi ЗДЕСЬ ЧУЖИЕ. Значения из примера (534,5…621,9) взяты из датасета
    котельной ТЭЦ En+ и к коллекторам Москвы отношения не имеют. У наших двух числовых
    типов диапазоны свои и разные: температура в камере это единицы и десятки градусов,
    а газовый датчик отдаёт 0,00…0,37 в единицах, которые заказчик пока не назвал.
    Пока порогов от заказчика нет, запускать правило на продуктивных данных нельзя:
    оно выдаст осмысленно выглядящий мусор, а это хуже отказа считать.
    """
    out = [0] * len(series)
    prev = None
    for i, (_, v) in enumerate(series):
        if not isinstance(v, (int, float)) or isinstance(v, bool):
            out[i] = 4                       # состояние, а не измерение
        elif v is None or v < lo or v > hi:
            out[i] = 1
        elif prev is not None and abs(v - prev) > max_step:
            out[i] = 2
        # За базу сравнения берём только настоящее измерение в диапазоне.
        prev = v if out[i] in (0, 2) else prev
    if freeze_n:
        run = 1
        for i in range(1, len(series)):
            # Нечисловые значения в счёт залипания не идут: пять «Норма» подряд —
            # это нормальная работа охранного канала, а не замерший датчик.
            if out[i] == 4 or out[i - 1] == 4:
                run = 1
                continue
            run = run + 1 if series[i][1] == series[i - 1][1] else 1
            if run >= freeze_n:
                for j in range(i - run + 1, i + 1):
                    if out[j] == 0:
                        out[j] = 3
    return out


if __name__ == "__main__":
    # Числа взяты из реального датасета: чистый коридор 534,5…621,9 °C,
    # порог скачка 5 °C за 10 минут (95-й перцентиль хороших строк — 4,3).
    t = list(range(12))
    vals = [560, 561, 560, 0.0, 562, 563, 700, 564, 564, 564, 564, 565]
    s = list(zip(t, vals))
    got = label(s, lo=534.5, hi=621.9, max_step=5.0, freeze_n=4)
    assert got[3] == 1, got          # 0.0 — вне диапазона
    assert got[6] == 1, got          # 700 — вне диапазона
    assert got[2] == 0, got          # 560 после 561 — нормальный шум
    assert got[8:12] == [3, 3, 3, 0], got  # четыре 564 подряд — залипание
    # скачок внутри диапазона
    got2 = label(list(zip(t[:4], [560, 561, 590, 591])), 534.5, 621.9, 5.0)
    assert got2 == [0, 0, 2, 0], got2

    # Текстовые значения вперемешку с числами — так выглядит реальный канал.
    # Главное: «Норма» получает метку 4, а НЕ 1. Иначе на числовых каналах
    # за 2025 год родилось бы 235 002 ложных отказа.
    mixed = [(1, 560.0), (2, "Норма"), (3, 561.0), (4, "Не замкнут"), (5, 700.0)]
    got3 = label(mixed, lo=534.5, hi=621.9, max_step=5.0)
    assert got3 == [0, 4, 0, 4, 1], got3
    assert got3[1] != 1 and got3[3] != 1, "состояние не должно считаться выбросом"

    # Нечисло не сбивает базу сравнения: скачок считается от последнего измерения.
    jump = [(1, 560.0), (2, "Норма"), (3, 600.0)]
    assert label(jump, lo=534.5, hi=621.9, max_step=5.0) == [0, 4, 2], \
        "скачок 560 -> 600 обязан найтись через текстовую запись"

    # Повторяющиеся состояния — не залипание датчика.
    states = [(i, "Норма") for i in range(6)]
    assert label(states, lo=0.0, hi=1.0, max_step=1.0, freeze_n=3) == [4] * 6

    # Канал целиком нечисловой: ни одной ложной аномалии.
    assert set(label([(i, "Обнаружено движение") for i in range(4)],
                     lo=0.0, hi=1.0, max_step=1.0)) == {4}
    print("ok")
