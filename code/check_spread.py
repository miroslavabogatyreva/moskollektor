#!/usr/bin/env python3
"""Разнос вероятности объекта по участкам: проверка MOS-150 (Q3.16).

Модель Николая v3 даёт одно число НА ОБЪЕКТ, объектов 16, а экраны показывают
3 173 участка. Разнос делит вероятность объекта между его участками весом из
истории отказов — представление `pred.section_weight` (миграция 028). Скрипт
спрашивает базу и печатает шесть строк «В-NN OK …» или «В-NN СБОЙ …».

Каждая строка называет знаменатель. «Сумма долей равна 1,000» без числа объектов
ничего не значит: на пустой выборке это утверждение верно и бессмысленно.

Код возврата: 1, если хоть одна строка красная; 0 только когда все шесть зелёные.

ЧЕГО ЭТОТ СКРИПТ НЕ ДОКАЗЫВАЕТ. Он проверяет ВЕС и арифметику разноса, а не то,
что разнос включён на стенде. Выключатель `forecast_spread_enabled` по умолчанию
стоит в 0, и это правильно: включение меняет шкалу вероятностей на два порядка
и обязано ехать вместе с новыми порогами автозаявок (раздел «пороги» в конце
вывода). Строка В-05 считает разнос сама, в памяти, не заглядывая в то, что
записано в pred.forecast_current. А вот строка В-06 смотрит именно туда: она
проверяет сторож — то, что разнос не тронет прогноз, который модель разнесла
сама по участкам. На синтетике это место не стережётся в принципе, потому что
в ней числа внутри объекта одинаковы по построению.

Подключение то же, что у бэкенда (backend/app/db.py): asyncpg и DATABASE_URL.

Запуск:  DATABASE_URL=postgresql://... python3 code/check_spread.py
Самопроверка без базы (арифметика разноса):  python3 code/check_spread.py --demo
"""

