def check_v05(d):
    """Разнос на живых весах: вероятность объекта сохраняется до 1e-9."""
    по_объекту = {}
    for r in d["вес"]:
        по_объекту.setdefault(r["object_id"], []).append(float(r["weight"]))
    if not по_объекту:
        return False, "В-05", "весов нет, разносить нечего"
    # Вероятность объекта берём разную, чтобы ошибка не спряталась за круглым числом.
    худшее, где = -1.0, None
    for i, (oid, веса) in enumerate(sorted(по_объекту.items())):
        p = 0.05 + 0.9 * (i + 1) / (len(по_объекту) + 1)
        отклонение = abs(sum(разнести_по_весу(p, веса)) - p)
        # Строгое > оставляло бы «где» пустым, когда все отклонения нулевые,
        # и зелёная строка печатала бы «на объекте None» — вид сбоя на успехе.
        if отклонение >= худшее:
            худшее, где = отклонение, oid
    ок = худшее < 1e-9
    как = (
        f"проверено {len(по_объекту)} объектов, "
        f"{sum(len(v) for v in по_объекту.values())} участков, "
        f"наибольшее расхождение {худшее:.2e} на объекте {где}"
    )
    return (
        ок,
        "В-05",
        (
            f"сумма разнесённого равна вероятности объекта: {как}"
            if ок
            else f"вероятность объекта не сохранилась: {как}"
        ),
    )


def check_v06(d):
    """Сторож: разносить можно только то, что модель НЕ разнесла сама.

    Проверка смотрит живой прогноз, а не выдуманные числа. Модель, считающая
    по объекту, отдаёт его участкам одно значение; заглушка считает по участку
    и отдаёт разные. Разнести второе значит стереть предсказание средним —
    поэтому publish.разнести() такой объект пропускает, и здесь видно, скольких
    объектов это сегодня касается.
    """
    живые = d["живые"]
    if not живые:
        return False, "В-06", ("pred.forecast_current пуст или не сходится с весами: "
                               "сторожу нечего показать")
    сам = [r for r in живые if r["участков"] > 1 and float(r["размах"]) > 1e-9]
    включён = bool(int(d["настройки"].get("forecast_spread_enabled", 0)))
    самый = max(живые, key=lambda r: r["различных"])
    как = (f"{len(сам)} из {len(живые)} объектов модель разнесла сама "
           f"(наибольший — {самый['name']}: {самый['различных']} различных "
           f"вероятностей на {самый['участков']} участках), "
           f"разнос их пропустит и прогноз не тронет")
    # Включённый разнос, который не разносит ни одного объекта, — это настройка,
    # обещающая работу, которой нет. Молчать об этом нельзя.
    if включён and len(сам) == len(живые):
        return False, "В-06", (f"разнос включён, но пропустит ВСЕ объекты: {как}. "
                               f"Либо модель считает по участку и разнос не нужен, "
                               f"либо выключатель поставлен ошибочно")
    состояние = "разнос включён" if включён else "разнос выключен (forecast_spread_enabled=0)"
    return True, "В-06", f"{состояние}; {как}"


