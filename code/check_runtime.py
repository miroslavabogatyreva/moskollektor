async def check_расписание(conn, окно_мин=24 * 60):
    """Планировщик не пропустил ни одного часового слота за последние сутки.

    **Чего не видит ни одна другая проверка.** Пропущенный расчёт не оставляет
    следа нигде: строки в `pred.run` нет, журнал контейнера живёт до пересоздания,
    а `check_m21` смотрит три последних прогона и на разрывы между ними не глядит.
    21.09.2026 `moskollektor-worker-1` пересоздали при выкладке, слот потерялся,
    и заметила это проверяющая сессия — тем, что ждала прогноза к 10:37 и не
    дождалась. Строка НФ-41 закрывает «прерванный расчёт не оставляет частично
    записанных данных», а «расчёт не запустился вовсе» не закрывает никто.

    Меряем две вещи, и вторая важнее первой. Наибольший разрыв между соседними
    стартами показывает пропуски в прошлом. Возраст последнего прогона показывает,
    работает ли планировщик прямо сейчас: остановись он час назад — разрывов
    в журнале ещё нет, а расчёта уже нет тоже.
    """
    # Окно наблюдения — параметр, а не константа внутри: иначе ветку «служба
    # стоит дольше окна» нечем предъявить, пока стенд жив. С окном в 30 минут
    # та же ветка проверяется на живых данных за секунду. Окно называется в тексте:
    # при нестандартном окне слово «сутки» в сообщении было бы неправдой.
    if (беда := запас_ослеплён(ЗАПАС_МИН, ИНТЕРВАЛ_МИН)):
        return False, беда
    окно = "сутки" if окно_мин == 24 * 60 else f"{окно_мин} мин"
    строки = await conn.fetch(РАЗРЫВЫ, окно_мин)
    норма_мин = ИНТЕРВАЛ_МИН + ЗАПАС_МИН

    возраст = None
    if строки:
        возраст = await conn.fetchval(
            "SELECT extract(epoch FROM now() - $1) / 60", строки[-1]["started_at"]
        )

    if len(строки) < 2:
        # Три разные беды, и они дают разный исход. Свежий стенд — ПРОПУСК:
        # красить его СБОЕМ нельзя, заказчик распакует пакет и увидит красное
        # на пустом журнале. Служба, стоящая дольше суток, — СБОЙ: окно пустое,
        # и без этой ветки самая тяжёлая поломка дала бы самый спокойный исход
        # (нашла проверяющая сессия 21.09.2026). Различает их один вопрос:
        # есть ли полные прогоны в журнале ВООБЩЕ, без ограничения по окну.
        был = await conn.fetchrow(
            """SELECT run_id, started_at,
                      extract(epoch FROM now() - started_at) / 3600 AS часов
                 FROM pred.run
                WHERE objects_total = (SELECT count(*) FROM ref.object_xref)
                ORDER BY started_at DESC LIMIT 1"""
        )
        неудачных = await conn.fetchval(
            "SELECT count(*) FROM pred.run WHERE status <> 'done' "
            "AND started_at > now() - make_interval(mins => $1)",
            окно_мин,
        )
        хвост = (f"; при этом в pred.run за сутки {неудачных} прогонов со "
                 f"status <> 'done' — значит расчёт запускается и падает"
                 if неудачных else "")
        if был is not None and был["часов"] > окно_мин / 60:
            return False, (
                f"полных прогонов за {окно} нет вовсе, последний {был['run_id']} "
                f"стартовал {был['часов']:.1f} ч назад при интервале "
                f"{ИНТЕРВАЛ_МИН} мин: расчёт стоит дольше окна наблюдения{хвост}"
            )
        сколько = "ни одного полного прогона" if not строки else "один полный прогон"
        return None, (
            f"за последние {окно} {сколько}: разрывы измерить не на чем, "
            f"дайте службе проработать хотя бы {ИНТЕРВАЛ_МИН * 2} минут{хвост}"
        )

    разрывы = промежутки([(с["run_id"], с["started_at"]) for с in строки])
    худший_мин, слева, справа = max(разрывы)
    пропусков = sum(1 for м, _, _ in разрывы if м > норма_мин)

    if возраст > норма_мин:
        # Оговорка про «не считает» не лишняя: запрос отбирает прогоны по
        # objects_total и не смотрит status, а у неудачного прогона objects_total
        # бывает NULL — такой прогон в ряд не попадёт. Значит планировщик, который
        # исправно стреляет и каждый раз падает, даст ту же красную строку, что
        # и остановившийся, и диагноз уведёт на шаг в сторону. Разные беды чинят
        # разным, поэтому строка называет обе. Нашла это проверяющая сессия,
        # замерив, что неудачных прогонов внутри фильтра сейчас ноль.
        return False, (
            f"последний полный прогон {строки[-1]['run_id']} стартовал "
            f"{возраст:.0f} мин назад при интервале {ИНТЕРВАЛ_МИН} мин "
            f"и запасе {ЗАПАС_МИН} мин: планировщик либо не запускается, либо "
            f"запускается и падает — проверьте в pred.run строки со status <> 'done'"
        )
    if пропусков:
        return False, (
            f"пропущено слотов за {окно}: {пропусков} из {len(разрывы)} промежутков; "
            f"худший разрыв {худший_мин:.0f} мин между прогонами {слева} и {справа} "
            f"при интервале {ИНТЕРВАЛ_МИН} мин"
        )
    return True, (
        f"{len(строки)} полных прогонов за {окно} без пропусков, худший разрыв "
        f"{худший_мин:.0f} мин при интервале {ИНТЕРВАЛ_МИН} мин; последний прогон "
        f"{строки[-1]['run_id']} стартовал {возраст:.0f} мин назад"
    )


