#!/usr/bin/env python3
"""Приёмка времени расчёта: строки М-21, НФ-72 и НФ-91.

М-21 — время формирования прогноза меньше 5 минут на продуктивном объёме.
НФ-72 — инференс по одному объекту меньше 5 минут.
НФ-91 — плановый расчёт не пропускает слоты. Строка наша, не из ТЗ: заказчик
такого требования не предъявлял, но пропущенный расчёт не виден ничем, а НФ-41
проверяет только то, что прерванный расчёт не оставил мусора.

**Что этот скрипт доказывает и чего не доказывает.** Он не запускает расчёт,
а читает журнал прогонов `pred.run` — тот самый, который расчёт заполняет сам
шестью колонками `ms_*`. Это доказательство «расчёт укладывался», а не «расчёт
уложится прямо сейчас»: чтобы получить второе, надо запустить прогон, а прогон
пишет в базу прогнозы и заявки, и приёмочная проверка такого делать не должна.
Поэтому скрипт требует, чтобы улов был свежим и настоящим: прогоны должны быть
по ВСЕМУ парку, а не по обрезанной выборке, и у них должны быть заполнены все
шесть стадий. Прогон с пустыми `ms_*` — это не быстрый прогон, а недомеренный.

Как получить улов, если скрипт красный:
    docker exec moskollektor-api-1 python -m app.worker.run --as-of 2026-06-30T23:59:59+03:00
    docker exec moskollektor-api-1 python -m app.worker.run --as-of ... --limit 1

Проверка по умолчанию отказывает. Нет DATABASE_URL, нет таблицы, ноль прогонов —
всё это СБОЙ, а не молчаливый ноль.

Запуск:  DATABASE_URL=postgresql://... python3 code/check_runtime.py
Самопроверка без базы:  python3 code/check_runtime.py --demo
"""

import asyncio
import os
import sys
from datetime import datetime, timedelta, timezone
from itertools import pairwise

try:
    import asyncpg
except ImportError:  # пакет живёт в образе бэкенда, локально его может не быть
    asyncpg = None

ROWS = ("М-21", "НФ-72", "НФ-91", "свёртка")

# Постановка: «время формирования прогноза менее 5 минут». Пять минут — это 300
# секунд, и меньше значит строго меньше.
НОРМАТИВ_С = 300.0

# Сколько прогонов по полному парку должно лежать в журнале. Три, а не один:
# один прогон не отличает «укладывается» от «повезло». Число из задачи Q3.5.
ПРОГОНОВ_НАДО = 3

# Планировщик считает полный расчёт раз в SCHEDULER_INTERVAL_MIN минут
# (backend/app/worker/scheduler.py). Значение читаем из окружения тем же способом,
# что и сам планировщик: захардкоженные 60 разошлись бы с .env стенда молча.
ИНТЕРВАЛ_МИН = int(os.environ.get("SCHEDULER_INTERVAL_MIN", "60"))
# Тот же планировщик отдельным заданием гоняет свёртку feat.refresh_section_daily.
СВЁРТКА_МИН = int(os.environ.get("SCHEDULER_REFRESH_INTERVAL_MIN", "5"))

# Запас поверх интервала, после которого слот считается пропущенным. Пять минут,
# и это абсолютная величина, а не доля интервала: доля в четверть часа прощала бы
# при часовом слоте разрыв в 75 минут, а живой случай 21.09.2026 дал 68 минут —
# слот уже потерян, а проверка ещё зелёная (поймал этот промах первый же прогон
# против стенда). Пяти минут хватает с запасом: сам расчёт идёт 32,7 с, старт
# контейнера — единицы секунд, APScheduler ставит задание в очередь мгновенно.
ЗАПАС_МИН = 5

# Запас для свёртки меньше: её слот пять минут, и пятиминутный запас прощал бы
# ровно один пропущенный слот из двух. Две минуты — это вчетверо больше самой
# свёртки при часовом расчёте (стадия ms_aggregate в pred.run занимает 3,1 с).
ЗАПАС_СВЁРТКИ_МИН = 2

СТАДИИ = (
    "ms_fetch",
    "ms_aggregate",
    "ms_features",
    "ms_inference",
    "ms_explain",
    "ms_write",
)


def длительность_с(строка):
    """Сколько секунд занял прогон по сумме шести стадий.

    None, если хоть одна стадия не замерена: сумма пяти стадий из шести — это
    не длительность прогона, а меньшее число, выдающее себя за неё. Разница
    здесь решающая, потому что мы сравниваем с нормативом.
    """
    if any(строка[к] is None for к in СТАДИИ):
        return None
    return sum(строка[к] for к in СТАДИИ) / 1000.0


def укладывается(секунд):
    """Строго меньше норматива. Ровно 300,0 секунды норматив не закрывает."""
    return секунд is not None and секунд < НОРМАТИВ_С


# Граница данных: последние сутки, по которым в базе есть свёртка журнала.
#
# ЗАЧЕМ ЭТО УСЛОВИЕ. До 21.09.2026 оба запроса отбирали прогоны только по
# `status` и `objects_total`, а срез `as_of` не смотрели вовсе. Планировщик
# на стенде каждый час считает прогноз на текущий момент — 21.09.2026, — тогда
# как выгрузка заказчика кончается 30.06.2026. Такой прогон читает пустое окно
# и занимает 5,6 с вместо 32,7 с, и проверка была зелёной на числе, которое
# не имеет отношения к продуктивному объёму: три последних прогона 147, 146, 145
# дали «худший 147: 5,6 с при норме 300», а у каждого из них факторы пустые
# у всех 3 173 прогнозов. Таких прогонов в журнале 122 из 135. Нашла это
# проверяющая сессия 21.09.2026, строка приёмки М-21 была снята.
#
# ПОЧЕМУ ГРАНИЦУ БЕРЁМ У СВЁРТКИ, А НЕ У ЖУРНАЛА. Очевидное
# `max(read_time) FROM smvu.reading` даёт то же число, но идёт 93,9 секунды:
# в журнале 313 млн строк, и Постгрес читает все партиции (замер 21.09.2026
# на стенде). `max(day) FROM feat.channel_daily` даёт ту же дату 2026-06-30
# за 18,6 мс, потому что свёртка меньше журнала в тысячу раз и по `day` есть
# индекс `channel_daily_day_idx`. Обогнать журнал свёртка не может по устройству,
# а не по счастливому стечению: `db/migrations/022_channel_daily.sql:64-76`
# заполняет её одним `INSERT ... SELECT r.read_time::date ... FROM smvu.reading
# GROUP BY`, без календаря и `generate_series`, так что каждый её день взят
# из настоящего показания. Проверяющая сессия замерила и это: строк свёртки
# с днём позже последнего чтения — ноль.
#
# ОДНА ЗАВИСИМОСТЬ, КОТОРУЮ НАДО ЗНАТЬ. День свёртки считается как
# `read_time::date`, то есть в поясе сеанса, а сравниваем мы с
# `(as_of AT TIME ZONE 'Europe/Moscow')::date`. Сейчас это одно и то же:
# `SHOW TimeZone` на стенде отдаёт `Europe/Moscow`. Смени кто-нибудь `TZ`
# контейнера — свёртка пересоберётся на датах UTC, и стороны разойдутся на сутки
# в сторону меньшего `max(day)`, то есть фильтр станет строже, а не мягче;
# ложно-зелёного прогона из этого не выйдет и здесь.
#
# Пояс задан явно: расчёт приводит срез к дате сам (`$1::date`
# в `backend/app/worker/features.py`) в московском времени контейнера, и сравнение
# должно идти в том же поясе, иначе срез 01.07 в час ночи по Москве прочитается
# как 30.06 по UTC и проскочит фильтр.
ГРАНИЦА_ДАННЫХ = "(SELECT max(day) FROM feat.channel_daily)"
ВНУТРИ_ДАННЫХ = (
    f"(r.as_of AT TIME ZONE 'Europe/Moscow')::date <= {ГРАНИЦА_ДАННЫХ}"
)

ПОЛНЫЕ_ПРОГОНЫ = f"""
SELECT r.run_id, r.as_of, r.objects_total, r.objects_scored,
       r.ms_fetch, r.ms_aggregate, r.ms_features, r.ms_inference,
       r.ms_explain, r.ms_write
  FROM pred.run r
 WHERE r.status = 'done'
   AND r.objects_total = (SELECT count(*) FROM ref.object_xref)
   AND {ВНУТРИ_ДАННЫХ}
 ORDER BY r.run_id DESC
 LIMIT $1
"""

# Сколько прогонов по полному парку есть вообще и сколько из них внутри данных.
# Нужен для диагноза: «прогонов нет» и «прогоны есть, но все за границей выгрузки» —
# это разные беды, и чинят их разными командами.
СКОЛЬКО_ПОЛНЫХ = f"""
SELECT count(*) AS всего,
       count(*) FILTER (WHERE {ВНУТРИ_ДАННЫХ}) AS внутри
  FROM pred.run r
 WHERE r.status = 'done'
   AND r.objects_total = (SELECT count(*) FROM ref.object_xref)
"""

ОДИН_ОБЪЕКТ = f"""
SELECT r.run_id, r.as_of, r.objects_total,
       r.ms_fetch, r.ms_aggregate, r.ms_features, r.ms_inference,
       r.ms_explain, r.ms_write
  FROM pred.run r
 WHERE r.status = 'done' AND r.objects_total = 1
   AND {ВНУТРИ_ДАННЫХ}
 ORDER BY r.run_id DESC
 LIMIT 1
"""

# Тот же отбор без условия на срез — нужен, чтобы отличить «прогона по одному
# объекту нет вовсе» от «есть, но за границей данных».
ОДИН_ОБЪЕКТ_ЛЮБОЙ = """
SELECT r.run_id, r.as_of FROM pred.run r
 WHERE r.status = 'done' AND r.objects_total = 1
 ORDER BY r.run_id DESC LIMIT 1
"""


async def check_m21(conn):
    """Полный расчёт по всему парку укладывается в 5 минут, и так три раза."""
    участков = await conn.fetchval("SELECT count(*) FROM ref.object_xref")
    граница = await conn.fetchval(f"SELECT {ГРАНИЦА_ДАННЫХ}")
    if граница is None:
        return False, (
            "свёртка feat.channel_daily пуста, границу данных взять не у чего: "
            "без неё замер нельзя отличить от расчёта по пустому окну"
        )
    строки = await conn.fetch(ПОЛНЫЕ_ПРОГОНЫ, ПРОГОНОВ_НАДО)
    if len(строки) < ПРОГОНОВ_НАДО:
        счёт = await conn.fetchrow(СКОЛЬКО_ПОЛНЫХ)
        return False, (
            f"прогонов по всем {участков} участкам со срезом внутри данных "
            f"{счёт['внутри']}, надо {ПРОГОНОВ_НАДО} (всего полных прогонов "
            f"{счёт['всего']}, данные кончаются {граница}): прогон со срезом "
            f"за границей выгрузки читает пустое окно и меряет не тот объём"
        )

    времена = [(с["run_id"], длительность_с(с)) for с in строки]
    недомерено = [rid for rid, t in времена if t is None]
    if недомерено:
        return False, (
            f"у прогонов {', '.join(map(str, недомерено))} замерены не все шесть "
            f"стадий — сумма неполного профиля не является длительностью прогона"
        )

    худший_id, худший = max(времена, key=lambda п: п[1])
    лучший = min(t for _, t in времена)
    if not укладывается(худший):
        return False, (
            f"худший прогон {худший_id}: {худший:.1f} с при нормативе {НОРМАТИВ_С:.0f} с "
            f"на {участков} участках"
        )

    доля = {к: max(с[к] for с in строки) for к in СТАДИИ}
    самая = max(доля, key=доля.get)
    # Номера прогонов и их срезы печатаем в зелёной строке нарочно: замер
    # на вчерашних данных и замер по пустому окну видны глазами, без запроса к базе.
    срезы = ", ".join(
        f"{с['run_id']} от {с['as_of'].date()}" for с in строки
    )
    return True, (
        f"{len(строки)} прогона по {участков} участкам, худший {худший_id}: "
        f"{худший:.1f} с, лучший {лучший:.1f} с при нормативе {НОРМАТИВ_С:.0f} с; "
        f"дороже всех стадия {самая} — {доля[самая] / 1000:.1f} с; "
        f"срезы внутри данных (по {граница}): {срезы}"
    )


async def check_nf72(conn):
    """Расчёт по одному объекту укладывается в 5 минут."""
    с = await conn.fetchrow(ОДИН_ОБЪЕКТ)
    if с is None:
        # Дыра здесь была та же, что в М-21, и закрыта тем же условием: отбор шёл
        # по ORDER BY run_id DESC без среза, поэтому первый же прогон планировщика
        # по одному объекту на сегодняшнюю дату забрал бы строку себе.
        любой = await conn.fetchrow(ОДИН_ОБЪЕКТ_ЛЮБОЙ)
        граница = await conn.fetchval(f"SELECT {ГРАНИЦА_ДАННЫХ}")
        if любой is None:
            return False, (
                "в журнале нет ни одного прогона по одному объекту: запустите "
                "python -m app.worker.run --as-of ... --limit 1"
            )
        return False, (
            f"прогоны по одному объекту есть (последний {любой['run_id']} "
            f"от {любой['as_of'].date()}), но все со срезом за границей данных "
            f"({граница}): такой прогон читает пустое окно"
        )
    секунд = длительность_с(с)
    if not укладывается(секунд):
        подробность = (
            "не все шесть стадий замерены" if секунд is None else f"{секунд:.1f} с"
        )
        return False, (
            f"прогон {с['run_id']} по одному объекту: {подробность} "
            f"при нормативе {НОРМАТИВ_С:.0f} с"
        )
    return True, (
        f"прогон {с['run_id']} по одному объекту, срез {с['as_of'].date()}: "
        f"{секунд:.1f} с при нормативе {НОРМАТИВ_С:.0f} с"
    )


def промежутки(прогоны):
    """Промежутки между соседними стартами: [(минут, слева, справа), ...].

    Вынесено из проверки нарочно: с базой её арифметику не проверить assert'ом,
    а ошибка здесь тихая — разрыв посчитается меньше настоящего, и пропущенный
    слот пройдёт зелёным.
    """
    return [
        ((b - a).total_seconds() / 60, слева, справа)
        for (слева, a), (справа, b) in pairwise(прогоны)
    ]


РАЗРЫВЫ = """
SELECT r.run_id, r.started_at
  FROM pred.run r
 WHERE r.objects_total = (SELECT count(*) FROM ref.object_xref)
   AND r.started_at > now() - make_interval(mins => $1)
 ORDER BY r.started_at
"""


async def check_расписание(conn, окно_мин=24 * 60):
    """Планировщик не пропустил ни одного часового слота за последние сутки.

    **Чего не видит ни одна другая проверка.** Пропущенный расчёт не оставляет
    следа нигде: строки в `pred.run` нет, журнал контейнера живёт до пересоздания,
    а `check_m21` смотрит три последних прогона и на разрывы между ними не глядит.
    21.09.2026 `moskollektor-worker-1` пересоздали при выкладке, слот потерялся,
    и заметила это проверяющая сессия — тем, что ждала прогноза к 10:37 и не
    дождалась. Строка НФ-41 закрывает «прерванный расчёт не оставляет частично
    записанных данных», а «расчёт не запустился вовсе» не закрывает никто.

    Меряем две вещи, и вторая важнее первой. Наибольший разрыв между соседними
    стартами показывает пропуски в прошлом. Возраст последнего прогона показывает,
    работает ли планировщик прямо сейчас: остановись он час назад — разрывов
    в журнале ещё нет, а расчёта уже нет тоже.
    """
    # Окно наблюдения — параметр, а не константа внутри: иначе ветку «служба
    # стоит дольше окна» нечем предъявить, пока стенд жив. С окном в 30 минут
    # та же ветка проверяется на живых данных за секунду. Окно называется в тексте:
    # при нестандартном окне слово «сутки» в сообщении было бы неправдой.
    окно = "сутки" if окно_мин == 24 * 60 else f"{окно_мин} мин"
    строки = await conn.fetch(РАЗРЫВЫ, окно_мин)
    норма_мин = ИНТЕРВАЛ_МИН + ЗАПАС_МИН

    возраст = None
    if строки:
        возраст = await conn.fetchval(
            "SELECT extract(epoch FROM now() - $1) / 60", строки[-1]["started_at"]
        )

    if len(строки) < 2:
        # Три разные беды, и они дают разный исход. Свежий стенд — ПРОПУСК:
        # красить его СБОЕМ нельзя, заказчик распакует пакет и увидит красное
        # на пустом журнале. Служба, стоящая дольше суток, — СБОЙ: окно пустое,
        # и без этой ветки самая тяжёлая поломка дала бы самый спокойный исход
        # (нашла проверяющая сессия 21.09.2026). Различает их один вопрос:
        # есть ли полные прогоны в журнале ВООБЩЕ, без ограничения по окну.
        был = await conn.fetchrow(
            """SELECT run_id, started_at,
                      extract(epoch FROM now() - started_at) / 3600 AS часов
                 FROM pred.run
                WHERE objects_total = (SELECT count(*) FROM ref.object_xref)
                ORDER BY started_at DESC LIMIT 1"""
        )
        неудачных = await conn.fetchval(
            "SELECT count(*) FROM pred.run WHERE status <> 'done' "
            "AND started_at > now() - make_interval(mins => $1)",
            окно_мин,
        )
        хвост = (f"; при этом в pred.run за сутки {неудачных} прогонов со "
                 f"status <> 'done' — значит расчёт запускается и падает"
                 if неудачных else "")
        if был is not None and был["часов"] > окно_мин / 60:
            return False, (
                f"полных прогонов за {окно} нет вовсе, последний {был['run_id']} "
                f"стартовал {был['часов']:.1f} ч назад при интервале "
                f"{ИНТЕРВАЛ_МИН} мин: расчёт стоит дольше окна наблюдения{хвост}"
            )
        сколько = "ни одного полного прогона" if not строки else "один полный прогон"
        return None, (
            f"за последние {окно} {сколько}: разрывы измерить не на чем, "
            f"дайте службе проработать хотя бы {ИНТЕРВАЛ_МИН * 2} минут{хвост}"
        )

    разрывы = промежутки([(с["run_id"], с["started_at"]) for с in строки])
    худший_мин, слева, справа = max(разрывы)
    пропусков = sum(1 for м, _, _ in разрывы if м > норма_мин)

    if возраст > норма_мин:
        # Оговорка про «не считает» не лишняя: запрос отбирает прогоны по
        # objects_total и не смотрит status, а у неудачного прогона objects_total
        # бывает NULL — такой прогон в ряд не попадёт. Значит планировщик, который
        # исправно стреляет и каждый раз падает, даст ту же красную строку, что
        # и остановившийся, и диагноз уведёт на шаг в сторону. Разные беды чинят
        # разным, поэтому строка называет обе. Нашла это проверяющая сессия,
        # замерив, что неудачных прогонов внутри фильтра сейчас ноль.
        return False, (
            f"последний полный прогон {строки[-1]['run_id']} стартовал "
            f"{возраст:.0f} мин назад при интервале {ИНТЕРВАЛ_МИН} мин "
            f"и запасе {ЗАПАС_МИН} мин: планировщик либо не запускается, либо "
            f"запускается и падает — проверьте в pred.run строки со status <> 'done'"
        )
    if пропусков:
        return False, (
            f"пропущено слотов за {окно}: {пропусков} из {len(разрывы)} промежутков; "
            f"худший разрыв {худший_мин:.0f} мин между прогонами {слева} и {справа} "
            f"при интервале {ИНТЕРВАЛ_МИН} мин"
        )
    return True, (
        f"{len(строки)} полных прогонов за {окно} без пропусков, худший разрыв "
        f"{худший_мин:.0f} мин при интервале {ИНТЕРВАЛ_МИН} мин; последний прогон "
        f"{строки[-1]['run_id']} стартовал {возраст:.0f} мин назад"
    )


СВЁРТКИ = """
SELECT refresh_id, started_at, finished_at, rows_updated, status
  FROM feat.refresh_run
 WHERE started_at > now() - make_interval(mins => $1)
 ORDER BY started_at
"""


async def check_свёртка(conn, окно_мин=24 * 60):
    """Свёртка идёт по расписанию и оставляет след, по которому это видно.

    **Зачем строка.** До 21.09.2026 `тик_свёртка` в планировщике звал функцию
    и печатал результат в журнал контейнера — в базе не оставалось ничего.
    Пропуск свёртки не видела ни одна проверка, а задержку нельзя было померить
    запросом: в `feat.section_daily` тринадцать колонок и ни одной временнóй,
    кроме `day`, а `day` — дата показания, не время расчёта.

    **Чего эта проверка НЕ доказывает.** Что выполняется НФ-73 («показание
    доходит до расчёта не позднее 300 секунд»). НФ-73 не выполняется по
    устройству: полный расчёт часовой, показание из :06 ждёт 3 540 секунд при
    нормативе 300. Здесь проверяется измеритель, а не само требование.
    """
    try:
        строки = await conn.fetch(СВЁРТКИ, окно_мин)
    except asyncpg.UndefinedTableError:
        return None, (
            "таблицы feat.refresh_run нет: миграция 023_refresh_run.sql не накатана, "
            "пропуск свёртки по-прежнему не виден ничем"
        )

    упавших = [с["refresh_id"] for с in строки if с["status"] == "failed"]
    if упавших:
        return False, (
            f"свёртка падала за сутки {len(упавших)} раз, последний прогон "
            f"{упавших[-1]}: показания не доходят до признаков"
        )
    успешные = [с for с in строки if с["status"] == "done"]
    if len(успешные) < 2:
        return None, (
            f"за сутки {len(успешные)} успешных свёрток: измерить разрывы не на чем, "
            f"дайте службе проработать хотя бы {СВЁРТКА_МИН * 2} минут"
        )

    возраст = await conn.fetchval(
        "SELECT extract(epoch FROM now() - $1) / 60", успешные[-1]["started_at"]
    )
    норма = СВЁРТКА_МИН + ЗАПАС_СВЁРТКИ_МИН
    if возраст > норма:
        return False, (
            f"последняя свёртка {успешные[-1]['refresh_id']} шла {возраст:.0f} мин "
            f"назад при интервале {СВЁРТКА_МИН} мин и запасе {ЗАПАС_СВЁРТКИ_МИН} мин: "
            f"признаки отстают от журнала"
        )

    разрывы = промежутки([(с["refresh_id"], с["started_at"]) for с in успешные])
    пропусков = sum(1 for м, _, _ in разрывы if м > норма)
    худший, слева, справа = max(разрывы)
    if пропусков:
        return False, (
            f"пропущено слотов свёртки за сутки: {пропусков} из {len(разрывы)}; "
            f"худший разрыв {худший:.1f} мин между прогонами {слева} и {справа} "
            f"при интервале {СВЁРТКА_МИН} мин"
        )
    длительности = sorted(
        (с["finished_at"] - с["started_at"]).total_seconds()
        for с in успешные if с["finished_at"]
    )
    # Медиана, а не среднее: одна свёртка, попавшая на полный расчёт, тянет
    # среднее вверх и прячет обычное время.
    про_время = (f", медиана длительности {длительности[len(длительности) // 2]:.1f} с"
                 if длительности else "")
    return True, (
        f"{len(успешные)} свёрток за сутки без пропусков, худший разрыв "
        f"{худший:.1f} мин при интервале {СВЁРТКА_МИН} мин; последняя шла "
        f"{возраст:.1f} мин назад, обновила {успешные[-1]['rows_updated']} строк"
        f"{про_время}"
    )


CHECKS = (
    ("М-21", check_m21),
    ("НФ-72", check_nf72),
    ("НФ-91", check_расписание),
    ("свёртка", check_свёртка),
)


async def run_checks(dsn):
    conn = await asyncpg.connect(dsn)
    try:
        out = []
        for name, fn in CHECKS:
            try:
                ok, text = await fn(conn)
            except asyncpg.PostgresError as e:
                ok, text = False, f"база отказала: {str(e).splitlines()[0]}"
            out.append((name, ok, text))
        return out
    finally:
        await conn.close()


def report(results):
    for name, ok, text in results:
        исход = "ПРОПУСК" if ok is None else ("OK" if ok else "СБОЙ")
        print(f"{name} {исход} {text}")
    # ПРОПУСК не роняет прогон: измерить не удалось — это не «не сошлось».
    return 1 if any(ok is False for _, ok, _ in results) else 0


def fail_all(reason):
    return report([(name, False, reason) for name in ROWS])


def demo(verbose=True):
    """Проверка арифметики без базы: что считается длительностью и что нормативом."""
    полный = dict(
        ms_fetch=4609,
        ms_aggregate=3094,
        ms_features=24402,
        ms_inference=66,
        ms_explain=73,
        ms_write=463,
    )
    assert abs(длительность_с(полный) - 32.707) < 1e-9, длительность_с(полный)
    assert укладывается(длительность_с(полный))

    # Сторож на условие среза. Базы здесь нет, поэтому проверяем текст запросов:
    # оба обязаны ограничивать прогоны границей данных. Убери кто-нибудь это
    # условие — и проверка снова станет мерить расчёт по пустому окну и зеленеть
    # на 5,6 секунды вместо 32,7 (так она и жила до 21.09.2026).
    for имя, запрос in (("ПОЛНЫЕ_ПРОГОНЫ", ПОЛНЫЕ_ПРОГОНЫ), ("ОДИН_ОБЪЕКТ", ОДИН_ОБЪЕКТ)):
        assert "as_of" in запрос and "feat.channel_daily" in запрос, (
            f"{имя} перестал отбирать прогоны по срезу внутри данных"
        )

    # Арифметика разрывов. Часовые слоты идут ровно, кроме одного пропуска:
    # между 12 и 14 прошло два часа, и это единственный промежуток выше нормы.
    def из_ч(ч, м):
        # Пояс здесь любой, лишь бы один на весь ряд: считаются разности, а не даты.
        return datetime(2026, 9, 21, ч, м, tzinfo=timezone.utc)

    ряд = [(11, из_ч(9, 0)), (12, из_ч(10, 0)), (14, из_ч(12, 0)), (15, из_ч(13, 0))]
    р = промежутки(ряд)
    assert [round(м) for м, _, _ in р] == [60, 120, 60], р
    норма = 60 + ЗАПАС_МИН
    assert [(м, a, b) for м, a, b in р if м > норма] == [(120.0, 12, 14)], р
    # Ровный ряд без пропусков не даёт ни одного превышения — иначе проверка
    # краснела бы всегда и перестала отличать исправное от сломанного.
    ровный = промежутки([(n, из_ч(9 + n, 0)) for n in range(5)])
    assert not [м for м, _, _ in ровный if м > норма], ровный
    # Слот длиннее нормы ровно на минуту уже пропуск: граница строгая.
    assert промежутки([(1, из_ч(9, 0)), (2, из_ч(10, 6))])[0][0] > норма

    # --- Свёртка: четыре исхода на заглушке вместо базы -----------------------
    #
    # Без заглушки эту проверку нечем проверить до выкладки: таблицы
    # feat.refresh_run на стенде ещё нет, а ручной накат миграции ломает
    # следующую выкладку (в schema_migration не появится строки, и migrate упадёт).
    # Заглушка отвечает на два запроса, которые делает check_свёртка: список
    # прогонов и возраст последнего.
    class _Заглушка:
        def __init__(self, строки, возраст_мин):
            self.строки, self.возраст = строки, возраст_мин

        async def fetch(self, *_):
            return self.строки

        async def fetchval(self, *_):
            return self.возраст

    def свёртка(строки, возраст):
        return asyncio.run(check_свёртка(_Заглушка(строки, возраст)))

    def прогон(rid, минут_назад, статус="done", строк=6346, длился=3):
        начало = из_ч(12, 0) - timedelta(minutes=минут_назад)
        return {"refresh_id": rid, "started_at": начало,
                "finished_at": начало + timedelta(seconds=длился),
                "rows_updated": строк, "status": статус}

    ровно = [прогон(n, 20 - n * 5) for n in range(5)]        # каждые 5 минут
    ок, текст = свёртка(ровно, 0.5)
    assert ок is True and "без пропусков" in текст, текст
    assert "обновила 6346 строк" in текст and "медиана длительности" in текст, текст

    # Свёртка не шла 12 минут при слоте 5 и запасе 2 — признаки отстают.
    ок, текст = свёртка(ровно, 12)
    assert ок is False and "признаки отстают от журнала" in текст, текст

    # Пропущенный слот внутри суток: между вторым и третьим прогоном 15 минут.
    дыра = [прогон(1, 40), прогон(2, 35), прогон(3, 20), прогон(4, 15)]
    ок, текст = свёртка(дыра, 0.5)
    assert ок is False and "пропущено слотов свёртки за сутки: 1" in текст, текст

    # Свёртка исправно запускается и падает — это отдельная беда, и называть её
    # надо отдельно: разрывов в журнале при этом нет вовсе.
    ок, текст = свёртка(ровно + [прогон(9, 1, статус="failed")], 0.5)
    assert ок is False and "свёртка падала за сутки 1 раз" in текст, текст

    # Пустой журнал — ПРОПУСК, а не СБОЙ: на свежем стенде мерить нечего.
    ок, текст = свёртка([], None)
    assert ок is None and "измерить разрывы не на чем" in текст, текст


    # Ровно норматив — не проходит: постановка требует «менее 5 минут».
    assert not укладывается(300.0)
    assert укладывается(299.999)

    # Недомеренный прогон не выдаёт себя за быстрый. Это не придирка: прогон
    # с пустой ms_features дал бы 8,3 секунды вместо 32,7 и прошёл бы норматив
    # с запасом, хотя самой дорогой стадии в нём просто не замерили.
    кривой = dict(полный, ms_features=None)
    assert длительность_с(кривой) is None
    assert not укладывается(длительность_с(кривой))
    assert sum(v for v in кривой.values() if v) / 1000 < 8.4, "пример потерял смысл"

    if not verbose:
        return
    print("демо М-21: 4609+3094+24402+66+73+463 мс = 32,7 с — норматив 300 с закрыт")
    print("демо М-21: ровно 300,0 с норматив НЕ закрывает, нужно строго меньше")
    print("демо М-21: прогон без ms_features даёт 8,3 с и обязан считаться СБОЕМ")
    print("демо М-21 и НФ-72: оба запроса отбирают прогоны по срезу внутри данных")
    print("демо расписания: пропущенный слот даёт разрыв 120 мин при норме 65")
    print("демо свёртки: четыре исхода на заглушке базы — падение, пропуск, "
          "отставание, зелёная")
    print("OK")


def main(argv):
    # арифметика обязана быть цела до любого похода в базу
    demo(verbose="--demo" in argv)
    if "--demo" in argv:
        return 0
    if asyncpg is None:
        return fail_all("не установлен asyncpg — тот же пакет, что у backend/app/db.py")
    dsn = os.environ.get("DATABASE_URL")
    if not dsn:
        return fail_all("не задана переменная DATABASE_URL, подключаться не к чему")
    try:
        results = asyncio.run(run_checks(dsn))
    except (OSError, ValueError, asyncpg.PostgresError, asyncio.TimeoutError) as e:
        return fail_all(f"нет связи с базой: {str(e).splitlines()[0]}")
    return report(results)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
