# Постановка: «время формирования прогноза менее 5 минут». Пять минут — это 300
# секунд, и меньше значит строго меньше.
НОРМАТИВ_С = 300.0


def предел_нф73_с(интервал_мин=None):
    """Сколько секунд может идти расчёт, чтобы НФ-73 ещё выполнялась.

    НФ-73 требует, чтобы показание доходило до расчёта не позднее 300 секунд.
    Худший случай складывается из двух слагаемых: показание пришло сразу после
    старта прогона и ждёт следующего слота (интервал), а потом идёт сам расчёт.
    Значит на расчёт остаётся `НОРМАТИВ_С − интервал`: при интервале 4 минуты
    это 60 секунд, при часовом — отрицательное число, то есть требование
    не выполнимо ни при какой скорости расчёта, как и было до MOS-146.

    Порог считается от интервала, а не зашит числом: сменят интервал — сдвинется
    и он. Нашла 28: до 21.09.2026 в докстроке ниже стояло, что за границей в 60 с
    «смотрит строка М-21», а М-21 смотрит только на 300 с. Расчёт, замедлившийся
    до 200 с, оставил бы М-21 зелёной и сломал бы НФ-73 молча: 240 + 200 = 440.
    """
    минут = интервал_мин if интервал_мин is not None else ИНТЕРВАЛ_МИН
    return НОРМАТИВ_С - минут * 60


def про_предел_нф73(интервал_мин=None):
    """Как назвать предел НФ-73 в зелёной строке М-21.

    Отрицательный предел арифметически верен, но как утверждение бессмыслен:
    «при пределе НФ-73 −3300 с» в самой заметной строке прогона читается как
    поломка счёта. Нашла 28, 21.09.2026. При невыполнимом интервале пишем словами
    и отсылаем к строке НФ-73, чтобы две строки говорили одно и то же.
    """
    минут = ИНТЕРВАЛ_МИН if интервал_мин is None else интервал_мин
    предел = предел_нф73_с(минут)
    if предел <= 0:
        return (f"при интервале {минут} мин НФ-73 невыполнима — "
                f"см. строку «НФ-73 арифметика» ниже")
    return f"и при пределе НФ-73 {предел:.0f} с на сам расчёт"

