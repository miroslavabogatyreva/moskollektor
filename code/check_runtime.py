async def check_нф73(conn, интервал_мин=None):
    """НФ-73 арифметикой: ожидание слота плюс сам расчёт против норматива 300 с.

    Требование — «показание, пришедшее потоком, доходит до расчёта не позднее
    300 секунд». Худший случай: показание пришло сразу после старта прогона,
    ждёт следующего слота (весь интервал), и потом идёт сам расчёт.

    **Почему это отдельная строка, а не условие внутри М-21.** М-21 сторожит
    свой норматив — 300 секунд на расчёт — и держит его с запасом в девять раз.
    НФ-73 при интервале 4 минуты оставляет расчёту всего 60 секунд, и прогон
    на 200 секунд был бы для М-21 зелёным, а для НФ-73 — провалом (240 + 200 =
    440 при нормативе 300). Один порог не может отвечать за два требования.
    Нашла 28, 21.09.2026: до этого связка держалась на фразе в докстроке
    «за этим смотрит строка М-21», а М-21 за этим не смотрела.

    **Строку приёмки это не закрывает.** Методика НФ-73 требует 20 показаний
    с засечкой времени через приёмный конец потока (задача 3.7, Ф-82), которого
    у нас нет. Здесь считается время по нашей схеме, а не замер по методике —
    поэтому зелёная строка говорит «арифметика сходится», а не «НФ-73 закрыта».
    """
    # Интервал параметром, а не только из окружения: иначе ветки «интервал сам
    # съедает норматив» и «расчёт длиннее предела» нечем предъявить на заглушке.
    интервал_мин = ИНТЕРВАЛ_МИН if интервал_мин is None else интервал_мин
    предел = предел_нф73_с(интервал_мин)
    ожидание = интервал_мин * 60
    if предел <= 0:
        return False, (
            f"интервал расчёта {интервал_мин} мин сам съедает норматив: ожидание "
            f"слота {ожидание:.0f} с при нормативе {НОРМАТИВ_С:.0f} с, на расчёт "
            f"не остаётся ничего — требование не выполнимо ни при какой скорости"
        )
    строки = await conn.fetch(ПОЛНЫЕ_ПРОГОНЫ, ПРОГОНОВ_НАДО)
    времена = [(с["run_id"], длительность_с(с)) for с in строки]
    времена = [(rid, t) for rid, t in времена if t is not None]
    if not времена:
        return None, (
            f"полных прогонов со срезом внутри данных нет: арифметику НФ-73 "
            f"не на чем проверить (предел на расчёт {предел:.0f} с)"
        )
    худший_id, худший = max(времена, key=lambda п: п[1])
    итого = ожидание + худший
    if итого >= НОРМАТИВ_С:
        return False, (
            f"худший прогон {худший_id}: ожидание слота {ожидание:.0f} с плюс "
            f"расчёт {худший:.1f} с = {итого:.1f} с при нормативе "
            f"{НОРМАТИВ_С:.0f} с — на сам расчёт остаётся строго меньше "
            f"{предел:.0f} с, а он идёт дольше"
        )
    return True, (
        f"арифметика сходится: ожидание слота {ожидание:.0f} с плюс худший расчёт "
        f"{худший:.1f} с (прогон {худший_id}) = {итого:.1f} с при нормативе "
        f"{НОРМАТИВ_С:.0f} с, запас {НОРМАТИВ_С - итого:.1f} с; на расчёт остаётся "
        f"строго меньше {предел:.0f} с. Строку приёмки это не закрывает: методика "
        f"требует 20 показаний через приёмный конец потока (задача 3.7)"
    )


async def check_свёртка(conn, окно_мин=24 * 60):
    """Свёртка идёт по расписанию и оставляет след, по которому это видно.

    **Зачем строка.** До 21.09.2026 `тик_свёртка` в планировщике звал функцию
    и печатал результат в журнал контейнера — в базе не оставалось ничего.
    Пропуск свёртки не видела ни одна проверка, а задержку нельзя было померить
    запросом: в `feat.section_daily` тринадцать колонок и ни одной временнóй,
    кроме `day`, а `day` — дата показания, не время расчёта.

    **Чего эта проверка НЕ доказывает.** Что выполняется НФ-73 («показание
    доходит до расчёта не позднее 300 секунд»). Здесь проверяется измеритель,
    а не само требование. Само требование закрывается арифметикой интервала:
    до MOS-146 расчёт шёл раз в час, и показание из :06 ждало 3 540 секунд при
    нормативе 300 — промах в двенадцать раз; при интервале 4 минуты худший случай
    это 240 секунд ожидания плюс 33,4 секунды самого расчёта, то есть 273 секунды
    против 300. Запас 26,6 секунды, и он держится, пока сам расчёт идёт строго
    меньше 60 секунд (240 + 60 = 300, а ровно 300 норматив не закрывает). За этой
    границей смотрит `предел_нф73_с()` в строке М-21 — отдельной проверкой, а не
    нормативом 300 с: расчёт на 200 секунд в М-21 укладывается, а НФ-73 ломает.
    Нашла 28, 21.09.2026.
    """
    if (беда := запас_ослеплён(ЗАПАС_СВЁРТКИ_МИН, СВЁРТКА_МИН)):
        return False, беда
    try:
        строки = await conn.fetch(СВЁРТКИ, окно_мин)
    except asyncpg.UndefinedTableError:
        return None, (
            "таблицы feat.refresh_run нет: миграция 023_refresh_run.sql не накатана, "
            "пропуск свёртки по-прежнему не виден ничем"
        )

    упавших = [с["refresh_id"] for с in строки if с["status"] == "failed"]
    if упавших:
        return False, (
            f"свёртка падала за сутки {len(упавших)} раз, последний прогон "
            f"{упавших[-1]}: показания не доходят до признаков"
        )
    успешные = [с for с in строки if с["status"] == "done"]
    if len(успешные) < 2:
        return None, (
            f"за сутки {len(успешные)} успешных свёрток: измерить разрывы не на чем, "
            f"дайте службе проработать хотя бы {СВЁРТКА_МИН * 2} минут"
        )

    возраст = await conn.fetchval(
        "SELECT extract(epoch FROM now() - $1) / 60", успешные[-1]["started_at"]
    )
    норма = СВЁРТКА_МИН + ЗАПАС_СВЁРТКИ_МИН
    if возраст > норма:
        return False, (
            f"последняя свёртка {успешные[-1]['refresh_id']} шла {возраст:.0f} мин "
            f"назад при интервале {СВЁРТКА_МИН} мин и запасе {ЗАПАС_СВЁРТКИ_МИН} мин: "
            f"признаки отстают от журнала"
        )

    разрывы = промежутки([(с["refresh_id"], с["started_at"]) for с in успешные])
    пропусков = sum(1 for м, _, _ in разрывы if м > норма)
    худший, слева, справа = max(разрывы)
    if пропусков:
        return False, (
            f"пропущено слотов свёртки за сутки: {пропусков} из {len(разрывы)}; "
            f"худший разрыв {худший:.1f} мин между прогонами {слева} и {справа} "
            f"при интервале {СВЁРТКА_МИН} мин"
        )
    длительности = sorted(
        (с["finished_at"] - с["started_at"]).total_seconds()
        for с in успешные if с["finished_at"]
    )
    # Медиана, а не среднее: одна свёртка, попавшая на полный расчёт, тянет
    # среднее вверх и прячет обычное время.
    про_время = (f", медиана длительности {длительности[len(длительности) // 2]:.1f} с"
                 if длительности else "")
    return True, (
        f"{len(успешные)} свёрток за сутки без пропусков, худший разрыв "
        f"{худший:.1f} мин при интервале {СВЁРТКА_МИН} мин; последняя шла "
        f"{возраст:.1f} мин назад, обновила {успешные[-1]['rows_updated']} строк"
        f"{про_время}"
    )


def зависшие(прогоны, сейчас, интервал_мин):
    """Прогоны в статусе running, начатые раньше, чем интервал планировщика назад.

    Живой расчёт идёт секунды (худший 3,6 с на 22.09.2026), следующий стартует
    через интервал. Running старше интервала — расчёт оборвали, а строка
    осталась: 22.09.2026 перезапуск worker при выкладке 037 оставил так прогон 669.
    """
    граница = сейчас - timedelta(minutes=интервал_мин)
    return [п for п in прогоны if п["started_at"] < граница]


async def check_зависший(conn):
    """НФ-41: прерванный расчёт не оставляет после себя незакрытой строки журнала."""
    строки = await conn.fetch(
        "SELECT run_id, started_at, now() AS сейчас FROM pred.run WHERE status = 'running'"
    )
    if not строки:
        return True, f"прогонов со status=running старше интервала {ИНТЕРВАЛ_МИН} мин: 0"
    сейчас = строки[0]["сейчас"]
    беда = зависшие(строки, сейчас, ИНТЕРВАЛ_МИН)
    мск = timezone(timedelta(hours=3))
    итог = (
        f"прогонов со status=running старше интервала {ИНТЕРВАЛ_МИН} мин: "
        f"{len(беда)} из {len(строки)} running"
    )
    if беда:
        return False, итог + " — " + ", ".join(
            f"{п['run_id']} (старт {п['started_at'].astimezone(мск):%d.%m %H:%M} мск, "
            f"{(сейчас - п['started_at']).total_seconds() / 60:.0f} мин назад)"
            for п in беда
        )
    return True, итог


