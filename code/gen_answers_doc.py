"""Собрать docs/meetings/2026-09-19-ответы-заказчика.md из выгрузки заказчика.

Самопроверка: python3 gen_meeting_doc.py --check — сверяет, что в собранном
документе столько же пар «вопрос — ответ», сколько непустых ответов в xlsx.
"""

import sys

import openpyxl

XLSX = "/Users/miroslavabogatyreva/Projects/moskollektor/docs/meetings/2026-09-19-вопросы-ответы.xlsx"
OUT = "/Users/miroslavabogatyreva/Projects/moskollektor/docs/meetings/2026-09-19-ответы-заказчика.md"
NOANSWER = {"???", "??", "?"}


def rows(ws):
    r = [
        x
        for x in ws.iter_rows(values_only=True)
        if any(c is not None and str(c).strip() for c in x)
    ]
    return r[1:]


def clean(v):
    return " ".join(str(v).split()) if v is not None else ""


def build():
    wb = openpyxl.load_workbook(XLSX, data_only=True)
    norm = rows(wb["Вопросы_нормализованные_и_Ответ"])
    syst = rows(wb["Вопросы_систематизация"])
    src = rows(wb["Исходник_групп"])

    # Нумерация сквозная по всем строкам с заполненной колонкой ответа, включая
    # те, где заказчик поставил «???». Номер «Ответ N» — это ссылка из приёмки,
    # поэтому порядок строк файла менять нельзя и пропускать строки тоже.
    replied = [r for r in syst if clean(r[5])]
    answered = [r for r in replied if clean(r[5]) not in NOANSWER]
    ignored = [r for r in replied if clean(r[5]) in NOANSWER]
    ours = [r for r in syst if clean(r[1]) == "Скайнет"]

    L = []
    w = L.append
    w("# Письменные ответы заказчика, 19.09.2026")
    w("")
    w(
        "Заказчик прислал файл `2026-09-19-вопросы-ответы.xlsx` — вопросы всех команд трека"
    )
    w(
        "«Город 8. ДЖКХ» и свои ответы на них. Это письменный источник класса А: на приёмке"
    )
    w(
        "цитата отсюда весит больше, чем наша запись устного ответа на встрече 17.09.2026."
    )
    w("")
    w(
        f"В файле три вкладки. Первая — {len(norm)} сводных вопроса, которые организатор склеил"
    )
    w(
        f"из вопросов команд, с ответами. Вторая — {len(syst)} вопросов от команд по одному,"
    )
    w(
        f"ответ есть у {len(answered)} из них, ещё {len(ignored)} помечены знаками вопроса,"
    )
    w(f"то есть заказчик их прочитал и отвечать не стал. Третья — {len(src)} вопросов")
    w("в том виде, в каком команды их прислали.")
    w("")
    w(
        "**Наша команда в файле называется «Скайнет», вопросы задавал Николай Тлехугов.**"
    )
    w(
        f"Наших вопросов {len(ours)}, и прямого ответа нет ни на один — они перечислены в конце."
    )
    w("")
    w("## Дефект первой вкладки: ответы съехали на строку")
    w("")
    w("Читать первую вкладку как «вопрос сверху — ответ справа» нельзя. Ответ про коды")
    w(
        "`-100` и `255` и про всплеск тревог 2021 года напечатан в строке 5, у вопроса про"
    )
    w("ролевую модель и LDAP. Ответ про координаты и картографический движок напечатан")
    w("в строке 13, у вопроса про несанкционированный доступ. Поэтому первоисточником")
    w("я считаю вторую вкладку: там вопрос команды и ответ заказчика стоят парой,")
    w("и спутать их нельзя. Ниже они идут под номерами «Ответ 1»…«Ответ N» — этими")
    w("номерами ссылаются строки `docs/acceptance-test.md`.")
    w("")
    w("---")
    w("")
    w(f"# Часть 1. Ответы заказчика на вопросы команд ({len(replied)} штук)")
    w("")
    w(
        "Вопрос и ответ приведены дословно, включая опечатки заказчика. Ответов по существу"
    )
    w(
        f"{len(answered)}, ещё {len(ignored)} строк заказчик пометил знаками вопроса — они идут"
    )
    w("здесь же и со сквозным номером, чтобы номер «Ответ N» не поехал.")
    w("")
    for n, r in enumerate(replied, 1):
        team = clean(r[1]) or "команда не указана"
        w(f"### Ответ {n}. Тема «{clean(r[0])}», спросила команда «{team}»")
        w("")
        w(f"> {clean(r[3])}")
        w("")
        if clean(r[5]) in NOANSWER:
            w(f"**Заказчик отвечать не стал**, в колонке ответа стоит «{clean(r[5])}».")
        else:
            w("**Заказчик ответил:**")
            w("")
            w(f"> {clean(r[5])}")
        w("")
    w("---")
    w("")
    w(f"# Часть 2. Сводные вопросы и ответы ({len(norm)} штук)")
    w("")
    w("Это первая вкладка файла. Колонка «Популярность» показывает, сколько команд")
    w("задали похожий вопрос. Помни про съехавшие строки: сверяй смысл ответа")
    w("с частью 1, а не с заголовком вопроса.")
    w("")
    for i, r in enumerate(norm, 1):
        w(
            f"### Сводный {i}. {clean(r[0])} (популярность {clean(r[1]).replace('.0', '')})"
        )
        w("")
        w(f"**Вопрос:** {clean(r[2])}")
        w("")
        w(f"**Ответ:** {clean(r[3]) or '— ответа нет —'}")
        w("")
    w("---")
    w("")
    w(f"# Часть 3. Наши вопросы, оставшиеся без ответа ({len(ours)} штук)")
    w("")
    w("Задавал Николай Тлехугов от команды «Скайнет». Числа в вопросах — по нашей")
    w("выгрузке от 09.09.2026, восемь журналов, 313 546 016 строк. Заказчик не ответил")
    w("ни на один из них: в колонке ответов пусто. Часть закрывается сводными ответами")
    w("косвенно, остальное остаётся нашим решением, и защищать его на приёмке нам.")
    w("")
    for i, r in enumerate(ours, 1):
        w(f"### Наш вопрос {i}")
        w("")
        w(f"> {clean(r[3])}")
        w("")
    w(
        f"# Часть 4. Вопросы, которые заказчик пометил знаком вопроса ({len(ignored)} штук)"
    )
    w("")
    w(
        "Он их прочитал и отвечать не стал. Для нас это значит: ответа не будет, решаем сами."
    )
    w("Полный текст каждого — в части 1 под его номером.")
    w("")
    for r in ignored:
        w(f"- «{clean(r[3])}» — команда «{clean(r[1]) or 'не указана'}»")
    w("")
    return "\n".join(L), len(replied), len(norm), len(ours)


if __name__ == "__main__":
    text, n_ans, n_norm, n_our = build()
    if "--check" in sys.argv:
        got = text.count("\n### Ответ ")
        assert got == n_ans, f"пар «вопрос — ответ» в документе {got}, в файле {n_ans}"
        got_norm = text.count("\n### Сводный ")
        assert got_norm == n_norm, f"сводных {got_norm}, в файле {n_norm}"
        got_our = text.count("\n### Наш вопрос ")
        assert got_our == n_our, f"наших вопросов {got_our}, в файле {n_our}"
        print(
            f"проверка прошла: ответов {n_ans}, сводных {n_norm}, наших вопросов {n_our}"
        )
    else:
        with open(OUT, "w") as fh:
            fh.write(text)
        print(
            f"записан {OUT}: ответов {n_ans}, сводных {n_norm}, наших вопросов {n_our}"
        )
