#!/usr/bin/env python3
"""Простой срок окупаемости (PP) проекта предиктивной диагностики.

Модель взята из файла En+ «2023-07-28_Цифровизация_экономические эффекты_VK1.xlsx»,
лист «ЕСЭ-ГГ_АСПД»: считаем среднегодовые затраты на аварийные ремонты и штрафы
за расчётный период, умножаем на коэффициент охвата (доля оборудования, покрытого
системой), вычитаем инвестиции — получаем денежный поток по годам.
"""


def payback(base_cost_per_year, coverage, capex):
    """base_cost_per_year — предотвращаемые затраты в год, млн руб.
    coverage — список долей охвата по годам (0..1), capex — инвестиции по годам.
    Возвращает (PP в годах или None, список накопленного потока)."""
    cum, flows, pp = 0.0, [], None
    for i, (k, inv) in enumerate(zip(coverage, capex)):
        flow = base_cost_per_year * k - inv
        prev = cum
        cum += flow
        flows.append(cum)
        if pp is None and prev < 0 <= cum:
            pp = i + prev / (prev - cum)  # доля года до пересечения нуля
    return pp, flows


if __name__ == "__main__":
    # АСПД гидроагрегатов Братской ГЭС: 3 аварии за 9 лет.
    # Ремонт: 60,7 + 4,1 + 4,1 млн, но по двум авариям в исходнике стоит пометка
    # «при работе АСПД затраты нельзя предотвратить» — в базу берём только 60,7.
    # Штрафы ОРЭМ 45 + 95 + 98 млн предотвращаются полностью.
    repair = 60.7 / 9                    # 6,744 млн руб./год
    fines = (45 + 95 + 98) / 9           # 26,444 млн руб./год
    base = repair + fines                # 33,189 млн руб./год
    assert round(base, 3) == 33.189, base

    # 18 гидроагрегатов, внедряем 1 / 5 / 6 / 6 штук; охват = накопленное/18
    installed, cover, total = [0, 1, 5, 6, 6, 0, 0, 0, 0, 0, 0], [], 0
    for n in installed:
        total += n
        cover.append(total / 18)
    capex = [23.4, 22.6, 24.0, 17.5] + [0.0] * 7

    pp, flows = payback(base, cover, capex)
    assert abs(pp - 5.581) < 0.01, pp          # в Excel PP = 5,58 года
    assert flows[0] == -23.4 and flows[4] < 0 < flows[5]
    print(f"Предотвращаемые затраты: {base:.2f} млн руб./год")
    print(f"Простой срок окупаемости: {pp:.2f} года")
    print("Накопленный поток по годам: " + ", ".join(f"{f:.1f}" for f in flows))
