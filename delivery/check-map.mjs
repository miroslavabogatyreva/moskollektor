#!/usr/bin/env node
// Экран «Карта объектов» глазами диспетчера — строка приёмки М-05.
//
// Зачем. До 22.09.2026 у М-05 машинной была только арифметика: масштаб оси
// (viewport.selfcheck.ts), цвет и плотность (risk.selfcheck.ts), сверка групп
// sections.json с деревом прогноза (code/check_model_and_objects.py). Вторую
// половину строки — «открыть раздел, узлы нарисованы, риск виден на самой схеме» —
// делал человек, и сводка печатала её РУЧНОЙ. Здесь она становится проверкой:
// браузер открывает /map со стенда и для КАЖДОГО коллектора из выпадающего
// списка считает то, что нарисовано.
//
// Что проверяется, по коллектору:
//   1. меток на оси столько же, сколько участков у коллектора в sections.json;
//   2. у каждой метки есть класс риска («класса нет» — провал: риск не виден);
//   3. никакие две метки не стоят в одной точке оси. Метка под меткой не видна
//      и не кликается, и приближение их не разлепит — пикет один и тот же.
//      Условие появилось на приёмке MOS-181: коллектор дерева собирает
//      несколько префиксов тега, и у их участков совпадают номера пикетов.
// И один раз на экран: клик по метке ведёт на /objects/{участок} и карточка
// называет тот же участок; консоль без ошибок и без исключений.
//
// Бандл и данные — со стенда: строку закрывает то, что отдано заказчику.
// Браузер свой (delivery/cdp.mjs), MCP-браузер для прогона не нужен.
//
// Запуск:
//     BASE_URL=https://135.106.216.101 node delivery/check-map.mjs
//     node delivery/check-map.mjs --selfcheck          # без браузера и сети
//
// Печатает строку «М-05 OK …» или «М-05 СБОЙ …» — её читает code/check_minimum.py.
// Код возврата 1 при СБОЕ.

import fs from 'node:fs'
import path from 'node:path'
import { свободныйПорт, поднятьПрокси, поднятьChrome, Вкладка } from './cdp.mjs'

const СТЕНД = new URL(process.env.BASE_URL || 'https://135.106.216.101')
const ЛОГИН = process.env.STAND_LOGIN || 'dispatcher1'
// DIST=frontend/dist — своя сборка вместо бандла стенда, данные /api со стенда.
// Для проверки правки до выкладки; строку М-05 закрывает только прогон без DIST.
const ДИСТ = process.env.DIST || ''

// ── вердикт: единственное место, где решается «красная или зелёная» ───────────
// коллекторы: [{ имя, ждём, меток, безКласса, совпавших, пример }]
// клик: { участок, путь, вКарточке } | null; ошибок: число ошибок консоли.
// зум: { до, после } — ширина окна каждой линии в пикетах до и после «+ приблизить».
export function вердикт({ коллекторы, клик, зум, ошибок }) {
  const беды = []
  if (коллекторы.length === 0) беды.push('в выпадающем списке 0 коллекторов')
  for (const к of коллекторы) {
    if (к.меток !== к.ждём) беды.push(`«${к.имя}»: меток ${к.меток}, участков ${к.ждём}`)
    if (к.безКласса) беды.push(`«${к.имя}»: без класса риска ${к.безКласса} меток`)
    if (к.совпавших)
      беды.push(`«${к.имя}»: ${к.совпавших} позиций, где метки стоят друг на друге (например ${к.пример})`)
  }
  if (!клик) беды.push('кликнуть не по чему')
  else if (клик.путь !== `/objects/${клик.участок}` || !клик.вКарточке)
    беды.push(`клик по участку ${клик.участок} увёл на ${клик.путь}, карточка его ${клик.вКарточке ? '' : 'не '}называет`)
  if (!зум) беды.push('зум: кнопки «+ приблизить» нет')
  else {
    if (!(зум.после[0] < зум.до[0])) беды.push(`зум: окно первой линии не сузилось (${зум.до[0]} -> ${зум.после[0]} пикетов)`)
    if (зум.после.slice(1).some((ш, i) => ш !== зум.до[i + 1])) беды.push('зум: сдвинулись окна чужих линий')
  }
  if (ошибок) беды.push(`ошибок в консоли ${ошибок}`)
  return беды
}

function самопроверка() {
  const к = { имя: 'объект Гамма', ждём: 400, меток: 400, безКласса: 0, совпавших: 0, пример: '' }
  const целое = { коллекторы: [к], клик: { участок: 420, путь: '/objects/420', вКарточке: true },
    зум: { до: [106, 60], после: [53, 60] }, ошибок: 0 }
  const проба = [
    ['целое состояние', целое, 0],
    ['метки друг на друге (MOS-181)', { ...целое, коллекторы: [{ ...к, совпавших: 62, пример: '1044:0 и 1051:0' }] }, 1],
    ['меток меньше участков', { ...целое, коллекторы: [{ ...к, меток: 399 }] }, 1],
    ['риск не виден', { ...целое, коллекторы: [{ ...к, безКласса: 3 }] }, 1],
    ['клик увёл не туда', { ...целое, клик: { участок: 420, путь: '/map', вКарточке: false } }, 1],
    ['карточка чужого участка', { ...целое, клик: { участок: 420, путь: '/objects/420', вКарточке: false } }, 1],
    ['ошибка в консоли', { ...целое, ошибок: 1 }, 1],
    ['список пуст', { ...целое, коллекторы: [] }, 1],
    ['зум не сузил окно', { ...целое, зум: { до: [106, 60], после: [106, 60] } }, 1],
    ['зум сдвинул чужую линию', { ...целое, зум: { до: [106, 60], после: [53, 30] } }, 1],
    ['кнопки зума нет', { ...целое, зум: null }, 1],
  ]
  let плохо = 0
  for (const [имя, з, ждём] of проба) {
    const было = вердикт(з).length
    if (было !== ждём) плохо++
    console.log(`  ${(было === ждём ? 'OK' : 'СБОЙ').padEnd(6)} ${имя.padEnd(34)} бед ${было}, ждали ${ждём}`)
  }
  console.log(плохо ? `самопроверка: ${плохо} расхождений` : 'самопроверка вердикта: проблем нет')
  return плохо
}

if (process.argv.includes('--selfcheck')) process.exit(самопроверка() ? 1 : 0)

// ── замер в браузере ─────────────────────────────────────────────────────────
const ждать = (мс) => new Promise((о) => setTimeout(о, мс))

// Выпадающий список коллекторов — тот, что под подписью «Коллектор». На экране
// есть ещё списки фильтров (MapFilters.tsx), и голый 'select option' брал их все.
const СПИСОК = `[...document.querySelectorAll('label')]
  .find(l => l.textContent.trim().startsWith('Коллектор')).querySelector('select')`

// Метки оси: <g> со значком или густой <rect>-чип, у обоих внутри <title>
// «Коллектор П, пикет К · участок N · класс риска» (MOS-243). Центр берём у самого элемента.
const МЕТКИ = `
  return [...document.querySelectorAll('svg[role="img"] [style*="cursor"]')].map(e => {
    const t = e.querySelector('title')?.textContent || ''
    const r = e.getBoundingClientRect()
    const x = +(r.x + r.width / 2).toFixed(2), y = +(r.y + r.height / 2).toFixed(2)
    const сверху = document.elementFromPoint(x, y)
    return { t, x, y, участок: +(t.match(/участок (\\d+)/) || [])[1],
             достаётся: сверху === e || e.contains(сверху) }
  })`

async function замер(в, порт) {
  await в.перейти(`http://127.0.0.1:${порт}/map`)
  for (let i = 0; i < 100 && !(await в.считать(
    `return document.querySelectorAll('svg[role="img"] [style*="cursor"]').length > 0`)); i++) await ждать(100)
  // Риск приходит отдельным запросом /api/risks: пока его нет, все метки
  // «класса нет», и проверка краснела бы от спешки, а не от экрана.
  for (let i = 0; i < 300 && !(await в.считать(`return performance.getEntriesByType('resource')
    .some(e => e.name.includes('/api/risks') && e.responseEnd > 0)`)); i++) await ждать(100)
  await ждать(300)
  const участки = await в.считать(`return (await (await fetch('/data/sections.json')).json())`)
  const варианты = await в.считать(`return [...${СПИСОК}.options].map(o => ({ v: o.value, имя: o.textContent }))`)

  const коллекторы = []
  for (const { v, имя } of варианты) {
    await в.считать(`const s = ${СПИСОК}; s.value = ${JSON.stringify(v)};
      s.dispatchEvent(new Event('change', { bubbles: true })); return 1`)
    const ждём = участки.filter((s) => String(s.collector) === v).length
    let метки = []
    for (let i = 0; i < 50; i++) {
      метки = await в.считать(МЕТКИ)
      if (метки.length === ждём) break
      await ждать(100)
    }
    const поМесту = new Map()
    for (const м of метки) {
      const ключ = `${м.x}:${м.y}`
      поМесту.set(ключ, [...(поМесту.get(ключ) || []), м.t.split(' · ')[0]])
    }
    const совпали = [...поМесту.values()].filter((с) => с.length > 1)
    коллекторы.push({
      имя: имя.split(' · ')[0], ждём, меток: метки.length,
      безКласса: метки.filter((м) => м.t.endsWith('класса нет')).length,
      совпавших: совпали.length, пример: совпали[0]?.join(' и ') || '',
    })
  }

  // Масштаб — единственное, что заказчик потребовал от схемы 19.09.2026. Жмём
  // «+ приблизить» у первой линии настоящей мышью: её окно обязано сузиться,
  // окна остальных линий коллектора — остаться как были.
  const ОКНА = `return [...document.querySelectorAll('svg[role="img"]')].map(e => {
    const m = (e.getAttribute('aria-label') || '').match(/ПК(\\d+)–ПК(\\d+)/)
    return m ? +m[2] - +m[1] : null })`
  // Зумим там, где линий больше всего: на коллекторе с одной линией условие
  // «чужие окна не сдвинулись» ничего не проверяет. На master линия всегда одна.
  const префиксов = new Map()
  for (const s of участки) префиксов.set(String(s.collector),
    (префиксов.get(String(s.collector)) || new Set()).add(s.smvu_key.split(':')[0]))
  const [многолинейный] = [...префиксов.entries()].sort((x, y) => y[1].size - x[1].size)[0]
  await в.считать(`const s = ${СПИСОК}; s.value = ${JSON.stringify(многолинейный)};
    s.dispatchEvent(new Event('change', { bubbles: true })); return 1`)
  await ждать(500)
  const кнопка = await в.считать(`const b = [...document.querySelectorAll('button')]
      .find(b => b.textContent.includes('приблизить') && !b.disabled)
    if (!b) return null
    const r = b.getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 }`)
  let зум = null
  if (кнопка) {
    const до = await в.считать(ОКНА)
    for (const type of ['mousePressed', 'mouseReleased'])
      await в.команда('Input.dispatchMouseEvent', { type, ...кнопка, button: 'left', clickCount: 1 })
    await ждать(300)
    зум = { до, после: await в.считать(ОКНА) }
  }

  // Клик настоящей мышью по первой метке последнего коллектора, которую мышь
  // достаёт. На полной густой оси чипы соседних пикетов налезают друг на друга
  // (у «объекта Кси» 303 метки): центр 1727 закрыт чипом 1728, и клик честно
  // открывал 1728. Это плотность, её разводит зум (MOS-126), а не дефект перехода.
  const м = (await в.считать(МЕТКИ)).find((м) => м.достаётся)
  let клик = null
  if (м) {
    for (const type of ['mousePressed', 'mouseReleased'])
      await в.команда('Input.dispatchMouseEvent', { type, x: м.x, y: м.y, button: 'left', clickCount: 1 })
    let путь = ''
    let вКарточке = false
    for (let i = 0; i < 100; i++) {
      путь = await в.считать('return location.pathname')
      вКарточке = await в.считать(`return document.body.innerText.includes('Участок ${м.участок}')`)
      if (вКарточке) break
      await ждать(100)
    }
    клик = { участок: м.участок, путь, вКарточке }
  }
  const ошибок = в.события.filter((с) => с.method === 'Runtime.exceptionThrown'
    || (с.method === 'Runtime.consoleAPICalled' && с.params.type === 'error')).length
  return { коллекторы, клик, зум, ошибок }
}

const порт = await свободныйПорт()
const отладка = await свободныйПорт()
const профиль = fs.mkdtempSync(path.join(process.env.TMPDIR || '/tmp', 'map-chrome-'))
const сервер = await поднятьПрокси(порт, { бандл: ДИСТ ? 'local' : 'stand', дист: ДИСТ, стенд: СТЕНД, логин: ЛОГИН })
const chrome = await поднятьChrome(отладка, профиль)
let з
try {
  з = await замер(await Вкладка.открыть(отладка), порт)
} finally {
  // Уборка не роняет проверку (разбор — в check-a11y.mjs).
  chrome.kill()
  await new Promise((о) => { chrome.once('exit', о); setTimeout(о, 3000) })
  сервер.close()
  try { fs.rmSync(профиль, { recursive: true, force: true }) } catch {}
}

const беды = вердикт(з)
const меток = з.коллекторы.reduce((a, к) => a + к.меток, 0)
const суть = `${ДИСТ ? `сборка ${ДИСТ}, данные ` : ''}${СТЕНД.origin}/map: коллекторов в списке ${з.коллекторы.length}, меток ${меток}, `
  + `клик по участку ${з.клик?.участок} -> ${з.клик?.путь}, `
  + `зум первой линии ${з.зум?.до[0]} -> ${з.зум?.после[0]} пикетов (линий ${з.зум?.до.length}), ошибок консоли ${з.ошибок}`
console.log(беды.length ? `М-05 СБОЙ ${суть}; ${беды.join('; ')}` : `М-05 OK ${суть}; у всех меток есть класс риска, метки не перекрываются`)
process.exit(беды.length ? 1 : 0)
