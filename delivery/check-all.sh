# run <строки приёмки> <название> <команда...>
run() {
  rows="$1"; name="$2"; shift 2
  out=$("$@" 2>&1)
  code=$?
  if [ $code -eq 0 ]; then
    printf 'OK    %-14s %s\n' "$rows" "$name"
    # Жёлтые строки печатаем и при успехе. Проверка может пройти целиком и при
    # этом сказать «проверять пока нечем» про одно из своих условий — так ведёт
    # себя «Ф-93 фильтры», пока MOS-122 не выложена. Без этой строки такое
    # предупреждение видно только когда скрипт упал по другой причине, то есть
    # ровно тогда, когда его уже никто не читает.
    printf '%s\n' "$out" | grep -F 'ВНИМАНИЕ' | sed 's/^/        /'
    ok=$((ok + 1))
  elif [ $code -eq 2 ] && printf '%s\n' "$out" | grep -q '^М-[0-9]* ОТКРЫТА '; then
    # Код 2 — строки приёмки не закрыты, но у каждой есть задача (check_minimum.py).
    # Не OK и не УПАЛА: в «успешно» не идёт и прогон не валит. Код 2 без строк
    # ОТКРЫТА — обычное падение: argparse тоже выходит с кодом 2.
    printf 'ОТКРЫТА %-12s %s\n' "$rows" "$name"
    printf '%s\n' "$out" | grep -E '^М-[0-9]+ ОТКРЫТА ' | cut -c1-160 | sed 's/^/        /'
    opened=$((opened + 1))
  else
    printf 'УПАЛА %-14s %s\n' "$rows" "$name"
    printf '%s\n' "$out" | tail -5 | sed 's/^/        /'
    fail=$((fail + 1))
    failed_list="$failed_list $name"
  fi
}

# Два пропуска разной природы, и складывать их в одно число нельзя.
# skip_msg — пропуск, который чинит человек: не задана переменная, не поставлены
# зависимости, нет доступа к докеру. Прогон на настроенной машине обязан дать здесь ноль.
# skip_state_msg — пропуск, который человек не чинит: данные на стенде прямо сейчас
# в таком состоянии, что проверять нечего, и через четыре минуты состояние другое.
# Разбор 22.09.2026: строка «направление/объяснение через API» у трёх прогонов подряд
# дала ПРОПУСК, ПРОПУСК и OK, и по числу «пропущено 3» было не понять, чего не хватило —
# переменной или удачи. Теперь итог печатает оба числа порознь.
skip_msg() {
  printf 'ПРОПУСК %-12s %s\n' "$1" "$2"
  skip=$((skip + 1))
}

skip_state_msg() {
  printf 'ПРОПУСК %-12s %s\n' "$1" "$2"
  skip_state=$((skip_state + 1))
}

