failed_list=""

# run <строки приёмки> <название> <команда...>
run() {
  rows="$1"; name="$2"; shift 2
  out=$("$@" 2>&1)
  code=$?
  if [ $code -eq 0 ]; then
    printf 'OK    %-14s %s\n' "$rows" "$name"
    ok=$((ok + 1))
  else
    printf 'УПАЛА %-14s %s\n' "$rows" "$name"
    printf '%s\n' "$out" | tail -5 | sed 's/^/        /'
    fail=$((fail + 1))
    failed_list="$failed_list $name"
  fi
}

skip_msg() {
  printf 'ПРОПУСК %-12s %s\n' "$1" "$2"
  skip=$((skip + 1))
}

