"""Эпизоды по словарю модели v3 — эталон `эпизоды()` без базы.

Значения — строки журнала СМВУ дословно (docs/day-one.md, таблица значений):
в них вся суть правки, и опечатка в одной букве дала бы ноль эпизодов молча.
Запуск из корня репозитория: `python3 -m pytest backend/tests`.
"""
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.ingest.model_failure_episodes import эпизоды  # noqa: E402

СЛОВАРЬ = {"Неисправен", "Батарея неисправна", "Много неисправных устройств", "Не определено"}
ЧАС = 3600
Т0 = datetime(2026, 4, 10, 9, 0, tzinfo=timezone.utc)
КОНЕЦ = datetime(2026, 6, 30, 20, 59, 59, tzinfo=timezone.utc)


def м(минут):
    return Т0 + timedelta(minutes=минут)


def test_разные_значения_словаря_подряд_один_эпизод():
    записи = [(м(0), 1, "Батарея неисправна"), (м(40), 2, "Неисправен"),
              (м(90), 3, "Много неисправных устройств"), (м(120), 4, "Норма")]
    итог = эпизоды(записи, СЛОВАРЬ, КОНЕЦ, ЧАС)
    assert len(итог) == 1
    э = итог[0]
    assert (э["started_at"], э["ended_at"], э["rows_cnt"]) == (м(0), м(120), 3)
    assert (э["fault_value"], э["closed_by"]) == ("Батарея неисправна", "Норма")


def test_неопределен_закрывает_эпизод_а_не_определено_продолжает():
    # «Неопределен» — экранное значение температурных датчиков, в словарь модели
    # не входит; «Не определено» — входит. Разница в двух буквах.
    закрыт = эпизоды([(м(0), 1, "Неисправен"), (м(30), 2, "Неопределен"),
                      (м(200), 3, "Норма")], СЛОВАРЬ, КОНЕЦ, ЧАС)
    assert закрыт == []  # 30 минут — короче порога
    продолжен = эпизоды([(м(0), 1, "Неисправен"), (м(30), 2, "Не определено"),
                         (м(200), 3, "Норма")], СЛОВАРЬ, КОНЕЦ, ЧАС)
    assert [(э["ended_at"], э["rows_cnt"]) for э in продолжен] == [(м(200), 2)]


def test_порог_строгий():
    ровно_час = [(м(0), 1, "Неисправен"), (м(60), 2, "Норма")]
    assert эпизоды(ровно_час, СЛОВАРЬ, КОНЕЦ, ЧАС) == []
    на_секунду_дольше = [(м(0), 1, "Неисправен"), (м(60) + timedelta(seconds=1), 2, "Норма")]
    assert len(эпизоды(на_секунду_дольше, СЛОВАРЬ, КОНЕЦ, ЧАС)) == 1


def test_незакрытый_мерится_до_конца_архива():
    поздний = [(КОНЕЦ - timedelta(minutes=30), 1, "Много неисправных устройств")]
    assert эпизоды(поздний, СЛОВАРЬ, КОНЕЦ, ЧАС) == []
    ранний = [(КОНЕЦ - timedelta(hours=2), 1, "Много неисправных устройств")]
    итог = эпизоды(ранний, СЛОВАРЬ, КОНЕЦ, ЧАС)
    assert [(э["ended_at"], э["closed_by"]) for э in итог] == [(None, None)]


def test_порядок_по_времени_и_номеру_записи_а_не_по_входу():
    # Файлы заказчика по времени не отсортированы; в одну секунду порядок
    # решает journal_id, как в ORDER BY read_time, journal_id.
    записи = [(м(120), 5, "Норма"), (м(0), 2, "Норма"), (м(0), 3, "Неисправен"),
              (м(0), 1, "Норма")]
    итог = эпизоды(записи, СЛОВАРЬ, КОНЕЦ, ЧАС)
    assert [(э["started_at"], э["ended_at"], э["rows_cnt"]) for э in итог] == [
        (м(0), м(120), 1)]


def test_два_эпизода_канала_не_склеиваются_через_норму():
    записи = [(м(0), 1, "Неисправен"), (м(70), 2, "Норма"),
              (м(75), 3, "Неисправен"), (м(200), 4, "Устройства на объекте исправны")]
    итог = эпизоды(записи, СЛОВАРЬ, КОНЕЦ, ЧАС)
    assert [э["started_at"] for э in итог] == [м(0), м(75)]
    assert итог[1]["closed_by"] == "Устройства на объекте исправны"
