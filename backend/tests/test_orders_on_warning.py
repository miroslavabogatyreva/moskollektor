"""Заявка по открытию предупреждения модели v3 (MOS-145, MOS-180, MOS-179).

Значения — из живого score.json на стенде 22.09.2026: у коллектора 12 предупреждение
открыто у префикса 889 (10.06.2026 08:36:56, окно до 10.07.2026 08:36:56), а по
вероятности побеждает 890 без предупреждения. Путь через базу — прогон worker
на стенде с откатом, разбор в docs/order-rules.md; здесь чистые функции.
"""
from datetime import timedelta

from app.domain.order_rules import (момент_файла, срок, заявки_по_предупреждениям,
                                    обоснование)
from app.worker.publish import ПОЛИТИКА_ПО_УМОЛЧАНИЮ, причина_записи
from app.worker.score_v3 import по_коллекторам, предупреждения


def _файл(*строки):
    поля = ("pfx", "p", "warning_open", "warning_opened_at", "warning_expires_at")
    return {"collectors": [dict(zip(поля, r)) | {"features": []} for r in строки]}


ЖИВОЙ = _файл(("889", 0.495, True, "2026-06-10T08:36:56", "2026-07-10T08:36:56"),
              ("890", 0.564, False, None, None),
              ("15", 0.444, True, None, None))


def test_флаг_предупреждения_не_теряется_у_проигравшего_префикса():
    по = по_коллекторам(ЖИВОЙ, {"889": 12, "890": 12, "15": 7})
    assert по[12]["p"] == 0.564
    assert по[12]["warning_open"] is True


def test_предупреждения_по_префиксам_а_не_по_коллекторам():
    открытые, без_момента = предупреждения(ЖИВОЙ)
    assert открытые == [{"pfx": "889", "opened_at": "2026-06-10T08:36:56",
                         "expires_at": "2026-07-10T08:36:56", "p": 0.495}]
    assert без_момента == ["15"]


def test_два_префикса_одного_коллектора_дают_два_набора_заявок():
    # Раньше ключ был по коллектору дерева и позднейшему открытию: второе
    # предупреждение того же коллектора склеивалось с первым.
    пр = [{"pfx": "889", "opened_at": "2026-06-10T08:36:56", "p": 0.495,
           "участки": [(2477, "889:1")]},
          {"pfx": "890", "opened_at": "2026-06-20T10:00:00", "p": 0.564,
           "участки": [(2600, "890:4")]}]
    план, _ = заявки_по_предупреждениям(пр, {2477, 2600}, {}, 3)
    assert {з["ключ"] for з in план.values()} == {
        "warn:889:2026-06-10T08:36:56:2477", "warn:890:2026-06-20T10:00:00:2600"}


def test_повторное_открытие_в_те_же_сутки_даёт_новый_ключ():
    утро = [{"pfx": "889", "opened_at": "2026-06-10T08:36:56", "p": 0.5,
             "участки": [(2477, "889:1")]}]
    вечер = [{**утро[0], "opened_at": "2026-06-10T20:00:00"}]
    а, _ = заявки_по_предупреждениям(утро, {2477}, {}, 3)
    б, _ = заявки_по_предупреждениям(вечер, {2477}, {}, 3)
    assert а[2477]["ключ"] != б[2477]["ключ"]


def test_срок_от_открытия_плюс_норматив_а_не_от_конца_окна():
    открыто = момент_файла("2026-06-10T08:36:56")
    assert срок(открыто, 16) - открыто == timedelta(hours=16)
    # Старая формула на горизонте 720: as_of + 720 − 12 = 708 ч после среза.
    assert срок(открыто, 16) - открыто != timedelta(hours=708)


def test_мёртвая_зона_не_глушит_участок_под_новым_предупреждением():
    п = dict(ПОЛИТИКА_ПО_УМОЛЧАНИЮ)
    t0 = момент_файла("2026-06-30T23:59:59")
    было = {"logged_probability": 0.80, "logged_at": t0, "risk_class": "high",
            "risk_class_since": t0}
    # p держится на 0,80: без предупреждения строки нет, с ним — есть.
    assert причина_записи(0.80, "high", было, t0, п) is None
    assert причина_записи(0.80, "high", было, t0, п, обязательно=True) == "warning"


def test_обоснование_берёт_число_префикса_и_маршрут():
    пр = [{"pfx": "889", "opened_at": "2026-06-10T08:36:56",
           "expires_at": "2026-07-10T08:36:56", "p": 0.495,
           "участки": [(2477, "889:1"), (2478, "889:2")]}]
    план, _ = заявки_по_предупреждениям(пр, {2477, 2478}, {2478: (12, 0.9)}, 3)
    т = обоснование(0.564, 720, "A", None, план[2477])
    assert "0.495" in т and "0.564" not in т
    assert "10.06.2026 08:36" in т and "10.07.2026 08:36" in т
    assert "889:2, 889:1" in т   # тяжёлый по весу — первым
