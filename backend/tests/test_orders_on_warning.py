"""Заявка по открытию предупреждения модели v3, а не по суточному порогу (MOS-145).

Значения — из живого score.json 22.09.2026 (MOS-145, комментарий 14516): у коллектора 12
предупреждение открыто у префикса 889, а по вероятности побеждает 890 без предупреждения.
"""
from app.domain.order_rules import по_предупреждениям
from app.worker.run_v3 import ключи_предупреждений
from app.worker.score_v3 import по_коллекторам


def _файл(*строки):
    return {"collectors": [dict(zip(("pfx", "p", "warning_open", "warning_opened_at"), r))
                           | {"features": []} for r in строки]}


def test_момент_открытия_берётся_у_префикса_с_предупреждением():
    данные = _файл(("889", 0.30, True, "2026-06-12T08:00:00"),
                   ("890", 0.5643, False, None))
    по = по_коллекторам(данные, {"889": 12, "890": 12})
    assert по[12]["p"] == 0.5643
    assert по[12]["warning_open"] is True
    assert по[12]["warning_opened_at"] == "2026-06-12T08:00:00"


def test_у_двух_открытых_префиксов_берётся_позднее_открытие():
    данные = _файл(("163", 0.7, True, "2026-06-01T10:00:00"),
                   ("164", 0.6, True, "2026-06-20T10:00:00"))
    по = по_коллекторам(данные, {"163": 4356, "164": 4356})
    assert по[4356]["warning_opened_at"] == "2026-06-20T10:00:00"


def test_ключи_только_у_коллекторов_под_предупреждением():
    по = {12: {"warning_open": True, "warning_opened_at": "2026-06-12T08:00:00"},
          6: {"warning_open": False, "warning_opened_at": None},
          15: {"warning_open": True, "warning_opened_at": None}}
    ключи, без_момента = ключи_предупреждений(по, {12: [1490, 1491], 6: [7], 15: [9]})
    assert ключи == {1490: "warn:12:2026-06-12T08:00:00",
                     1491: "warn:12:2026-06-12T08:00:00"}
    assert без_момента == [15]


def test_заявка_один_раз_на_предупреждение_и_без_порога():
    ключи = {1490: "warn:12:2026-06-12T08:00:00", 7: "warn:6:2026-06-20T10:00:00"}
    кандидаты = [{"section_id": 1490, "probability": 0.30},   # ниже 0,63 — всё равно берём
                 {"section_id": 7, "probability": 0.87},
                 {"section_id": 3, "probability": 0.99}]      # без предупреждения — нет
    assert [к["section_id"] for к in по_предупреждениям(кандидаты, ключи, set())] == [1490, 7]
    # По предупреждению коллектора 12 заявки уже лежат — повтора нет
    уже = {"warn:12:2026-06-12T08:00:00"}
    assert [к["section_id"] for к in по_предупреждениям(кандидаты, ключи, уже)] == [7]
