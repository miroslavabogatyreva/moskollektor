"""Сироты `pred.run` после kill посреди расчёта (MOS-183): контракт `закрыть_оборванные()`.

Перезапуск контейнера `worker` убивает процесс вместе с `finally` в `прогон()`
— строка `pred.run` остаётся со `status='running'` навсегда. Так остался прогон
669 от 22.09.2026: его оборвала выкладка MOS-180 в 20:36. `закрыть_оборванные()`
закрывает все running разом, потому что держит `БЛОКИРОВКА` (48217): пока она у
нас, живого прогона не существует и любая running-строка — сирота.

Базы нет, как и везде в backend/tests: соединение — заглушка в духе
`code/check_runtime._Заглушка`, которая пишет вызовы и отдаёт заготовленные
ответы. Проверяем контракт, а не SQL-движок: кто берёт блокировку, что и с каким
аргументом пишет, и что блокировка снимается всегда — даже когда CTE падает.
Корутины гоняем через `asyncio.run` внутри обычных тестов: `pytest-asyncio`
в проекте нет.
"""
import asyncio

import pytest
from app.worker.run import БЛОКИРОВКА, ПРИЧИНА_ОБРЫВА, закрыть_оборванные


class _Заглушка:
    """Asyncpg-подобное соединение: пишет вызовы, отдаёт заготовленные ответы.

    Очередь отдаётся по порядку вызовов `fetchval`; исключение в очереди
    бросается вместо ответа — так проверяем `finally` при падении CTE.
    """

    def __init__(self, *ответы):
        self.ответы = list(ответы)
        self.вызовы = []

    async def fetchval(self, запрос, *арг):
        self.вызовы.append((запрос, арг))
        assert self.ответы, f"заглушке не хватило ответов на {запрос[:60]!r}"
        ответ = self.ответы.pop(0)
        if isinstance(ответ, BaseException):
            raise ответ
        return ответ


def _вызовы(заглушка, подстрока):
    """Все вызовы fetchval, чей запрос содержит подстроку."""
    return [(з, арг) for з, арг in заглушка.вызовы if подстрока in з]


def test_трое_сирот_закрываются_счётчиком_и_блокировка_снимается():
    соединение = _Заглушка(True, 3, True)
    assert asyncio.run(закрыть_оборванные(соединение)) == {"закрыто": 3}

    # CTE выполняется ровно один раз; fetchval(SQL, ПРИЧИНА_ОБРЫВА): SQL —
    # первый аргумент, причина — второй.
    обновления = _вызовы(соединение, "UPDATE pred.run")
    assert len(обновления) == 1, "закрытие сирот — один CTE-запрос"
    assert обновления[0][1] == (ПРИЧИНА_ОБРЫВА,)

    снятия = _вызовы(соединение, "pg_advisory_unlock")
    assert len(снятия) == 1
    assert снятия[0][1] == (БЛОКИРОВКА,)
    assert БЛОКИРОВКА == 48217


def test_занятая_блокировка_не_трогает_ни_сирот_ни_чужую_блокировку():
    # pg_try_advisory_lock вернул False — идёт настоящий расчёт.
    соединение = _Заглушка(False)
    assert asyncio.run(закрыть_оборванные(соединение)) == {"занято": True}

    assert not _вызовы(соединение, "UPDATE"), "чужой расчёт закрывать нельзя"
    assert not _вызовы(соединение, "pg_advisory_unlock"), (
        "чужую блокировку снимать нельзя")
    assert len(соединение.вызовы) == 1, "кроме попытки взять блокировку — ничего"


def test_сирот_нет_счётчик_ноль_но_блокировка_снимается():
    соединение = _Заглушка(True, 0, True)
    assert asyncio.run(закрыть_оборванные(соединение)) == {"закрыто": 0}
    assert _вызовы(соединение, "pg_advisory_unlock"), (
        "ноль сирот — не повод оставить блокировку себе")


def test_падение_cte_всё_равно_снимает_блокировку():
    # Снятие живёт в finally: исключение всплывает, блокировка — нет.
    соединение = _Заглушка(True, RuntimeError("база отвалилась"), True)
    with pytest.raises(RuntimeError, match="база отвалилась"):
        asyncio.run(закрыть_оборванные(соединение))

    снятия = _вызовы(соединение, "pg_advisory_unlock")
    assert len(снятия) == 1, "снятие блокировки — в finally"
    assert снятия[0][1] == (БЛОКИРОВКА,)


def test_причина_оборван_перезапуском_дословно():
    # Приёмка ищет эту формулировку в pred.run.error_text — дословно.
    assert ПРИЧИНА_ОБРЫВА == "оборван перезапуском"

    соединение = _Заглушка(True, 1, True)
    asyncio.run(закрыть_оборванные(соединение))
    обновления = _вызовы(соединение, "UPDATE pred.run")
    assert обновления[0][1] == ("оборван перезапуском",), (
        "в error_text уходит ровно эта формулировка")


def test_sql_закрывает_только_сирот():
    соединение = _Заглушка(True, 1, True)
    asyncio.run(закрыть_оборванные(соединение))
    обновления = _вызовы(соединение, "UPDATE pred.run")
    # Переносы строк в CTE не должны мешать искать куски запроса.
    sql = " ".join(обновления[0][0].split())

    assert "SET status = 'failed'" in sql
    assert "finished_at = now()" in sql
    assert "error_text" in sql
    assert "WHERE status = 'running'" in sql, (
        "закрываем только сирот, а не строки всех статусов")
