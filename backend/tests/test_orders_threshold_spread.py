"""Q6.10, MOS-154: порог заявки — к вероятности объекта, участок — по наибольшей доле.

Прежний путь заявок (порог по вероятности, без предупреждений модели) после разноса
(`forecast_spread_enabled`, задача 3.16) видит у участка ДОЛЮ вероятности объекта.
Потолок доли при alpha = 1: 0,0278 у объекта Мю (521 участок), 0,3051 у Сигмы
(9 участков) — даже наибольший втрое ниже самого низкого порога 0,97. Ни одна
заявка не заведётся, и молча. Поэтому при включённом разносе порог сравниваем
с вероятностью объекта (сумма долей его участков), а заявку ставим на участок
с наибольшей долей — одну на объект.
"""
from app.domain.order_rules import обоснование, пороговый_отбор

ПОРОГИ = {"A": 0.97, "B": 0.98, "C": 0.99}


def _к(sid, p, crit="A"):
    return {"section_id": sid, "probability": p, "crit": crit}


# Объект 7 с вероятностью 0,99, разнесённой по трём участкам: 0,6 / 0,3 / 0,09.
ВЕСА = {1: (7, 0.6), 2: (7, 0.3), 3: (7, 0.09)}
РАЗНЕСЕНО = [_к(1, 0.6), _к(2, 0.3), _к(3, 0.09)]


def test_без_разноса_порог_по_участку_как_было():
    отбор = пороговый_отбор([_к(1, 0.975), _к(2, 0.5)], ПОРОГИ, {})
    assert [к["section_id"] for к in отбор] == [1]
    assert "p_объекта" not in отбор[0]


def test_с_разносом_порог_к_объекту_и_один_участок_с_наибольшей_долей():
    отбор = пороговый_отбор(РАЗНЕСЕНО, ПОРОГИ, ВЕСА)
    # По участкам ни один не выше 0,97, по объекту 0,99 > 0,97 — одна заявка.
    assert [к["section_id"] for к in отбор] == [1]
    assert abs(отбор[0]["p_объекта"] - 0.99) < 1e-9


def test_с_разносом_объект_ниже_порога_заявки_не_даёт():
    низко = [_к(1, 0.5), _к(2, 0.3), _к(3, 0.1)]      # объект 0,9 < 0,97
    assert пороговый_отбор(низко, ПОРОГИ, ВЕСА) == []


def test_участок_без_веса_судится_сам_по_себе():
    отбор = пороговый_отбор(РАЗНЕСЕНО + [_к(99, 0.98)], ПОРОГИ, ВЕСА)
    assert sorted(к["section_id"] for к in отбор) == [1, 99]


def test_обоснование_называет_оба_числа_раздельно():
    к = пороговый_отбор(РАЗНЕСЕНО, ПОРОГИ, ВЕСА)[0]
    т = обоснование(к["probability"], 24, "A", None, объект=к["p_объекта"])
    assert "по объекту — 0.990" in т and "доля участка — 0.600" in т, т
