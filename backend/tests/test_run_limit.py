"""`--limit` на пути модели v3 (MOS-168): срез участков и запрет заявок.

Прогон 501 на стенде при `--limit` посчитал все 3 173 участка и завёл 18 заявок:
на пути v3 флаг до правки не делал ничего. Тесты держат обе половины правки.

Входы структурные, не числа модели: `урезать()` не смотрит на значения, только
на порядок section_id, а выравнивание трёх списков проверяем тем, что каждый
элемент несёт свой участок. Участок 1490 — настоящий, «798:0» из шапки run_v3.py:
он висит на двух коллекторах, и его выдача идёт не по порядку section_id.
"""
import pytest

from app.worker.run_v3 import урезать, заявки_разрешены


def _выдача(участки):
    """Три списка в порядке выдачи run_v3.собрать: по коллекторам, не по id."""
    return (list(участки), [f"p{s}" for s in участки], [[{"f": f"f{s}"}] for s in участки])


def test_урезать_берёт_первые_по_section_id_и_держит_выравнивание():
    # Порядок выдачи — по коллекторам, поэтому id идут вразнобой.
    участки, вер, ф = урезать(*_выдача([1490, 7, 3000, 12, 1]), 3)
    assert участки == [1, 7, 12]
    assert вер == ["p1", "p7", "p12"]
    assert ф == [[{"f": "f1"}], [{"f": "f7"}], [{"f": "f12"}]]


def test_урезать_детерминирован_при_любом_порядке_входа():
    а = урезать(*_выдача([1490, 7, 3000, 12, 1]), 2)
    б = урезать(*_выдача([1, 12, 3000, 7, 1490]), 2)
    assert а == б


@pytest.mark.parametrize("предел", [None, 5, 50])
def test_урезать_без_предела_или_с_большим_пределом_не_трогает_выдачу(предел):
    вход = _выдача([1490, 7, 3000, 12, 1])
    assert урезать(*вход, предел) == вход


@pytest.mark.parametrize("предел", [0, -1])
def test_урезать_отвергает_пустой_предел(предел):
    with pytest.raises(ValueError):
        урезать(*_выдача([1490, 7]), предел)


def test_заявки_только_на_полном_прогоне_или_с_откатом():
    assert заявки_разрешены(None, False)          # плановый прогон
    assert заявки_разрешены(None, True)
    assert заявки_разрешены(50, True)             # проверка стадии, всё откатится
    assert not заявки_разрешены(50, False)        # кусок парка — настоящих заявок нет
