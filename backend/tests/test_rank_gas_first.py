"""US-01 сц. 3 «При равном риске важнее газ» (docs/user-stories.md).

Порядок систем назвал заказчик, ответ 5: «Газовые, пожарные, охранные, и далее
по нисходящему рангу». Ранг участка ставит расчёт (publish.ранги), дашборд
только сортирует по нему — поэтому проверяем расчёт.
"""
from app.worker import publish


def test_equal_probability_gas_above_security():
    # Участок 0 — охранный, участок 1 — газовый, вероятность одна.
    важность = [publish.важность_системы("Охранная подсистема"),
                publish.важность_системы("Газовая охрана")]
    assert publish.ранги([0.5, 0.5], важность) == [2, 1]


def test_order_gas_fire_security_other():
    системы = ["Температурная подсистема", "Охранная подсистема",
               "Пожарная охрана", "Газовая охрана", None]
    важность = [publish.важность_системы(s) for s in системы]
    assert publish.ранги([0.3] * 5, важность) == [4, 3, 2, 1, 5]


def test_probability_still_wins_over_system():
    важность = [publish.важность_системы("Газовая охрана"),
                publish.важность_системы("Охранная подсистема")]
    assert publish.ранги([0.4, 0.6], важность) == [2, 1]


def test_without_systems_order_by_section_as_before():
    assert publish.ранги([0.5, 0.5, 0.5]) == [1, 2, 3]
