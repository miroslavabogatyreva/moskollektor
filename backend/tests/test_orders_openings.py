"""Заявки по открытиям предупреждений: MOS-182 (Q6.13) и MOS-184 (Q6.14).

MOS-182 — worker читает не только `collectors[].warning_open`, но и список всех
открытий `alerts[]`: открытие, закрытое между двумя обновлениями score.json, тоже
получает заявку. Числа — из прогона с откатом 22.09.2026 (Jira MOS-182, комментарий
14531): файл 2026-04-01, у префикса 1051 два открытия, 04:54:26 (к срезу закрылось)
и 07:44:31 (открыто), у 257 — 10:26:23 (закрылось).

MOS-184 — участки предупреждения выбираются один раз, при первом прогоне, который
его увидел. Пересчёт веса после открытия (миграция 038 на стенде 22.09.2026) новых
заявок на то же предупреждение не заводит: 44 заявки вместо 33.

Решение Славы 26.09.2026 (MOS-182, комментарий 14677): заявка на каждое открытие,
но новая не заводится, если на участке уже есть незакрытая заявка с ненаступившим
сроком (строка приёмки Ф-48); участков на предупреждение — 3.
"""

from datetime import datetime

from app.domain.order_rules import МОСКВА, заявки_по_предупреждениям, обоснование
from app.worker.score_v3 import открытия


def _файл(collectors, alerts, horizon_h=720, thr=0.63):
    поля = ("pfx", "p", "warning_open", "warning_opened_at", "warning_expires_at")
    return {
        "horizon_h": horizon_h,
        "alert_threshold": thr,
        "collectors": [dict(zip(поля, r)) | {"features": []} for r in collectors],
        "alerts": [{"pfx": p, "t": t} for p, t in alerts],
    }


ФАЙЛ_0401 = _файл(
    collectors=[
        ("1051", 0.71, True, "2026-04-01T07:44:31", "2026-05-01T07:44:31"),
        ("257", 0.40, False, None, None),
        ("645", 0.52, False, None, None),
    ],
    alerts=[
        ("645", "2026-03-10T12:00:00"),  # раньше границы — не берём
        ("1051", "2026-04-01T04:54:26"),  # закрылось к срезу
        ("257", "2026-04-01T10:26:23"),  # закрылось к срезу
        ("1051", "2026-04-01T07:44:31"),
    ],
)  # это же открыто сейчас

ГРАНИЦА = datetime(2026, 3, 31, 23, 59, 59, tzinfo=МОСКВА)


# ------------------------------------------------------------------ MOS-182


def test_закрытое_между_обновлениями_открытие_попадает_в_список():
    о = открытия(ФАЙЛ_0401, ГРАНИЦА)
    пары = sorted((п["pfx"], п["opened_at"]) for п in о)
    assert пары == [
        ("1051", "2026-04-01T04:54:26"),
        ("1051", "2026-04-01T07:44:31"),
        ("257", "2026-04-01T10:26:23"),
    ]


def test_открытие_из_двух_списков_не_двоится_и_берёт_поля_открытого():
    о = {(п["pfx"], п["opened_at"]): п for п in открытия(ФАЙЛ_0401, ГРАНИЦА)}
    открытое = о[("1051", "2026-04-01T07:44:31")]
    assert открытое["p"] == 0.71 and открытое["expires_at"] == "2026-05-01T07:44:31"
    assert not открытое["закрыто"]


def test_у_закрытого_открытия_нет_сегодняшней_вероятности():
    # alerts[] несёт только pfx и t. Подставить p из collectors[] — значит выдать
    # сегодняшнее число за число момента открытия.
    закрытое = {п["opened_at"]: п for п in открытия(ФАЙЛ_0401, ГРАНИЦА)}[
        "2026-04-01T10:26:23"
    ]
    assert закрытое["p"] is None and закрытое["закрыто"]
    assert закрытое["порог"] == 0.63
    # Окно риска закрытого открытия — t + horizon_h файла.
    assert закрытое["expires_at"] == "2026-05-01T10:26:23"


def test_открытия_не_позже_границы_не_берутся_а_открытое_сейчас_берётся_всегда():
    граница = datetime(2026, 4, 1, 8, 0, tzinfo=МОСКВА)
    пары = sorted((п["pfx"], п["opened_at"]) for п in открытия(ФАЙЛ_0401, граница))
    # 04:54:26 раньше границы и закрыто — его прошлый прогон уже видел;
    # 07:44:31 тоже раньше, но открыто сейчас — ключ заявки держит его от повтора.
    assert пары == [("1051", "2026-04-01T07:44:31"), ("257", "2026-04-01T10:26:23")]


def test_файл_без_alerts_даёт_только_открытые_сейчас():
    файл = _файл(
        collectors=[("889", 0.5, True, "2026-06-10T08:36:56", "2026-07-10T08:36:56")],
        alerts=[],
    )
    del файл["alerts"]
    assert [п["pfx"] for п in открытия(файл, ГРАНИЦА)] == ["889"]


def test_обоснование_закрытого_открытия_говорит_что_оно_закрылось():
    закрытое = {п["opened_at"]: п for п in открытия(ФАЙЛ_0401, ГРАНИЦА)}[
        "2026-04-01T10:26:23"
    ]
    план, _ = заявки_по_предупреждениям(
        [закрытое | {"участки": [(50, "257:0")]}], {50}, {}, 3
    )
    т = обоснование(0.4, 720, "A", None, план[50])
    assert "к срезу уже закрылось" in т and "выше порога модели 0.630" in т
    assert "0.400" not in т, (
        "сегодняшняя вероятность участка выдана за вероятность открытия"
    )


# ------------------------------------------------------------------ MOS-184

ВЕСА_ДО = {1: (7, 0.9), 2: (7, 0.8), 3: (7, 0.7), 4: (7, 0.1), 5: (7, 0.05)}
# Миграция 038 пересчитала вес: тяжёлыми стали 4 и 5.
ВЕСА_ПОСЛЕ = {1: (7, 0.1), 2: (7, 0.2), 3: (7, 0.3), 4: (7, 0.9), 5: (7, 0.8)}
ПРЕДУПРЕЖДЕНИЕ = {
    "pfx": "889",
    "opened_at": "2026-06-10T08:36:56",
    "p": 0.5,
    "участки": [(s, f"889:{s}") for s in (1, 2, 3, 4, 5)],
}


def test_смена_веса_после_открытия_не_заводит_новых_заявок():
    первый, _ = заявки_по_предупреждениям([ПРЕДУПРЕЖДЕНИЕ], {1, 2, 3, 4, 5}, ВЕСА_ДО, 3)
    assert sorted(первый) == [1, 2, 3]
    # Второй прогон: у предупреждения уже есть заявки — участки выбраны, вес не важен.
    второй, _ = заявки_по_предупреждениям(
        [ПРЕДУПРЕЖДЕНИЕ],
        {1, 2, 3, 4, 5},
        ВЕСА_ПОСЛЕ,
        3,
        уже_выбраны={("889", "2026-06-10T08:36:56")},
    )
    assert второй == {}


def test_новое_открытие_того_же_префикса_выбирает_участки_заново():
    новое = ПРЕДУПРЕЖДЕНИЕ | {"opened_at": "2026-06-20T10:00:00"}
    план, _ = заявки_по_предупреждениям(
        [новое],
        {1, 2, 3, 4, 5},
        ВЕСА_ПОСЛЕ,
        3,
        уже_выбраны={("889", "2026-06-10T08:36:56")},
    )
    assert sorted(план) == [3, 4, 5]


# ------------------------------------------- Ф-48: живая заявка на участке


def test_живая_заявка_на_участке_глушит_новую_заявку_на_нём():
    новое = ПРЕДУПРЕЖДЕНИЕ | {"opened_at": "2026-06-20T10:00:00"}
    план, _ = заявки_по_предупреждениям([новое], {1, 2, 3, 4, 5}, ВЕСА_ДО, 3, живые={1})
    # Участок 1 уже в работе — заявку на него не дублируем и НЕ подменяем четвёртым:
    # три худших участка предупреждения — это 1, 2, 3.
    assert sorted(план) == [2, 3]


def test_два_открытия_одного_префикса_в_одном_прогоне_дают_одну_заявку_на_участок():
    о = открытия(ФАЙЛ_0401, ГРАНИЦА)
    for п in о:
        п["участки"] = {
            "1051": [(10, "1051:0"), (11, "1051:1")],
            "257": [(20, "257:0")],
        }[п["pfx"]]
    план, _ = заявки_по_предупреждениям(о, {10, 11, 20}, {}, 3)
    assert sorted(план) == [10, 11, 20]
    # Ключ — позднего открытия, того, что открыто сейчас: по нему проверка М-10
    # находит заявку открытого предупреждения. Раннее названо в заявке, а не потеряно.
    assert план[10]["ключ"] == "warn:1051:2026-04-01T07:44:31:10"
    assert [(р["pfx"], р["opened_at"]) for р in план[10]["ранние"]] == [
        ("1051", "2026-04-01T04:54:26")
    ]
    т = обоснование(0.71, 720, "A", None, план[10])
    assert "01.04.2026 04:54" in т, т


def test_обоснование_без_порога_в_файле_не_падает():
    закрытое = {"pfx": "257", "opened_at": "2026-04-01T10:26:23", "p": None, "закрыто": True,
                "порог": None, "expires_at": "2026-05-01T10:26:23"}
    план, _ = заявки_по_предупреждениям([закрытое | {"участки": [(50, "257:0")]}], {50}, {}, 3)
    assert "выше порога модели," in обоснование(0.4, 720, "A", None, план[50])
