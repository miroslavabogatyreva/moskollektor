# Слова, которые код подставляет ВМЕСТЕ с числом. Если такое слово стоит ещё
# и в шаблоне сразу после {value}, фраза удвоит его: «в 333 раза раза реже».
СЛОВА_ИЗ_КОДА = ("раз", "раза", "запись", "записи", "записей", "сутки", "суток")


def форма_шаблонов_верна(шаблоны: dict) -> list[str]:
    """Коды шаблонов, где после {value} стоит слово, которое подставит и код.

    Проверка формы, а не текста: она ловит расхождение кода со справочником,
    не требуя от справочника конкретных формулировок. Зовётся и самопроверкой
    на выдуманном словаре, и расчётом на настоящем — одним и тем же кодом,
    поэтому разойтись им негде.
    """
    плохие = []
    for код, фраза_ in шаблоны.items():
        хвост = фраза_.split("{value}", 1)[1].lstrip() if "{value}" in фраза_ else ""
        if хвост.split(" ")[0].strip(".,;:—") in СЛОВА_ИЗ_КОДА:
            плохие.append(код)
    return плохие


def _selfcheck():
    имена = ["days_since_last_reading", "bad7", "rate_ratio_year"]

    # 1. Опасное отклонение попадает в текст, безопасное — нет.
    ф = [{"f": "bad7", "v": 131.0, "d": "up"}, {"f": "chatter_7d", "v": 0.0, "d": "down"}]
    т = объяснить(ШАБЛОНЫ, ф, 2)
    assert "131 запись" in т, т          # 131 оканчивается на 1 — «запись», не «записей»
    assert "дребезж" not in т and "нет." not in т, f"безопасное отклонение просочилось: {т}"
    assert т.count("\n") == 0, "из двух признаков опасен один, значит строка одна"

    # 2. Отношение меньше единицы читается как «в N раз», а не «в 0,003 раза».
    т = объяснить(ШАБЛОНЫ, [{"f": "rate_ratio_year", "v": 0.003, "d": "down"}], None)
    assert "в 333 раз" in т, т
    # 3. Нулевое отношение — отдельная фраза, без арифметики.
    т = объяснить(ШАБЛОНЫ, [{"f": "rate_ratio_year", "v": 0.0, "d": "down"}], None)
    assert "не написал ни одной строки" in т, т
    assert "0,0" not in т and "0 раз" not in т, т

    # 4. Пятый случай приёмщика: все три отклонения в безопасную сторону.
    #    Это участок 2477, самый опасный в парке. Пустая строка недопустима —
    #    её не примет ограничение forecast_explanation_not_blank, а NULL соврал бы,
    #    что объяснение не собрано.
    #    Признаки берём только односторонние: у rate_ratio_* безопасной стороны
    #    нет вовсе (решение 16.09.2026), и участок с ним под этот случай не подходит.
    ф = [{"f": "bad7", "v": 0.0, "d": "down"},
         {"f": "undefined_share_7d", "v": 0.0, "d": "down"},
         {"f": "chatter_7d", "v": 0.0, "d": "down"}]
    assert all(ф_["d"] not in ОПАСНАЯ_СТОРОНА[ф_["f"]] for ф_ in ф), \
        "случай потерял смысл: один из признаков стал опасным в эту сторону"
    т = объяснить(ШАБЛОНЫ, ф, 110)
    assert т, "участок без опасных отклонений остался без объяснения"
    assert "110 суток" in т, т
    assert "{value}" not in т

    # 4-бис. Два признака одного семейства дают ОДНУ фразу, а освободившееся место
    #    занимает следующий признак. Без этого участок 1 (ключ 1044:0) получал
    #    16.09.2026 две фразы, различавшиеся только фоном сравнения, и обе
    #    заканчивались словами «Замолчавший датчик об аварии не сообщит».
    ф = [{"f": "rate_ratio_7d", "v": 0.0, "d": "down"},
         {"f": "rate_ratio_year", "v": 0.0, "d": "down"},
         {"f": "bad7", "v": 94.0, "d": "up"}]
    assert СЕМЕЙСТВО[ф[0]["f"]] == СЕМЕЙСТВО[ф[1]["f"]], \
        "случай потерял смысл: признаки перестали быть одним семейством"
    строки = объяснить(ШАБЛОНЫ, ф, None).split("\n")
    assert len(строки) == 2, (len(строки), строки)
    assert len(set(строки)) == 2, ("фразы повторяются", строки)
    assert any("Неисправен" in с for с in строки), \
        ("место второй фразы не занял следующий признак", строки)

    # 4-трис. Фикстура обязана покрывать каждую опасную сторону каждого признака.
    #    Эта проверка стоит здесь потому, что её отсутствие уже стоило нам ложного
    #    успеха: 16.09.2026 случай 4-бис проходил не из-за склейки семейств, а из-за
    #    того, что в фикстуре не было шаблона rate_ratio_7d.zero — второй признак
    #    молча не давал фразы, и склейку проверять было нечем. Фикстура, отставшая
    #    от справочника, делает зелёной любую проверку, которая на неё смотрит.
    for признак, стороны in ОПАСНАЯ_СТОРОНА.items():
        for сторона in стороны:
            assert фраза(ШАБЛОНЫ, признак, 0.0 if сторона == "down" else 12.0, сторона), \
                (признак, сторона, "нет шаблона в фикстуре — сверить с ref.explain_template")

    # 5. Ни опасных отклонений, ни молчания — честный NULL, а не выдуманная фраза.
    assert объяснить(ШАБЛОНЫ, [{"f": "bad7", "v": 0.0, "d": "down"}], 0) is None

    # 6. Признака нет в справочнике фраз — в объяснение он попасть не может.
    #    Это условие готовности блока Q7.
    assert объяснить(ШАБЛОНЫ, [{"f": "silence_normalized", "v": 88779.0, "d": "up"}], None) is None, \
        "признак без шаблона просочился в текст"

    # 7. Подстановка не оставляет {value} ни в одной фразе справочника.
    for код, шаблон in ШАБЛОНЫ.items():
        имя = код.split(".")[0]
        if имя == "section_silent":
            continue
        сторона = код.split(".")[1] if "." in код else "up"
        т = фраза(ШАБЛОНЫ, имя, 0.5 if "share" in имя else 12.0,
                  "down" if сторона == "zero" else сторона)
        assert т and "{value}" not in т, (код, т)

    # 8. Склонения: «1 сутки», «2 суток», «11 суток», «21 сутки».
    assert _склонение(1, "сутки", "суток", "суток") == "сутки"
    assert _склонение(11, "раз", "раза", "раз") == "раз"
    assert _склонение(21, "сутки", "суток", "суток") == "сутки"
    assert _склонение(333, "раз", "раза", "раз") == "раза"

    # 9. Сборка на весь парк сохраняет порядок участков.
    тексты = собрать(ШАБЛОНЫ,
                     [[{"f": "bad7", "v": 131.0, "d": "up"}], []],
                     [[2.0, 131.0, 1.0], [110.0, 0.0, 0.0]], имена)
    assert len(тексты) == 2 and "131" in тексты[0] and "110 суток" in тексты[1], тексты

    # 10. Форма шаблонов: слово после {value} не должно повторять то, что
    #     подставит код. Этот случай и есть заплата на ошибку 16.09.2026.
    assert форма_шаблонов_верна(ШАБЛОНЫ) == [], форма_шаблонов_верна(ШАБЛОНЫ)
    плохой = {"bad7.up": "по коллектору {value} записей «Неисправен»"}
    assert форма_шаблонов_верна(плохой) == ["bad7.up"], "проверка формы не ловит удвоение слова"

    # 11. Склонения на числах, которые правда встречаются в парке.
