def _склонение(n: int, одна: str, две: str, пять: str) -> str:
    """сутки/суток, раз/раза. Без этого фраза читается как машинный перевод."""
    n = abs(n) % 100
    if 11 <= n <= 14:
        return пять
    return {1: одна, 2: две, 3: две, 4: две}.get(n % 10, пять)


def _разряды(n: int) -> str:
    """33279 -> «33 279». Неразрывный пробел, чтобы число не разорвало по строкам."""
    return f"{n:,}".replace(",", "\u00a0")


def _число(имя: str, значение: float, сторона: str) -> str:
    """Значение признака вместе с его словом, в том виде, в каком читает человек.

    **Слово приходит отсюда, а не из шаблона, и это правило, а не мелочь.**
    Русское склонение зависит от числа: «1 запись», «84 записи», «271 запись»,
    «12 записей». В SQL этого не посчитать, поэтому шаблон несёт только {value},
    а число со своим словом собирает код. 16.09.2026 слово стояло в обоих местах
    сразу, и настоящие шаблоны дали «в 333 раза раза реже», «в 20 раз раза реже»
    и «молчат 110 суток суток подряд» — миграция 016 убрала слово из шаблонов.

    Четыре случая, и каждый взят из беды, найденной на боевом прогоне: отношение
    меньше единицы печатается как «в 8 раз», а не «в 0,125 раза»; доля — процентами;
    счётчик записей — с правильным склонением; сутки молчания — тоже.
    """
    if имя in ("rate_ratio_7d", "rate_ratio_year"):
        if сторона == "down":
            во_сколько = round(1 / значение) if значение else 0
            return f"{во_сколько} {_склонение(во_сколько, 'раз', 'раза', 'раз')}"
        во_сколько = round(значение, 1)
        целое = int(во_сколько)
        return (f"{целое} {_склонение(целое, 'раз', 'раза', 'раз')}"
                if во_сколько == целое else f"{во_сколько:.1f}".replace(".", ",") + " раза")
    if имя == "undefined_share_7d":
        return f"{round(значение * 100)} %"
    if имя in ("bad7", "chatter_7d"):
        n = round(значение)
        return f"{n} {_склонение(n, 'запись', 'записи', 'записей')}"
    if имя == ПРИЗНАК_МОЛЧАНИЯ:
        n = round(значение)
        return f"{n} {_склонение(n, 'сутки', 'суток', 'суток')}"

    # Признаки модели v3 (миграция 034). Часы модель считает от момента решения,
    # но диспетчеру «2 016 часов» ничего не говорит — переводим в сутки, как везде
    # на экране. Доли печатаем процентами, счётчики — со своим словом.
    if имя in ("ev_h_since_prev", "ev_gap_last"):
        # Меньше двух суток — считаем часами. «Прошло 1 сутки» читается криво:
        # у слова «сутки» нет единственного числа, а «прошло 34 часа» и точнее,
        # и по-русски. Поймано на живом прогоне 22.09.2026, участок 1727.
        # Сравниваем ИСХОДНОЕ значение, а не округлённое: 47,6 округляется до 48,
        # и проверка по округлённому уводила бы его в сутки — «2 суток» вместо
        # «48 часов». Поймано самопроверкой ниже.
        часов = round(значение)
        if значение < 48:
            return f"{часов} {_склонение(часов, 'час', 'часа', 'часов')}"
        суток = round(значение / 24)
        return f"{суток} {_склонение(суток, 'сутки', 'суток', 'суток')}"
    if имя in ("ev_relapse_rate", "act_share_7d"):
        return f"{round(значение * 100)} %"
    if имя in ("n_dying_ch", "ev_open_ch"):
        n = round(значение)
        return f"{_разряды(n)} {_склонение(n, 'канал', 'канала', 'каналов')}"
    if имя in ("ev_inc_72h", "ev_inc_168h"):
        n = round(значение)
        return f"{n} {_склонение(n, 'авария', 'аварии', 'аварий')}"
    if имя in ("n_alarm_7d", "n_alarm_28d", "n_rows_28d", "n_undef_28d"):
        n = round(значение)
        return f"{_разряды(n)} {_склонение(n, 'запись', 'записи', 'записей')}"
    return f"{round(значение)}"


def код_шаблона(имя: str, значение: float, сторона: str) -> str:
    """Какую строку справочника берём.

    Нулевое отношение — отдельный шаблон, а не арифметика: «в 0,0 раза реже»
    не значит ничего, а «за неделю не написал ни строки» значит ровно то,
    что произошло. Случай не редкий: rate_ratio_year = 0 у 2 681 участка
    из 3 173 на прогоне 7.
    """
    if имя in ("rate_ratio_7d", "rate_ratio_year") and not значение:
        return f"{имя}.zero"
    return f"{имя}.{сторона}"


def фраза(шаблоны: dict, имя: str, значение: float | None, сторона: str) -> str | None:
    """Готовая строка для диспетчера. None — фразы для такого случая нет.

    **Пустое значение — это не ноль.** Модель v3 ставит NaN там, где истории нет
    вовсе: у коллектора без единого прошлого инцидента `ev_h_since_prev` пуст,
    и в JSON он приезжает как null. Написать «прошло 0 суток» значило бы сказать
    «авария была только что» про коллектор, где аварий не было никогда.
    """
    if значение is None:
        return None
    for код in (код_шаблона(имя, значение, сторона), имя):
        шаблон = шаблоны.get(код)
        if шаблон:
            return шаблон.replace("{value}", _число(имя, значение, сторона))
    return None


def объяснить(шаблоны: dict, факторы: list[dict], суток_молчания: float | None) -> str | None:
    """Объяснение одного прогноза: до трёх строк, каждая про один признак.

    Порядок фраз — по силе отклонения, как их отобрала стадия 5. Безопасные
    отклонения отбрасываются здесь, а не там: стадия 5 выбирает, ЧТО отклонилось,
    а эта функция решает, о чём из этого стоит говорить.
    """
    строки, семейства = [], set()
    for ф in факторы:
        имя, сторона = ф["f"], ф["d"]
        if сторона not in ОПАСНАЯ_СТОРОНА.get(имя, set()):
            continue
        сем = СЕМЕЙСТВО.get(имя, имя)
        if сем in семейства:
            continue
        т = фраза(шаблоны, имя, ф["v"], сторона)
        if т:
            строки.append(т)
            семейства.add(сем)
        if len(строки) == ФРАЗ:
            break

    if строки:
        return "\n".join(строки)

    # Ни одного опасного отклонения. Если участок молчит — причина риска именно
    # в этом, и она называется прямо. Если не молчит — объяснять нечем, и NULL
    # честнее выдуманной фразы.
    шаблон = шаблоны.get("section_silent")
    if шаблон and суток_молчания:
        return шаблон.replace("{value}", _число(ПРИЗНАК_МОЛЧАНИЯ, суток_молчания, "up"))
    return None


async def загрузить_шаблоны(conn) -> dict:
    return {r["feature_code"]: r["phrase_ru"]
            for r in await conn.fetch("SELECT feature_code, phrase_ru FROM ref.explain_template")}


def собрать(шаблоны: dict, факторы_по_участкам: list[list[dict]],
            значения: list[list[float | None]], имена: list[str]) -> list[str | None]:
    """Тексты на весь парк, в порядке участков."""
    i_молчания = имена.index(ПРИЗНАК_МОЛЧАНИЯ)
    return [объяснить(шаблоны, ф, строка[i_молчания])
            for ф, строка in zip(факторы_по_участкам, значения)]


