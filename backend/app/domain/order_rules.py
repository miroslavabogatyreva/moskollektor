async def справочники(conn) -> dict[str, dict]:
    """Все коды, которые правило может вписать в заявку, — в id. Нет кода — ошибка.

    `{"priority": {код: (id, часов_реакции)}, "order_type": {код: id},
    "activity_type": {код: id}, "потолок_ч": float}`. Недостающий код роняет стадию
    заявок до первой вставки, с именем кода: заявка без вида работ проваливает М-11,
    а тихий ноль строк выглядит как «риска нет». Так же и потолок превентивности:
    без него заявки класса C получили бы срок 72 ч, позже медианы упреждения.
    """
    нужно = {"priority": set(ПРИОРИТЕТ.values()), "order_type": {ВИД_ЗАКАЗА},
             "activity_type": set(ВИД_РАБОТ.values())}
    итог: dict[str, dict] = {}
    for таблица, коды in нужно.items():
        колонки = "code, id, response_hours" if таблица == "priority" else "code, id"
        строки = await conn.fetch(
            f"SELECT {колонки} FROM ref.{таблица} WHERE code = ANY($1::text[])", sorted(коды))
        итог[таблица] = {r["code"]: (r["id"], r["response_hours"]) if таблица == "priority"
                         else r["id"] for r in строки}
        нет = sorted(коды - итог[таблица].keys())
        if нет:
            raise LookupError(f"в ref.{таблица} нет кодов {нет}: заявку без них не заводим")
    потолок = await conn.fetchval(
        "SELECT value FROM ref.app_setting WHERE key = 'order_preventive_cap_h'")
    if потолок is None:
        raise LookupError("в ref.app_setting нет order_preventive_cap_h (миграция 037): "
                          "срок заявки не от чего ограничить")
    итог["потолок_ч"] = float(потолок)
    return итог


async def _сколько_худших(conn) -> int:
    """Сколько худших участков коллектора получают заявку. 0 — правило выключено."""
    значение = await conn.fetchval(
        "SELECT value FROM ref.app_setting WHERE key = 'order_top_sections_per_object'")
    return int(значение) if значение is not None else 0


async def _веса(conn) -> dict[int, tuple[int, float]]:
    """`{section_id: (collector_id, вес)}` из pred.section_weight."""
    return {r["section_id"]: (r["object_id"], float(r["weight"]))
            for r in await conn.fetch(
                "SELECT section_id, object_id, weight FROM pred.section_weight")}


async def _разнос(conn) -> dict[int, tuple[int, float]]:
    """Веса участков, если разнос включён (forecast_spread_enabled), иначе пусто."""
    включено = await conn.fetchval(
        "SELECT value FROM ref.app_setting WHERE key = 'forecast_spread_enabled'")
    return await _веса(conn) if включено is not None and int(включено) else {}


def худшие_по_коллектору(кандидаты: list, веса: dict[int, tuple[int, float]],
                         сколько: int) -> list:
    """Из участков одного коллектора оставить `сколько` с самым тяжёлым весом.

    **Зачем правило вообще.** Модель v3 даёт одно число на коллектор, поэтому порог
    пропускает либо все его участки, либо ни одного: замер на стенде 22.09.2026 —
    при пороге 0,63 выше него 2 167 участков из 3 173, все участки шести коллекторов.
    Заявка на каждый — список, который диспетчер не отработает.

    **Почему вес.** Он считает долю отказов участка внутри коллектора
    (pred.section_weight, MOS-150). Как делитель вероятности вес не годится —
    это разобрано в шапке миграции 035, — а как порядок обхода годится: начинать
    надо с того пикета, где ломалось чаще.

    Участок без веса не выбрасывается, а идёт в конец своей группы: «веса нет»
    значит «истории нет», а не «отказов не было».
    """
    по_коллектору: dict[int, list] = {}
    for к in кандидаты:
        коллектор = веса.get(к["section_id"], (None, 0.0))[0]
        по_коллектору.setdefault(коллектор, []).append(к)

    итог = []
    for коллектор, группа in по_коллектору.items():
        if коллектор is None:      # участков без коллектора правило не касается
            итог.extend(группа)
            continue
        группа.sort(key=lambda к: (-веса.get(к["section_id"], (None, 0.0))[1],
                                   к["section_id"]))
        итог.extend(группа[:сколько])
    return итог


def заявки_по_предупреждениям(предупреждения: list[dict], в_прогоне: set[int],
                              веса: dict[int, tuple[int, float]], сколько: int,
                              уже_выбраны: set[tuple[str, str]] = frozenset(),
                              живые: set[int] = frozenset()
                              ) -> tuple[dict[int, dict], list[str]]:
    """`{section_id: предупреждение}` — на какие участки заводить заявки, и префиксы,
    ни одного участка которых нет в прогоне.

    Каждое открытие предупреждения модели даёт заявки на `сколько` самых тяжёлых
    по весу участков своего префикса (order_top_sections_per_object, ноль — на все),
    и у каждой свой ключ `warn:<pfx>:<момент открытия>:<section_id>`. Порог
    вероятности здесь не участвует: решение «выдавать или нет» модель уже приняла,
    открыв предупреждение, и её Precision посчитана именно для этого момента.
    Повторное открытие — новый момент, новый ключ, новые заявки.

    **Участки выбираются один раз** (MOS-184). `уже_выбраны` — пары (pfx, открытие),
    у которых заявки уже есть: такое предупреждение пропускаем целиком. Иначе
    пересчёт веса после открытия выбирает другую тройку, у неё другие ключи, и на
    то же предупреждение заводятся новые заявки — на стенде 22.09.2026 их стало 44
    вместо 33.

    **Живая заявка на участке глушит новую** (Ф-48, решение Славы 26.09.2026).
    `живые` — участки с незакрытой заявкой, срок которой не наступил. Такой участок
    из тройки выпадает и не подменяется четвёртым: бригада на нём уже работает.

    **Два открытия одного префикса в одном прогоне** (MOS-182) ведут на одни
    участки, а номер заявки один на строку журнала. Идём от позднего открытия
    к раннему: ключ получает позднее — то, что может быть открыто сейчас, и по нему
    проверка М-10 найдёт заявку, — а ранние попадают в заявку списком `ранние`.

    `маршрут` — ключи тех же участков по порядку обхода: он идёт в обоснование.
    """
    план: dict[int, dict] = {}
    вне_прогона: list[str] = []
    for п in sorted(предупреждения, key=lambda п: момент_файла(п["opened_at"]), reverse=True):
        if (п["pfx"], п["opened_at"]) in уже_выбраны:
            continue
        свои = sorted(((sid, ключ) for sid, ключ in п["участки"] if sid in в_прогоне),
                      key=lambda x: (-веса.get(x[0], (None, 0.0))[1], x[0]))
        if not свои:
            вне_прогона.append(п["pfx"])
            continue
        взять = свои[:сколько] if сколько else свои
        суть = {к: v for к, v in п.items() if к != "участки"}
        новые = []
        for sid, ключ in взять:
            if sid in живые:
                continue
            if sid in план:
                план[sid]["ранние"].append(суть)
                continue
            новые.append((sid, ключ))
        маршрут = [ключ for _, ключ in новые]
        for sid, _ in новые:
            план[sid] = {**суть, "маршрут": маршрут, "ранние": [],
                         "ключ": f"warn:{п['pfx']}:{п['opened_at']}:{sid}"}
    return план, вне_прогона


# Предупреждения, у которых заявки уже есть: (pfx, момент открытия) из ключа
# warn:<pfx>:<открытие>:<участок>. Момент открытия сам содержит двоеточия, поэтому
# ключ режем по первому и последнему двоеточию, а не по всем.
УЖЕ_ВЫБРАНЫ = """
SELECT DISTINCT split_part(source_key, ':', 2) AS pfx,
       substring(source_key FROM '^warn:[^:]+:(.*):[0-9]+$') AS opened_at
  FROM maint.notification
 WHERE source_system = $1 AND source_key LIKE 'warn:%'
"""

# Участки с живой заявкой (Ф-48): не закрыта и не отменена, срок не наступил к срезу
# прогона. Любая заявка на техническом месте участка, не только автозаявка: если
# диспетчер завёл заявку руками, бригада туда уже едет.
ЖИВЫЕ = """
SELECT DISTINCT x.section_id
  FROM maint.notification n
  JOIN ref.object_xref x ON x.func_location_id = n.func_location_id
 WHERE n.status IN ('OPEN', 'IN_PROCESS') AND n.due_at > $1
   AND x.section_id = ANY($2::int[])
"""


async def план_заявок(conn, предупреждения: list[dict], в_прогоне: set[int],
                      обнаружено: datetime) -> dict:
    """Заявки, которых ещё нет: читается ДО записи прогноза.

    До записи, потому что участки плана publish.записать обязан положить в журнал
    этого прогона (MOS-180): заявка ссылается на строку журнала, а мёртвая зона её
    пропустила бы. Повтор по ключу всё равно отсекает индекс uq_notif_forecast_key
    при вставке; здесь база подаёт правилу то, чего по ключу не отсечь, — уже
    выбранные предупреждения (MOS-184) и живые заявки на участках (Ф-48).
    `обнаружено` — срез прогона: срок живой заявки сравниваем с ним.
    """
    уже_выбраны = {(r["pfx"], r["opened_at"])
                   for r in await conn.fetch(УЖЕ_ВЫБРАНЫ, ИСТОЧНИК)}
    участки = sorted({sid for п in предупреждения for sid, _ in п["участки"]})
    живые = {r["section_id"] for r in await conn.fetch(ЖИВЫЕ, обнаружено, участки)}
    план, вне = заявки_по_предупреждениям(
        предупреждения, в_прогоне, await _веса(conn), await _сколько_худших(conn),
        уже_выбраны, живые)
    return {"участки": план, "уже": len(уже_выбраны), "живых": len(живые),
            "вне_прогона": вне}


async def завести(conn, run_id: int, direction: str = "sensor_failure",
                  план: dict[int, dict] | None = None) -> dict:
    """Стадия автозаявок: по прогнозам прогона завести заявки и заказы ТОиР.

    `план` — `{section_id: предупреждение}` из план_заявок() на пути модели v3;
    None — прежний путь (заглушка, feat.v1), суточный порог по вероятности участка.

    Возвращает числа для отчёта о прогоне: сколько участков отобрано, сколько
    заявок заведено, сколько отброшено индексом как повтор и сколько участков плана
    не нашли своей строки в журнале прогона. Последнее обязано быть нулём: не ноль —
    значит publish.записать не положил участок плана в журнал, и заявка потерялась.

    Заявка и заказ ТОиР пишутся одной транзакцией. Заказ нужен не для красоты:
    вид работ у нас берётся из справочников ref.order_type и ref.activity_type,
    а ссылаются на них колонки заказа. Заявка без заказа — это заявка без вида
    работ, и приёмочная строка М-11 её не засчитает.
    """
    коды = await справочники(conn)
    кандидаты = await conn.fetch(ОТБОР, run_id, direction)
    if план is None:
        п = await пороги(conn)
        отобрано = пороговый_отбор([dict(к) for к in кандидаты], п, await _разнос(conn))
        if (сколько := await _сколько_худших(conn)):
            отобрано = худшие_по_коллектору(отобрано, await _веса(conn), сколько)
    else:
        отобрано = [к for к in кандидаты if к["section_id"] in план]

    заведено = 0
    async with conn.transaction():
        for к in отобрано:
            крит = к["crit"]
            приоритет, часов_реакции = коды["priority"][ПРИОРИТЕТ[крит]]
            з = план[к["section_id"]] if план is not None else None
            обнаружено = к["as_of"]      # срез прогона, который заметил риск
            if з is None:
                открыто = None
                окно = конец_окна(к["as_of"], к["horizon_h"])
                ключ = f"day:{к['func_location_id']}:{сутки(к['as_of'])}"
            else:
                открыто = момент_файла(з["opened_at"])
                окно = (момент_файла(з["expires_at"]) if з.get("expires_at")
                        else конец_окна(к["as_of"], к["horizon_h"]))
                ключ = з["ключ"]
            due_at = срок(обнаружено, min(часов_реакции, коды["потолок_ч"]))
            тема = f"Превентивные работы по прогнозу, участок {к['smvu_key']}"
            notif_id = await conn.fetchval(
                ВСТАВКА_ЗАЯВКИ,
                номер_заявки(к["forecast_id"]), ВИД_СООБЩЕНИЯ, тема,
                обоснование(к["probability"], к["horizon_h"], крит, к["explanation_ru"], з,
                            к.get("p_объекта")),
                к["func_location_id"], приоритет, обнаружено, due_at,
                ИСТОЧНИК, ключ, к["forecast_id"], открыто, окно,
            )
            if notif_id is None:
                continue  # индекс uq_notif_forecast_key: заявка с этим ключом уже есть
            await conn.execute(
                ВСТАВКА_ЗАКАЗА,
                номер_заказа(к["forecast_id"]), коды["order_type"][ВИД_ЗАКАЗА],
                коды["activity_type"][ВИД_РАБОТ[крит]], тема, к["func_location_id"],
                notif_id, приоритет, обнаружено, due_at,
            )
            заведено += 1

    return {
        "правило": "порог" if план is None else "открытие предупреждения",
        "участков": len(кандидаты),
        "отобрано": len(отобрано),
        "заявок": заведено,
        "повторов": len(отобрано) - заведено,
        "без_строки_журнала": 0 if план is None else len(план) - len(отобрано),
    }


async def проверить_реестр(conn) -> bool:
    """Реестр ТОиР на месте: пара чисел, а не один счётчик.

    Один счётчик здесь обманывает. «3 173 технических места» ничего не говорит
    о том, нашёл ли расчёт объект для КАЖДОГО участка: участок без
    func_location_id выпадет из отбора молча, и заявок просто станет меньше.
    Поэтому проверяем два числа сразу и требуем, чтобы второе было нулём.
    """
    участков = await conn.fetchval(
        "SELECT count(*) FROM asset.func_location WHERE hierarchy_level = 4"
    )
    без_места = await conn.fetchval(
        "SELECT count(*) FROM ref.object_xref WHERE func_location_id IS NULL"
    )
    всего = await conn.fetchval("SELECT count(*) FROM ref.object_xref")
    ок = участков == всего and без_места == 0
    print(
        f"реестр ТОиР: технических мест уровня «участок» {участков}, "
        f"участков в object_xref {всего}, из них без места {без_места} — "
        f"{'сошлось' if ок else 'РАСХОЖДЕНИЕ'}"
    )
    if not ок:
        print(
            "   накатите db/migrations/010_orders.sql ещё раз: на чистой базе "
            "его часть 2 отработала до заливки выгрузки и вставила ноль строк"
        )
    return ок


# --------------------------------------------------------------- самопроверка


def _selfcheck():
    """Случаи, на которых правило обязано отказать, и те, на которых нет."""
    # 1. Срок — момент обнаружения плюс норматив реакции, и горизонт в нём не участвует.
    # Числа — нормативы ref.priority после миграции 037 (A 16, B 48, C 72 ч).
    открыто = момент_файла("2026-06-10T08:36:56")      # префикс 889, score.json 22.09
    assert открыто == datetime(2026, 6, 10, 8, 36, 56, tzinfo=МОСКВА), открыто
    for часов in (16, 48, 72):
        assert срок(открыто, часов) - открыто == timedelta(hours=часов), часов
    # Старая формула as_of + horizon − запас на горизонте 720 давала 708 ч вместо 16.
    as_of = datetime(2026, 6, 30, 23, 59, 59, tzinfo=МОСКВА)
    assert (срок(as_of, 16) - as_of) != timedelta(hours=720 - 12)
    # Конец окна — граница риска, а не срок: у прежнего пути это as_of + horizon_h.
    assert конец_окна(as_of, 720) == datetime(2026, 7, 30, 23, 59, 59, tzinfo=МОСКВА)
    # Норматива нет — срок ставить не от чего, и это отказ, а не заявка «на сейчас».
    try:
        срок(as_of, 0)
    except ValueError:
        pass
    else:
        raise AssertionError("нулевой норматив реакции обязан быть отказом")

    # 2. Объект ниже порога заявки не получает.
    assert нужна_заявка(0.9701, "A") and not нужна_заявка(0.9700, "A")
    assert not нужна_заявка(0.975, "B"), "класс B строже класса A, 0,975 ему мало"
    assert not нужна_заявка(0.985, "C"), "класс C строже всех, 0,985 ему мало"
    # Ровно на пороге — не заводим: «выше порога» значит строго выше.
    assert not нужна_заявка(ПОРОГ["A"], "A")
    # Неизвестный класс судим по самому строгому порогу, а не пропускаем.
    assert not нужна_заявка(0.98, "Z") and нужна_заявка(0.995, "Z")

    # 3. Ключ прежнего пути — московская дата: две прогонки одной ночной смены
    # обязаны дать ОДИН ключ, а в UTC дали бы два.
    from datetime import timezone

    ночь1 = datetime(2026, 7, 1, 2, 0, tzinfo=МОСКВА)
    ночь2 = datetime(2026, 7, 1, 4, 0, tzinfo=МОСКВА)
    assert сутки(ночь1) == сутки(ночь2), (сутки(ночь1), сутки(ночь2))
    assert ночь1.astimezone(timezone.utc).date() != ночь2.astimezone(timezone.utc).date()
    assert сутки(datetime(2026, 7, 1, 23, 59, tzinfo=МОСКВА)) != сутки(
        datetime(2026, 7, 2, 0, 1, tzinfo=МОСКВА))

    # 3а. Путь v3: заявки на N тяжёлых участков префикса, у каждой свой ключ, и
    # повторное открытие того же префикса в те же сутки даёт НОВЫЕ ключи.
    веса = {10: (1, 0.5), 11: (1, 0.9), 12: (1, 0.1), 20: (2, 0.4)}
    пр = [{"pfx": "889", "opened_at": "2026-06-10T08:36:56", "p": 0.495,
           "участки": [(10, "889:0"), (11, "889:1"), (12, "889:2")]},
          {"pfx": "847", "opened_at": "2026-06-30T13:28:37", "p": 0.868,
           "участки": [(20, "847:0")]},
          {"pfx": "264", "opened_at": "2026-06-30T10:00:00", "p": 0.7, "участки": []}]
    план, вне = заявки_по_предупреждениям(пр, {10, 11, 12, 20}, веса, 2)
    assert sorted(план) == [10, 11, 20], план          # 12 — третий по весу, не берём
    assert план[11]["ключ"] == "warn:889:2026-06-10T08:36:56:11", план[11]
    assert план[10]["маршрут"] == ["889:1", "889:0"], план[10]   # тяжёлый — первым
    assert вне == ["264"], вне                         # участков нет — назван, не потерян
    пр[0]["opened_at"] = "2026-06-10T20:00:00"          # закрылось и открылось вечером
    план2, _ = заявки_по_предупреждениям(пр, {10, 11, 12, 20}, веса, 2)
    assert план2[11]["ключ"] != план[11]["ключ"], "повторное открытие склеилось с первым"
    # --limit: участка нет в прогоне — берётся следующий по весу, а не пропадает заявка.
    план3, _ = заявки_по_предупреждениям(пр, {10, 12, 20}, веса, 2)
    assert sorted(план3) == [10, 12, 20], план3
    # Ноль в настройке — все участки префикса, как на прежнем пути.
    assert len(заявки_по_предупреждениям(пр, {10, 11, 12, 20}, веса, 0)[0]) == 4

    # 4. Обоснование не бывает пустым — иначе М-11 красная.
    assert обоснование(0.9991, 24, "A", None).strip()
    assert "0.999" in обоснование(0.9991, 24, "A", None)
    assert обоснование(0.5, 24, "A", "Датчик молчит.").endswith("Датчик молчит.")
    # Под предупреждением число — префикса, открывшего его, а не прогноза участка.
    т = обоснование(0.87, 720, "A", None, план[11])
    assert "0.495" in т and "0.870" not in т and "889:1, 889:0" in т, т

    # 5. Номера влезают в свои колонки: notification_no и order_no — varchar(12).
    assert len(номер_заявки(126637)) == 12 == len(номер_заказа(126637))
    assert номер_заявки(126637) == "AF0000126637"
    assert номер_заявки(1) != номер_заявки(2)

    # Отбор худших участков коллектора (миграция 035). Правило нужно потому, что
    # модель v3 даёт одно число на коллектор: порог пропускает либо всех, либо никого.
    участки = [{"section_id": s, "probability": 0.7} for s in (10, 11, 12, 20, 21, 99)]
    веса = {10: (1, 0.5), 11: (1, 0.9), 12: (1, 0.1), 20: (2, 0.4), 21: (2, 0.6)}
    # 99 веса не имеет вовсе — у него нет и коллектора, правило его не касается.
    двое = худшие_по_коллектору(участки, веса, 2)
    assert sorted(к["section_id"] for к in двое) == [10, 11, 20, 21, 99], двое
    один = худшие_по_коллектору(участки, веса, 1)
    assert sorted(к["section_id"] for к in один) == [11, 21, 99], один
    # Просят больше, чем есть в коллекторе, — отдаём сколько есть, без ошибки.
    assert len(худшие_по_коллектору(участки, веса, 99)) == 6
    # Порядок внутри группы по весу, а при равных весах — по номеру участка:
    # иначе два прогона подряд заведут заявки на разные участки без причины.
    ровные = [{"section_id": s, "probability": 0.7} for s in (31, 30)]
    одинаковые = {30: (3, 0.5), 31: (3, 0.5)}
    assert худшие_по_коллектору(ровные, одинаковые, 1)[0]["section_id"] == 30

    print("order_rules selfcheck ok: срок от обнаружения, пороги, ключи предупреждений, обоснование, отбор худших")


def main(argv):
    _selfcheck()
    dsn = os.environ.get("DATABASE_URL")
    if not dsn:
        print("DATABASE_URL не задана — сверку реестра ТОиР пропускаю")
        return 0
    import asyncpg

    async def сверить():
        conn = await asyncpg.connect(dsn)
        try:
            return await проверить_реестр(conn)
        finally:
            await conn.close()

    return 0 if asyncio.run(сверить()) else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
