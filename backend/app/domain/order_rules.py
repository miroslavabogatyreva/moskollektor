"""Правило, по которому расчёт заводит превентивную заявку. Q6.2 (MOS-57).

Приёмка: М-10 (заявку заводит расчёт, а не диспетчер), М-11 (объект, вид работ,
срок и обоснование заполнены), М-12 (из заявки открывается прогноз), М-13 (срок
работ раньше прогнозируемого отказа).

Правило целиком — в docs/order-rules.md с разбором на одном участке. Здесь код
и три таблицы-ручки, которые это правило задают: ПОРОГ, ЗАПАС_Ч и ВИД_РАБОТ.

**Почему сравнение сроков живёт в Python, а не в SQL.** Ту же величину — запас
между сроком работ и прогнозируемым отказом — считает приёмочный скрипт
code/check_orders.py функцией lead_hours(). Две реализации одной методики
расходятся молча, поэтому здесь формула одна и она в Python: заявку собирает
Python, он же и считает срок. SQL получает готовый timestamptz.

**Момент отказа — это as_of прогона плюс горизонт прогноза,** pred.run.as_of +
pred.forecast.horizon_h. Не now(): расчёт на историческом срезе (выгрузка
кончается 30.06.2026) иначе ставил бы сроки на сегодня и все заявки выглядели бы
просроченными.

Запуск самопроверки:
    python -m app.domain.order_rules              # без базы: пороги, сроки, сутки
    DATABASE_URL=postgresql://... python -m app.domain.order_rules
                                                  # плюс сверка реестра ТОиР
"""

import asyncio
import os
import sys
from datetime import datetime, timedelta
from zoneinfo import ZoneInfo

МОСКВА = ZoneInfo("Europe/Moscow")

# Класс критичности участка проставлен в asset.func_location.criticality_id
# миграцией 010_orders.sql по системе, к которой относятся каналы участка:
# A — пожарная или газовая охрана, B — охранная подсистема или диспетчерский
# контроль, C — температура, диагностика, каналов нет.

# Вероятность отказа за горизонт, выше которой заводится заявка.
# Числа выбраны по распределению прогона 51 на стенде (медиана 0,125, p90 0,728,
# p99 0,969) так, чтобы смена получала десятки заявок, а не сотни: на этом прогоне
# правило даёт 32 заявки на 3 173 участка, то есть 1,0 % парка. Обоснование
# и таблица «порог → сколько участков» — docs/order-rules.md.
# ponytail: три константы, а не таблица настроек. Задача Q4.12 заводит
# ref.app_setting — тогда пороги переедут туда и станут правиться из админки.
ПОРОГ = {"A": 0.97, "B": 0.98, "C": 0.99}

# Сколько часов работы обязаны закончиться ДО прогнозируемого отказа.
# Чем критичнее участок, тем больше запас: на критичном участке бригада должна
# успеть не впритык.
ЗАПАС_Ч = {"A": 12, "B": 8, "C": 4}

# Вид работ ТОиР. Различает их выезд: обход — мимо, осмотр — глазами на месте,
# диагностика — с прибором и с проверкой канала связи.
ВИД_РАБОТ = {"A": "PCM", "B": "PIN", "C": "POC"}

# Приоритет заявки. Код '1' (аварийный, реакция 4 часа) автозаявке не достаётся
# никогда: превентивная работа, которую надо начать через четыре часа,
# называется аварийной, а не превентивной.
ПРИОРИТЕТ = {"A": "2", "B": "3", "C": "4"}

ВИД_ЗАКАЗА = "PREV"
ВИД_СООБЩЕНИЯ = "WR"  # запрос на работу
ИСТОЧНИК = "forecast"  # отличает автозаявку от заведённой руками


def нужна_заявка(вероятность: float, критичность: str) -> bool:
    """Участок с такой вероятностью и таким классом заслуживает заявки.

    Неизвестный класс критичности — это не повод молча пропустить участок
    и не повод завести заявку наугад: берём самый строгий из порогов.
    """
    return вероятность > ПОРОГ.get(критичность, max(ПОРОГ.values()))


def момент_отказа(as_of: datetime, horizon_h: int) -> datetime:
    """Когда прогноз ждёт отказ. Та же формула, что в code/check_orders.py."""
    return as_of + timedelta(hours=horizon_h)


def срок(as_of: datetime, horizon_h: int, критичность: str) -> datetime:
    """Плановый срок работ: строго между моментом расчёта и моментом отказа.

    Запас берётся из ЗАПАС_Ч, но не больше половины горизонта. Ограничение
    не теоретическое: при горизонте 24 часа и запасе 12 часов работы пришлись бы
    ровно на середину, а при горизонте 6 часов тот же запас в 12 часов увёл бы
    срок на 6 часов В ПРОШЛОЕ — заявка родилась бы просроченной. Половина
    горизонта оставляет бригаде столько же времени, сколько остаётся до отказа.
    """
    if horizon_h <= 0:
        raise ValueError(f"горизонт прогноза {horizon_h} ч: ставить срок не к чему")
    запас_ч = min(ЗАПАС_Ч.get(критичность, min(ЗАПАС_Ч.values())), horizon_h / 2)
    return as_of + timedelta(hours=horizon_h - запас_ч)


def запас_часов(due_at: datetime, as_of: datetime, horizon_h: int) -> float:
    """Сколько часов между сроком работ и прогнозируемым отказом."""
    return (момент_отказа(as_of, horizon_h) - due_at).total_seconds() / 3600


def сутки(момент: datetime):
    """Московская дата момента — тот самый ключ, по которому заявки не плодятся.

    Повторяет выражение уникального индекса uq_notif_forecast_daily
    (timezone('Europe/Moscow', reported_at)::date). Зона именно московская:
    в UTC граница суток приходится на 03:00 по Москве, то есть на середину
    ночной смены, и два прогона одной смены попали бы в разные сутки.
    """
    return момент.astimezone(МОСКВА).date()


def обоснование(
    вероятность: float, horizon_h: int, критичность: str, текст_прогноза: str | None
) -> str:
    """Текст заявки для диспетчера: число, класс участка и объяснение прогноза.

    Число стоит первым и всегда: объяснение к прогнозу собирается задачей Q7.7
    и у части прогнозов его нет (в pred.forecast.explanation_ru лежит NULL).
    Заявка без обоснования проваливает М-11, поэтому пустой эта строка быть
    не может ни при каких данных.
    """
    голова = (
        f"Вероятность потери связи с каналом за {horizon_h} ч — "
        f"{вероятность:.3f}, класс участка {критичность}."
    )
    return f"{голова} {текст_прогноза}" if текст_прогноза else голова


def номер_заявки(forecast_id: int) -> str:
    """Номер сообщения ТОиР, 12 знаков — ровно столько в maint.notification."""
    return f"AF{forecast_id:010d}"


def номер_заказа(forecast_id: int) -> str:
    return f"AW{forecast_id:010d}"


# --------------------------------------------------------------------- база


ОТБОР = """
SELECT f.forecast_id, f.probability, f.horizon_h, f.explanation_ru,
       r.as_of, x.smvu_key, x.func_location_id, c.code AS crit
  FROM pred.forecast f
  JOIN pred.run r            ON r.run_id = f.run_id
  JOIN ref.object_xref x     ON x.section_id = f.section_id
  JOIN asset.func_location l ON l.id = x.func_location_id
  JOIN ref.criticality c     ON c.id = l.criticality_id
 WHERE f.run_id = $1 AND f.direction = $2
"""

# ON CONFLICT именно по uq_notif_forecast_daily, с повторением его выражения
# и его условия: без частичного WHERE Постгрес этот индекс не опознает и вставка
# упадёт вместо того, чтобы пропустить повтор.
ВСТАВКА_ЗАЯВКИ = """
INSERT INTO maint.notification
       (notification_no, notification_kind, subject, long_text, func_location_id,
        priority_id, reported_at, due_at, source_system, source_key, forecast_id)
SELECT $1, $2, $3, $4, $5, p.id, $6, $7, $8, $9, $10
  FROM ref.priority p WHERE p.code = $11
ON CONFLICT (coalesce(func_location_id, 0), coalesce(equipment_id, 0),
             (timezone('Europe/Moscow', reported_at)::date))
     WHERE source_system = 'forecast'
DO NOTHING
RETURNING id
"""

ВСТАВКА_ЗАКАЗА = """
INSERT INTO maint.work_order
       (order_no, order_type_id, activity_type_id, subject, func_location_id,
        notification_id, priority_id, planned_start, planned_finish)
SELECT $1, o.id, a.id, $2, $3, $4, p.id, $5, $6
  FROM ref.order_type o, ref.activity_type a, ref.priority p
 WHERE o.code = $7 AND a.code = $8 AND p.code = $9
ON CONFLICT (order_no) DO NOTHING
"""


async def завести(conn, run_id: int, direction: str = "sensor_failure") -> dict:
    """Стадия автозаявок: по прогнозам прогона завести заявки и заказы ТОиР.

    Возвращает три числа, которые нужны в отчёте о прогоне: сколько участков
    прошло порог, сколько заявок заведено, сколько отброшено уникальным индексом
    как повтор за те же сутки. Порог и повтор — разные причины не завести заявку,
    и складывать их в одно «пропущено» нельзя: первое означает «риска нет»,
    второе — «заявка уже есть».

    Заявка и заказ ТОиР пишутся одной транзакцией. Заказ нужен не для красоты:
    вид работ у нас берётся из справочников ref.order_type и ref.activity_type,
    а ссылаются на них колонки заказа. Заявка без заказа — это заявка без вида
    работ, и приёмочная строка М-11 её не засчитает.
    """
    кандидаты = await conn.fetch(ОТБОР, run_id, direction)
    выше_порога = [к for к in кандидаты if нужна_заявка(к["probability"], к["crit"])]

    заведено = 0
    async with conn.transaction():
        for к in выше_порога:
            крит = к["crit"]
            due_at = срок(к["as_of"], к["horizon_h"], крит)
            тема = f"Превентивные работы по прогнозу, участок {к['smvu_key']}"
            notif_id = await conn.fetchval(
                ВСТАВКА_ЗАЯВКИ,
                номер_заявки(к["forecast_id"]),
                ВИД_СООБЩЕНИЯ,
                тема,
                обоснование(
                    к["probability"], к["horizon_h"], крит, к["explanation_ru"]
                ),
                к["func_location_id"],
                к["as_of"],
                due_at,
                ИСТОЧНИК,
                str(к["forecast_id"]),
                к["forecast_id"],
                ПРИОРИТЕТ[крит],
            )
            if notif_id is None:
                continue  # уникальный индекс: заявка на этот объект за эти сутки уже есть
            await conn.execute(
                ВСТАВКА_ЗАКАЗА,
                номер_заказа(к["forecast_id"]),
                тема,
                к["func_location_id"],
                notif_id,
                к["as_of"],
                due_at,
                ВИД_ЗАКАЗА,
                ВИД_РАБОТ[крит],
                ПРИОРИТЕТ[крит],
            )
            заведено += 1

    return {
        "участков": len(кандидаты),
        "выше_порога": len(выше_порога),
        "заявок": заведено,
        "повторов": len(выше_порога) - заведено,
    }


async def проверить_реестр(conn) -> bool:
    """Реестр ТОиР на месте: пара чисел, а не один счётчик.

    Один счётчик здесь обманывает. «3 173 технических места» ничего не говорит
    о том, нашёл ли расчёт объект для КАЖДОГО участка: участок без
    func_location_id выпадет из отбора молча, и заявок просто станет меньше.
    Поэтому проверяем два числа сразу и требуем, чтобы второе было нулём.
    """
    участков = await conn.fetchval(
        "SELECT count(*) FROM asset.func_location WHERE hierarchy_level = 4"
    )
    без_места = await conn.fetchval(
        "SELECT count(*) FROM ref.object_xref WHERE func_location_id IS NULL"
    )
    всего = await conn.fetchval("SELECT count(*) FROM ref.object_xref")
    ок = участков == всего and без_места == 0
    print(
        f"реестр ТОиР: технических мест уровня «участок» {участков}, "
        f"участков в object_xref {всего}, из них без места {без_места} — "
        f"{'сошлось' if ок else 'РАСХОЖДЕНИЕ'}"
    )
    if not ок:
        print(
            "   накатите db/migrations/010_orders.sql ещё раз: на чистой базе "
            "его часть 2 отработала до заливки выгрузки и вставила ноль строк"
        )
    return ок


# --------------------------------------------------------------- самопроверка


def _selfcheck():
    """Три случая, на которых правило обязано отказать, и один, на котором нет."""
    as_of = datetime(2026, 6, 30, 23, 59, 59, tzinfo=МОСКВА)
    отказ = момент_отказа(as_of, 24)
    assert отказ == datetime(2026, 7, 1, 23, 59, 59, tzinfo=МОСКВА), отказ

    # 1. Срок работ обязан быть СТРОГО раньше отказа — иначе заявка не превентивная.
    for крит in ("A", "B", "C"):
        due = срок(as_of, 24, крит)
        assert as_of < due < отказ, (крит, due)
        assert запас_часов(due, as_of, 24) == ЗАПАС_Ч[крит], (крит, due)
    # Критичному участку достаётся запас больше, чем обычному.
    assert срок(as_of, 24, "A") < срок(as_of, 24, "C")
    # Короткий горизонт не уводит срок в прошлое: запас режется половиной горизонта.
    due6 = срок(as_of, 6, "A")
    assert as_of < due6 < момент_отказа(as_of, 6), due6
    assert запас_часов(due6, as_of, 6) == 3.0, due6
    # Горизонта нет — срок ставить не к чему, и это отказ, а не ноль часов запаса.
    try:
        срок(as_of, 0, "A")
    except ValueError:
        pass
    else:
        raise AssertionError("нулевой горизонт обязан быть отказом")

    # 2. Объект ниже порога заявки не получает.
    assert нужна_заявка(0.9701, "A") and not нужна_заявка(0.9700, "A")
    assert not нужна_заявка(0.975, "B"), "класс B строже класса A, 0,975 ему мало"
    assert not нужна_заявка(0.985, "C"), "класс C строже всех, 0,985 ему мало"
    # Ровно на пороге — не заводим: «выше порога» значит строго выше.
    assert not нужна_заявка(ПОРОГ["A"], "A")
    # Неизвестный класс судим по самому строгому порогу, а не пропускаем.
    assert not нужна_заявка(0.98, "Z") and нужна_заявка(0.995, "Z")

    # 3. Повторная заявка за те же сутки. Ключ — московская дата, и две прогонки
    # одной ночной смены обязаны дать ОДИН ключ, а не два.
    ночь1 = datetime(2026, 7, 1, 2, 0, tzinfo=МОСКВА)
    ночь2 = datetime(2026, 7, 1, 4, 0, tzinfo=МОСКВА)
    assert сутки(ночь1) == сутки(ночь2), (сутки(ночь1), сутки(ночь2))
    # А в UTC они попали бы в разные сутки — ровно та ошибка, от которой
    # индекс написан на timezone('Europe/Moscow', …).
    from datetime import timezone

    assert (
        ночь1.astimezone(timezone.utc).date() != ночь2.astimezone(timezone.utc).date()
    )
    # Соседние сутки остаются разными.
    assert сутки(datetime(2026, 7, 1, 23, 59, tzinfo=МОСКВА)) != сутки(
        datetime(2026, 7, 2, 0, 1, tzinfo=МОСКВА)
    )

    # 4. Обоснование не бывает пустым — иначе М-11 красная.
    assert обоснование(0.9991, 24, "A", None).strip()
    assert "0.999" in обоснование(0.9991, 24, "A", None)
    assert обоснование(0.5, 24, "A", "Датчик молчит.").endswith("Датчик молчит.")

    # 5. Номера влезают в свои колонки: notification_no и order_no — varchar(12).
    assert len(номер_заявки(126637)) == 12 == len(номер_заказа(126637))
    assert номер_заявки(126637) == "AF0000126637"
    assert номер_заявки(1) != номер_заявки(2)

    print("order_rules selfcheck ok: пороги, срок раньше отказа, сутки, обоснование")


def main(argv):
    _selfcheck()
    dsn = os.environ.get("DATABASE_URL")
    if not dsn:
        print("DATABASE_URL не задана — сверку реестра ТОиР пропускаю")
        return 0
    import asyncpg

    async def сверить():
        conn = await asyncpg.connect(dsn)
        try:
            return await проверить_реестр(conn)
        finally:
            await conn.close()

    return 0 if asyncio.run(сверить()) else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
