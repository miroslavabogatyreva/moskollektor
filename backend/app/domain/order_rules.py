"""Правило, по которому расчёт заводит превентивную заявку. Q6.2 (MOS-57).

Приёмка: М-10 (заявку заводит расчёт, а не диспетчер), М-11 (объект, вид работ,
срок и обоснование заполнены), М-12 (из заявки открывается прогноз), М-13 (срок
работ — норматив реакции от момента, когда система заметила риск).

Правило целиком — в docs/order-rules.md с разбором на одном участке. Здесь код
и таблицы-ручки, которые это правило задают: ПОРОГ, ВИД_РАБОТ и ПРИОРИТЕТ.

**Срок заявки — момент обнаружения плюс меньшее из двух чисел** (MOS-179):
норматива реакции приоритета (ref.priority.response_hours, 16 / 48 / 72 ч по
Регламенту) и потолка превентивности (ref.app_setting.order_preventive_cap_h,
медиана упреждения модели). Норматив говорит, за сколько Регламент велит устранить
саму неисправность; потолок — за сколько отказ обычно наступает после предупреждения.
Заявка со сроком позже медианы упреждения в большинстве случаев опоздает к отказу,
то есть превентивной не будет. Момент обнаружения — срез прогона, который завёл
заявку: риск заметила система в этот момент. Момент открытия предупреждения модели
(`warning_opened_at` в score.json) хранится отдельной колонкой: считать срок от него
значит родить заявку просроченной, если предупреждение открылось до выкладки
(прогон с откатом 22.09.2026: у 30 заявок из 33 срок оказался раньше среза).
До MOS-179 срок считался от as_of + horizon_h как от «момента отказа», но модель
говорит «отказ возможен в ближайшие horizon_h часов», а не «отказ в час horizon_h»:
при горизонте 720 такой срок уезжал на 29,5 суток вперёд.

Конец окна риска хранится отдельно, в maint.notification.risk_window_end: на пути
v3 это `warning_expires_at` модели, на прежнем — as_of + horizon_h. Это граница,
до которой прогноз обещает риск, а не предсказанный момент отказа.

Запуск самопроверки:
    python -m app.domain.order_rules              # без базы: пороги, сроки, сутки
    DATABASE_URL=postgresql://... python -m app.domain.order_rules
                                                  # плюс сверка реестра ТОиР
"""

