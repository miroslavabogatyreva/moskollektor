async def пороги(conn) -> dict[str, float]:
    """Пороги по классу критичности из ref.app_setting (миграция 035).

    Настройки нет — берём прежние константы: так путь без миграции работает
    ровно как работал, а не падает и не заводит заявки наугад.
    """
    строки = {r["key"]: float(r["value"]) for r in await conn.fetch(
        "SELECT key, value FROM ref.app_setting WHERE key LIKE 'order_threshold_%'")}
    return {к: строки.get(f"order_threshold_{к.lower()}", по_умолчанию)
            for к, по_умолчанию in ПОРОГ.items()}


def нужна_заявка(вероятность: float, критичность: str,
                 пороги_: dict[str, float] | None = None) -> bool:
    """Участок с такой вероятностью и таким классом заслуживает заявки.

    Неизвестный класс критичности — это не повод молча пропустить участок
    и не повод завести заявку наугад: берём самый строгий из порогов.
    """
    п = пороги_ or ПОРОГ
    return вероятность > п.get(критичность, max(п.values()))


def пороговый_отбор(кандидаты: list, пороги_: dict[str, float],
                    разнос: dict[int, tuple[int, float]]) -> list:
    """Прежний путь заявок: кто из участков прошёл порог (Q6.10, MOS-154).

    `разнос` — веса pred.section_weight, если разнос вероятности по участкам
    включён (forecast_spread_enabled), иначе пусто. Без разноса судим участок по его
    вероятности, как было. С разносом у участка лежит ДОЛЯ вероятности объекта:
    потолок доли у объекта Мю из 521 участка — 0,0278, и порог 0,97 не пройдёт никто,
    молча. Поэтому порог сравниваем с вероятностью объекта — суммой долей его
    участков, — а заявку ставим на участок с наибольшей долей, одну на объект.
    Её класс критичности и берём для порога. `p_объекта` уходит в обоснование.
    Участок без веса судится сам по себе: объекта у него нет.
    """
    if not разнос:
        return [к for к in кандидаты if нужна_заявка(к["probability"], к["crit"], пороги_)]
    итог, по_объекту = [], {}
    for к in кандидаты:
        объект = разнос.get(к["section_id"], (None, 0.0))[0]
        if объект is None:
            if нужна_заявка(к["probability"], к["crit"], пороги_):
                итог.append(к)
        else:
            по_объекту.setdefault(объект, []).append(к)
    for группа in по_объекту.values():
        лучший = min(группа, key=lambda к: (-к["probability"], к["section_id"]))
        p_объекта = sum(к["probability"] for к in группа)
        if нужна_заявка(p_объекта, лучший["crit"], пороги_):
            итог.append({**лучший, "p_объекта": p_объекта})
    return итог


def срок(момент: datetime, часов_реакции: float) -> datetime:
    """Срок работ: момент обнаружения риска плюс часы реакции.

    Часы реакции — меньшее из норматива приоритета и потолка превентивности,
    выбирает их завести(); здесь только сложение и отказ на нуле.

    Горизонт прогноза здесь не участвует нарочно. Он говорит, как долго держится
    риск, а не когда нужна бригада: при горизонте 720 срок от конца окна уехал бы
    на месяц, и заявка перестала бы быть превентивной.
    """
    if часов_реакции <= 0:
        raise ValueError(f"норматив реакции {часов_реакции} ч: срок поставить не от чего")
    return момент + timedelta(hours=часов_реакции)


def конец_окна(as_of: datetime, horizon_h: int) -> datetime:
    """Граница окна риска прогноза на прежнем пути: до неё прогноз обещает риск."""
    return as_of + timedelta(hours=horizon_h)


def момент_файла(значение: str) -> datetime:
    """Время из score.json: наивное московское, как `as_of` файла (run.py)."""
    м = datetime.fromisoformat(значение)
    return м if м.tzinfo else м.replace(tzinfo=МОСКВА)


def сутки(момент: datetime):
    """Московская дата момента — часть ключа заявки прежнего пути, `day:<место>:<дата>`.

    Зона именно московская: в UTC граница суток приходится на 03:00 по Москве,
    то есть на середину ночной смены, и два прогона одной смены попали бы
    в разные сутки и дали бы две заявки.
    """
    return момент.astimezone(МОСКВА).date()


def обоснование(
    вероятность: float, horizon_h: int, критичность: str, текст_прогноза: str | None,
    предупреждение: dict | None = None, объект: float | None = None,
) -> str:
    """Текст заявки для диспетчера: число, класс участка и объяснение прогноза.

    Число стоит первым и всегда: объяснение к прогнозу собирается задачей Q7.7
    и у части прогнозов его нет (в pred.forecast.explanation_ru лежит NULL).
    Заявка без обоснования проваливает М-11, поэтому пустой эта строка быть
    не может ни при каких данных.

    Под предупреждением модели число берётся у ПРЕФИКСА, который его открыл,
    а не у прогноза участка: участок несёт максимум по коллектору, и это может
    быть вероятность соседнего префикса (разбор ревью Codex 22.09.2026).
    """
    if предупреждение is None and объект is not None:
        # Разнос включён (Q6.10): порог прошёл объект, а у участка — его доля.
        голова = (
            f"Вероятность потери связи с каналом за {horizon_h} ч по объекту — "
            f"{объект:.3f}, доля участка — {вероятность:.3f} (наибольшая в объекте), "
            f"класс участка {критичность}."
        )
    elif предупреждение is None:
        голова = (
            f"Вероятность потери связи с каналом за {horizon_h} ч — "
            f"{вероятность:.3f}, класс участка {критичность}."
        )
    else:
        п = предупреждение
        окно = (f", окно риска до {момент_файла(п['expires_at']):%d.%m.%Y %H:%M}"
                if п.get("expires_at") else "")
        if п.get("p") is None:
            # Закрытое к срезу открытие из alerts[] (MOS-182): вероятность момента
            # открытия файл не передаёт, а сегодняшняя — это другое число.
            порог = (f" {п['порог']:.3f}" if isinstance(п.get("порог"), (int, float))
                     else "")
            число = (f"к срезу уже закрылось; вероятность потери связи за {horizon_h} ч "
                     f"в момент открытия — выше порога модели{порог}")
        else:
            число = f"вероятность потери связи за {horizon_h} ч — {п['p']:.3f}"
        голова = (
            f"Модель открыла предупреждение по префиксу {п['pfx']} "
            f"{момент_файла(п['opened_at']):%d.%m.%Y %H:%M}{окно}: {число}, класс участка "
            f"{критичность}. Обход начать с участков {', '.join(п['маршрут'])}."
        )
        if п.get("ранние"):
            голова += " В этом же прогоне на участок указали и более ранние открытия: " + ", ".join(
                f"{р['pfx']} {момент_файла(р['opened_at']):%d.%m.%Y %H:%M}"
                + (" (к срезу закрылось)" if р.get("закрыто") else "")
                for р in п["ранние"]) + "."
    return f"{голова} {текст_прогноза}" if текст_прогноза else голова


