"""Стадии 3–5 расчёта по выдаче модели v3: `score.json` -> участки, вероятности, факторы.

**Чем этот путь отличается от прежнего.** Раньше worker сам собирал 22 признака
`feat.v1` по журналу (48,3 секунды из 60 в бюджете) и слал их модели. Модель v3
обучена на других 42 признаках, и считать их второй раз у себя нельзя: ML-команда
пишет прямо, что «любая мелкая разница молча испортит прогноз». Поэтому признаки
и вероятности приезжают готовым файлом от образа `ml-score`, а наша работа — три вещи:

1. перевести ключ модели (`pfx`, 32 значения) на наш `collector_id` (16) —
   `backend/app/worker/score_v3.py` и представление `pred.pfx_collector`;
2. спросить у образа `ml` вклады признаков, чтобы объяснить риск диспетчеру;
3. разложить вероятность коллектора на его участки.

**Почему участки коллектора получают ОДНО число, а не долю.** Разнос из MOS-150
делит вероятность между участками так, что сумма долей внутри коллектора равна
единице. С заглушкой это работало: она давала каждому участку своё число, и сторож
в `publish.py` разнос пропускал. С моделью v3 число одно на коллектор, и деление
уводит максимум по парку до 0,076 при вероятности коллектора 0,87 — замер
22.09.2026 на `pred.section_weight`. Порог заявки 0,63 стал бы недостижим,
а карточка показала бы «риск 2 %» там, где модель говорит 87 %. Поэтому разнос
остаётся выключенным (`forecast_spread_enabled = 0`), а участок несёт вероятность
своего коллектора как есть. Вес участка при этом не пропадает — он сгодится
для порядка обхода внутри коллектора, но это отдельная задача, а не деление числа.

**Вклад и значение — разные величины под одним именем `v`.** В нашем контракте
`feat.v1` поле `v` фактора несёт значение признака; в ответе модели v3 `factors[].v`
несёт вклад признака в вероятность. Имя, порядок и сторону берём из вкладов,
а число для фразы — из значений `features`. Перепутав их, я получил «прошло
0 суток» на всех коллекторах: вклады округляются в ноль.
"""

import asyncio

from app.mlclient import client
from app.worker import score_v3

СХЕМА_ПРИЗНАКОВ = "feat.v3"

МОСТ = "SELECT pfx, collector_id FROM pred.pfx_collector"

# Участки коллектора. Тот же путь «канал -> узел -> коллектор», что в 029,
# только в обратную сторону и без каналов: нам нужны участки, а не датчики.
#
# DISTINCT ON, а не DISTINCT, и это не украшение. Участок 1490 («798:0», пикет 0
# префикса 798) принадлежит ДВУМ коллекторам сразу: 13 его каналов висят на объекте
# Зита, 3 — на объекте Бета. Простой DISTINCT дал 3 174 участка при 3 173 в справочнике,
# и запись прогноза упала на UniqueViolationError по ключу (run_id, section_id) —
# поймано первым же прогоном на стенде 22.09.2026.
#
# Относим участок к коллектору, где у него больше каналов: то же правило большинства,
# что в мосте ключей (миграция 033), и по той же причине — отдать участок обоим
# значило бы показать один пикет в двух местах с разным риском.
УЧАСТКИ_КОЛЛЕКТОРА = """
SELECT DISTINCT ON (c.section_id)
       c.section_id, p.object_id AS collector_id, count(*) AS каналов
  FROM smvu.channel c
  JOIN smvu.object_tree n ON n.object_id = c.object_id
  JOIN smvu.object_tree p ON p.object_id = n.parent_id AND p.level = 2
 WHERE c.is_active AND c.section_id IS NOT NULL
 GROUP BY c.section_id, p.object_id
 ORDER BY c.section_id, каналов DESC, p.object_id
"""


async def мост_ключей(conn) -> dict[str, int]:
    """`{pfx: collector_id}` из представления. Пусто — миграции 033 нет."""
    return {r["pfx"]: r["collector_id"] for r in await conn.fetch(МОСТ)}


async def участки_коллекторов(conn) -> dict[int, list[int]]:
    """`{collector_id: [section_id, ...]}` — по чему раскладывается вероятность."""
    итог: dict[int, list[int]] = {}
    for r in await conn.fetch(УЧАСТКИ_КОЛЛЕКТОРА):
        итог.setdefault(r["collector_id"], []).append(r["section_id"])
    return итог


def факторы_по_вкладам(
    ответ_модели: dict,
    признаки: dict[int, list[float | None]],
    имена: list[str],
    сколько: int,
) -> dict[int, list[dict]]:
    """`{collector_id: [{f, v, d}, ...]}` в порядке убывания вклада.

    `v` — значение признака (для фразы), `d` — сторона по ЗНАКУ ВКЛАДА:
    «up» значит «этот признак поднял риск». Так же читает `explain.объяснить`.
    """
    по_имени = {имя: i for i, имя in enumerate(имена)}
    предсказание = ответ_модели["predictions"][0]
    итог: dict[int, list[dict]] = {}
    for коллектор, вклады in zip(предсказание["section_ids"], предсказание["factors"]):
        ряд = признаки[коллектор]
        итог[коллектор] = [
            {
                "f": в["f"],
                "v": ряд[по_имени[в["f"]]],
                "d": "up" if в["v"] > 0 else "down",
            }
            for в in вклады[:сколько]
            if в["f"] in по_имени
        ]
    return итог


def урезать(
    участки: list[int], вероятности: list[float], факторы: list[list[dict]], предел: int
) -> tuple[list[int], list[float], list[list[dict]]]:
    """Первые `предел` участков по возрастанию section_id — для `--limit` (MOS-168).

    **Порядок по section_id, а не по риску.** Так же отбирает участки прежний
    путь (`ORDER BY section_id LIMIT N` в run.py), и `--limit 50` на обоих путях
    означает одни и те же 50 участков — прогоны можно сравнить между собой.
    Отбор по риску дал бы участки одного-двух самых опасных коллекторов: у v3
    вероятность одна на коллектор, и проверочный прогон видел бы только их.

    Три списка режутся одними индексами: фактор, уехавший к чужому участку,
    дал бы диспетчеру объяснение чужого риска.
    """
    if предел is None or предел >= len(участки):
        return участки, вероятности, факторы
    if предел < 1:
        raise ValueError(f"--limit {предел}: считать нечего")
    индексы = sorted(range(len(участки)), key=lambda i: участки[i])[:предел]
    return (
        [участки[i] for i in индексы],
        [вероятности[i] for i in индексы],
        [факторы[i] for i in индексы],
    )


def заявки_разрешены(предел: int | None, откат: bool) -> bool:
    """Заводить ли автозаявки в этом прогоне (MOS-168).

    Прогон с `--limit` — проверочный: он видит кусок парка, а правило «худшие
    участки коллектора» (order_rules.худшие_по_коллектору) на куске коллектора
    выбирает не те участки, что на целом. Настоящие заявки по такому отбору
    ушли бы бригадам. С `--rollback` стадия проходит целиком и откатывается —
    так она проверяется, не оставляя заявок.
    """
    return not предел or откат


# Участки префикса — по ключу участка «префикс:пикет». Это тот же префикс, по которому
# модель открывает предупреждение (MOS-180): 30 префиксов в ref.object_xref против 32
# в score.json 22.09.2026, недостающие 264 и 672 предупреждений не имели.
УЧАСТКИ_ПРЕФИКСА = "SELECT section_id, smvu_key FROM ref.object_xref"


async def участки_префиксов(conn) -> dict[str, list[tuple[int, str]]]:
    """`{pfx: [(section_id, smvu_key), ...]}` — куда ведёт предупреждение модели."""
    итог: dict[str, list[tuple[int, str]]] = {}
    for r in await conn.fetch(УЧАСТКИ_ПРЕФИКСА):
        итог.setdefault(r["smvu_key"].split(":")[0], []).append((r["section_id"], r["smvu_key"]))
    return итог


async def собрать(
    conn, путь_файла: str, run_id: int, horizon_h: int, направление: str, факторов: int
) -> dict:
    """Всё, что нужно `publish.записать`, плюс диагностика для журнала прогона.

    Возвращает участки, вероятности, факторы и значения признаков — списками
    одной длины и в одном порядке, как их ждёт прежний путь расчёта.
    """
    данные = score_v3.прочитать(путь_файла)
    мост = await мост_ключей(conn)
    if not мост:
        raise score_v3.ФайлНеГодится(
            "представления pred.pfx_collector нет — не накатана миграция 033, "
            "ключ модели не на что переводить"
        )

    по_коллекторам = score_v3.по_коллекторам(данные, мост)
    чужие = по_коллекторам.pop("_чужие", [])
    участки_по_коллектору = await участки_коллекторов(conn)

    # Спрашиваем вклады у образа `ml` — по одному запросу на весь парк коллекторов.
    коллекторы = sorted(по_коллекторам)
    значения = [по_коллекторам[к]["features"] for к in коллекторы]
    # urllib синхронный, а мы внутри цикла событий: без to_thread запрос к модели
    # заблокировал бы его целиком — вместе с планировщиком и всеми соединениями.
    ответ = await asyncio.to_thread(
        client.predict,
        run_id,
        данные["as_of"],
        horizon_h,
        коллекторы,
        значения,
        (направление,),
        feature_names=данные["feature_names"],
        schema_version=СХЕМА_ПРИЗНАКОВ,
    )

    # Вероятность модели и вероятность из файла обязаны совпасть: считает их один
    # и тот же код на одних и тех же весах. Расхождение значит, что образ `ml`
    # и образ `ml-score` собраны из разных версий, и дальше считать нельзя.
    из_файла = [по_коллекторам[к]["p"] for к in коллекторы]
    из_модели = ответ["predictions"][0]["probability"]
    расхождение = max((abs(a - b) for a, b in zip(из_файла, из_модели)), default=0.0)

    факторы_кол = факторы_по_вкладам(
        ответ,
        {к: по_коллекторам[к]["features"] for к in коллекторы},
        данные["feature_names"],
        факторов,
    )

    участки: list[int] = []
    вероятности: list[float] = []
    факторы: list[list[dict]] = []
    без_участков: list[int] = []
    for к in коллекторы:
        свои = участки_по_коллектору.get(к) or []
        if not свои:
            без_участков.append(к)
            continue
        for sid in свои:
            участки.append(sid)
            вероятности.append(по_коллекторам[к]["p"])
            факторы.append(факторы_кол.get(к, []))

    # Предупреждения модели по префиксам и участки, на которые они ведут. Префикс без
    # участков в справочнике остаётся в списке с пустыми участками: order_rules
    # назовёт его вслух, а не потеряет молча.
    открытые, без_момента = score_v3.предупреждения(данные)
    по_префиксу = await участки_префиксов(conn)
    for п in открытые:
        п["участки"] = по_префиксу.get(п["pfx"], [])

    return {
        "предупреждения": открытые,
        "предупреждений_без_момента": без_момента,
        "участки": участки,
        "вероятности": вероятности,
        "факторы": факторы,
        "коллекторов": len(коллекторы),
        "участков": len(участки),
        "предупреждений": len(открытые) + len(без_момента),
        "срез": данные["as_of"],
        "модель": данные["model_version"],
        "порог_модели": данные.get("alert_threshold"),
        "расхождение_с_файлом": расхождение,
        "префиксы_без_моста": чужие,
        "коллекторы_без_участков": без_участков,
        "словарь_отказа": данные.get("failure_values"),
        "значения_вне_словаря": данные.get("unknown_values") or [],
    }


def _selfcheck():
    """Разбор вкладов и раскладка по участкам — на образцах, без базы."""
    имена = ["ev_h_since_prev", "n_dying_ch", "hour"]
    ответ = {
        "predictions": [
            {
                "section_ids": [7, 12],
                "probability": [0.8, 0.3],
                "factors": [
                    [
                        {"f": "ev_h_since_prev", "v": 0.42},
                        {"f": "n_dying_ch", "v": -0.10},
                        {"f": "hour", "v": 0.01},
                    ],
                    [{"f": "n_dying_ch", "v": 0.22}, {"f": "hour", "v": -0.05}],
                ],
            }
        ]
    }
    признаки = {7: [2016.0, 3.0, 13.0], 12: [480.0, 1.0, 5.0]}

    ф = факторы_по_вкладам(ответ, признаки, имена, 2)
    # Значение для фразы — из признаков, сторона — по знаку вклада.
    assert ф[7] == [
        {"f": "ev_h_since_prev", "v": 2016.0, "d": "up"},
        {"f": "n_dying_ch", "v": 3.0, "d": "down"},
    ], ф[7]
    assert ф[12] == [
        {"f": "n_dying_ch", "v": 1.0, "d": "up"},
        {"f": "hour", "v": 5.0, "d": "down"},
    ], ф[12]
    # Просят два — отдаём два, даже если модель прислала три.
    assert all(len(v) <= 2 for v in ф.values())
    # Признак, которого нет в именах, не роняет разбор и не выдумывает индекс.
    ответ["predictions"][0]["factors"][0].append({"f": "чужой_признак", "v": 0.9})
    assert len(факторы_по_вкладам(ответ, признаки, имена, 9)[7]) == 3

    print(
        "run_v3 selfcheck ok: вклад даёт сторону, значение даёт число, чужой признак пропущен"
    )


if __name__ == "__main__":
    _selfcheck()
