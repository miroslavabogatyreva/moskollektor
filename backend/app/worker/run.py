class Секундомер:
    """Длительность стадии в миллисекундах, как её ждут колонки pred.run."""

    def __init__(self):
        self.мс = {}

    def стадия(self, имя):
        return _Стадия(self, имя)


class _Стадия:
    def __init__(self, с, имя):
        self.с, self.имя = с, имя

    def __enter__(self):
        self.t = time.perf_counter()
        return self

    def __exit__(self, *e):
        self.с.мс[self.имя] = int((time.perf_counter() - self.t) * 1000)
        return False


def факторы(значения: list[list[float | None]], имена: list[str],
            объяснимые: set[str] | None = None,
            только_опасные: bool = True) -> list[list[dict]]:
    """Три признака, сильнее всего отклонившихся от нормы парка, на каждый участок.

    **Норма берётся из самого парка, а не из константы.** У признаков разные единицы
    и разные распределения: bad7 меряется тысячами записей, undefined_share_7d —
    долей от нуля до единицы. Сравнивать их порогами нельзя, поэтому считаем место
    значения среди остальных участков: 0 — самый маленький в парке, 1 — самый
    большой, 0,5 — ровно посередине. Отклонение — это расстояние от середины.
    Способ не требует ни параметров, ни знания формы распределения.

    Сторона отклонения едет вместе с признаком: шаблоны в ref.explain_template
    различают rate_ratio_year.up и rate_ratio_year.down, и это не педантизм —
    «писал в 333 раза реже» и «в 333 раза чаще» означают противоположное.

    Здесь выбираются признаки, а русскую фразу собирает backend/app/domain/explain.py
    (задача Q7.7): она подставит value в шаблон и запишет текст в explanation_ru.

    **Кандидаты ограничены теми признаками, которым есть чем объяснить** — то есть
    теми, у кого в ref.explain_template есть фраза. Без ограничения стадия выбирает
    признак, для которого текста не существует, и объяснение выходит пустым.
    Замер 16.09.2026 показал, что это не теория: у трёх самых опасных участков
    парка тройка отклонений вышла readings_1d, readings_7d, readings_30d — три
    признака, говорящие одно и то же «участок молчит», и ни для одного из них
    шаблона нет. Задача Q7.6 предполагала обратное, дословно: «в тройку самых
    отклонившихся от нормы признаков остальные не попадут». Замер это опроверг.
    Побочная польза: семейства вроде readings_1d/7d/30d больше не занимают все
    три места одинаковым по смыслу текстом.

    **Отбор идёт сразу среди опасных отклонений, а не отбрасывает безопасные после.**
    Разница не теоретическая, она посчитана 16.09.2026 на всех 3 173 участках:
    если отобрать три самых отклонившихся в любую сторону и потом выбросить
    безопасные, одну фразу вместо трёх получают 427 участков; если отбирать сразу
    среди опасных — 198. Двести двадцать девять участков получают более полное
    объяснение от одной перестановки, и ни одного лишнего запроса это не стоит.
    Какая сторона опасна — таблица ОПАСНАЯ_СТОРОНА в backend/app/domain/explain.py,
    одна на весь проект: правило, записанное в двух местах, однажды разойдётся.
    """
    ряды = []
    for i in range(len(имена)):
        столбец = sorted(з for з in (строка[i] for строка in значения) if з is not None)
        ряды.append(столбец)

    итог = []
    for строка in значения:
        кандидаты = []
        for i, имя in enumerate(имена):
            з, столбец = строка[i], ряды[i]
            if з is None or len(столбец) < 2:
                continue
            if объяснимые is not None and имя not in объяснимые:
                continue
            # Место в парке от 0 до 1. Берём СЕРЕДИНУ полосы одинаковых значений,
            # а не её левый край: bisect_left при равных значениях возвращает позицию
            # первого из них, и признак, одинаковый у всего парка, получал место 0,
            # то есть «этот участок самый маленький», с отклонением 1,0. Проверка
            # поймала это 16.09.2026 на трёх участках с одинаковым значением признака;
            # в боевом прогоне ошибка давала максимальное отклонение каждому нулю,
            # который делят тысячи участков.
            место = ((bisect.bisect_left(столбец, з) + bisect.bisect_right(столбец, з))
                     / 2 / len(столбец))
            отклонение = abs(место - 0.5) * 2
            сторона = "up" if место > 0.5 else "down"
            if только_опасные and сторона not in explain.ОПАСНАЯ_СТОРОНА.get(имя, set()):
                continue
            if отклонение > 0:
                кандидаты.append((отклонение, имя, з, сторона))
        кандидаты.sort(key=lambda к: -к[0])
        итог.append([{"f": имя, "v": round(float(з), 4), "d": сторона,
                      "dev": round(откл, 3)}
                     for откл, имя, з, сторона in кандидаты[:ФАКТОРОВ_В_ОБЪЯСНЕНИИ]])
    return итог


async def прогон(conn, as_of: datetime | None = None, horizon_h: int | None = None,
                 предел: int | None = None, full_log: bool | None = None,
                 заявки: bool = True) -> dict:
    """Один расчёт. Возвращает итог прогона — то же, что легло в pred.run.

    `предел` — считать только первые N участков по возрастанию section_id, на обоих
    путях: прежнем (отбор до сборки признаков) и v3 (срез после чтения score.json).
    `заявки` — заводить ли автозаявки на стадии 7; решает `run_v3.заявки_разрешены()`.

    `full_log` — писать ли в журнал каждый объект (MOS-147). По умолчанию его
    решает срез: названный явно `--as-of` означает обратный расчёт для замера
    метрик, и такой прогон обязан писать всё, потому что метрики М-18 и М-19
    считаются по журналу. Прогон по расписанию среза не называет и пишет
    изменения плюс пульс.
    """
    часы = Секундомер()
    if not await conn.fetchval("SELECT pg_try_advisory_lock($1)", БЛОКИРОВКА):
        print("занято: расчёт уже идёт в другом процессе")
        return {"status": "занято"}

    if full_log is None:
        full_log = as_of is not None
    as_of = as_of or datetime.now().astimezone()
    run_id = await conn.fetchval(
        "INSERT INTO pred.run (status, as_of, full_log) VALUES ('running', $1, $2) "
        "RETURNING run_id", as_of, full_log)

    итог, ошибка, участков, посчитано = "failed", None, None, None
    try:
        # MOS-110 (Q4.12): горизонт правит администратор, не пересборка образа.
        # Чтение — ПОСЛЕ INSERT INTO pred.run и внутри try (нашла 58): если его
        # поднять выше блокировки, как было сначала, упавший тик (например, до
        # наката 020_app_setting.sql) не оставляет в pred.run ни строки, и со
        # стороны это выглядит не как «расчёт упал», а как «расчёт перестал
        # запускаться» — здесь тот же тик падает и остаётся в журнале как failed.
        requested_horizon = horizon_h
        if horizon_h is None and not ПУТЬ_SCORE:
            значение = await conn.fetchval(
                "SELECT value FROM ref.app_setting WHERE key = 'forecast_horizon_h'")
            # is None, не or: пустая таблица — это None, а явный 0 — это 0, и это
            # разные случаи (нашла 44) — or молча подменил бы настоящий 0 на 24.
            horizon_h = int(значение) if значение is not None else ГОРИЗОНТ_Ч

        # --- 0-бис. Кто отвечает и на тех ли признаках обучен -------------------
        # Схема признаков зависит от того, откуда берём числа: свои 22 (feat.v1)
        # или выдачу модели v3 (feat.v3). Ждём ту, по которой сейчас считаем,
        # иначе проверка контракта отвергнет правильную модель.
        по_v3 = bool(ПУТЬ_SCORE)
        # Collector warning history is persisted independently of the sparse journal.
        модель = await asyncio.to_thread(client.get_model)
        client.проверить_контракт(модель, run_v3.СХЕМА_ПРИЗНАКОВ if по_v3 else None)
        if по_v3:
            score_data = score_v3.прочитать(ПУТЬ_SCORE)
            horizon_h = score_v3.горизонт_продукта(score_data, модель, requested_horizon)
        print(f"прогон {run_id}, срез {as_of:%d.%m.%Y %H:%M}, горизонт {horizon_h} ч")
        версия = модель.get("model_version")
        print(f"   модель {версия}, схема признаков {модель.get('feature_schema')}"
              f"{', ЗАГЛУШКА' if модель.get('degraded') else ''}")
        await conn.execute("UPDATE pred.run SET model_version = $1 WHERE run_id = $2", версия, run_id)

        # --- 1. Граница данных --------------------------------------------------
        # Живого потока СМВУ у нас пока нет — приём показаний это задача Q3.7.
        # Стадия честно меряет то, что делает: узнаёт, докуда доехали данные.
        #
        # ОДНО ОПРЕДЕЛЕНИЕ КРАЯ НА ВЕСЬ ПРОДУКТ (MOS-148), запрос — в app.db.
        # До этой правки здесь стоял max(read_time) по smvu.reading с окном
        # в 90 суток, а планировщик выбирал срез по max(day) свёртки — два
        # определения одной величины в двух соседних файлах. Замер 22.09.2026
        # на стенде: оба дают 2026-06-30 23:59:59+03, но журнал считается
        # 60 964 мс (перемерено проверяющей — 64 974 мс, тот же порядок), а край
        # по свёртке — 0–1 мс на живом соединении прогона и 49,5 мс первым вызовом
        # в новом соединении. Три числа у одного запроса, и различает их методика,
        # а не удача: первый вызов платит за план и прогрев, дальше он бесплатен.
        #
        # Вместе с журналом ушла и ловушка окна. Оно отсчитывалось от as_of,
        # а не от now(): плановый прогон брал край как раз своим срезом и всегда
        # попадал внутрь, а ручной прогон с сегодняшним срезом отстоял от края
        # на 84 суток — до края окна оставалось 6 суток. С 28.09.2026 такой
        # прогон получил бы край = None и отставание = None при живых данных,
        # и ни в логе, ни в API об этом не сказалось бы ни слова. У свёртки
        # окна нет вовсе.
        with часы.стадия("ms_fetch"):
            край = await conn.fetchval(КРАЙ_ДАННЫХ)
        отставание = (as_of - край).total_seconds() / 86400 if край else None
        if край is None:
            # Пустая свёртка — это законный случай до первого refresh_channel_daily,
            # и молчать о нём нельзя: дальше расчёт пойдёт по срезу, который никто
            # не сверил с данными.
            print("   край данных неизвестен: свёртка feat.channel_daily пуста")
        else:
            # Печатаем край в поясе СРЕЗА, а не в том, в котором его отдала база.
            # asyncpg возвращает timestamptz в UTC, а as_of приходит московским —
            # и две соседние строки журнала оказывались в разных поясах: «срез
            # 01.07.2026 01:00» и «данные доехали до 30.06.2026 20:59». Кто вычтет
            # их глазами, получит 4 часа 1 минуту вместо 1 часа 1 секунды. Нашла
            # проверяющая сессия 22.09.2026 на прогоне 507. Тот же класс ошибки,
            # что в коммите d176033: величина верна, пояс печати чужой.
            print(f"   данные доехали до {край.astimezone(as_of.tzinfo):%d.%m.%Y %H:%M}"
                  f"{f', срез старше на {отставание:.0f} сут' if отставание and отставание > 1 else ''}")

        # --- 2. Суточная свёртка за двое суток -----------------------------------
        with часы.стадия("ms_aggregate"):
            свёрнуто = await conn.fetchval(
                "SELECT feat.refresh_section_daily($1::date - 1, $2::date)", as_of, as_of)
        print(f"   свёртка обновила {свёрнуто} строк")

        if по_v3:
            # --- 3–4. Признаки и вероятности приезжают готовыми ------------------
            # Обе стадии меряются вместе: своей работы по сборке признаков у нас
            # тут нет вовсе, а ms_features с нулём соврал бы, будто она бесплатна.
            with часы.стадия("ms_features"):
                v3 = await run_v3.собрать(conn, ПУТЬ_SCORE, run_id, horizon_h,
                                          НАПРАВЛЕНИЕ, ФАКТОРОВ_В_ОБЪЯСНЕНИИ)
            участки, значения = v3["участки"], None
            вероятности, ф_готовые = v3["вероятности"], v3["факторы"]
            if предел:
                # MOS-168: файл несёт весь парк, и без среза здесь `--limit` молча
                # не работал — прогон 501 на стенде при --limit посчитал все 3 173
                # участка и завёл 18 заявок. Режем до записи, чтобы и журнал,
                # и заявки видели только эти участки.
                всего = len(участки)
                участки, вероятности, ф_готовые = run_v3.урезать(
                    участки, вероятности, ф_готовые, предел)
                print(f"   --limit {предел}: берём {len(участки)} участков из {всего} "
                      f"по возрастанию section_id")
            участков = посчитано = len(участки)
            # Инференс прошёл внутри стадии выше — запрос к модели за вкладами
            # там же. Ноль здесь честнее, чем пустая колонка: своей стадии
            # инференса у этого пути нет, а не «она не измерена».
            часы.мс["ms_inference"] = 0

            # Срез файла обязан совпадать со срезом прогона, иначе мы пишем
            # вчерашний риск сегодняшним числом. Разрешённый зазор — ЗАПАС_ФАЙЛА_Ч.
            # Время в score.json наивное, БЕЗ пояса, и оно московское: образ
            # ml-score считает по данным заказчика, а они в московском времени
            # (backend/app/ingest/smvu_csv.py, MSK). Подставлять сюда пояс прогона
            # нельзя — планировщик берёт срез из базы в UTC, и один и тот же момент
            # разошёлся бы ровно на три часа. Поймано первым же автоматическим
            # расчётом на стенде 22.09.2026: «срез файла отстал на 3.0 ч».
            срез_файла = datetime.fromisoformat(v3["срез"])
            if срез_файла.tzinfo is None:
                срез_файла = срез_файла.replace(tzinfo=МОСКВА)
            отставание_файла = abs((as_of - срез_файла).total_seconds() / 3600)
            if отставание_файла > ЗАПАС_ФАЙЛА_Ч:
                raise score_v3.ФайлНеГодится(
                    f"срез файла {v3['срез']} отстал от среза прогона на "
                    f"{отставание_файла:.1f} ч при допуске {ЗАПАС_ФАЙЛА_Ч} ч — "
                    f"ml-score не отработал, считать нечем")
            print(f"   модель {v3['модель']}: коллекторов {v3['коллекторов']}, "
                  f"участков {участков}, открытых предупреждений {v3['предупреждений']}")
            print(f"   вероятности: максимум {max(вероятности):.4f}, "
                  f"медиана {sorted(вероятности)[посчитано // 2]:.4f}; "
                  f"файл и модель разошлись на {v3['расхождение_с_файлом']:.2e}")
            if v3["префиксы_без_моста"]:
                print(f"   ВНИМАНИЕ: префиксы без перевода в коллектор — "
                      f"{', '.join(v3['префиксы_без_моста'])}: их прогноз потерян")
            if v3["коллекторы_без_участков"]:
                print(f"   ВНИМАНИЕ: у коллекторов {v3['коллекторы_без_участков']} "
                      f"нет ни одного участка — прогноз некуда положить")
            if v3["значения_вне_словаря"]:
                print(f"   ВНИМАНИЕ: расчёт встретил значения вне словаря отказа: "
                      f"{v3['значения_вне_словаря']}")
        else:
            # --- 3. Сборка признаков ------------------------------------------------
            отбор = None
            if предел:
                отбор = [r["section_id"] for r in await conn.fetch(
                    "SELECT section_id FROM ref.object_xref ORDER BY section_id LIMIT $1", предел)]
            with часы.стадия("ms_features"):
                участки, значения, диаг = await features.собрать(conn, as_of, отбор)
            участков = len(участки)
            print(f"   признаки: {участков} участков × {len(client.FEATURE_NAMES)}, "
                  f"суток свёртки {диаг['суток_свёртки']}")

            # --- 4. Инференс ---------------------------------------------------------
            with часы.стадия("ms_inference"):
                ответ = await asyncio.to_thread(
                    client.predict, run_id, as_of.isoformat(), horizon_h, участки, значения,
                    (НАПРАВЛЕНИЕ,))
            вероятности = ответ["predictions"][0]["probability"]
            ф_готовые = None
            посчитано = len(вероятности)
            print(f"   модель ответила по {посчитано} участкам, "
                  f"максимум {max(вероятности):.4f}, медиана {sorted(вероятности)[посчитано // 2]:.4f}")

        # --- 5. Объяснения: три самых отклонившихся признака -----------------------
        with часы.стадия("ms_explain"):
            # Суффиксы .up/.down в коде шаблона — это направление отклонения,
            # а признак один: rate_ratio_year.down и rate_ratio_year.up описывают
            # rate_ratio_year. Поэтому суффикс отрезаем.
            шаблоны = await explain.загрузить_шаблоны(conn)
            # Форму НАСТОЯЩИХ шаблонов проверяем здесь, на живом справочнике.
            # Самопроверка explain.py держит свою копию словаря и доказывает только
            # согласие кода с этой копией; 16.09.2026 копия разошлась с базой,
            # и фраза вышла «молчат 110 суток суток подряд». Одна и та же функция
            # зовётся там на выдуманном словаре, здесь — на том, что накатано.
            if (кривые := explain.форма_шаблонов_верна(шаблоны)):
                print(f"   ВНИМАНИЕ: в шаблонах {кривые} после {{value}} стоит слово, "
                      f"которое подставит и код — фраза удвоит его")
            объяснимые = {к.split(".")[0] for к in шаблоны}
            if ф_готовые is not None:
                # Путь v3: что отклонилось, решила сама модель — факторы приехали
                # вкладами из ответа `/predict`. Наш отбор по месту в парке тут
                # не нужен и был бы хуже: он меряет необычность значения, а вклад
                # меряет вложенный риск. Фильтр по объяснимым остаётся — признак
                # без фразы даёт пустое объяснение (замер 16.09.2026, задача Q7.6).
                ф = [[з for з in строка if з["f"] in объяснимые] for строка in ф_готовые]
                тексты = [explain.объяснить(шаблоны, строка, None) for строка in ф]
            else:
                ф = факторы(значения, client.FEATURE_NAMES, объяснимые)
                тексты = explain.собрать(шаблоны, ф, значения, client.FEATURE_NAMES)
        с_текстом = sum(1 for т in тексты if т)
        print(f"   признаков с фразой в справочнике: {len(объяснимые)}, "
              f"участков с выбранными признаками: {sum(1 for с in ф if с)}, "
              f"с готовым текстом: {с_текстом}")

        # --- 6. Запись, свёртка, NOTIFY --------------------------------------------
        with часы.стадия("ms_write"):
            записано = await publish.записать(conn, run_id, as_of, horizon_h,
                                              НАПРАВЛЕНИЕ, участки, вероятности, ф, тексты,
                                              full_log=full_log)
        разбор = ", ".join(f"{имя} {n}" for имя, n in sorted(записано["причины"].items()))
        print(f"   в журнал {записано['журнал']} строк из {записано['участков']} "
              f"посчитанных ({разбор or 'ничего не менялось'}), "
              f"разослан NOTIFY {publish.КАНАЛ}")

        # --- 7. Автозаявки ---------------------------------------------------------
        # Стадия идёт ПОСЛЕ записи прогноза, а не вместе с ней: заявка ссылается
        # на forecast_id, и пока прогноз не лёг в базу, ссылаться не на что.
        # Своей колонки ms_* у стадии нет — в pred.run их ровно шесть, и заводить
        # седьмую ради заявок значит менять схему прогонов из блока Q6.
        if заявки:
            if по_v3:
                счёт = await order_rules.завести_предупреждения(conn, run_id, v3, horizon_h)
            else:
                счёт = await order_rules.завести(conn, run_id, НАПРАВЛЕНИЕ)
            print(f"   заявки ({счёт['правило']}): отобрано {счёт['отобрано']} участков "
                  f"из {счёт['участков']}, заведено {счёт['заявок']}, "
                  f"повторных выдач пропущено {счёт['повторов']}")
        else:
            print("   заявки НЕ заводятся: прогон с --limit без --rollback")
        итог = "done"

    except client.ModelRejected as e:
        # Модель ответила и сказала, что запрос неверен. Виноваты мы, чинить нам.
        итог, ошибка = "failed", f"модель отвергла запрос: {e}"
        print(f"   ОТКАЗ МОДЕЛИ: {e}")
        await publish.пометить_устаревшим(conn, ошибка)
    except client.ModelUnavailable as e:
        # Модель не ответила. Прошлый прогноз остаётся, но помечается устаревшим.
        итог, ошибка = "degraded", f"модель недоступна: {e}"
        устарело = await publish.пометить_устаревшим(conn, ошибка)
        print(f"   МОДЕЛЬ НЕ ОТВЕТИЛА: {e}; помечено устаревшими строк: {устарело}")
    except Exception as e:
        итог, ошибка = "failed", f"{type(e).__name__}: {e}"
        print(f"   ОШИБКА: {ошибка}")
        await publish.пометить_устаревшим(conn, ошибка)
    finally:
        await conn.execute(
            """UPDATE pred.run SET finished_at = now(), status = $2, error_text = $3,
                   objects_total = $4, objects_scored = $5,
                   ms_fetch = $6, ms_aggregate = $7, ms_features = $8,
                   ms_inference = $9, ms_explain = $10, ms_write = $11
                 WHERE run_id = $1""",
            run_id, итог, ошибка, участков, посчитано,
            *[часы.мс.get(к) for к in ("ms_fetch", "ms_aggregate", "ms_features",
                                       "ms_inference", "ms_explain", "ms_write")])
        await conn.fetchval("SELECT pg_advisory_unlock($1)", БЛОКИРОВКА)

    строка = dict(await conn.fetchrow("SELECT * FROM pred.run WHERE run_id = $1", run_id))
    всего_мс = sum(v for k, v in строка.items() if k.startswith("ms_") and v)
    print(f"прогон {run_id}: {итог}, стадии {sum(1 for k, v in строка.items() if k.startswith('ms_') and v is not None)}/6, "
          f"суммарно {всего_мс / 1000:.1f} с")
    return строка


def _selfcheck():
    """Проверка на выдуманных числах: считает ли выбор факторов то, что обещает."""
    имена = ["a", "b", "c"]
    # Участок 0 — крайний снизу по «a», участок 3 — крайний сверху.
    значения = [[0.0, 5.0, 1.0], [1.0, 5.0, 1.0], [2.0, 5.0, 1.0], [9.0, 5.0, 1.0]]
    ф = факторы(значения, имена, только_опасные=False)
    assert ф[0][0]["f"] == "a" and ф[0][0]["d"] == "down", ф[0]
    assert ф[3][0]["f"] == "a" and ф[3][0]["d"] == "up", ф[3]
    # Признак, одинаковый у всех, отклонением быть не может.
    assert all(п["f"] != "b" for с in ф for п in с), ф
    # Белый список: признак без шаблона в тройку не попадает, даже будучи крайним.
    ф2 = факторы(значения, имена, объяснимые={"c"}, только_опасные=False)
    assert all(п["f"] == "c" for с in ф2 for п in с) or all(с == [] for с in ф2), ф2
    assert all(п["f"] != "a" for с in ф2 for п in с), "признак без шаблона просочился"
    # Пустой белый список оставляет объяснение пустым, а не падает.
    assert факторы(значения, имена, объяснимые=set(), только_опасные=False) == [[], [], [], []]
    # С включённым фильтром выдуманные признаки не проходят вовсе: опасной стороны
    # у них нет, и это правильный отказ, а не потеря данных.
    assert факторы(значения, имена) == [[], [], [], []]
    # Настоящий признак проходит только своей опасной стороной.
    только_bad7 = факторы([[0.0], [131.0]], ["bad7"])
    assert только_bad7[1] and только_bad7[1][0]["d"] == "up", только_bad7
    assert только_bad7[0] == [], "отклонение bad7 вниз — хорошая новость, в объяснение не идёт"
    # Больше трёх признаков в объяснение не едет.
    много = [[float(i * j) for j in range(10)] for i in range(5)]
    assert all(len(с) <= ФАКТОРОВ_В_ОБЪЯСНЕНИИ
               for с in факторы(много, [f"f{j}" for j in range(10)], только_опасные=False))
    print("run selfcheck ok: выбор факторов, направление, белый список")


# Заявки прогона с откатом — строкой JSON в stdout, до отката (просьба 78, замер метрик
# по потоку заявок): откат снимает побочные эффекты, но вместе с ними и сами заявки.
# LEFT JOIN на коллектор: участок без коллектора попадает в выгрузку с null, а не пропадает.
ЗАЯВКИ_ПРОГОНА = """
SELECT n.id, coalesce(w.collector_id,so.object_id) AS object_id,
       coalesce(ws.section_id,f.section_id) AS section_id, n.source_key, n.reported_at, n.due_at,
       coalesce(w.opened_at,n.warning_opened_at) AS warning_opened_at
  FROM maint.notification n
  LEFT JOIN pred.forecast f ON f.forecast_id = n.forecast_id
  LEFT JOIN pred.warning_section ws ON ws.id=n.warning_section_id
  LEFT JOIN pred.warning w ON w.warning_key=ws.warning_key
  LEFT JOIN pred.section_object so ON so.section_id = f.section_id
 WHERE (n.source_system = 'forecast' AND f.run_id = $1)
    OR (n.source_system = 'forecast_warning' AND w.first_run_id = $1)
 ORDER BY n.id
"""
ПРИСТАВКА_ЗАЯВКИ = "ЗАЯВКА_JSON"


async def выгрузить_заявки(conn, run_id: int) -> int:
    """Напечатать заявки прогона по одной строке `ЗАЯВКА_JSON {...}`. -> сколько."""
    строки = await conn.fetch(ЗАЯВКИ_ПРОГОНА, run_id)
    for r in строки:
        print(ПРИСТАВКА_ЗАЯВКИ, json.dumps(
            {"id": r["id"], "object_id": r["object_id"], "section_id": r["section_id"],
             "source_key": r["source_key"],
             "reported_at": r["reported_at"].astimezone(МОСКВА).isoformat(),
             "due_at": r["due_at"].astimezone(МОСКВА).isoformat(),
             "warning_opened_at": r["warning_opened_at"] and
                                  r["warning_opened_at"].astimezone(МОСКВА).isoformat()},
            ensure_ascii=False))
    return len(строки)


async def main():
    р = argparse.ArgumentParser(description="Прогон расчёта прогноза")
    р.add_argument("--as-of", help="момент среза, например 2026-06-30T23:59:59+03:00")
    # Без default: не заданный флаг обязан дойти до прогон() как None и попасть
    # в ту же ветку чтения из ref.app_setting, что и вызов планировщика без
    # горизонта, а не тихо подменяться на ГОРИЗОНТ_Ч раньше, чем таблица
    # успеет сказать своё слово (нашла 44).
    р.add_argument("--horizon", type=int, help="без флага — из ref.app_setting")
    р.add_argument("--limit", type=int,
                   help="считать только первые N участков по section_id (оба пути); "
                        "без --rollback заявки не заводятся, а текущий прогноз "
                        "заменяется этими N участками")
    р.add_argument("--rollback", action="store_true", help="откатить всё, что записали")
    р.add_argument("--full-log", action="store_true",
                   help="писать в журнал каждый объект; без флага это решает --as-of")
    р.add_argument("--selfcheck", action="store_true", help="проверка без базы и без модели")
    а = р.parse_args()
    if а.selfcheck:
        _selfcheck()
        return 0

    conn = await asyncpg.connect(os.environ["DATABASE_URL"], command_timeout=900)
    try:
        as_of = datetime.fromisoformat(а.as_of) if а.as_of else None
        заявки = run_v3.заявки_разрешены(а.limit, а.rollback)
        if а.rollback:
            tr = conn.transaction()
            await tr.start()
            try:
                строка = await прогон(conn, as_of, а.horizon, а.limit,
                                      True if а.full_log else None, заявки)
                if строка.get("run_id"):
                    print(f"   заявок прогона выгружено строкой {ПРИСТАВКА_ЗАЯВКИ}: "
                          f"{await выгрузить_заявки(conn, строка['run_id'])}")
            finally:
                await tr.rollback()
                print("откат сделан: в базе следов прогона нет")
        else:
            строка = await прогон(conn, as_of, а.horizon, а.limit,
                                  True if а.full_log else None, заявки)
        return 0 if строка.get("status") in ("done", "занято") else 1
    finally:
        await conn.close()


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))
