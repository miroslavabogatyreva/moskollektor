"""Запись прогноза и оповещение. Часть задачи Q3.2 (MOS-32), стадии 6 и 7.

Две таблицы, и они не дублируют друг друга. `pred.forecast` — история: строка
на каждый прогон, по ней считаются метрики и на неё ссылаются заявки и вердикты.
`pred.forecast_current` — то, что API отдаёт на каждый чих: одна строка на участок,
переписывается целиком в конце расчёта.

**Почему одной транзакцией.** Между удалением прошлого текущего прогноза и записью
нового API не должен увидеть пустую таблицу: диспетчер в этот момент получил бы
«прогноза нет» вместо прогноза. Транзакция закрывает эту щель, а `NOTIFY` уезжает
после `COMMIT` — Postgres придерживает уведомления до конца транзакции сам,
поэтому подписчик не может проснуться раньше, чем данные видны.

**Стадии 6 из docs/HLD.md здесь нет намеренно.** HLD велит на этой стадии обновлять
`geo.object_risk` для раскраски карты. Обновлять нечем: `ref.object_xref.geo_object_id`
пуст у всех 3 173 участков (проверено 16.09.2026), а `geo.object_risk` ключуется
именно этим uuid. Карта у нас схема на SVG и рисуется по `section_id` — решение
ОВ-53 от 15.09.2026. Придут координаты — вернём стадию.
"""

import json
from datetime import datetime, timezone

# Канал оповещения. Его слушает API и рассылает кадр в открытые SSE (HLD разд. 8.2,
# стадия 8). Имя канала — часть контракта с Q4, менять его в одиночку нельзя.
КАНАЛ = "forecast_ready"


def ранги(вероятности: list[float]) -> list[int]:
    """Место участка по риску: 1 — самый опасный.

    Равные вероятности получают разные ранги, и это сознательно: risk_rank
    объявлен NOT NULL и уникальной сортировки от него не требуется, а журнал
    прогнозов должен листаться устойчиво. Порядок равных задаёт номер участка.
    """
    порядок = sorted(range(len(вероятности)), key=lambda i: (-вероятности[i], i))
    места = [0] * len(вероятности)
    for место, i in enumerate(порядок, start=1):
        места[i] = место
    return места


# Политика записи журнала (MOS-147, миграция 026). Значения по умолчанию нужны
# на случай пустой таблицы настроек — ровно так же страхует себя горизонт прогноза
# в run.py. Настоящие значения живут в ref.app_setting и меняются через API.
ПОЛИТИКА_ПО_УМОЛЧАНИЮ = {
    "forecast_deadband": 0.02,
    "forecast_heartbeat_min": 60.0,
    "risk_class_hysteresis": 0.02,
    "risk_class_hold_min": 10.0,
    # 0,80, а не 0,97 (миграция 036, MOS-106): 0,97 подобран под заглушку модели,
    # которая давала числа до 0,9991. Модель v3 даёт по парку максимум 0,8676,
    # и класс high при гистерезисе 0,02 требовал бы 0,99 — недостижимо, карта
    # оставалась одноцветной. Число обязано совпадать с 036_risk_threshold_v3.sql:
    # здесь умолчание на случай пустой таблицы настроек, там — значение при накате,
    # и разойдись они, заказчик получил бы одно поведение при накате с нуля
    # и другое при пустом справочнике.
    "risk_threshold_high": 0.80,
}


async def политика(conn) -> dict:
    """Настройки записи журнала из ref.app_setting, недостающие — из умолчаний."""
    строки = await conn.fetch(
        "SELECT key, value FROM ref.app_setting WHERE key = ANY($1::text[])",
        list(ПОЛИТИКА_ПО_УМОЛЧАНИЮ))
    из_базы = {r["key"]: float(r["value"]) for r in строки}
    return {**ПОЛИТИКА_ПО_УМОЛЧАНИЮ, **из_базы}


def класс_риска(p: float, прошлый: str | None, порог: float, гистерезис: float) -> str:
    """Класс с гистерезисом: поднимаем выше порога+дельта, снимаем ниже порога−дельта.

    Между двумя границами класс НЕ меняется — остаётся прошлым. Это и есть
    гистерезис: ISA-18.2 (IEC 62682) зовёт дребезгом переход туда-обратно три
    раза за 60 секунд и называет средством мёртвую зону. При расчёте раз
    в 4 минуты объект с вероятностью ровно у порога прыгал бы 15 раз в час —
    и писал бы строку в журнал, и мигал бы на экране у диспетчера.

    Класс — это НЕ risk_rank: ранг у нас сквозное место от 1 до 3 173, и на живой
    модели дрожание в четвёртом знаке переставляет соседей, то есть «ранг сменился»
    верно почти для всех объектов почти всегда.
    """
    if p >= порог + гистерезис:
        return "high"
    if p <= порог - гистерезис:
        return "normal"
    return прошлый or "normal"


def причина_записи(p: float, класс: str, прошлое: dict | None, сейчас, п: dict,
                   full_log: bool = False, обязательно: bool = False) -> str | None:
    """Почему строка идёт в журнал — или None, если не идёт.

    `обязательно` — участок, на который в этом прогоне заводится заявка по новому
    предупреждению модели (MOS-180). Заявка ссылается на строку журнала этого
    прогона, а мёртвая зона такую строку пропустила бы: на стенде 22.09.2026
    из прогонов 621…639 строки в журнал легли только у 633 (пульс, 3 173), у 634–639
    ноль — и заявка по новому предупреждению ждала бы пульса до часа.

    Порядок проверок важен: `full` старше всех, потому что прогон для замера
    метрик обязан быть полным; `first` старше `change`, потому что сравнивать
    не с чем. Мёртвая зона меряется от ПОСЛЕДНЕГО ЗАПИСАННОГО значения, а не
    от прошлого расчёта: иначе дрейф по полпроцента за прогон не запишется
    никогда, сколько бы он ни накопил.
    """
    if full_log:
        return "full"
    if not прошлое or прошлое.get("logged_at") is None:
        return "first"
    if abs(p - (прошлое["logged_probability"] or 0.0)) >= п["forecast_deadband"]:
        return "change"
    if класс != прошлое.get("risk_class"):
        return "change"
    возраст_мин = (сейчас - прошлое["logged_at"]).total_seconds() / 60
    if возраст_мин >= п["forecast_heartbeat_min"]:
        return "heartbeat"
    if обязательно:
        return "warning"
    return None


def удержать_класс(кандидат: str, прошлое: dict | None, сейчас, п: dict) -> str:
    """Класс не меняется чаще, чем раз в risk_class_hold_min минут."""
    if not прошлое or прошлое.get("risk_class") is None:
        return кандидат
    прошлый = прошлое["risk_class"]
    if кандидат == прошлый:
        return прошлый
    с = прошлое.get("risk_class_since")
    if с is not None and (сейчас - с).total_seconds() / 60 < п["risk_class_hold_min"]:
        return прошлый
    return кандидат


# --- Разнос вероятности объекта по участкам (MOS-150) ------------------------
# Модель Николая v3 даёт одно число НА ОБЪЕКТ, объектов 16, а экраны показывают
# 3 173 участка. Без разноса 521 плитка объекта Мю красится одним цветом.
# Вес участка внутри объекта считает представление pred.section_weight
# (миграция 028): (отказы + alpha) / (отказы объекта + alpha * число участков).
#
# Насколько числа внутри объекта должны совпасть, чтобы считать их ОДНИМ числом
# объекта. Модель, предсказывающая по объекту, отдаёт одно и то же значение, и
# разойтись оно может только на округлении при передаче через JSON. Всё, что
# больше, — это уже предсказание по участку, и трогать его нельзя.
ДОПУСК_ОДИНАКОВОСТИ = 1e-9


async def веса_участков(conn) -> dict[int, tuple[int, float]]:
    """section_id -> (object_id, вес внутри объекта). Пусто — разнос выключен."""
    включено = await conn.fetchval(
        "SELECT value FROM ref.app_setting WHERE key = 'forecast_spread_enabled'")
    # is None, а не or: выключатель со значением 0 и отсутствующая строка — разные
    # случаи только для сообщения, но ветка одна, и читать её должно быть видно.
    if включено is None or not int(включено):
        return {}
    return {r["section_id"]: (r["object_id"], float(r["weight"]))
            for r in await conn.fetch(
                "SELECT section_id, object_id, weight FROM pred.section_weight")}


def разнести(участки: list[int], вероятности: list[float],
             веса: dict[int, tuple[int, float]]) -> tuple[list[int], list[float]]:
    """Вероятность объекта -> вероятности его участков. -> (индексы, вероятности).

    Возвращает ИНДЕКСЫ, а не участки: рядом идут факторы и тексты объяснений,
    и отфильтровать их вызывающий обязан теми же индексами, иначе объяснение
    приедет к чужому участку.

    **Вероятность объекта берётся средним по его участкам.** Модель v3 отдаёт
    одно число, размноженное на участки объекта, — среднее равно этому числу
    и не зависит от того, сколько участков объекта попало в прогон.

    **Веса перенормируются по фактически присутствующим участкам.** Прогон
    с `--limit 50` приносит кусок объекта, и сумма их весов меньше единицы;
    без перенормировки вероятность объекта усохла бы во столько же раз,
    и проверка «сумма равна исходной» падала бы только на урезанном прогоне.

    **Участок без веса выпадает из расчёта совсем.** Это семь участков, которых
    нет в feat.section_daily: признаки модель берёт оттуда, предсказывать нечем.
    Строки в pred.forecast_current у них не будет, и API ответит «прогноза нет» —
    то же, чего требует MOS-144, но без правки NOT NULL у probability.
    """
    по_объекту: dict[int, list[int]] = {}
    for i, sid in enumerate(участки):
        if sid in веса:
            по_объекту.setdefault(веса[sid][0], []).append(i)

    индексы: list[int] = []
    новые: list[float] = []
    пропущено: dict[int, int] = {}
    for oid, места in по_объекту.items():
        p = [float(вероятности[i]) for i in места]
        # СТОРОЖ. Разносить можно только то, что ещё не разнесено. Если модель
        # дала участкам объекта РАЗНЫЕ числа, она предсказала по участку сама,
        # и её прогноз тут и лежит. Взять от него среднее и раздать по весам
        # значит стереть предсказание молча: участок с 0,99 и участок с 0,00
        # получат одно и то же число, умноженное на свой вес, а в журнале
        # не будет ни ошибки, ни предупреждения.
        # Случай не выдуманный: заглушка модели предсказывает по участку прямо
        # сейчас — 470 различных вероятностей на 521 участке объекта Мю
        # (замер 21.09.2026). Контракт это разрешает: в predict.v1.schema.json
        # section_ids и probability — два параллельных массива, и одинаковость
        # чисел внутри объекта нигде не обещана.
        if len(места) > 1 and max(p) - min(p) > ДОПУСК_ОДИНАКОВОСТИ:
            пропущено[oid] = len(set(p))
            индексы.extend(места)
            новые.extend(p)          # прогноз модели идёт как есть, нетронутым
            continue
        сумма_весов = sum(веса[участки[i]][1] for i in места)
        # Недостижимо через pred.section_weight: там weight > 0 при любом alpha > 0,
        # а при alpha = 0 и объекте без отказов представление упало бы делением
        # на ноль раньше, чем дошло сюда. Сторож стоит потому, что функция чистая
        # и веса ей может подать кто угодно — самопроверка подаёт нули.
        if сумма_весов <= 0:
            continue
        p_объекта = sum(p) / len(p)
        for i in места:
            индексы.append(i)
            новые.append(p_объекта * веса[участки[i]][1] / сумма_весов)

    порядок = sorted(range(len(индексы)), key=lambda k: индексы[k])
    return [индексы[k] for k in порядок], [новые[k] for k in порядок], пропущено


async def записать(conn, run_id: int, as_of, horizon_h: int, direction: str,
                   участки: list[int], вероятности: list[float],
                   факторы: list[list[dict]],
                   тексты: list[str | None] | None = None,
                   *, full_log: bool = False, сейчас=None, spread_enabled: bool = True,
                   политика_записи: dict | None = None,
                   обязательно: frozenset[int] = frozenset()) -> dict:
    """Стадии 6 и 7: прогноз в историю, свёртка в текущее, NOTIFY.

    Возвращает словарь: сколько строк ушло в журнал, по скольким участкам считали
    и по каким причинам строки записаны. Одним числом отвечать больше нельзя —
    с MOS-147 «посчитано» и «записано» это разные числа.

    Текст объяснения кладётся ТОЙ ЖЕ вставкой, что и прогноз, а не отдельным
    UPDATE следом. Иначе между двумя запросами существует состояние «прогноз есть,
    объяснения нет», и если второй запрос не дойдёт, диспетчер получит число
    без причины. Прогноз и его объяснение появляются в базе вместе или никак.
    """
    тексты = тексты or [None] * len(участки)
    сейчас = сейчас or datetime.now(timezone.utc)
    п = политика_записи or await политика(conn)

    # Разнос (MOS-150). Пустой словарь означает «разнос выключен», и тогда ни один
    # список не меняется — ровно то, что работает сегодня на заглушке модели.
    # Ранги считаются ПОСЛЕ разноса: место участка по риску задают разнесённые
    # числа, а не исходные, иначе порядок на дашборде останется объектным.
    пропущено: dict[int, int] = {}
    if spread_enabled and (вес := await веса_участков(conn)):
        индексы, вероятности, пропущено = разнести(участки, вероятности, вес)
        участки = [участки[i] for i in индексы]
        факторы = [факторы[i] for i in индексы]
        тексты = [тексты[i] for i in индексы]
        for oid, различных in sorted(пропущено.items()):
            print(f"   объект {oid}: {различных} различных вероятностей, "
                  f"модель разнесла сама, разнос пропущен")

    места = ранги(вероятности)

    async with conn.transaction():
        # Прошлое состояние читаем ДО перезаписи текущего прогноза: в нём лежит
        # последнее ЗАПИСАННОЕ значение, от которого меряется мёртвая зона.
        прошлое = {r["section_id"]: dict(r) for r in await conn.fetch(
            """SELECT section_id, logged_probability, logged_at, risk_class, risk_class_since
                 FROM pred.forecast_current""")}

        строки, текущее, причины = [], [], {}
        for sid, p, место, ф, т in zip(участки, вероятности, места, факторы, тексты):
            было = прошлое.get(sid)
            кандидат = класс_риска(float(p), (было or {}).get("risk_class"),
                                   п["risk_threshold_high"], п["risk_class_hysteresis"])
            класс = удержать_класс(кандидат, было, сейчас, п)
            причина = причина_записи(float(p), класс, было, сейчас, п, full_log,
                                     sid in обязательно)
            ф_json = json.dumps(ф, ensure_ascii=False)
            if причина:
                строки.append((run_id, sid, direction, horizon_h, float(p), место,
                               ф_json, т, причина))
                причины[причина] = причины.get(причина, 0) + 1
                записано_p, записано_в = float(p), сейчас
            else:
                записано_p, записано_в = было["logged_probability"], было["logged_at"]
            # Отсчёт удержания класса начинается заново только при смене класса.
            с_каких_пор = (было or {}).get("risk_class_since")
            if (было or {}).get("risk_class") != класс or с_каких_пор is None:
                с_каких_пор = сейчас
            текущее.append((sid, run_id, as_of, horizon_h, float(p), место, ф_json,
                            записано_p, записано_в, класс, с_каких_пор))

        await conn.executemany(
            """INSERT INTO pred.forecast
                   (run_id, section_id, direction, horizon_h, probability, risk_rank,
                    factors, explanation_ru, write_reason)
               VALUES ($1, $2, $3, $4, $5, $6, $7::jsonb, $8, $9)""", строки)

        # Полная перезапись, а не UPDATE по участкам: участок, выпавший из расчёта,
        # обязан исчезнуть из текущего прогноза, а не остаться там с прошлым числом.
        # Текущий прогноз остаётся ПОЛНЫМ, 3 173 строки на прогон, — разрежается
        # только журнал (MOS-147). Это разные вопросы: «что показать диспетчеру
        # сейчас» и «что система показывала в момент T».
        # Колонка `as_of` (до миграции 025 называлась `computed_at`) — срез данных,
        # а не время расчёта: сюда едет `as_of` прогона, тот же, что в pred.run.as_of.
        # Время работы расчёта лежит в pred.run.started_at, и API отдаёт его под
        # именем `computed_at` — одно имя, одна величина (MOS-118).
        await conn.execute("DELETE FROM pred.forecast_current")
        await conn.executemany(
            """INSERT INTO pred.forecast_current
                   (section_id, run_id, as_of, horizon_h, probability, risk_rank,
                    is_stale, factors, logged_probability, logged_at,
                    risk_class, risk_class_since)
               VALUES ($1, $2, $3, $4, $5, $6, false, $7::jsonb, $8, $9, $10, $11)""",
            текущее)

        await conn.execute(f"NOTIFY {КАНАЛ}, '{run_id}'")
    return {"журнал": len(строки), "участков": len(участки), "причины": причины,
            "разнос_пропущен": пропущено}


async def пометить_устаревшим(conn, причина: str) -> int:
    """Расчёт не прошёл: прошлый прогноз остаётся, но перестаёт выдавать себя за свежий.

    HLD разд. 6.6, «чего делать нельзя»: показывать старый прогноз без пометки.
    По этому прогнозу человек отправляет бригаду; отдать вчерашнее под видом
    сегодняшнего — это не деградация, а обман. Строк нет вовсе — возвращаем 0,
    и API ответит «прогноза нет», что тоже правда.
    """
    итог = await conn.execute("UPDATE pred.forecast_current SET is_stale = true WHERE NOT is_stale")
    return int(итог.split()[-1])


def _selfcheck():
    assert ранги([0.1, 0.9, 0.5]) == [3, 1, 2], ранги([0.1, 0.9, 0.5])
    # Равные вероятности не должны давать одинаковый ранг: колонка NOT NULL,
    # а журнал прогнозов листается по ней.
    assert ранги([0.5, 0.5, 0.5]) == [1, 2, 3]
    assert ранги([0.0]) == [1]
    assert sorted(ранги([0.3, 0.7, 0.7, 0.1])) == [1, 2, 3, 4]
    _selfcheck_политика()
    _selfcheck_разнос()
    print("publish selfcheck ok")


def _selfcheck_разнос():
    """Разнос вероятности объекта по участкам (MOS-150): базы не нужно.

    Проверяется три вещи. СУММА: разнесённые вероятности участков обязаны
    складываться ровно в ту вероятность, которую дала модель на объект — уехала
    сумма, значит часть риска объекта потерялась по дороге, и на экране это
    выглядит как обычные числа, чуть меньше правильных. СТОРОЖ: объект, которому
    модель дала разные числа, разносить нельзя. ПОРЯДОК: индексы возвращаются
    по возрастанию, иначе объяснения приедут к чужим участкам.
    """
    # Один объект, четыре участка, веса 0,5 / 0,25 / 0,15 / 0,10. Модель даёт
    # объекту 0,8 и размножает это число на все его участки.
    вес = {10: (1, 0.50), 11: (1, 0.25), 12: (1, 0.15), 13: (1, 0.10)}
    инд, новые, пропущено = разнести([10, 11, 12, 13], [0.8, 0.8, 0.8, 0.8], вес)
    assert инд == [0, 1, 2, 3], инд
    assert пропущено == {}, пропущено
    assert abs(sum(новые) - 0.8) < 1e-9, sum(новые)
    assert новые == sorted(новые, reverse=True), новые
    assert abs(новые[0] - 0.4) < 1e-12, новые[0]   # 0,8 × 0,5 = 0,4

    # Два объекта в одном прогоне: каждый сохраняет СВОЮ вероятность, а не общую.
    вес2 = {10: (1, 0.5), 11: (1, 0.5), 20: (2, 0.9), 21: (2, 0.1)}
    _, новые2, _ = разнести([10, 11, 20, 21], [0.4, 0.4, 0.9, 0.9], вес2)
    assert abs(новые2[0] + новые2[1] - 0.4) < 1e-9, новые2
    assert abs(новые2[2] + новые2[3] - 0.9) < 1e-9, новые2

    # Объект, где не отказывал никто: alpha уравнивает всех, каждый получает 1/N.
    ровно = {30: (3, 1 / 3), 31: (3, 1 / 3), 32: (3, 1 / 3)}
    _, поровну, _ = разнести([30, 31, 32], [0.6, 0.6, 0.6], ровно)
    assert all(abs(x - 0.2) < 1e-12 for x in поровну), поровну

    # Участок без веса выпадает из расчёта, а не получает ноль: это те семь,
    # которых нет в свёртке. Индексы обязаны показать, кого убрали.
    инд3, новые3, _ = разнести([10, 99, 11], [0.8, 0.8, 0.8], {10: (1, 0.6), 11: (1, 0.4)})
    assert инд3 == [0, 2], инд3
    assert abs(sum(новые3) - 0.8) < 1e-9, новые3

    # Прогон с --limit: пришла половина объекта, веса перенормированы, и сумма
    # по-прежнему равна вероятности объекта. Без перенормировки вышло бы 0,6.
    инд4, новые4, _ = разнести([10, 11], [0.8, 0.8], вес)
    assert инд4 == [0, 1], инд4
    assert abs(sum(новые4) - 0.8) < 1e-9, sum(новые4)
    assert abs(новые4[0] - 0.8 * 0.5 / 0.75) < 1e-12, новые4

    # Индексы идут по возрастанию при любом порядке объектов во входе.
    инд5, _, _ = разнести([20, 10, 21, 11], [0.9, 0.4, 0.9, 0.4], вес2)
    assert инд5 == [0, 1, 2, 3], инд5

    # Вероятность нуль остаётся нулём: разнос не выдумывает риск.
    _, нули, _ = разнести([10, 11], [0.0, 0.0], {10: (1, 0.9), 11: (1, 0.1)})
    assert нули == [0.0, 0.0], нули

    # --- СТОРОЖ: модель предсказала по участку, разносить нечего ---------------
    # Ровно то, что отдаёт заглушка сегодня. Числа обязаны дойти до базы
    # НЕТРОНУТЫМИ, а объект — попасть в отчёт как пропущенный.
    свои = {10: (1, 0.9), 11: (1, 0.1)}
    инд6, новые6, проп6 = разнести([10, 11], [0.99, 0.01], свои)
    assert инд6 == [0, 1], инд6
    assert новые6 == [0.99, 0.01], новые6
    assert проп6 == {1: 2}, проп6
    # Без сторожа вышло бы среднее 0,5, разнесённое по весам: [0,45; 0,05] —
    # участок с 0,01 стал бы впятеро опаснее, а участок с 0,99 вдвое безопаснее.

    # Сторож различает объекты: один разносим, второй нет, и суммы не смешиваются.
    смесь = {10: (1, 0.5), 11: (1, 0.5), 20: (2, 0.9), 21: (2, 0.1)}
    инд7, новые7, проп7 = разнести([10, 11, 20, 21], [0.4, 0.4, 0.9, 0.2], смесь)
    assert инд7 == [0, 1, 2, 3], инд7
    assert abs(новые7[0] + новые7[1] - 0.4) < 1e-9, новые7   # объект 1 разнесён
    assert [новые7[2], новые7[3]] == [0.9, 0.2], новые7      # объект 2 не тронут
    assert проп7 == {2: 2}, проп7

    # Расхождение МЕНЬШЕ допуска — это одно число, побитое округлением JSON,
    # и разносить его надо. Граница проверяется с обеих сторон, иначе сторож
    # молча съест нормальный объектный прогноз.
    мелочь = 1e-12
    _, новые8, проп8 = разнести([10, 11], [0.8, 0.8 + мелочь], {10: (1, 0.5), 11: (1, 0.5)})
    assert проп8 == {}, проп8
    assert abs(sum(новые8) - (0.8 + мелочь / 2)) < 1e-9, новые8
    _, _, проп9 = разнести([10, 11], [0.8, 0.8 + 1e-6], {10: (1, 0.5), 11: (1, 0.5)})
    assert проп9 == {1: 2}, проп9

    # Объект из ОДНОГО участка сторож не трогает: сравнивать не с чем, и разнос
    # отдаёт участку всю вероятность объекта целиком.
    _, один, проп10 = разнести([10], [0.7], {10: (1, 0.3)})
    assert один == [0.7], один
    assert проп10 == {}, проп10

    # Нулевые веса: объект выпадает целиком, а не делится на ноль. Через
    # pred.section_weight это недостижимо, но функция чистая и обязана держать удар.
    инд11, новые11, _ = разнести([10, 11], [0.8, 0.8], {10: (1, 0.0), 11: (1, 0.0)})
    assert инд11 == [] and новые11 == [], (инд11, новые11)


def _selfcheck_политика():
    """Политика записи журнала (MOS-147): девять случаев, база не нужна.

    Проверка обязана ловить не только «записали, когда надо», но и «НЕ записали,
    когда не надо» — второе и есть вся задача.
    """
    from datetime import timedelta

    п = dict(ПОЛИТИКА_ПО_УМОЛЧАНИЮ)
    t0 = datetime(2026, 9, 21, 12, 0, tzinfo=timezone.utc)

    def прошлое(p, когда, класс="normal", с=None):
        return {"logged_probability": p, "logged_at": когда,
                "risk_class": класс, "risk_class_since": с or когда}

    # 1. Первого прогноза объекта не с чем сравнивать — пишем всегда.
    assert причина_записи(0.5, "normal", None, t0, п) == "first"
    assert причина_записи(0.5, "normal", прошлое(None, None), t0, п) == "first"
    # 2. Изменение больше мёртвой зоны — пишем.
    assert причина_записи(0.53, "normal", прошлое(0.50, t0), t0, п) == "change"
    # 3. Изменение меньше мёртвой зоны и пульс не подошёл — НЕ пишем.
    assert причина_записи(0.505, "normal", прошлое(0.50, t0), t0, п) is None
    # 4. Ничего не менялось, но прошёл час — пишем по пульсу.
    час_спустя = t0 + timedelta(minutes=60)
    assert причина_записи(0.50, "normal", прошлое(0.50, t0), час_спустя, п) == "heartbeat"
    # 5. Класс сменился при крошечном изменении вероятности — пишем.
    assert причина_записи(0.50, "high", прошлое(0.50, t0), t0, п) == "change"
    # 6. Прогон для замера метрик пишет всё, даже когда не менялось ничего.
    assert причина_записи(0.50, "normal", прошлое(0.50, t0), t0, п, full_log=True) == "full"
    # 6а. Участок под новым предупреждением пишется, хотя мёртвая зона его бы пропустила,
    #     а причина другой записи не подменяется: изменение остаётся изменением.
    assert причина_записи(0.505, "normal", прошлое(0.50, t0), t0, п, обязательно=True) == "warning"
    assert причина_записи(0.53, "normal", прошлое(0.50, t0), t0, п, обязательно=True) == "change"

    # 7. Гистерезис: между порогом−дельта и порогом+дельта класс НЕ меняется.
    порог, д = п["risk_threshold_high"], п["risk_class_hysteresis"]
    assert класс_риска(порог + д, "normal", порог, д) == "high"
    assert класс_риска(порог - д, "high", порог, д) == "normal"
    assert класс_риска(порог, "high", порог, д) == "high"      # у самого порога
    assert класс_риска(порог, "normal", порог, д) == "normal"  # класс держится
    assert класс_риска(0.1, None, порог, д) == "normal"

    # 8. Удержание: класс не меняется чаще, чем раз в risk_class_hold_min.
    рано = t0 + timedelta(minutes=п["risk_class_hold_min"] - 1)
    поздно = t0 + timedelta(minutes=п["risk_class_hold_min"] + 1)
    было = прошлое(0.5, t0, "normal", t0)
    assert удержать_класс("high", было, рано, п) == "normal"
    assert удержать_класс("high", было, поздно, п) == "high"

    # 9. Дрейф по полпроцента за прогон обязан записаться, когда накопит
    #    мёртвую зону. Это и проверяет, что сравниваем с последним ЗАПИСАННЫМ
    #    значением, а не с прошлым расчётом: во втором случае не запишется никогда.
    состояние, записей, p = прошлое(0.50, t0, "normal", t0), 0, 0.50
    for шаг in range(1, 9):
        p = 0.50 + 0.005 * шаг
        причина = причина_записи(p, "normal", состояние, t0, п)
        if причина:
            записей += 1
            состояние = прошлое(p, t0, "normal", t0)
    assert записей == 2, записей  # на 4-м и на 8-м шаге, по 0,02 накопленного дрейфа


if __name__ == "__main__":
    _selfcheck()
