ПОГОДА_СВЕЖА_МИН = 59
# Не 60: норматив «Метеоданных» в GET /api/sources — 3600 с ровно, и при
# заборе раз в 60 минут шаг 60–61 минута сам давал бы минуту «отстаёт»
# каждый час — ложную тревогу от собственного расписания, а не от источника.

# Между отказом и восстановлением тик молчит: иначе час простоя источника —
# это 60 одинаковых строк «недоступен» в журнале контейнера. Флаг живёт
# в процессе worker, переживает отдельные тики, но не рестарт.
_ПОГОДА_БЫЛ_ОТКАЗ = False


async def тик_погода():
    """Ф-85: держит погоду не старше часа, забирая её за сутки до среза прогноза.

    Планировщик зовёт эту функцию раз в минуту (MOS-241), а не раз в час — раньше
    отказ источника (например, api ещё не поднялся после общего
    `docker compose up -d api worker`, MOS-237) откладывал следующую попытку
    на целый час, и весь этот час «Метеоданные» на экране источников висели «—».
    Функция сама решает, пора ли идти за новым часом: если последний УСПЕШНЫЙ
    забор свежее `ПОГОДА_СВЕЖА_МИН` минут, делать нечего, тик молча выходит.
    Отказ не двигает `fetched_at`, поэтому следующий тик — уже через минуту —
    увидит ту же самую устаревшую метку и попробует снова, без ожидания часа.

    Срез берём у текущего прогноза (pred.forecast_current), а не считаем заново:
    при проигрывании архива (SCORE_V3_REPLAY) он стоит на июне, а не на крае
    данных, и погода должна стоять рядом с тем же часом.
    """
    conn = await asyncpg.connect(os.environ["DATABASE_URL"], command_timeout=60)
    try:
        забрано_недавно = await conn.fetchval(
            "SELECT max(fetched_at) > now() - $1::interval FROM ext.weather_hourly",
            timedelta(minutes=ПОГОДА_СВЕЖА_МИН),
        )
        if забрано_недавно:
            return
        срез = await conn.fetchval(
            "SELECT max(r.as_of) FROM pred.forecast_current fc "
            "JOIN pred.run r ON r.run_id = fc.run_id"
        )
        if срез is None:
            print("погода: прогноза ещё нет, забирать не на какой срез")
            return
        global _ПОГОДА_БЫЛ_ОТКАЗ
        try:
            n = await забрать_погоду(conn, срез)
        except Exception as e:  # noqa: BLE001 — сеть, HTTP, пустой ответ — источник недоступен
            if not _ПОГОДА_БЫЛ_ОТКАЗ:
                print(f"погода: источник недоступен, попробую снова через минуту: {e!r}")
                _ПОГОДА_БЫЛ_ОТКАЗ = True
            return
        if _ПОГОДА_БЫЛ_ОТКАЗ:
            print(f"погода: источник снова отвечает, забрано {n} ч до среза {срез:%d.%m.%Y %H:%M %z}")
            _ПОГОДА_БЫЛ_ОТКАЗ = False
        else:
            print(f"погода: забрано {n} ч до среза {срез:%d.%m.%Y %H:%M %z}")
    finally:
        await conn.close()


async def тик_свёртка():
    """НФ-73: только стадия 2 (свёртка), без блокировки — с полным прогоном не конфликтует.

    **Каждый запуск оставляет строку в `feat.refresh_run`** (миграция 023). До
    21.09.2026 свёртка писала только `print` в журнал контейнера, который живёт
    до пересоздания: пропуск свёртки не видела ни одна проверка, а её задержку
    нельзя было померить запросом. Строку заводим ДО вызова функции и закрываем
    после — иначе свёртка, упавшая на середине, не оставила бы следа вовсе,
    а это ровно тот случай, ради которого журнал и заведён.
    """
    conn = await asyncpg.connect(os.environ["DATABASE_URL"], command_timeout=60)
    try:
        refresh_id = await conn.fetchval(
            "INSERT INTO feat.refresh_run (status) VALUES ('running') RETURNING refresh_id"
        )
        try:
            as_of = datetime.now().astimezone()
            свёрнуто = await conn.fetchval(
                "SELECT feat.refresh_section_daily($1::date - 1, $2::date)", as_of, as_of
            )
        except Exception as e:
            await conn.execute(
                "UPDATE feat.refresh_run SET status = 'failed', finished_at = now(), "
                "error_text = $2 WHERE refresh_id = $1",
                refresh_id, f"{type(e).__name__}: {e}"[:1000],
            )
            print(f"свёртка упала: {type(e).__name__}: {e}")
            raise
        await conn.execute(
            "UPDATE feat.refresh_run SET status = 'done', finished_at = now(), "
            "rows_updated = $2 WHERE refresh_id = $1",
            refresh_id, свёрнуто,
        )
        print(f"свёртка {refresh_id}: обновила {свёрнуто} строк")
    finally:
        await conn.close()


