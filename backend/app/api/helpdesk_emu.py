"""Хелпдеск: эмулятор системы учёта заявок заказчика. Задача MOS-63 (план 6.8),
приёмка Ф-87, НФ-69, Ф-96.

ЭМУЛЯТОР, НЕ ИНТЕГРАЦИЯ. Заказчик закрыл ОВ-50 письменно 19.09.2026: реестр заявок
живёт в самописном хелпдеске на Django, «напрямую системы до сих пор не
интегрированы и не будут интегрированы», а «для синтетических макетов достаточно
симуляции». Условие к симуляции он поставил тем же письмом: данные должны быть
«адекватные и правдоподобные, а не просто случайные числа» (сводный 9). Поэтому
статус заявки — детерминированная функция её номера и возраста, а не `random()`:
тот же `notification_no` в любой момент времени даёт тот же ответ, и статус только
идёт вперёд по циклу, никогда назад.

ЦИКЛ ХЕЛПДЕСКА. Django-хелпдеск заказчика ведёт заявку по четырём шагам: принята →
назначена бригада → в работе → выполнена. Диапазоны времени между шагами — из
диспетчерской практики, не из данных заказчика (реестра заявок и историю
обработки он не даёт, ОВ-50):
  - 5…30 мин от заведения до «принята» — обычная скорость диспетчера прочитать
    новую заявку;
  - 15…90 мин от «принята» до «назначена бригада» — найти свободную бригаду;
  - 1…4 ч от заведения до «в работе» — верхняя граница из задания MOS-63,
    нижнюю подобрала так, чтобы «в работе» не наступало раньше «назначена бригада»;
  - «выполнена» — в случайной точке между 60 % и 95 % срока заявки (due_at −
    reported_at): почти всегда укладывается в срок, но не всегда впритык
    к заведению, как было бы у мгновенного закрытия.
Числа хешем от notification_no, не `random.seed()`: генератор случайных чисел
Python не гарантирует одну и ту же последовательность между версиями и процессами,
а нам нужна воспроизводимость навсегда, а не только в пределах одного запуска.

При сроке заявки короче 6 ч «выполнена» иногда уходит за `due_at` — при 4 ч так
у 120 из 2000 заявок (проверено симуляцией), у 6 ч и длиннее такого уже не
бывает. Сегодня сроки заявок 12 и 16 ч (`ref.priority.response_hours`), это
безопасная зона.

МАРШРУТ БЕЗ /api, как у эмулятора погоды (app.api.weather): nginx его наружу
не отдаёт (deploy/nginx/nginx.conf проксирует только /api/), worker и api ходят
на api:8000 напрямую.

ТОЛЬКО ЧТЕНИЕ. Один GET, тела запроса нет, состояния эмулятор не хранит — все
входные данные (notification_no, reported_at, due_at) называет вызывающий.
"""

import hashlib
from datetime import datetime, timedelta
from pathlib import Path

from fastapi import APIRouter, HTTPException, Query
from pydantic import BaseModel

emu_router = APIRouter(prefix="/emu/helpdesk/v1")

# Имена бригад детерминированы тем же хешем, что и шаги: та же заявка — та же
# бригада на всех статусах после назначения (приёмка «исполнитель стабилен»).
БРИГАДЫ = ["Бригада №3", "Бригада №7", "Бригада №12", "Бригада №19", "Бригада №24"]


class Тикет(BaseModel):
    notification_no: str
    external_status: str
    external_status_at: datetime
    external_assignee: str


class ОтветХелпдеска(BaseModel):
    schema_version: str
    tickets: list[Тикет]


def _доля(notification_no: str, соль: str) -> float:
    """Детерминированная псевдослучайная доля [0, 1) от номера заявки и соли шага.

    Делим на 2**32, не на 0xFFFFFFFF: числитель достигает 0xFFFFFFFF, и деление
    на само 0xFFFFFFFF дало бы ровно 1.0 — `БРИГАДЫ[int(1.0 * len(БРИГАДЫ))]`
    вышел бы за конец списка (IndexError). При делении на 2**32 доля строго
    меньше 1.0 для любого 32-битного числителя.
    """
    х = hashlib.sha256(f"{notification_no}:{соль}".encode()).hexdigest()
    return int(х[:8], 16) / 2**32


def шаги_цикла(
    notification_no: str, reported_at: datetime, due_at: datetime
) -> list[tuple[str, datetime, str]]:
    """Четыре отметки цикла (имя шага, момент, исполнитель) по возрастанию времени."""
    исполнитель = БРИГАДЫ[int(_доля(notification_no, "бригада") * len(БРИГАДЫ))]
    принята = reported_at + timedelta(minutes=5 + _доля(notification_no, "принята") * 25)
    назначена = принята + timedelta(minutes=15 + _доля(notification_no, "назначена") * 75)
    в_работе = reported_at + timedelta(hours=1 + _доля(notification_no, "в_работе") * 3)
    в_работе = max(в_работе, назначена + timedelta(minutes=5))
    срок = due_at - reported_at
    выполнена = reported_at + срок * (0.6 + _доля(notification_no, "выполнена") * 0.35)
    выполнена = max(выполнена, в_работе + timedelta(minutes=10))
    return [
        ("принята", принята, исполнитель),
        ("назначена бригада", назначена, исполнитель),
        ("в работе", в_работе, исполнитель),
        ("выполнена", выполнена, исполнитель),
    ]


def текущий_шаг(
    notification_no: str, reported_at: datetime, due_at: datetime, as_of: datetime
) -> tuple[str, datetime, str] | None:
    """Последний наступивший к `as_of` шаг цикла или None — заявка ещё не принята."""
    текущий = None
    for имя, момент, исполнитель in шаги_цикла(notification_no, reported_at, due_at):
        if момент <= as_of:
            текущий = (имя, момент, исполнитель)
    return текущий


@emu_router.get("/tickets", response_model=ОтветХелпдеска)
async def emu_tickets(
    notification_no: list[str] = Query(...),
    reported_at: list[datetime] = Query(...),
    due_at: list[datetime] = Query(...),
    as_of: datetime | None = None,
):
    if not (len(notification_no) == len(reported_at) == len(due_at)):
        raise HTTPException(
            400, "notification_no, reported_at и due_at должны прийти одной длины"
        )
    сейчас = as_of or datetime.now().astimezone()
    тикеты = []
    for номер, заведена, срок in zip(notification_no, reported_at, due_at):
        шаг = текущий_шаг(номер, заведена, срок, сейчас)
        if шаг is None:
            continue
        имя, момент, исполнитель = шаг
        тикеты.append(
            {
                "notification_no": номер,
                "external_status": имя,
                "external_status_at": момент,
                "external_assignee": исполнитель,
            }
        )
    return {"schema_version": "helpdesk.v1", "tickets": тикеты}


if __name__ == "__main__":
    М = "Europe/Moscow"
    from zoneinfo import ZoneInfo

    ПОЯС = ZoneInfo(М)
    завед = datetime(2026, 9, 1, 10, 0, tzinfo=ПОЯС)
    срок = завед + timedelta(hours=16)

    шаги = шаги_цикла("AF0000999001", завед, срок)
    имена = [и for и, _, _ in шаги]
    assert имена == ["принята", "назначена бригада", "в работе", "выполнена"], имена
    моменты = [м for _, м, _ in шаги]
    assert моменты == sorted(моменты), "шаги идут не по возрастанию времени"
    assert моменты[0] <= завед + timedelta(minutes=30), "принята позже верхней границы 30 мин"
    assert моменты[2] <= завед + timedelta(hours=4), "в работе позже верхней границы 4 ч"
    assert моменты[3] <= срок, "выполнена позже due_at"

    исполнители = {и for _, _, и in шаги}
    assert len(исполнители) == 1, "исполнитель должен быть один на всю заявку"

    # До первого шага статуса нет вовсе.
    assert текущий_шаг("AF0000999001", завед, срок, завед) is None
    # Сразу после первого шага статус — «принята», не «назначена бригада».
    assert текущий_шаг("AF0000999001", завед, срок, моменты[0] + timedelta(seconds=1))[0] == "принята"
    # Между вторым и третьим шагом статус монотонно не откатывается назад.
    между = моменты[1] + (моменты[2] - моменты[1]) / 2
    assert текущий_шаг("AF0000999001", завед, срок, между)[0] == "назначена бригада"
    # После всех шагов — «выполнена», и дальше время не меняет статус.
    assert текущий_шаг("AF0000999001", завед, срок, срок + timedelta(days=365))[0] == "выполнена"

    # Тот же номер и другие даты — те же доли, другие абсолютные моменты: детерминизм
    # держится на notification_no, а не на входных reported_at/due_at.
    завед2 = завед + timedelta(days=10)
    шаги2 = шаги_цикла("AF0000999001", завед2, завед2 + timedelta(hours=16))
    assert (шаги2[0][1] - завед2) == (шаги[0][1] - завед), "смещение первого шага должно повторяться"

    # Разные номера — разные бригады хотя бы иногда (не все пять в одну).
    бригады = {шаги_цикла(f"AF{n:010d}", завед, срок)[0][2] for n in range(20)}
    assert len(бригады) > 1, "все двадцать заявок достались одной бригаде — хеш не разводит номера"

    # Ф-96: contracts/examples/orders/external_status.json — не выдуманный образец,
    # а настоящий ответ. Ключи каждого тикета обязаны совпадать с полями модели
    # Тикет — ни пятого поля из request (было раньше, поймала проверяющая), ни
    # пропущенного поля ответа.
