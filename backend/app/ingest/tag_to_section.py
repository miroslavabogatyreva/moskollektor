#!/usr/bin/env python3
"""Ключ участка коллектора из справочника каналов СМВУ.

Зачем. Заказчик не присылает участок ни отдельной колонкой, ни ссылкой. В выгрузке
от 09.09.2026 участок приходится собирать из двух мест справочника каналов:

    тег_инженерной_системы   "847-11.1.131.2."   -> коллектор  847
    название_датчика         "КД АВ ПК106 ур.3"  -> пикет       106

Почему именно так. Все 11 485 тегов уникальны, по одному на канал, — значит тег целиком
это ключ датчика, а не места. Место лежит в названии: 93,3 % названий содержат номер
пикета ("ПК106", "ПК588-ПК591", "ПК0+6"). Пикет — участок работ, так он назван
в глоссарии ТЗ заказчика (docs/tz-djkh.pdf, разд. 1).

Почему пара, а не один пикет. Пикетаж у каждого коллектора свой и начинается с нуля:
из 32 префиксов 27 имеют канал на ПК0. ПК0 коллектора 847 и ПК0 коллектора 914 —
разные точки города. Ключ участка поэтому пара (коллектор, пикет).

Оставшиеся 6,7 % названий (765 каналов) пикета не содержат. Участка у них нет,
section_key возвращает None, но коллектор из тега у них есть всегда, и загрузчик
пишет его в smvu.channel.collector отдельно (collector_of). Куда такой канал
отнести, говорит location_kind (миграция 031): 44 охранные зоны ("Охранная зона
Ленинский 83"), 717 датчиков в зданиях диспетчерских ("Темп. диспетчерская ДП"),
3 без ответа. Один канал из 765 пикет всё-таки имеет, только записан без «ПК»:
"ОД АВ 185+5" — его ловит узкое правило PICKET_NO_PK.

Переехал сюда из `code/` 15.09.2026 задачей Q2.6: разбор нужен загрузчику
`backend/app/ingest/smvu_csv.py`, а он работает внутри образа, куда `code/` не копируется.
Копии в `code/` не осталось намеренно — две реализации одного разбора разойдутся молча.
В комментариях `db/migrations/004_events.sql` и `005_xref.sql` остался прежний путь:
эти файлы уже накатаны, и правка текста сменила бы их sha256, а `app.migrate` на этом
падает — так он и задуман.

Проверка:
    python3 backend/app/ingest/tag_to_section.py                                  самопроверка
    python3 backend/app/ingest/tag_to_section.py dataset/справочник_каналов_датчиков.csv   отчёт
"""

import re
import sys

# "ПК106", "ПК 106", "пк106+8", "ПК588-ПК591" -> берём первое число.
# Плюс и минус после номера — это смещение в метрах внутри пикета ("ПК0+6"),
# на участок оно не влияет.
PICKET = re.compile(r"ПК\s*(\d+)", re.IGNORECASE)

# "ПК176+6,5" — смещение в метрах внутри пикета. Запятая как разделитель дробной части,
# так пишет заказчик. Встречается у 3827 названий из 11 485.
OFFSET = re.compile(r"ПК\s*(\d+)\s*\+\s*(\d+(?:[.,]\d+)?)", re.IGNORECASE)

# Пикет без буквенного «ПК»: "ОД АВ 185+5" (канал 645-1.1.117.5.) — так на выгрузке
# от 15.09.2026 записан ровно один датчик. Правило нарочно узкое: «АВ», пробел,
# число, плюс, цифра. Шире брать нельзя — "ДД каб.201+201А" тоже «число+число»,
# но это номер кабинета в здании, а не смещение внутри пикета.
PICKET_NO_PK = re.compile(r"(?<!\w)АВ\s+(\d+)\s*\+\s*\d")

# Охранная зона — группа датчиков, а не точка на оси коллектора. В теге её выдаёт
# адрес 4096 ("15-11.1.4096.4095.") или групповой узел "-g<n>." ("884-g1."),
# в названии — слово в начале, в том числе с разорванной скобкой
# ("[Охранная зонаКоллектор Мосрентген").
ZONE_TAG = re.compile(r"\.4096\.|-g\d+\.$")
ZONE_NAME = ("Охранная зона", "[Охранная зона]")

# Куда отнесён канал. Порядок проверки в location_kind совпадает с порядком здесь.
LOCATION_KINDS = ("section", "zone", "building", "unknown")


def collector_of(tag):
    """Коллектор — префикс тега до дефиса, "847-11.1.131.2." -> "847", или None.

    Тег даёт коллектор всегда, есть в названии пикет или нет. До 21.09.2026 коллектор
    писался только вместе с пикетом, и 765 каналов из 11 485 теряли его молча.
    """
    if not tag:
        return None
    return tag.split("-", 1)[0].strip() or None


def picket_of(name):
    """Номер пикета из названия датчика или None."""
    found = PICKET.search(name or "") or PICKET_NO_PK.search(name or "")
    return int(found.group(1)) if found else None


def location_kind(tag, name, object_kind):
    """section, zone, building или unknown — где стоит канал.

    object_kind — вид_объекта из справочника объектов по ид_объект канала
    ("controlHouse", "guardObject") или None. Здание берём только по виду объекта:
    по названию «ДП» не отличить диспетчерскую от двери в коллектор у ДП.
    Порядок важен: пикет в названии сильнее всего, зона сильнее здания —
    "Охранная зона Шкаф ОПС" висит на controlHouse, но это зона.
    """
    name = name or ""
    if collector_of(tag) and picket_of(name) is not None:
        return "section"
    if ZONE_TAG.search(tag or "") or name.startswith(ZONE_NAME):
        return "zone"
    if object_kind == "controlHouse":
        return "building"
    return "unknown"


def section_key(tag, name):
    """Пара (коллектор, пикет) или None, если канал не в коллекторе.

    tag  — тег_инженерной_системы, например "847-11.1.131.2."
    name — название_датчика, например "КД АВ ПК106 ур.3"
    """
    collector, picket = collector_of(tag), picket_of(name)
    if collector is None or picket is None:
        return None
    return collector, picket


def linear_metres(name):
    """Расстояние от начала коллектора в метрах, или None.

    В названии встречается смещение внутри пикета: "ПК176+6,5". Пикет — десять метров,
    значит координата это пикет × 10 плюс смещение: 176 × 10 + 6,5 = 1 766,5 м.
    Разделитель дробной части в выгрузке — запятая.

    Зачем нужно. Координат и адресов заказчик не прислал, данные обезличены, а строка
    приёмки М-05 требует карту. Линейная координата — наш запасной ход: по ней рисуется
    схема коллектора в одну ось, даже если географии не будет вовсе (ОВ-53).

    Почему десять, а не сто. До 17.09.2026 мы считали пикет стометровым по общему
    железнодорожному нормативу. На встрече заказчик назвал десять метров дважды:
    голосом ([00:42:15] записи) и письменно, прямым ответом на вопрос «можно ли
    считать 100 метров» — «10 м». Данные с ним согласны: у 3 808 названий со
    смещением 99,3 % смещений меньше десяти, максимум 30. При стометровом пикете
    смещения растекались бы по всему диапазону до ста. Шаг между соседними
    извещателями шлейфа 847 при этом выходит 7 метров вместо прежних 97 — для
    пожарных извещателей это правдоподобно, а 97 метров были абсурдом.

    Смещение есть не у всех: на выгрузке от 09.09.2026 таких названий 3827 из 11 485.
    У остальных возвращаем метры по началу пикета, а не None, — иначе датчик без
    смещения выпадет с оси целиком.
    """
    if not name:
        return None
    found = OFFSET.search(name)
    if found:
        return int(found.group(1)) * 10 + float(found.group(2).replace(",", "."))
    found = PICKET.search(name)
    if found:
        return int(found.group(1)) * 10.0
    return None


def report(path):
    """Печатает покрытие по настоящему справочнику каналов."""
    import collections
    import csv

    with open(path, encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    sections = collections.Counter()
    unresolved = []
    for r in rows:
        key = section_key(r.get("тег_инженерной_системы"), r.get("название_датчика"))
        if key:
            sections[key] += 1
        else:
            unresolved.append(r.get("название_датчика"))
    total = len(rows)
    ok = sum(sections.values())
    print(f"каналов в справочнике: {total}")
    print(f"привязано к участку:   {ok} ({100 * ok / total:.1f} %)")
    print(f"без участка:           {len(unresolved)} ({100 * len(unresolved) / total:.1f} %)")
    print(f"участков получилось:   {len(sections)}")
    print(f"коллекторов:           {len({c for c, _ in sections})}")
    print("\nбез участка, первые 5 — проверить, что это датчики в зданиях:")
    for n in unresolved[:5]:
        print(f"   {n}")


def selfcheck():
    # обычный случай: коллектор из тега, пикет из названия
    assert section_key("847-11.1.131.2.", "КД АВ ПК106 ур.3") == ("847", 106)
    assert section_key("15-11.1.104.2.", "ТД ПК86-85") == ("15", 86)

    # смещение в метрах внутри пикета участка не меняет
    assert section_key("847-1.1.1.1.", "ДД ПК0+6") == ("847", 0)
    assert section_key("847-1.1.1.1.", "ДД ПК2+1") == ("847", 2)

    # диапазон в названии: берём начало
    assert section_key("257-1.1.1.1.", "ТД ПК588-ПК591") == ("257", 588)

    # пробел после ПК встречается в выгрузке: "КД дверь ДП ПК 8"
    assert section_key("414-1.1.1.1.", "КД дверь ДП ПК 8 ") == ("414", 8)

    # ПК0 у разных коллекторов — разные участки, иначе вся сеть схлопнется в одну точку
    assert section_key("847-1.1.1.1.", "ДД ПК0") != section_key("914-1.1.1.1.", "ДД ПК0")

    # датчик в диспетчерской: участка нет, и это не ошибка
    assert section_key("672-1.1.1.1.", "КД окно пультовая ДП") is None
    assert section_key("163-1.1.1.1.", "ИПР ДП тамбур") is None

    # линейная координата: пикет десять метров плюс смещение (заказчик, 17.09.2026)
    assert linear_metres("ТЕМП ПК176+6,5") == 1766.5
    assert linear_metres("ДД ПК175+9,5") == 1759.5
    # шаг между соседними извещателями шлейфа — 7 метров
    assert round(linear_metres("ТЕМП ПК176+6,5") - linear_metres("ДД ПК175+9,5"), 1) == 7.0
    # смещение не выходит за длину пикета: 9,5 < 10, иначе это уже следующий пикет
    assert linear_metres("ДД ПК175+9,5") - linear_metres("КД АВ ПК175 ур.3") == 9.5
    # точка вместо запятой тоже встречается
    assert linear_metres("ТЕМП ПК10+2.5") == 102.5
    # без смещения — начало пикета, а не None: датчик не должен выпасть с оси
    assert linear_metres("КД АВ ПК106 ур.3") == 1060.0
    # датчик в диспетчерской на оси коллектора не лежит
    assert linear_metres("КД окно пультовая ДП") is None

    # мусор на входе не роняет разбор
    assert section_key(None, "ДД ПК5") is None
    assert section_key("", "ДД ПК5") is None
    assert section_key("847-1.1.1.1.", None) is None
    assert linear_metres(None) is None
    assert linear_metres("") is None

    print("selfcheck ok")


if __name__ == "__main__":
    if len(sys.argv) > 1:
        report(sys.argv[1])
    else:
        selfcheck()
