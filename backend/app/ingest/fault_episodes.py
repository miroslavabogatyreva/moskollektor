#!/usr/bin/env python3
"""Построение эпизодов отказа: smvu.reading -> smvu.fault_episode. Задача Q2.16 (MOS-96).

**Что такое эпизод.** Канал пишет в журнал значение за значением. Эпизод отказа
открывается на первой записи со значением, которое smvu.fault_rule называет отказом
для этого типа датчика, и закрывается первой следующей записью канала с любым другим
значением. Отказом считается эпизод длиннее порога — min_duration_seconds из того же
правила, по умолчанию 3600 секунд.

**Почему эпизод, а не запись.** Канал 228571 «ТЕМП ПК275+9» за 2025 год дал «Норма»
22 167 раз и «Неисправен» 22 156 — он мигает между ними, медиана промежутка 2 секунды.
Это дребезг контакта. Возьми мы записи, модель выучила бы дребезг вместо деградации.

**Почему порог в час и откуда он берётся.** 99,93 % эпизодов состоят из одной записи,
медиана длительности 56 секунд. Час — стартовое значение, выбранное нами, а не
заказчиком: вопрос ОВ-47 ему задан, ответа нет. Поэтому числа в коде нет вовсе,
порог читается из smvu.fault_rule и задаётся по типу датчика — придёт ответ, менять
надо будет строку в таблице.

**Сортировка решает, и здесь мы уже ошиблись один раз.** Файлы заказчика по времени
не отсортированы: в ext-journal-2026.csv время идёт назад между соседними строками
741 744 раза. Эпизод, собранный в порядке строк файла, и эпизод, собранный по времени, —
разные эпизоды: первый счёт дал 11 454, пересчёт с сортировкой по времени — 10 416.
Порядок здесь всюду `(read_time, journal_id)`, и это договорённость из
docs/for-ml-team.md разд. 2, а не удобство.

**Чем это отличается от эталона analysis/episodes.py.** Двумя вещами, обе намеренные.
Первая: эталон считает отказом только «Неисправен», а правило схемы — ещё
и «Неопределен» у «Теплового датчика» и «Датчика температуры». Поэтому эпизодов
здесь больше, и сверка с эталонными 10 416 идёт по подмножеству fault_value =
'Неисправен'. Вторая: эталон берёт закрывающее значение как max(next_val) по группе,
то есть максимум по алфавиту. Для «Нормы» и «Обесточен» он случайно верен — они
по алфавиту больше «Неисправен», — а для «Затоплен» нет: «З» меньше «Н», и такой
эпизод получает closed_by = 'Неисправен'. Тем же max берётся и время конца, поэтому
многозаписный незакрытый эпизод у эталона выглядит закрытым. Здесь и то и другое
берётся у последней записи эпизода явной сортировкой.

**Три случая, которые нельзя проскочить.**

1. *Эпизод сквозь тишину выгрузки.* 7 и 8 апреля 2024 СМВУ не написала ни строки
   по всему парку. Канал, замолчавший 6 апреля и заговоривший 9-го, выглядит как
   трёхсуточный отказ. Такие эпизоды помечаются spans_outage по smvu.data_outage,
   а не выбрасываются: среди них есть и настоящие отказы.
2. *Незакрытый эпизод.* Канал ушёл в отказ и больше ничего не сказал: 51 такой
   эпизод упирается в конец выгрузки, шесть — в снятие самого канала. Длительность
   у них неизвестна, поэтому в таблицу попадают только те, что **уже** длятся дольше
   порога на момент конца архива, и ended_at у них остаётся NULL. Это цензурированное
   наблюдение: для оценки наработки годится, для обучения на «отказ случился» — нет.
3. *Разные плохие значения подряд.* У теплового датчика отказ означают и «Неисправен»,
   и «Неопределен». Идущие подряд, они образуют ОДИН эпизод, а fault_value у него —
   значение первой записи, по нему же берётся порог.

**Чем эпизод закрывается — числа 16.09.2026, и они НЕ те, что в комментарии схемы.**
Комментарий к `smvu.fault_episode.closed_by` в `db/migrations/004_events.sql` называет
«Норма» 86,2 %, «Обесточен» 9,0 %, «Затоплен» 3,7 %, «Неопределен» 1,1 %. По построенной
таблице (25 383 закрытых эпизода) выходит другое: «Норма» 77,0 %, «Неопределен» 15,4 %,
«Обесточен» 0,08 % (20 эпизодов), «Затоплен» 0,02 % (4 эпизода). Сильнее всего разошёлся
«Обесточен» — в сто с лишним раз.

Сравнивать напрямую нельзя, и в этом же причина расхождения: комментарий считался по ВСЕМ
эпизодам архива, включая полуторамиллионный дребезг короче часа, а здесь лежат только
прошедшие порог. Плюс знаменатель вырос за счёт 14 964 эпизодов «Неопределен», которых
у эталона не было вовсе. Миграция накатана, править её комментарий нельзя — поэтому
верное число названо здесь и в `docs/day-one.md`. Отдельно: значение «Затоплен» в журнале
есть (634 записи только за июнь 2021), но эпизод им закрывается 4 раза на весь архив,
а у всех 25 каналов типа «Датчик затопления» его нет ни разу за 2025 год.

**Резать по каналам, а не по времени.** Эпизод пересекает границу месяца, канал
не пересекает. Каналы-отказники дают 5,2 % строк журнала (268 328 из 5 141 395
за июнь 2026), то есть читать надо около 16 млн строк, а не 313 млн.
"""
import argparse
import asyncio
import os
import time

import asyncpg

# Каналы, у которых в журнале есть хоть одна запись, подходящая под правило.
# Идёт по частичному индексу reading_fault_idx (1,5 млн строк из 313 млн).
КАНАЛЫ_С_ОТКАЗОМ = """
SELECT DISTINCT r.channel_id
  FROM smvu.reading r
  JOIN smvu.channel c USING (channel_id)
  LEFT JOIN smvu.fault_rule f ON f.sensor_kind = c.sensor_kind
                             AND f.fault_value = r.value_text
 WHERE f.fault_value IS NOT NULL
    -- Канал-заглушка без типа: правила по типу у него нет, но «Неисправен»
    -- означает отказ у всех девятнадцати типов, значит и у него.
    OR (c.sensor_kind IS NULL AND r.value_text IN (
            SELECT fault_value FROM smvu.fault_rule
             GROUP BY fault_value
            HAVING count(*) = (SELECT count(*) FROM smvu.sensor_kind)))
"""

# Построение эпизодов для пачки каналов. $1 — каналы, $2 — конец архива.
#
# Почему LEFT JOIN, а не IN-список значений: правило зависит от типа датчика,
# и «Неопределен» плох у двух типов из девятнадцати. Соединение идёт по паре
# (канал, значение) с таблицей из полусотни строк — это hash join, а не скан.
ПОСТРОИТЬ = """
WITH универсальные AS (
    -- Значения, означающие отказ у КАЖДОГО известного типа датчика. Сейчас это
    -- одно значение — «Неисправен»: оно стоит во всех девятнадцати строках
    -- правила, тогда как «Неопределен» — только у двух типов.
    SELECT fault_value, max(min_duration_seconds) AS min_duration_seconds
      FROM smvu.fault_rule
     GROUP BY fault_value
    HAVING count(*) = (SELECT count(*) FROM smvu.sensor_kind)
),
правило AS (
    SELECT c.channel_id, f.fault_value, f.min_duration_seconds
      FROM smvu.channel c
      JOIN smvu.fault_rule f USING (sensor_kind)
     WHERE c.channel_id = ANY($1)
    UNION ALL
    -- Канал без типа датчика. Таких 1 142 — это заглушки, заведённые заливкой
    -- для каналов, которых нет в справочнике заказчика, плюс каналы, чей тип
    -- не прошёл сверку со справочником (задача Q2.15). Соединение по sensor_kind
    -- не даёт для них НИ ОДНОЙ строки правила, и без этой ветки они выпадали
    -- из построения целиком: 274 из них пишут «Неисправен», 12 645 записей.
    -- Поймано сверкой с эталоном 16.09.2026 — недобор 280 эпизодов во всех годах
    -- сразу, и это единственная причина, дававшая недобор систематически.
    SELECT c.channel_id, u.fault_value, u.min_duration_seconds
      FROM smvu.channel c CROSS JOIN универсальные u
     WHERE c.channel_id = ANY($1) AND c.sensor_kind IS NULL
),
записи AS (
    SELECT r.channel_id, r.read_time, r.journal_id, r.value_text, r.section_id,
           (p.channel_id IS NOT NULL) AS плохо
      FROM smvu.reading r
      LEFT JOIN правило p ON p.channel_id = r.channel_id
                         AND p.fault_value = r.value_text
     WHERE r.channel_id = ANY($1)
),
-- Соседи считаются по ВСЕМ записям канала, а не только по плохим: эпизод
-- закрывает первая запись с любым другим значением, в том числе числовая.
сосед AS (
    SELECT *,
           lag(плохо)       OVER w AS пред_плохо,
           lead(read_time)  OVER w AS след_время,
           lead(value_text) OVER w AS след_значение
      FROM записи
    WINDOW w AS (PARTITION BY channel_id ORDER BY read_time, journal_id)
),
плохие AS (
    SELECT *, NOT coalesce(пред_плохо, false) AS начало
      FROM сосед WHERE плохо
),
-- Номер эпизода внутри канала: сколько начал встретилось до этой строки включительно.
группы AS (
    SELECT *, count(*) FILTER (WHERE начало)
                 OVER (PARTITION BY channel_id ORDER BY read_time, journal_id
                       ROWS UNBOUNDED PRECEDING) AS эпизод
      FROM плохие
),
собрано AS (
    SELECT channel_id,
           min(read_time) AS started_at,
           count(*)::int  AS rows_cnt,
           -- Значение и участок берём у ПЕРВОЙ записи эпизода, конец — у последней.
           -- Не max(): максимум по алфавиту врёт на «Затоплен», а max по времени
           -- прячет NULL и делает незакрытый эпизод закрытым.
           (array_agg(value_text     ORDER BY read_time,      journal_id))[1]      AS fault_value,
           (array_agg(section_id     ORDER BY read_time,      journal_id))[1]      AS section_id,
           (array_agg(след_время     ORDER BY read_time DESC, journal_id DESC))[1] AS ended_at,
           (array_agg(след_значение  ORDER BY read_time DESC, journal_id DESC))[1] AS closed_by
      FROM группы GROUP BY channel_id, эпизод
)
INSERT INTO smvu.fault_episode
       (channel_id, section_id, started_at, ended_at, rows_cnt, closed_by,
        fault_value, spans_outage)
SELECT s.channel_id, s.section_id, s.started_at, s.ended_at, s.rows_cnt, s.closed_by,
       s.fault_value,
       EXISTS (SELECT 1 FROM smvu.data_outage o
                WHERE tstzrange(s.started_at, coalesce(s.ended_at, $2))
                   && tstzrange(o.started_at, o.ended_at))
  FROM собрано s
  JOIN правило p ON p.channel_id = s.channel_id AND p.fault_value = s.fault_value
 -- Незакрытый эпизод мерим до конца архива: он длится НЕ МЕНЬШЕ этого.
 WHERE coalesce(s.ended_at, $2) - s.started_at
       > make_interval(secs => p.min_duration_seconds)
"""


async def конец_архива(conn) -> "object":
    """Время последней записи журнала.

    max(read_time) по всей таблице — это скан 109 партиций и минута времени
    (замерено 16.09.2026 на соседней задаче: 62,8 секунды). Партиции нарезаны
    до конца 2027 года и пустых среди них большинство, поэтому идём с конца
    и останавливаемся на первой непустой.
    """
    партиции = [r["имя"] for r in await conn.fetch("""
        SELECT c.relname AS имя
          FROM pg_inherits i JOIN pg_class c ON c.oid = i.inhrelid
         WHERE i.inhparent = 'smvu.reading'::regclass
           AND c.relname <> 'reading_default'
         ORDER BY c.relname DESC""")]
    for имя in партиции:
        конец = await conn.fetchval(f"SELECT max(read_time) FROM smvu.{имя}")
        if конец is not None:
            return конец
    raise RuntimeError("в smvu.reading нет ни одной записи — строить эпизоды не из чего")


async def построить(conn, частей: int = 8, тихо: bool = False) -> dict:
    """Построить эпизоды по всему архиву. Таблица обязана быть пустой.

    Возвращает диагностику. Пачками режем каналы, а не время: эпизод пересекает
    границу месяца, а канал не пересекает.
    """
    окон = await conn.fetchval("SELECT count(*) FROM smvu.data_outage")
    if окон == 0:
        raise RuntimeError(
            "smvu.data_outage пуста: эпизоды, тянущиеся сквозь тишину выгрузки, "
            "не пометились бы и уехали в обучение с выдуманной длительностью. "
            "Сначала накатить db/migrations/017_fault_episodes.sql")

    t0 = time.time()
    конец = await конец_архива(conn)
    каналы = [r["channel_id"] for r in await conn.fetch(КАНАЛЫ_С_ОТКАЗОМ)]

    # Прогон возобновляемый: пропускаем каналы, эпизоды которых уже лежат в таблице.
    # Вставка одной пачки транзакционна, поэтому канал либо построен целиком, либо
    # не построен вовсе — промежуточного состояния не бывает. Без этого оборванная
    # связь заставляла бы чистить таблицу, а чистка — это удаление, которого в проекте
    # мы не делаем. Проверено уловом 16.09.2026: туннель упал на первой пачке,
    # она откатилась целиком, таблица осталась пустой.
    построенные = {r["channel_id"] for r in await conn.fetch(
        "SELECT DISTINCT channel_id FROM smvu.fault_episode")}
    осталось = [ч for ч in каналы if ч not in построенные]
    if not тихо:
        print(f"   каналов с отказом по правилу: {len(каналы)}, "
              f"конец архива {конец:%d.%m.%Y %H:%M}, окон тишины {окон}")
        if построенные:
            print(f"   уже построено каналов: {len(построенные)}, "
                  f"строю оставшиеся {len(осталось)}")
    каналы = осталось

    for k in range(частей):
        пачка = [ч for ч in каналы if ч % частей == k]
        t = time.time()
        ответ = await conn.execute(ПОСТРОИТЬ, пачка, конец)
        if not тихо:
            print(f"   пачка {k + 1}/{частей}: каналов {len(пачка)}, "
                  f"{ответ.split()[-1]} эпизодов, {time.time() - t:.1f} с", flush=True)

    диаг = dict(await conn.fetchrow("""
        SELECT count(*)                                            AS эпизодов,
               count(DISTINCT channel_id)                          AS каналов,
               count(*) FILTER (WHERE ended_at IS NULL)            AS незакрытых,
               count(*) FILTER (WHERE spans_outage)                AS сквозь_тишину,
               count(*) FILTER (WHERE fault_value = 'Неисправен')  AS неисправен,
               count(*) FILTER (WHERE fault_value = 'Неопределен') AS неопределен
          FROM smvu.fault_episode"""))
    диаг["секунд"] = round(time.time() - t0, 1)
    return диаг


# Эталон: эпизоды «Неисправен» длиннее часа, закрытые. Незакрытые в счёт 10 416
# не входят — в analysis/episodes.py длительность у них NULL, и условие dur_h>1 ложно.
ЭТАЛОННОЕ_ПОДМНОЖЕСТВО = """
SELECT extract(year FROM started_at AT TIME ZONE 'Europe/Moscow')::int AS год,
       count(*) AS эпизодов
  FROM smvu.fault_episode
 WHERE fault_value = 'Неисправен' AND ended_at IS NOT NULL
 GROUP BY 1 ORDER BY 1
"""

# docs/for-ml-team.md разд. 2, «что перепроверить». Восемь чисел, а не одно:
# сумма может сойтись при разъехавшихся слагаемых.
ЭТАЛОН_ПО_ГОДАМ = {2019: 286, 2020: 2422, 2021: 3177, 2022: 1781,
                   2023: 704, 2024: 235, 2025: 971, 2026: 840}

# Сверка 16.09.2026 дала 10 419 против 10 416 — шесть лет из восьми совпали точно,
# 2020 разошёлся на 1, 2021 на 2. Все три разобраны поимённо: это эпизоды «Неисправен»
# у каналов 228401 (2020), 115264 и 212734 (2021), внутри которых есть «Неопределен».
# У эталона такой эпизод кончался на первом «Неопределен» и выходил короче часа
# (0,21 ч, 0,27 ч и 0,29 ч), а правило схемы считает «Неопределен» продолжением отказа
# для этих типов датчика, эпизод длится дальше (25,09 ч, 1,48 ч и 20,33 ч) и порог
# проходит. Это не ошибка ни у нас, ни у эталона — разные определения отказа,
# и разница ровно в три эпизода на 10 416.
РАЗОБРАННОЕ_РАСХОЖДЕНИЕ = 3


async def сверить_с_эталоном(conn) -> tuple[dict, dict]:
    """Наш счёт против analysis/episodes.py. Возвращает (наше по годам, расхождения)."""
    наше = {r["год"]: r["эпизодов"] for r in await conn.fetch(ЭТАЛОННОЕ_ПОДМНОЖЕСТВО)}
    расхождения = {г: (наше.get(г, 0), э) for г, э in ЭТАЛОН_ПО_ГОДАМ.items()
                   if наше.get(г, 0) != э}
    return наше, расхождения


