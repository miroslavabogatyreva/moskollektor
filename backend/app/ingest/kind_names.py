"""Имена типов датчика и инженерной системы: сверка со справочниками базы.

Зачем. Загрузчик проверяет тип_датчика и тип_инж_системы по smvu.sensor_kind
(19 строк) и smvu.system_kind (6 строк). До 21.09.2026 сверка шла точным
совпадением строки, и «Охранная  подсистема» с двойным пробелом, «охранная
подсистема» строчными или «КД AB» с латинскими A и B ушли бы в NULL и в отчёт
о качестве, хотя тип тот же самый. Латиница-двойник в кириллическом тексте —
обычное дело для выгрузок, которые кто-то правил руками в Excel.

Что не меняется. На выгрузке от 15.09.2026 все значения совпадают со справочником
буква в букву, и с нормализацией тип получает то же число каналов. В базу пишем
каноническое имя из справочника, а не то, что пришло в файле, — внешний ключ
иначе отверг бы строку. Значение, которое не нашлось и после нормализации,
по-прежнему снимается в NULL и попадает в load.error (строка приёмки Ф-78).
"""

import re

# Латинские буквы, которые на глаз не отличить от кириллических. Только пары,
# одинаковые в начертании: латинская «H» — это кириллическая «Н», а не «Х».
_LOOKALIKE = str.maketrans("ABCEHKMOPTXaceopxy", "АВСЕНКМОРТХасеорху")
_SPACES = re.compile(r"\s+")


def norm_kind(value):
    """Ключ сравнения: без краевых пробелов, пробелы схлопнуты, строчные, ё -> е.

    Латиницу переводим в кириллицу ДО перевода в строчные: у заглавных и строчных
    двойников разные пары ("B" есть, "b" нет — строчная «в» на «b» не похожа).
    """
    if value is None:
        return ""
    value = _SPACES.sub(" ", value.strip()).translate(_LOOKALIKE)
    return value.lower().replace("ё", "е")


def canon_map(names):
    """{нормализованное имя: имя из справочника базы}."""
    return {norm_kind(n): n for n in names}


def canon(value, mapping):
    """Имя из справочника базы для значения из файла, или None — не нашлось."""
    return mapping.get(norm_kind(value))
