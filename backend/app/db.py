"""Пул соединений с базой, общий для всех методов API. Заводится здесь, а не
внутри каждого модуля, потому что deps.py (Q4.1) и списочные методы (Q4.3, 4.6,
4.10) читают одну и ту же базу через один и тот же пул: два пула на процесс
только удвоили бы число соединений без всякой пользы.

Здесь же лежит КРАЙ_ДАННЫХ — единственное определение границы выгрузки заказчика
(MOS-148). Модуль выбран потому, что его импортируют обе стороны — и API, и worker, —
а сам он не тянет ни apscheduler, ни клиента модели.
"""
import asyncio
import json
import os

import asyncpg


async def _init_conn(conn: asyncpg.Connection) -> None:
    # asyncpg отдаёт jsonb как сырую строку, если не поставить кодек: pred.forecast.factors
    # (Q4.3) иначе придёт клиенту как JSON-строка внутри JSON, а не вложенным объектом.
    await conn.set_type_codec(
        "jsonb", encoder=json.dumps, decoder=json.loads, schema="pg_catalog", format="text",
    )


_pool: asyncpg.Pool | None = None
# Замок на заведение пула (задача 1.4). Без него одновременные первые запросы
# к свежему api заводили по пулу каждый: пока первый ждёт create_pool, _pool
# ещё None. Нагрузочный прогон 27.09.2026 — 30 запросов разом выбрали все
# 100 соединений базы, nginx отвечал 504. Тест — code/tests/test_db_pool.py.
_pool_lock = asyncio.Lock()


async def get_pool() -> asyncpg.Pool:
    global _pool
    if _pool is None:
        async with _pool_lock:
            if _pool is None:
                _pool = await asyncpg.create_pool(os.environ["DATABASE_URL"], init=_init_conn)
    return _pool


# Отдельный пул журнала действий (задача 1.4): middleware write_audit_log
# (backend/app/api/main.py) пишет строку, пока запрос ещё держит своё соединение
# из get_conn — FastAPI отдаёт его только после отправки ответа. Из общего пула
# это второе соединение на запрос, и когда десять запросов разом держат по одному,
# все десять ждут второе и не дождутся никогда: нагрузочный прогон 27.09.2026 —
# 30 запросов разом, 30 ответов 504 по минуте. Свой пул на два соединения
# ни у кого ничего не ждёт, поэтому и не блокируется.
_audit_pool: asyncpg.Pool | None = None


async def get_audit_pool() -> asyncpg.Pool:
    global _audit_pool
    if _audit_pool is None:
        async with _pool_lock:
            if _audit_pool is None:
                _audit_pool = await asyncpg.create_pool(
                    os.environ["DATABASE_URL"], init=_init_conn, min_size=1, max_size=2,
                )
    return _audit_pool


async def get_conn():
    pool = await get_pool()
    async with pool.acquire() as conn:
        yield conn


# Край выгрузки заказчика — ОДНО определение на весь продукт (MOS-148).
#
# Три места спрашивают «докуда доехали данные»: планировщик выбирает этим срез
# прогона (app.worker.scheduler), расчёт меряет отсюда отставание среза
# (app.worker.run), API показывает это число на плитке дашборда
# (app.api.routes.data_status). До MOS-148 определений было два: планировщик брал
# max(day) по свёртке, а расчёт — max(read_time) по журналу с окном в 90 суток.
# Сегодня оба дают 2026-06-30 23:59:59+03 и расхождения не видно, но это разные
# величины, и разойтись они могут молча.
#
# ПОЧЕМУ ГРАНИЦУ БЕРЁМ У СВЁРТКИ, А НЕ У ЖУРНАЛА. Замер 22.09.2026 на стенде:
# max(read_time) по всей smvu.reading — 60 964 мс (перемерено проверяющей сессией:
# 64 974 мс, тот же порядок), ответ до секунды тот же самый. Край по свёртке стоит
# 0–1 мс на живом соединении прогона (видно в pred.run.ms_fetch) и 49,5 мс первым
# вызовом в новом соединении — первый платит за план и прогрев. Называть одно число
# без методики нельзя: у этого запроса их три, и они отличаются в полсотни раз. Минуту на один максимум API отдать
# не может: НФ-89 требует обновлять экран не реже раза в минуту. Обогнать журнал
# свёртка не может по устройству — 022_channel_daily.sql берёт каждый день
# из read_time::date настоящего показания, без календаря, — значит ошибка такой
# мерки делает край РАНЬШЕ, а не позже.
#
# КОНСТАНТЫ ЗДЕСЬ НЕТ НАРОЧНО: записанная дата устареет в тот день, когда
# заказчик пришлёт хоть одну строку.
# Приведение к timestamptz делает БАЗА, а не Python: так момент считается
# в поясе сеанса (TimeZone = Europe/Moscow на стенде) и приезжает в asyncpg
# уже с поясом. Без приведения вернулся бы наивный timestamp, и его пояс зависел
# бы от настроек процесса, а не базы — при разъезде настроек срез уехал бы
# на три часа молча.
#
# NULL означает «свёртка пуста», а не «край неизвестен по ошибке»: до первого
# прогона feat.refresh_channel_daily таблица законно пустая. Каждый читатель
# обязан разобрать этот случай сам и сказать о нём вслух.
КРАЙ_ДАННЫХ = """
SELECT ((max(day) + 1)::timestamp - interval '1 second')::timestamptz
  FROM feat.channel_daily
"""
